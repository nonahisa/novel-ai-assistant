import { describe, expect, test } from "vitest";
import { hasHonorific, stripHonorific } from "../../src/core/nameHonorific";

/**
 * 敬称を外す境界の検算（設計書6.5.9）。
 *
 * **外しすぎるほうが危ない。** 「おじいさま」を「おじい」にすると、
 * 作中に無い呼び名で人物どうしを結びはじめる。外し損ねるのは
 * 候補が1つ出ないだけで済むが、誤って結ぶと資料が壊れる。
 */
describe("名前から敬称を外す", () => {
  test.each([
    ["密倉さん", "密倉"],
    ["奥原くん", "奥原"],
    ["三門くん", "三門"],
    ["太志君", "太志"],
    ["文佳ちゃん", "文佳"],
    ["純也くん", "純也"],
    ["白瀬様", "白瀬"],
    ["マイナ先生", "マイナ"],
    // 長い敬称から照合する。「殿下」で切ると「エレナ妃」が残る
    ["エレナ妃殿下", "エレナ"],
    // 爵位と「夫人」付き。同じ人物を別レコードにしないため
    ["ヴォイド・コンストラクタ男爵", "ヴォイド・コンストラクタ"],
    ["ジェクティ・コンストラクタ男爵夫人", "ジェクティ・コンストラクタ"],
  ])("「%s」→「%s」", (name, expected) => {
    expect(stripHonorific(name)).toBe(expected);
    expect(hasHonorific(name)).toBe(true);
  });

  test.each([
    // 敬称込みでひとつの呼びかけ語。外すと「おじい」「お嬢」になる
    ["おじいさま"],
    ["おばあちゃん"],
    ["お嬢様"],
    ["お母さん"],
    ["ご主人様"],
    // 敬称そのものだけの呼び方。外すと何も残らない
    ["先生"],
    ["さん"],
    ["姫"],
    ["殿下"],
    // 残りが1字。「母」では呼び名として成り立たない
    ["母さん"],
    // 敬称が付いていない
    ["密倉文佳"],
    ["三門太志"],
    [""],
  ])("「%s」はそのまま", (name) => {
    expect(stripHonorific(name)).toBe(name);
    expect(hasHonorific(name)).toBe(false);
  });

  test("外すのは1つだけ。重ねた呼び方を別の語にしない", () => {
    expect(stripHonorific("白瀬様様")).toBe("白瀬様");
  });

  test("前後の空白は落とす", () => {
    expect(stripHonorific("  密倉さん  ")).toBe("密倉");
  });
});
