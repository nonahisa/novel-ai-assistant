import { describe, expect, test } from "vitest";
import {
  isOnyomiReading,
  opensOnyomiCompound,
} from "../../src/core/onyomiReading";

/**
 * 音読みをつないだだけの熟語を見分ける（作者の報告、2026-09-12）。
 *
 * **音読みで普通に読める熟語をかなにしても、読みやすくならない。**
 * ここで確かめたいのは2つある。
 *
 * 1. 作者の挙げた4語が「音読みをつないだだけ」と分かること
 * 2. **本当にひらくべき語を巻き込まないこと**——連濁・促音便を許したので、
 *    許しすぎていないかを、ひらくべき語の側からも見る
 */
describe("音読みをつないだだけか", () => {
  test.each([
    // 作者の報告に出た4語（すべて表の音をつないだだけ）
    ["基礎学力", "きそがくりょく"],
    ["人物適性", "じんぶつてきせい"],
    ["遺伝適性", "いでんてきせい"],
    ["実技加点", "じつぎかてん"],
    // 促音便（ガク＋コウ）
    ["学校", "がっこう"],
  ])("%s は音読み（%s）", (kanji, kana) => {
    expect(isOnyomiReading(kanji, kana)).toBe(true);
  });

  test("連濁を許す（会社＝カイ＋シャ→がいしゃ）", () => {
    expect(isOnyomiReading("商事会社", "しょうじがいしゃ")).toBe(true);
  });

  /**
   * **訓が混じれば音読みではない。** 「株」は表に音を1つも持たない
   * （訓「かぶ」だけ）ので、読みを組めない。
   */
  test("訓が混じると false（株式会社）", () => {
    expect(isOnyomiReading("株式会社", "かぶしきがいしゃ")).toBe(false);
  });

  test.each([
    // 本当にひらくべき語。音をつないでも一致しない
    ["出来", "できる"],
    ["出来", "でき"],
    ["何時", "いつ"],
    // 表外字を含む（「謂」「殆」は常用漢字表に無い）
    ["所謂", "いわゆる"],
    ["殆", "ほとんど"],
  ])("%s → %s は音読みではない", (kanji, kana) => {
    expect(isOnyomiReading(kanji, kana)).toBe(false);
  });

  test("1字は対象外（「然し」のような形は見ない）", () => {
    // 「然」の音は「ゼン」「ネン」だが、そもそも1字なので判定しない
    expect(isOnyomiReading("然", "ぜん")).toBe(false);
  });

  /**
   * **連濁と促音便を許したことで、本当にひらくべき語を巻き込んでいないか。**
   *
   * ひらくのが定石とされる語を並べて掃く。どれも音をつないだ形と一致しない
   * （訓が元・当て字・表外字のいずれか）ので、関門は素通りする。
   * ここが崩れたら、許す変形を広げすぎたということである。
   */
  test.each([
    ["出来", "でき"],
    ["何処", "どこ"],
    ["何故", "なぜ"],
    ["流石", "さすが"],
    ["一寸", "ちょっと"],
    ["貴方", "あなた"],
    ["生憎", "あいにく"],
    ["大人", "おとな"],
    ["今日", "きょう"],
    ["昨日", "きのう"],
    ["一人", "ひとり"],
    ["田舎", "いなか"],
    ["土産", "みやげ"],
    ["laptop" /* 漢字でない並び */, "らっぷとっぷ"],
  ])("ひらくのが定石の語（%s）は音読みではない", (kanji, kana) => {
    expect(isOnyomiReading(kanji, kana)).toBe(false);
  });

  /**
   * **ここは巻き込む**（作者の規則どおりの結果として記録しておく）。
   *
   * 「丁度＝チョウ＋ド」「是非＝ゼ＋ヒ」「沢山＝タク＋サン」は、当て字だが
   * **表の音をつないだ形と一致する**ので、この関門は落とす。ひらくのが定石の
   * 語でもあるため、落としてよいかは作者の判断が要る（実装は規則に従う）。
   */
  test.each([
    ["丁度", "ちょうど"],
    ["是非", "ぜひ"],
    ["沢山", "たくさん"],
  ])("当て字でも音が一致する語（%s）は落とす", (kanji, kana) => {
    expect(isOnyomiReading(kanji, kana)).toBe(true);
  });

  test("読みが余っていれば一致しない", () => {
    // 途中まで合っても、かなが全部なくなるまで組めなければ false
    expect(isOnyomiReading("基礎", "きそがく")).toBe(false);
    expect(isOnyomiReading("基礎学力", "きそ")).toBe(false);
  });
});

/**
 * 原文と修正案を突き合わせて、ひらこうとしている箇所を取り出す。
 *
 * **差分が粗く落ちる形**（置き換えが多いと `diffChars` は「まるごと消して
 * まるごと足す」になる）でも見つけられることを、作者の報告そのもので確かめる。
 */
describe("修正案が音読みの熟語をひらいているか", () => {
  test("作者の報告そのもの（4語まとめて・数字を挟む）", () => {
    expect(
      opensOnyomiCompound(
        "基礎学力六十点、人物適性百点、遺伝適性百点、実技加点八十点。",
        "きそがくりょく六十点、じんぶつてきせい百点、いでんてきせい百点、じつぎかてん八十点。"
      )
    ).toBe(true);
  });

  test("1語だけでも見つける", () => {
    expect(
      opensOnyomiCompound("基礎学力の試験だった。", "きそがくりょくの試験だった。")
    ).toBe(true);
  });

  test.each([
    ["出来る", "できる"],
    ["所謂、彼は強い。", "いわゆる、彼は強い。"],
    ["殆ど眠れなかった。", "ほとんど眠れなかった。"],
    ["然し彼は歩いた。", "しかし彼は歩いた。"],
    ["何時も通りだった。", "いつも通りだった。"],
    // ひらきではない直し（語尾を整えただけ）も巻き込まない
    ["彼は静かに頷いたのであった。", "彼は静かに頷いた。"],
  ])("本当のひらき・別の直し（%s）は巻き込まない", (original, suggestion) => {
    expect(opensOnyomiCompound(original, suggestion)).toBe(false);
  });

  test("変わっていなければ見ない", () => {
    expect(opensOnyomiCompound("基礎学力", "基礎学力")).toBe(false);
    expect(opensOnyomiCompound("基礎学力", "")).toBe(false);
  });
});
