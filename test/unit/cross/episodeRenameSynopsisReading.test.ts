/**
 * 話の名前を変えたとき、各話あらすじと読みの辞書がついてくる（設計書6.68.2）。
 *
 * ## 何が起きていたか（0.126.3 まで）
 *
 * 名前だけの改名（`followEpisodeFileRenames`）は、パスで話を指す4つの台帳しか
 * 付け替えていなかった。ところが
 *
 * - **各話あらすじ**は、話数の読めない話（「幕間.txt」など）を**ファイル名**で引く
 *   （`synopsisKey` の `?#ファイル名`）。名前を変えると、あらすじが一覧から消えた
 * - **読みの辞書**は、話の**相対パス**をファイル名にして置く（`.aiwriter/readings/
 *   本文__003.txt.json`）。話数に関わらず、名前を変えると作者の直した読みが外れた
 *
 * 先にこのテストを書き、落ちる升を確かめてから直した（再現テスト）。
 */

const work: WorkEntry = {
  id: "work_test",
  title: "氷の街",
  folderPath: path.join("C:", "novels", "work"),
  registeredAt: "2026-09-03T00:00:00.000Z",
};

function diskPath(...parts: string[]): string {
  return Uri.file(path.join(work.folderPath, ...parts)).fsPath;
}

const encoder = new TextEncoder();
const lookup = (filePath: string): WorkEntry | undefined => findWorkForFile([work], filePath);

function synopsisRow(fileName: string, chapter: number | null): ChapterSynopsis {
  return {
    chapter,
    fileName,
    title: null,
    synopsis: "湖のほとりで二人が誓う。",
    sourceHash: "h",
    model: null,
    promptVersion: null,
    // 作者が書き直したあらすじ（中身は変えずに、指し先だけが変わること）
    autoGenerated: false,
    authorNotes: "作者のメモ",
    emotion: null,
    updatedAt: null,
  };
}

/** あらすじと読みの辞書を1話ぶん置く。`chapter` はあらすじの鍵の話数 */
async function seedRecords(fileName: string, chapter: number | null): Promise<void> {
  const store = new SynopsisStore(work);
  const set = await store.load();
  await store.save({ ...set, episodes: [...set.episodes, synopsisRow(fileName, chapter)] });
  const episodePath = diskPath("本文", fileName);
  const loaded = await loadReadingDictionary(work, episodePath);
  await saveReadingDictionary(
    work,
    episodePath,
    {
      ...loaded.file,
      entries: [{ word: "十分", quote: "十分に", reading: "じっぷん", source: "author" }],
    },
    loaded.hash
  );
}

async function followed(
  fileName: string,
  chapter: number | null
): Promise<{ synopsis: boolean; reading: boolean }> {
  const set = await new SynopsisStore(work).load();
  const row = findSynopsis(set, fileName, chapter);
  const dict = await loadReadingDictionary(work, diskPath("本文", fileName));
  return {
    synopsis:
      row?.synopsis === "湖のほとりで二人が誓う。" && row.authorNotes === "作者のメモ",
    reading:
      dict.file.entries.length === 1 &&
      dict.file.entries[0].reading === "じっぷん" &&
      dict.file.episode === `本文/${fileName}`,
  };
}

function episodeFile(fileName: string, chapter: number | null): EpisodeFile {
  return {
    filePath: diskPath("本文", fileName),
    fileName,
    ext: path.extname(fileName),
    chapterStart: chapter,
    chapterEnd: chapter,
    subtitle: null,
    kind: "episode",
    isInitialName: true,
    counts: { total: 0, withoutSpaces: 0, withoutBlankLines: 0 },
    hasMetadata: true,
    metaTitle: "湖畔の誓い",
    declaredCharCount: null,
    metaUpdatedAt: null,
  } as unknown as EpisodeFile;
}

describe("名前を変えたとき、各話あらすじと読みの辞書がついてくる", () => {
  const disk = new Map<string, Uint8Array>();
  const originalWarning = window.showWarningMessage;
  const originalInfo = window.showInformationMessage;

  beforeEach(() => {
    disk.clear();
    workspace.textDocuments = [];
    workspace.fs = memoryFs(disk, {
      methods: ["createDirectory", "readFile", "writeFile", "rename", "delete", "stat", "readDirectory"],
      folderStat: { type: FileType.Directory, ctime: 0, mtime: 0, size: 0 },
      readDirectory: "nested",
    });
    window.showWarningMessage = originalWarning;
    window.showInformationMessage = originalInfo;
    setEpisodeRenameWorkLookup(undefined);
  });

  describe("製品の中の改名（右クリックでサブタイトルを付ける）", () => {
    test("話数の読める話", async () => {
      disk.set(diskPath("本文", "003.txt"), encoder.encode("【タイトル】\n湖畔の誓い\n\n【本文（1行）】\n本文です。"));
      await seedRecords("003.txt", 3);
      window.showWarningMessage = (async () => "変える") as typeof window.showWarningMessage;

      await renameWithSubtitle(work, episodeFile("003.txt", 3));

      expect(disk.has(diskPath("本文", "003_湖畔の誓い.txt"))).toBe(true);
      expect(await followed("003_湖畔の誓い.txt", 3)).toEqual({ synopsis: true, reading: true });
    });

    test("話数の読めない話", async () => {
      disk.set(diskPath("本文", "幕間.txt"), encoder.encode("【タイトル】\n湖畔の誓い\n\n【本文（1行）】\n本文です。"));
      await seedRecords("幕間.txt", null);
      window.showWarningMessage = (async () => "変える") as typeof window.showWarningMessage;

      await renameWithSubtitle(work, episodeFile("幕間.txt", null));

      const renamed = [...disk.keys()]
        .filter((key) => key.startsWith(diskPath("本文")) && key.endsWith(".txt"))
        .map((key) => path.basename(key));
      expect(renamed).toHaveLength(1);
      expect(renamed[0]).not.toBe("幕間.txt");
      expect(await followed(renamed[0], null)).toEqual({ synopsis: true, reading: true });
    });
  });

  describe("製品の中の改名（本文の .md 化）", () => {
    test("話数の読めない話", async () => {
      disk.set(diskPath("本文", "幕間.txt"), encoder.encode("本文です。"));
      await seedRecords("幕間.txt", null);
      setEpisodeRenameWorkLookup(() => work);

      await convertOne(diskPath("本文", "幕間.txt"));

      expect(disk.has(diskPath("本文", "幕間.md"))).toBe(true);
      expect(await followed("幕間.md", null)).toEqual({ synopsis: true, reading: true });
      // 古い名前の辞書は残さない（同じ名前の話を後で作ったとき、別の話の読みが効かない）
      expect(disk.has(readingDictionaryPath(work, diskPath("本文", "幕間.txt")))).toBe(false);
    });

    test("話数の読める話", async () => {
      disk.set(diskPath("本文", "003.txt"), encoder.encode("本文です。"));
      await seedRecords("003.txt", 3);
      setEpisodeRenameWorkLookup(() => work);

      await convertOne(diskPath("本文", "003.txt"));

      expect(await followed("003.md", 3)).toEqual({ synopsis: true, reading: true });
    });
  });

  describe("エクスプローラーでの改名", () => {
    test("話数の読めない話", async () => {
      await seedRecords("幕間.txt", null);
      disk.set(diskPath("本文", "幕間 湖畔.txt"), encoder.encode("本文です。"));

      const outcomes = await followExplorerRenames(
        [{ fromPath: diskPath("本文", "幕間.txt"), toPath: diskPath("本文", "幕間 湖畔.txt") }],
        lookup
      );

      expect(await followed("幕間 湖畔.txt", null)).toEqual({ synopsis: true, reading: true });
      expect(outcomes[0]?.notice?.text).toContain("各話あらすじ1件");
      expect(outcomes[0]?.notice?.text).toContain("読みの辞書1件");
    });

    test("話数の読める話", async () => {
      await seedRecords("003.txt", 3);
      disk.set(diskPath("本文", "003_湖畔の誓い.txt"), encoder.encode("本文です。"));

      await followExplorerRenames(
        [{ fromPath: diskPath("本文", "003.txt"), toPath: diskPath("本文", "003_湖畔の誓い.txt") }],
        lookup
      );

      expect(await followed("003_湖畔の誓い.txt", 3)).toEqual({ synopsis: true, reading: true });
    });
  });

  describe("開いたときに訊いて付け替える（OS・git pull での改名）", () => {
    test("話数の読める話（投稿状態に載っている）", async () => {
      await seedRecords("003.txt", 3);
      const posting = new PostingStore(work);
      await posting.save({
        ...(await posting.load()),
        posts: [{ episodePath: "本文/003.txt", site: "kakuyomu", postedAt: "2026-11-01T00:00:00.000Z" }],
      });
      // OS で名前を変えた（辞書もあらすじも旧名のまま）
      disk.set(diskPath("本文", "003_湖畔の誓い.txt"), encoder.encode("本文です。"));
      window.showInformationMessage = (async () => "付け替える") as typeof window.showInformationMessage;

      await new RenameDriftChecker({
        memento: { get: <T>(_key: string, fallback: T) => fallback, update: async () => undefined },
        listEpisodePaths: async () => [diskPath("本文", "003_湖畔の誓い.txt")],
      }).checkOnOpen(work);

      expect(await followed("003_湖畔の誓い.txt", 3)).toEqual({ synopsis: true, reading: true });
    });
  });

  describe("付け替えの中身", () => {
    test("新しい名前に別の辞書があれば上書きせず、警告に回す", async () => {
      await seedRecords("幕間.txt", null);
      // 新しい名前の話にも、作者が直した辞書がある
      const target = diskPath("本文", "幕間 湖畔.txt");
      const other = await loadReadingDictionary(work, target);
      await saveReadingDictionary(
        work,
        target,
        { ...other.file, entries: [{ word: "湖畔", quote: "湖畔の", reading: "こはん", source: "author" }] },
        other.hash
      );

      const summary = await followEpisodeFileRenames(work, [
        { fromPath: diskPath("本文", "幕間.txt"), toPath: target },
      ]);

      expect(summary.readingDictionaries).toBe(0);
      expect(summary.failures.some((failure) => failure.startsWith("読みの辞書"))).toBe(true);
      // どちらの辞書も消えていない
      expect((await loadReadingDictionary(work, target)).file.entries[0].reading).toBe("こはん");
      expect(
        (await loadReadingDictionary(work, diskPath("本文", "幕間.txt"))).file.entries[0].reading
      ).toBe("じっぷん");
    });

    test("話数のあるあらすじは、同じ名前でも名前の付け替えに巻き込まない", async () => {
      // 番外編フォルダーの「幕間.txt」と同じ名前でも、話数で引く行は名前で動かさない
      const store = new SynopsisStore(work);
      await store.save({ ...(await store.load()), episodes: [synopsisRow("幕間.txt", 7)] });

      const summary = await followEpisodeFileRenames(work, [
        { fromPath: diskPath("本文", "幕間.txt"), toPath: diskPath("本文", "幕間 湖畔.txt") },
      ]);

      expect(summary.synopses).toBe(0);
      expect((await store.load()).episodes[0].fileName).toBe("幕間.txt");
    });

    test("知らせの文言に「各話あらすじN件」「読みの辞書N件」が入る", () => {
      const text = describeLedgerFollowSummary({
        ...emptyLedgerFollowSummary(),
        synopses: 1,
        readingDictionaries: 2,
      });
      expect(text).toBe("各話あらすじ1件・読みの辞書2件を付け替えました。");
    });
  });

  /** 1話ぶんの辞書を置く（読みで見分ける） */
  async function seedDictionary(rel: string, reading: string): Promise<void> {
    const episodePath = diskPath(...rel.split("/"));
    const loaded = await loadReadingDictionary(work, episodePath);
    await saveReadingDictionary(
      work,
      episodePath,
      { ...loaded.file, entries: [{ word: "十分", quote: "十分に", reading, source: "author" }] },
      loaded.hash
    );
  }

  async function readingOf(rel: string): Promise<string | undefined> {
    const loaded = await loadReadingDictionary(work, diskPath(...rel.split("/")));
    if (loaded.hash === undefined) return undefined;
    expect(loaded.file.episode).toBe(rel);
    return loaded.file.entries[0]?.reading;
  }

  function renumbered(fromName: string, toName: string, oldNumber: number, newNumber: number) {
    return {
      fromPath: diskPath("本文", fromName),
      toPath: diskPath("本文", toName),
      fromFileName: fromName,
      toFileName: toName,
      oldNumber,
      newNumber,
    };
  }

  describe("話数の付け替え（挿入・削除）でも、読みの辞書がついてくる", () => {
    test("挿入：後ろの話から順に1つずつずれ、辞書も同じ話についていく", async () => {
      await seedDictionary("本文/003.txt", "さん");
      await seedDictionary("本文/004.txt", "よん");

      // 付け替えは後ろから（行き先が空いている順）。`done` はその順のまま渡ってくる
      const summary = await followEpisodeLedgers(work, [
        renumbered("004.txt", "005.txt", 4, 5),
        renumbered("003.txt", "004.txt", 3, 4),
      ]);

      expect(await readingOf("本文/004.txt")).toBe("さん");
      expect(await readingOf("本文/005.txt")).toBe("よん");
      expect(await readingOf("本文/003.txt")).toBeUndefined();
      expect(summary.readingDictionaries).toBe(2);
      expect(summary.failures).toEqual([]);
    });

    test("削除：消えた話の辞書は次の話へ渡さず控えに残し、残っていることを知らせる", async () => {
      await seedDictionary("本文/003.txt", "さん");
      await seedDictionary("本文/004.txt", "よん");
      await seedDictionary("本文/005.txt", "ご");

      const summary = await followEpisodeLedgers(
        work,
        [renumbered("004.txt", "003.txt", 4, 3), renumbered("005.txt", "004.txt", 5, 4)],
        { filePath: diskPath("本文", "003.txt"), number: 3 }
      );

      // 消えた話の読みが、詰めて同じ名前になった別の話に効かない
      expect(await readingOf("本文/003.txt")).toBe("よん");
      expect(await readingOf("本文/004.txt")).toBe("ご");
      expect(summary.readingDictionaries).toBe(2);
      expect(summary.readingDictionariesOrphaned).toBe(1);
      expect(summary.failures).toEqual([]);
      // 消えた話の辞書は消さない（中身ごと控えに残る）
      const kept = [...disk.entries()].filter(([key]) => key.includes(".removed"));
      expect(kept).toHaveLength(1);
      expect(new TextDecoder().decode(kept[0][1])).toContain("さん");
      expect(describeLedgerFollowSummary(summary)).toContain("消えた話の読みの辞書が1件残っています");
    });

    test("削除：最後の話を消したときは、辞書をその場に残して知らせる", async () => {
      await seedDictionary("本文/005.txt", "ご");

      const summary = await followEpisodeLedgers(work, [], {
        filePath: diskPath("本文", "005.txt"),
        number: 5,
      });

      expect(await readingOf("本文/005.txt")).toBe("ご");
      expect(summary.readingDictionariesOrphaned).toBe(1);
    });
  });

  describe("エクスプローラーで章フォルダーの名前を変えたとき", () => {
    test("4つの台帳に載っていない話でも、読みの辞書と話数の無い話のあらすじがついてくる", async () => {
      await seedDictionary("本文/第一章/003.txt", "さん");
      await seedDictionary("本文/第一章/幕間.txt", "まくあい");
      const store = new SynopsisStore(work);
      await store.save({ ...(await store.load()), episodes: [synopsisRow("幕間.txt", null)] });
      // 別のフォルダーの辞書は巻き込まない
      await seedDictionary("本文/第二章/004.txt", "よん");

      const outcomes = await followExplorerRenames(
        [{ fromPath: diskPath("本文", "第一章"), toPath: diskPath("本文", "第一章 旅立ち") }],
        lookup
      );

      expect(await readingOf("本文/第一章 旅立ち/003.txt")).toBe("さん");
      expect(await readingOf("本文/第一章 旅立ち/幕間.txt")).toBe("まくあい");
      expect(await readingOf("本文/第二章/004.txt")).toBe("よん");
      // あらすじは名前（フォルダーを含まない）で引くので、フォルダーの改名では変わらずに引ける
      const set = await store.load();
      expect(findSynopsis(set, "幕間.txt", null)?.authorNotes).toBe("作者のメモ");
      expect(outcomes[0]?.notice?.text).toContain("読みの辞書2件");
    });
  });
});
