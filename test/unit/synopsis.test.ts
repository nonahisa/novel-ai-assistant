import { describe, expect, test } from "vitest";
import {
  parseSynopsisResult,
  validateSynopsisResult,
} from "../../src/core/synopsisValidation";
import {
  dedupeSynopsisEpisodes,
  emptySynopsisSet,
  findSynopsis,
  parseSynopsisSet,
  upsertSynopsis,
  type ChapterSynopsis,
} from "../../src/models/synopsis";
import { buildSynopsisPrompt } from "../../src/prompts/synopsis";

function episode(overrides: Partial<ChapterSynopsis> = {}): ChapterSynopsis {
  return {
    chapter: 1,
    fileName: "001.txt",
    title: null,
    synopsis: "灯が幽霊になったことに気づく。",
    sourceHash: "hash1",
    model: "test",
    promptVersion: "1.0",
    autoGenerated: true,
    authorNotes: "",
    updatedAt: null,
    ...overrides,
  };
}

describe("あらすじの応答を読む", () => {
  test("コードフェンス付きでも読める", () => {
    const result = parseSynopsisResult(
      '```json\n{"synopsis":"灯が転生する。","subtitles":[],"confidence":"high"}\n```'
    );

    expect(result?.synopsis).toBe("灯が転生する。");
  });

  test("形が違えば null を返す（壊れた値を保存しない）", () => {
    expect(parseSynopsisResult("こんにちは")).toBeNull();
    expect(parseSynopsisResult('{"subtitles":[]}')).toBeNull();
  });
});

describe("サブタイトル案の検証", () => {
  const build = (texts: string[]) => ({
    synopsis: "灯が転生する。",
    subtitles: texts.map((text) => ({ text, kind: "出来事型", reason: null })),
    confidence: "high",
  });

  test("15字を超える案は落とす（切り詰めない）", () => {
    // 途中で切れた言葉はサブタイトルにならない
    const result = validateSynopsisResult(
      build(["湖畔の誓い", "あまりにも長すぎて到底入りきらないサブタイトルの案"])
    );

    expect(result.subtitles.map((s) => s.text)).toEqual(["湖畔の誓い"]);
    expect(result.rejectedSubtitles[0].reason).toBe("too_long");
  });

  test("ファイル名に使えない文字を含む案は落とす", () => {
    // そのままファイル名になるので、通すと作者の原稿ファイルが壊れる
    const result = validateSynopsisResult(build(["再会/別離", "再会と別離"]));

    expect(result.subtitles.map((s) => s.text)).toEqual(["再会と別離"]);
    expect(result.rejectedSubtitles[0].reason).toBe("forbidden_char");
  });

  test("同じ案が重なったら1つにする", () => {
    const result = validateSynopsisResult(build(["湖畔の誓い", "湖畔の誓い"]));

    expect(result.subtitles).toHaveLength(1);
    expect(result.rejectedSubtitles[0].reason).toBe("duplicate");
  });

  test("あらすじは150字に収める", () => {
    const result = validateSynopsisResult({
      synopsis: "あ".repeat(300),
      subtitles: [],
      confidence: "high",
    });

    expect(result.synopsis.length).toBeLessThanOrEqual(150);
  });
});

describe("あらすじの保存", () => {
  test("同じ話は差し替え、話数の順に並べる", () => {
    const first = upsertSynopsis(emptySynopsisSet(), episode({ chapter: 3 }));
    const second = upsertSynopsis(first.set, episode({ chapter: 1 }));
    const third = upsertSynopsis(
      second.set,
      episode({ chapter: 3, synopsis: "書き直し" })
    );

    expect(third.set.episodes.map((e) => e.chapter)).toEqual([1, 3]);
    expect(findSynopsis(third.set, "001.txt", 3)?.synopsis).toBe("書き直し");
  });

  test("作者が書き直したあらすじは上書きしない", () => {
    const authored = upsertSynopsis(
      emptySynopsisSet(),
      episode({ synopsis: "作者が書いたあらすじ", autoGenerated: false })
    );

    const result = upsertSynopsis(
      authored.set,
      episode({ synopsis: "AIが作ったあらすじ" })
    );

    expect(result.set.episodes[0].synopsis).toBe("作者が書いたあらすじ");
    expect(result.skippedByAuthor).toBe(true);
  });

  test("作者のメモは生成で消えない", () => {
    const withNote = upsertSynopsis(
      emptySynopsisSet(),
      episode({ authorNotes: "この話は伏線" })
    );

    const result = upsertSynopsis(
      withNote.set,
      episode({ synopsis: "作り直し" })
    );

    expect(result.set.episodes[0].authorNotes).toBe("この話は伏線");
    expect(result.set.episodes[0].synopsis).toBe("作り直し");
  });

  test("合本のように同じファイル名で話数が違うものを区別する", () => {
    const first = upsertSynopsis(
      emptySynopsisSet(),
      episode({ fileName: "N2600GO.txt", chapter: 1 })
    );
    const second = upsertSynopsis(
      first.set,
      episode({ fileName: "N2600GO.txt", chapter: 2, synopsis: "2話" })
    );

    expect(second.set.episodes).toHaveLength(2);
  });

  test("サブタイトル提案でファイル名が変わっても、同じ話数なら差し替える（二重登録の防止）", () => {
    // サブタイトル提案でのリネーム（generateSynopses.ts の proposeSubtitles）で
    // ファイル名が変わったあとも、同じ話数なら別の話として増えてはいけない
    // （実機で「第17話」が無題版・サブタイトル付き版の2つ表示された不具合、2026-08-13）
    const first = upsertSynopsis(
      emptySynopsisSet(),
      episode({ fileName: "017.txt", chapter: 17, title: null })
    );
    const second = upsertSynopsis(
      first.set,
      episode({
        fileName: "017_狐霊の進化と呪詛の謎.txt",
        chapter: 17,
        title: "狐霊の進化と呪詛の謎",
        synopsis: "リネーム後のあらすじ",
      })
    );

    expect(second.set.episodes).toHaveLength(1);
    expect(second.set.episodes[0].synopsis).toBe("リネーム後のあらすじ");
  });
});

describe("重複エントリの統合", () => {
  test("重複が無ければ何もしない", () => {
    const result = dedupeSynopsisEpisodes([
      episode({ chapter: 1 }),
      episode({ chapter: 2 }),
    ]);
    expect(result.removed).toBe(0);
    expect(result.episodes).toHaveLength(2);
  });

  test("同じ話数の重複は1つにまとめる。作者が書いたものを優先する", () => {
    const result = dedupeSynopsisEpisodes([
      episode({
        chapter: 17,
        fileName: "017.txt",
        synopsis: "AIが作った版",
        autoGenerated: true,
      }),
      episode({
        chapter: 17,
        fileName: "017_狐霊の進化と呪詛の謎.txt",
        synopsis: "作者が書き直した版",
        autoGenerated: false,
      }),
    ]);

    expect(result.removed).toBe(1);
    expect(result.episodes).toHaveLength(1);
    expect(result.episodes[0].synopsis).toBe("作者が書き直した版");
  });

  test("更新日時が同点（未設定同士）なら、後にあるほう（＝リネーム後）を残す", () => {
    const result = dedupeSynopsisEpisodes([
      episode({ chapter: 17, fileName: "017.txt", synopsis: "旧", updatedAt: null }),
      episode({
        chapter: 17,
        fileName: "017_後.txt",
        synopsis: "新",
        updatedAt: null,
      }),
    ]);

    expect(result.episodes[0].synopsis).toBe("新");
  });

  test("負けた側にしか無いメモは引き継ぐ", () => {
    const result = dedupeSynopsisEpisodes([
      episode({
        chapter: 17,
        fileName: "017.txt",
        authorNotes: "",
        updatedAt: "2026-08-13T09:00:00.000Z",
      }),
      episode({
        chapter: 17,
        fileName: "017_後.txt",
        authorNotes: "伏線を回収する回",
        updatedAt: "2026-08-13T08:00:00.000Z",
      }),
    ]);

    expect(result.episodes).toHaveLength(1);
    expect(result.episodes[0].authorNotes).toBe("伏線を回収する回");
  });
});

describe("あらすじJSONの検証", () => {
  test("壊れていたら例外にする（空として上書きしない）", () => {
    expect(() => parseSynopsisSet({ episodes: [] })).toThrow("schemaVersion");
    expect(() =>
      parseSynopsisSet({ schemaVersion: "0.1", episodes: [{ fileName: "a" }] })
    ).toThrow("synopsis");
  });

  test("欠けている任意項目は既定値で補う", () => {
    const set = parseSynopsisSet({
      schemaVersion: "0.1",
      episodes: [{ fileName: "001.txt", synopsis: "あらすじ" }],
    });

    expect(set.episodes[0]).toMatchObject({
      chapter: null,
      autoGenerated: true,
      authorNotes: "",
    });
  });
});

describe("あらすじのプロンプト", () => {
  test("サブタイトルが要らないときは空配列を求める", () => {
    const prompt = buildSynopsisPrompt({
      chapterLabel: "第7話",
      chapterText: "本文",
      previousSynopses: [],
      characterNames: [],
      needsSubtitle: false,
    });

    expect(prompt).toContain("subtitles は空配列");
    expect(prompt).not.toContain("3案提案してください");
  });

  test("前話のあらすじから出来事を持ち込ませない", () => {
    const prompt = buildSynopsisPrompt({
      chapterLabel: "第7話",
      chapterText: "本文",
      previousSynopses: ["第6話のあらすじ"],
      characterNames: ["灯"],
      needsSubtitle: true,
    });

    expect(prompt).toContain("ここから出来事を持ち込まないこと");
    expect(prompt).toContain("第6話のあらすじ");
  });
});
