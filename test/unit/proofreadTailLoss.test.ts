import { describe, expect, it } from "vitest";
import { dropsOriginalTail } from "../../src/core/proofreadValidation";

/**
 * **推敲は原文まるごとを置き換える**（設計書6.60）。だから修正案は、
 * 直した箇所だけでなく原文と同じ範囲を覆っていなければならない。
 *
 * 作者の報告（2026-09-01、実データ）——原文「悶絶しながらしながら沼ワニに
 * 近づくと、槍は中ほどからぽっきり折れていた。」に対して、修正案が
 * 「悶絶しながら」だけ返ってきた。指摘（「しながら」の重複）は正しいが、
 * 押すと**一文が6文字になる**。沼ワニも槍も消える。
 */
describe("原文のうしろを落とした修正案", () => {
  const 原文 =
    "悶絶しながらしながら沼ワニに近づくと、槍は中ほどからぽっきり折れていた。";

  it("直した断片だけを返してきたら、見分ける", () => {
    expect(dropsOriginalTail(原文, "悶絶しながら")).toBe(true);
  });

  it("原文と同じ範囲を覆っていれば、通す", () => {
    // 重複を削っただけで、沼ワニも槍も残っている正しい修正案
    expect(
      dropsOriginalTail(
        原文,
        "悶絶しながら沼ワニに近づくと、槍は中ほどからぽっきり折れていた。"
      )
    ).toBe(false);
  });

  it("語尾を変えただけの修正案は、対象にしない", () => {
    // **長さがほぼ変わらないものは見ない。** ここを見ると、
    // 文末を直すまっとうな修正案まで弾いてしまう
    expect(
      dropsOriginalTail("彼は静かに頷いたのであった。", "彼は静かに頷いた。")
    ).toBe(false);
  });

  it("修正案が空なら、もともと「直し方は作者に委ねる」指摘である", () => {
    expect(dropsOriginalTail(原文, "")).toBe(false);
  });

  it("空白や改行の違いでは判定を変えない", () => {
    expect(
      dropsOriginalTail(
        "悶絶しながら 沼ワニに 近づくと、槍は 折れていた。",
        "悶絶しながら沼ワニに近づくと、槍は折れていた。"
      )
    ).toBe(false);
  });
});
