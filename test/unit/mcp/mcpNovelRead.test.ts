  write(folder, ".aiwriter/config.json", {
    schemaVersion: "1",
    workTitle: name,
    manuscriptDir: "本文",
    settingsDir: "設定",
    createdAt: "2026-01-01T00:00:00.000Z",
  });
  if (options.allow) {
    write(folder, ".aiwriter/external-access.json", {
      schemaVersion: "2",
      clients: [{ name: "claude-code", tools: options.allow, sampling: false, decidedAt: "" }],
    });
  }

  write(folder, "本文/001_灯.txt", "　港の灯が消えた夜、少年は防波堤の先に立っていた。\n　父はまだ帰らない。\n");
