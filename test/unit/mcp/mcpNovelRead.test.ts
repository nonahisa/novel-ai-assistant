/** 作品フォルダーの中身（場所と中身）。何も書いていないことを確かめる */
function snapshot(folder: string): Record<string, string> {
  const result: Record<string, string> = {};
  const walk = (dir: string): void => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = nodePath.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else result[nodePath.relative(folder, full)] = fs.readFileSync(full, "utf8");
    }
  };
  walk(folder);
  return result;
}

beforeEach(() => {
  library = fs.mkdtempSync(nodePath.join(os.tmpdir(), "novelai-read-mcp-"));
  setExternalClientName("claude-code");
});

afterEach(() => {
  fs.rmSync(library, { recursive: true, force: true });
  setExternalClientName("");
});

describe("novel.read——登録と許可", () => {
  test("転送層に名前を渡して登録してある", () => {
    expect(server).toContain('registerTool(\n  "novel.read"');
    expect(server).toContain('tool("novel.read"');
  });

  test("記録の重さは抜粋（設定資料の引用・最新話の末尾が渡る）", () => {
    expect(exposureOf("novel.read", { folder: "x", kind: "settings" })).toBe("excerpt");
    expect(exposureOf("novel.read", { folder: "x", kind: "resume" })).toBe("excerpt");
  });

  test("記録には何を読んだかだけを残し、引いた語は残さない", () => {
    const folder = makeWork("記録", { allow: ["novel.read"] });
    recordExternalAccess({
      tool: "novel.read",
      args: { folder, kind: "settings", term: "筋の書かれた語", recordKind: "location" },
      ok: true,
      result: {},
    });
    recordExternalAccess({ tool: "novel.read", args: { folder, kind: "chronicle" }, ok: true, result: {} });
    const log = fs.readFileSync(nodePath.join(folder, ".aiwriter", "history", "external.jsonl"), "utf8");
    expect(log).toContain("設定資料を読んだ（場所）");
    expect(log).toContain("年表を読んだ");
    expect(log).not.toContain("筋の書かれた語");
  });

  test("印が無い作品は断る（既定は拒否）", () => {
    const folder = makeWork("印なし");
    expect(() =>
      assertExternalAccessAllowed({ folder, kind: "settings" }, "novel.read")
    ).toThrow();
  });

  test("ほかの道具だけを許した作品は断る", () => {
    const folder = makeWork("走査だけ", { allow: ["novel.scan"] });
    expect(() =>
      assertExternalAccessAllowed({ folder, kind: "settings" }, "novel.read")
    ).toThrow();
  });

  test("novel.read を許した作品は、どの kind でも通る", () => {
    const folder = makeWork("読む口", { allow: ["novel.read"] });
    for (const kind of ["settings", "resume", "foreshadows", "chronicle", "relations", "locations"]) {
      expect(() => assertExternalAccessAllowed({ folder, kind }, "novel.read")).not.toThrow();
    }
  });

  test("\"*\" は novel.read も覆う（作者の裁定 2026-10-16 の2）", () => {
    const folder = makeWork("全部", { allow: ["*"] });
    expect(() =>
      assertExternalAccessAllowed({ folder, kind: "chronicle" }, "novel.read")
    ).not.toThrow();
  });
});

describe("novel.read——中身", () => {
  test("settings：語を渡さなければ、種類ごとの名前と短い紹介だけを返す", () => {
    const folder = makeWork("設定");
    const result = novelRead({ folder, kind: "settings" });
    if (result.kind !== "settings") throw new Error(result.kind);
    const names = result.records.map((record) => `${record.recordKind}:${record.name}`);
    expect(names).toEqual([
      "character:灯野・ハルト",
      "character:灯野・ソウ",
      "location:港町",
      "location:防波堤",
    ]);
    // 語で引いていないときは記録の全体を返さない（一覧が太るため）
    expect(result.records[0].record).toBeUndefined();
    expect(result.records[0].summary).toContain("港町で父の船を待っている");
  });

  test("settings：語で引くと、別名・名前の片方でも当たり、記録の全体を返す", () => {
    const folder = makeWork("語で引く");
    const byAlias = novelRead({ folder, kind: "settings", term: "灯の子" });
    if (byAlias.kind !== "settings") throw new Error(byAlias.kind);
    expect(byAlias.records.map((record) => record.id)).toEqual(["char_0001"]);
    expect(byAlias.records[0].record).toMatchObject({ id: "char_0001", name: "灯野・ハルト" });

    // 中黒で区切った名前の片方（本文での呼び方）でも引ける
    const byPart = novelRead({ folder, kind: "settings", term: "ハルト" });
    if (byPart.kind !== "settings") throw new Error(byPart.kind);
    expect(byPart.records.map((record) => record.id)).toEqual(["char_0001"]);
  });

  test("settings：recordKind で種類を絞る", () => {
    const folder = makeWork("絞る");
    const result = novelRead({ folder, kind: "settings", recordKind: "location" });
    if (result.kind !== "settings") throw new Error(result.kind);
    expect(result.records.map((record) => record.id)).toEqual(["loc_0001", "loc_0002"]);
  });

  test("settings：壊れた記録は直さず、読めなかったファイルとして返す", () => {
    const folder = makeWork("壊れた記録");
    write(folder, "設定/characters/char_0003.json", "{ 壊れている");
    const before = fs.readFileSync(nodePath.join(folder, "設定/characters/char_0003.json"), "utf8");
    const result = novelRead({ folder, kind: "settings" });
    if (result.kind !== "settings") throw new Error(result.kind);
    expect(result.unreadableFiles).toEqual(["設定/characters/char_0003.json"]);
    expect(fs.readFileSync(nodePath.join(folder, "設定/characters/char_0003.json"), "utf8")).toBe(before);
  });

  test("resume：製品と同じ1枚（最新話の末尾・前話までのあらすじ・未回収の伏線・メモ・単話プロット）", () => {
    const folder = makeWork("再開");
    const result = novelRead({ folder, kind: "resume" });
    if (result.kind !== "resume") throw new Error(result.kind);
    expect(result.markdown).toContain("# 執筆再開：再開");
    expect(result.markdown).toContain("父の字を指でなぞった");
    expect(result.markdown).toContain("少年が防波堤で父の船を待つ。");
    expect(result.markdown).toContain("帰らない父の船");
    expect(result.markdown).toContain("母の名前を決める");
    expect(result.markdown).toContain("便りを読む。");
    expect(result.markdown).toContain("少年が父の帰りを待ち");
    // MCP で出さない節は、黙って落とさず理由を返す
    expect(result.omitted.map((entry) => entry.section)).toEqual(
      expect.arrayContaining(["todayGoal", "relatedScenes"])
    );
  });

  test("foreshadows：台帳の記録と、製品と同じ一覧の文書", () => {
    const folder = makeWork("伏線");
    const result = novelRead({ folder, kind: "foreshadows" });
    if (result.kind !== "foreshadows") throw new Error(result.kind);
    expect(result.records.map((record) => record.id)).toEqual(["foreshadow_0001"]);
    expect(result.markdown).toContain("帰らない父の船");
  });

  test("chronicle：話ごとの行（あらすじ・登場人物）を、作品フォルダーからの相対で返す", () => {
    const folder = makeWork("年表");
    const result = novelRead({ folder, kind: "chronicle" });
    if (result.kind !== "chronicle") throw new Error(result.kind);
    expect(result.rows.map((row) => row.chapter)).toEqual([1, 2, 3]);
    expect(result.rows[0].synopsis).toBe("少年が防波堤で父の船を待つ。");
    expect(result.rows[2].appeared.map((person) => person.name)).toContain("灯野・ソウ");
    expect(result.rows[0].workPath).toBe("本文/001_灯.txt");
    expect(result.markdown).toContain("# 年表");
    // 機械の中の絶対パスを外へ出さない
    expect(JSON.stringify(result)).not.toContain(library.replace(/\\/g, "\\\\"));
  });

  test("relations：人物どうしの関係", () => {
    const folder = makeWork("相関");
    const result = novelRead({ folder, kind: "relations" });
    if (result.kind !== "relations") throw new Error(result.kind);
    expect(result.graph.nodes.map((node) => node.name)).toEqual(
      expect.arrayContaining(["灯野・ハルト", "灯野・ソウ"])
    );
    expect(result.graph.edges.length).toBeGreaterThan(0);
  });

  test("locations：場所の略図の中身（点と線）", () => {
    const folder = makeWork("略図");
    const result = novelRead({ folder, kind: "locations" });
    if (result.kind !== "locations") throw new Error(result.kind);
    expect(result.sketch.points.map((point) => point.name)).toEqual(
      expect.arrayContaining(["港町", "防波堤"])
    );
    expect(result.sketch.lines.length).toBe(1);
  });

  test("どの kind も作品フォルダーに何も書かない", () => {
    const folder = makeWork("書かない");
    const before = snapshot(folder);
    for (const kind of ["settings", "resume", "foreshadows", "chronicle", "relations", "locations"] as const) {
      novelRead({ folder, kind });
    }
    expect(snapshot(folder)).toEqual(before);
  });
});
