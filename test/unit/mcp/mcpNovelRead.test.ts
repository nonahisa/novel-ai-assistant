/**
 * 投稿サイト用に変換した本文と題（棚卸しの8件目。2026-10-16）。製品の［投稿サイト用に
 * 変換してコピー］と同じ変換。**投稿はしない**（貼る文を返すだけ）。
 */
describe("novel.read——投稿サイト用（posting）", () => {
  function postingOf(input: Omit<Parameters<typeof novelRead>[0], "kind">) {
    const result = novelRead({ ...input, kind: "posting" });
    if (result.kind !== "posting") throw new Error(result.kind);
    return result;
  }

  test("サイトの記法に変換し、シーンメモを落とし、題を添える", () => {
    const folder = makeWork("投稿");
    // 原稿の記法は `{漢字|かんじ}`（ルビ）と `{{強調}}`（傍点）
    write(folder, "本文/004_灯台.txt", "　{灯台|とうだい}の明かりが{{揺れた}}。\n// メモ：ここで母を出す\n　少年は走った。\n");
    const result = postingOf({ folder, site: "narou", file: "本文/004_灯台.txt" });
    expect(result.siteLabel).toBe("小説家になろう");
    expect(result.title).toBe("灯台");
    expect(result.text).toContain("｜灯台《とうだい》");
    expect(result.text).not.toContain("{");
    expect(result.text).not.toContain("母を出す");
    expect(result.truncated).toBe(false);
    expect(result.next).toBeNull();
    expect(result.file).toBe("本文/004_灯台.txt");
  });

  test("note はルビを括弧書きにし、貼り付けで入らないものを知らせる", () => {
    const folder = makeWork("note");
    write(folder, "本文/004_灯台.md", "# 灯台の夜\n\n　{灯台|とうだい}の明かり。\n\n![灯台](images/lighthouse.png)\n");
    const result = postingOf({ folder, site: "note", file: "本文/004_灯台.md" });
    expect(result.text).toContain("灯台（とうだい）");
    // note の題名は先頭の見出し（本文欄へは入れない）
    expect(result.title).toBe("灯台の夜");
    expect(result.text).not.toContain("# 灯台の夜");
    expect(result.note?.images).toHaveLength(1);
    expect(result.notices.join("\n")).toContain("画像1枚");
  });

  test("site・file が無ければ名前を挙げて断る", () => {
    const folder = makeWork("引数なし");
    expect(() => postingOf({ folder, file: "本文/001_灯.txt" })).toThrow(/site/);
    expect(() => postingOf({ folder, site: "narou" })).toThrow(/file/);
  });

  test("本文のファイルでないもの・作品フォルダーの外は断る", () => {
    const folder = makeWork("本文以外");
    expect(() => postingOf({ folder, site: "narou", file: "設定/plot.md" })).toThrow(/本文のファイルではありません/);
    expect(() => postingOf({ folder, site: "narou", file: "../外.txt" })).toThrow();
  });

  test("競合の跡が残る話は変換しない", () => {
    const folder = makeWork("競合");
    write(folder, "本文/004_競合.txt", "<<<<<<< HEAD\n　こちら\n=======\n　あちら\n>>>>>>> other\n");
    expect(() => postingOf({ folder, site: "narou", file: "本文/004_競合.txt" })).toThrow(/競合/);
  });

  test("合本は collectedOrder で話を指す。指さなければ一覧を添えて断る", () => {
    const folder = makeWork("合本");
    const sep = (n: number) => `------------------------- エピソード${n}開始 -------------------------`;
    write(
      folder,
      "本文/合本.txt",
      [
        sep(1), "【エピソードタイトル】", "1話　出航", "", "【本文】", "　船が出た。", "",
        sep(2), "【エピソードタイトル】", "2話　嵐", "", "【本文】", "　嵐が来た。", "",
      ].join("\n")
    );
    expect(() => postingOf({ folder, site: "narou", file: "本文/合本.txt" })).toThrow(/collectedOrder.*2＝第2話「嵐」/);
    const second = postingOf({ folder, site: "narou", file: "本文/合本.txt", collectedOrder: 2 });
    expect(second.collectedOrder).toBe(2);
    expect(second.title).toBe("嵐");
    expect(second.text).toBe("　嵐が来た。");
    expect(() => postingOf({ folder, site: "narou", file: "本文/合本.txt", collectedOrder: 5 })).toThrow(/5 番目/);
  });

  test("長い話は行の境目で分けて返し、続きをたどると全文がそろう（上限を超えない）", () => {
    const folder = makeWork("長い話");
    const line = "　少年は防波堤の先で、潮の匂いを吸いこみながら父の船を待ちつづけた。";
    const lines = Array.from({ length: 600 }, (_, index) => `${line}${index + 1}`);
    write(folder, "本文/004_長い.txt", `${lines.join("\n")}\n`);

    const pages: string[] = [];
    let offset: number | undefined = undefined;
    for (let guard = 0; guard < 50; guard++) {
      const result = postingOf({ folder, site: "kakuyomu", file: "本文/004_長い.txt", offset });
      expect(estimateTokens(JSON.stringify(result, null, 2))).toBeLessThanOrEqual(READ_RESULT_TOKEN_BUDGET);
      pages.push(result.text);
      if (!result.next) break;
      expect(result.truncated).toBe(true);
      expect(result.notices.join("\n")).toContain(`offset: ${result.next.offset}`);
      offset = result.next.offset;
    }
    expect(pages.length).toBeGreaterThan(1);
    expect(pages.join("\n")).toBe(lines.join("\n"));
  });

  test("記録の重さは本文（1話をまるごと返すため）で、どの話かを残す", () => {
    expect(exposureOf("novel.read", { folder: "x", kind: "posting" })).toBe("body");
    const folder = makeWork("投稿の記録", { allow: ["novel.read"] });
    recordExternalAccess({
      tool: "novel.read",
      args: { folder, kind: "posting", site: "narou", file: "本文/001_灯.txt" },
      ok: true,
      result: {},
    });
    const log = fs.readFileSync(nodePath.join(folder, ".aiwriter", "history", "external.jsonl"), "utf8");
    expect(log).toContain('"file":"本文/001_灯.txt"');
    expect(log).toContain('"exposure":"body"');
    expect(log).toContain("投稿サイト用の本文を読んだ");
  });

  test("執筆量も投稿用も、作品フォルダーに何も書かない", () => {
    const folder = makeWork("書かない2");
    const before = snapshot(folder);
    novelRead({ folder, kind: "writingStats" });
    novelRead({ folder, kind: "posting", site: "note", file: "本文/001_灯.txt" });
    expect(snapshot(folder)).toEqual(before);
  });
});

/**
 * 予定の段（2026-10-16 の続き。設計書6.87.24）。`novel.propose kind: schedule` の
 * 案は段を id か名前で指すが、外部AIには段の id を読む口が無く、断りの文に並ぶ一覧を
 * 頼りにするしかなかった。読む口で id・名前・日数・期日・状態を返し、その id で案を置ける。
 */
describe("novel.read——予定の段（schedule）", () => {
  function writeSchedule(folder: string, schedules: unknown[]): void {
    write(folder, "設定/スケジュール.json", { schemaVersion: "1", schedules });
  }

  const contest = {
    id: "sch_1",
    kind: "contest",
    name: "灯台賞",
    followsGoals: false,
    milestone: "2026-12-31",
    targetChars: null,
    steps: [
      { id: "stp_w", key: "write", label: "執筆", days: 30, due: null, status: "doing", doneAt: null, note: "" },
      { id: "stp_r", key: "revise", label: "推敲", days: 10, due: "2026-12-20", status: "todo", doneAt: null, note: "" },
    ],
    serial: null,
    note: "",
    createdAt: "",
    updatedAt: "",
  };

  function scheduleOf(folder: string) {
    const result = novelRead({ folder, kind: "schedule" });
    if (result.kind !== "schedule") throw new Error(result.kind);
    return result;
  }

  test("道具の説明に schedule がある", () => {
    expect(server).toContain("schedule＝");
  });

  test("スケジュールごとに、段の id・名前・日数・期日・状態を返す", () => {
    const folder = makeWork("予定");
    writeSchedule(folder, [contest]);
    const result = scheduleOf(folder);
    expect(result.schedules).toHaveLength(1);
    const [schedule] = result.schedules;
    expect(schedule).toMatchObject({
      id: "sch_1",
      name: "灯台賞",
      scheduleKind: "contest",
      milestoneLabel: "締切",
      milestone: "2026-12-31",
      followsGoals: false,
    });
    expect(schedule.steps).toEqual([
      { id: "stp_w", label: "執筆", days: 30, due: null, status: "doing", statusLabel: "進行中", doneAt: null },
      { id: "stp_r", label: "推敲", days: 10, due: "2026-12-20", status: "todo", statusLabel: "未着手", doneAt: null },
    ]);
    expect(result.next).toBeNull();
    expect(result.unreadableFiles).toEqual([]);
  });

  test("読んだ id のまま novel.propose kind: schedule の案を置ける", () => {
    const folder = makeWork("予定と案", { allow: ["*"] });
    writeSchedule(folder, [contest]);
    const [schedule] = scheduleOf(folder).schedules;
    const placed = novelPropose({
      folder,
      kind: "schedule",
      ledger: { schedule: schedule.id, step: schedule.steps[1].id, days: 14 },
      reason: "推敲に余裕を持たせるため",
    });
    expect(placed.file).toMatch(/^\.aiwriter\/pending-ledger\/scheduleStep-[0-9a-f]+\.json$/);
  });

  test("作品目標設定に従う公募は、propose と同じ名前で返す（締切は目標から）", () => {
    const folder = makeWork("目標に従う");
    write(folder, ".aiwriter/goals.json", {
      schemaVersion: "0.1",
      perEpisodeChars: null,
      contest: { name: "短編賞", url: null, deadline: "2026-11-30", minChars: 10000, maxChars: null, dailyGoal: null },
    });
    writeSchedule(folder, [{ ...contest, id: "sch_goals", name: "", followsGoals: true, milestone: null }]);
    const [schedule] = scheduleOf(folder).schedules;
    expect(schedule.name).toBe("作品目標設定の応募先");
    expect(schedule.milestone).toBe("2026-11-30");
    expect(schedule.followsGoals).toBe(true);
  });

  test("目標の応募先があるのに、ファイルにまだ公募の行が無いときは、案を置けないことを断る", () => {
    const folder = makeWork("行が無い");
    write(folder, ".aiwriter/goals.json", {
      schemaVersion: "0.1",
      perEpisodeChars: null,
      contest: { name: "短編賞", url: null, deadline: "2026-11-30", minChars: 10000, maxChars: null, dailyGoal: null },
    });
    writeSchedule(folder, []);
    const result = scheduleOf(folder);
    expect(result.schedules).toEqual([]);
    expect(result.notices.join("")).toContain("一度段を直すまでファイルにありません");
  });

  test("スケジュールが無い作品は空で返し、作者が画面で作ることを断る", () => {
    const result = scheduleOf(makeWork("予定なし"));
    expect(result.schedules).toEqual([]);
    expect(result.file).toBeNull();
    expect(result.notices.join("")).toContain("スケジュールがまだありません");
  });

  test("壊れたスケジュールは直さず、読めなかったファイルとして返す", () => {
    const folder = makeWork("壊れた予定");
    write(folder, "設定/スケジュール.json", "{壊れている");
    const before = fs.readFileSync(nodePath.join(folder, "設定/スケジュール.json"), "utf8");
    const result = scheduleOf(folder);
    expect(result.schedules).toEqual([]);
    expect(result.unreadableFiles).toEqual(["設定/スケジュール.json"]);
    expect(fs.readFileSync(nodePath.join(folder, "設定/スケジュール.json"), "utf8")).toBe(before);
  });

  test("大きいときはスケジュールの境目で分け、続きをたどると全部が1回ずつ揃う（上限を超えない）", () => {
    const folder = makeWork("予定が多い");
    const many = Array.from({ length: 40 }, (_, index) => ({
      ...contest,
      id: `sch_${index}`,
      name: `賞${index}`,
      steps: Array.from({ length: 30 }, (_, step) => ({
        id: `stp_${index}_${step}`,
        key: "custom",
        label: `段${step}の長い名前${"あ".repeat(40)}`,
        days: 3,
        due: null,
        status: "todo",
        doneAt: null,
        note: "",
      })),
    }));
    writeSchedule(folder, many);
    const seen: string[] = [];
    let offset: number | undefined = 0;
    let rounds = 0;
    while (offset !== undefined && rounds < 100) {
      const page = novelRead({ folder, kind: "schedule", offset });
      if (page.kind !== "schedule") throw new Error(page.kind);
      expect(estimateTokens(JSON.stringify(page, null, 2))).toBeLessThanOrEqual(READ_RESULT_TOKEN_BUDGET);
      seen.push(...page.schedules.map((entry) => entry.id));
      offset = page.next?.offset;
      rounds++;
    }
    expect(rounds).toBeGreaterThan(1);
    expect(seen).toEqual(many.map((entry) => entry.id));
  });

  test("記録には予定を読んだことだけを残す。何も書かない", () => {
    const folder = makeWork("予定の記録", { allow: ["novel.read"] });
    writeSchedule(folder, [contest]);
    expect(() => assertExternalAccessAllowed({ folder, kind: "schedule" }, "novel.read")).not.toThrow();
    const before = snapshot(folder);
    novelRead({ folder, kind: "schedule" });
    expect(snapshot(folder)).toEqual(before);
    recordExternalAccess({ tool: "novel.read", args: { folder, kind: "schedule" }, ok: true, result: {} });
    const log = fs.readFileSync(nodePath.join(folder, ".aiwriter", "history", "external.jsonl"), "utf8");
    expect(log).toContain("予定の段を読んだ");
  });
});
