/**
 * 年表を、外部AIがそのまま読める大きさで返す（2026-10-16）。
 *
 * 確認用の作品（24話）へ撃ったら、年表だけ約2,000行（見積もり約4万トークン）を返し、
 * 呼び出し側（Claude Code）の上限を超えてファイルへ逃がされた。既定でも上限を超えず、
 * 省いた分と続きの取り方を返すことを見張る。**測るのは実際に届く形**
 * （`server.ts` の `ok()` と同じ `JSON.stringify(value, null, 2)`）。
 */
describe("novel.read——年表の返す量", () => {
  /** 話を40に増やし、各話あらすじを長くした作品（全部を返すと上限を超える大きさ） */
  function makeLongWork(name: string): string {
    const folder = makeWork(name);
    const episodes = [];
    for (let chapter = 1; chapter <= 40; chapter++) {
      const file = `${String(chapter).padStart(3, "0")}_話${chapter}.txt`;
      if (chapter > 3) write(folder, `本文/${file}`, `　第${chapter}話の本文。少年は港へ通った。\n`);
      episodes.push({
        chapter,
        fileName: chapter <= 3 ? ["001_灯.txt", "002_朝.txt", "003_便り.txt"][chapter - 1] : file,
        title: `話${chapter}`,
        // 和文は1字がほぼ1トークンになる。300字×40話で、あらすじだけで1万を超える
        synopsis: `第${chapter}話のあらすじ。` + "少年は防波堤で父の船を待ち、潮の匂いの中で夜を明かした。".repeat(10),
        sourceHash: "",
        model: null,
        promptVersion: null,
        autoGenerated: true,
        authorNotes: "",
        updatedAt: null,
      });
    }
    write(folder, "設定/chapter_synopses.json", { schemaVersion: "0.1", episodes });
    return folder;
  }

  function chronicleOf(input: Parameters<typeof novelRead>[0]) {
    const result = novelRead(input);
    if (result.kind !== "chronicle") throw new Error(result.kind);
    return result;
  }

  test("見積もり：和文は1字≈1トークン、ASCII は3字≈1トークン", () => {
    expect(estimateTokens("あ".repeat(100))).toBe(100);
    expect(estimateTokens("a".repeat(300))).toBe(100);
    expect(estimateTokens("")).toBe(0);
  });

  test("既定（引数なし）でも上限を超えず、省いた件数と続きの取り方を返す", () => {
    const folder = makeLongWork("長い年表");
    const result = chronicleOf({ folder, kind: "chronicle" });
    expect(estimateTokens(JSON.stringify(result, null, 2))).toBeLessThanOrEqual(READ_RESULT_TOKEN_BUDGET);
    expect(result.total).toBe(40);
    expect(result.truncated).toBe(true);
    expect(result.rows.length).toBeGreaterThan(0);
    expect(result.rows.length).toBeLessThan(40);
    expect(result.rows[0].chapter).toBe(1);
    expect(result.next).toEqual({ offset: result.rows.length });
    expect(result.notices.join("\n")).toContain(`offset: ${result.rows.length}`);
    // 文書も返す行だけで組む（全部の文書を返すと、行を絞っても同じ中身が二重に残る）
    expect(result.markdown).toContain("第1話のあらすじ");
    expect(result.markdown).not.toContain("第40話のあらすじ");
  });

  test("続き（offset）を順にたどると、全部の話が1回ずつ揃う", () => {
    const folder = makeLongWork("続き");
    const seen: Array<number | null> = [];
    let offset: number | undefined = undefined;
    for (let guard = 0; guard < 40; guard++) {
      const result = chronicleOf({ folder, kind: "chronicle", offset });
      expect(estimateTokens(JSON.stringify(result, null, 2))).toBeLessThanOrEqual(READ_RESULT_TOKEN_BUDGET);
      seen.push(...result.rows.map((row) => row.chapter));
      if (!result.next) {
        expect(result.truncated).toBe(false);
        break;
      }
      offset = result.next.offset;
    }
    expect(seen).toEqual(Array.from({ length: 40 }, (_, index) => index + 1));
  });

  test("話数の範囲（fromEpisode・toEpisode。両端を含む）で絞る", () => {
    const folder = makeLongWork("範囲");
    const result = chronicleOf({ folder, kind: "chronicle", fromEpisode: 5, toEpisode: 7 });
    expect(result.rows.map((row) => row.chapter)).toEqual([5, 6, 7]);
    expect(result.total).toBe(3);
    expect(result.truncated).toBe(false);
    expect(result.next).toBeNull();
  });

  test("範囲の始まりが終わりより後なら断る", () => {
    const folder = makeLongWork("逆さの範囲");
    expect(() => novelRead({ folder, kind: "chronicle", fromEpisode: 9, toEpisode: 3 })).toThrow(/fromEpisode/);
  });

  test("合本（1行が複数話）は、範囲と重なれば入れる", () => {
    const row = { chapter: 10, chapterEnd: 12 };
    expect(chronicleRowInRange(row, 12, 20)).toBe(true);
    expect(chronicleRowInRange(row, 1, 10)).toBe(true);
    expect(chronicleRowInRange(row, 13, 20)).toBe(false);
    expect(chronicleRowInRange(row, undefined, 9)).toBe(false);
    // 話数の分からない行は、範囲を指したときは入れない（どこに当たるか決められない）
    expect(chronicleRowInRange({ chapter: null, chapterEnd: null }, 1, 5)).toBe(false);
    expect(chronicleRowInRange({ chapter: null, chapterEnd: null }, undefined, undefined)).toBe(true);
  });

  test("語（term）で絞る：人物は名前の片方でも当たる", () => {
    const folder = makeLongWork("語");
    // 灯野・ソウは第3話にだけ登場する
    const byName = chronicleOf({ folder, kind: "chronicle", term: "ソウ" });
    expect(byName.rows.map((row) => row.chapter)).toEqual([3]);
    // あらすじ・題の文字にも当たる
    const byText = chronicleOf({ folder, kind: "chronicle", term: "第12話のあらすじ" });
    expect(byText.rows.map((row) => row.chapter)).toEqual([12]);
  });

  test("件数の上限（limit）", () => {
    const folder = makeLongWork("件数");
    const result = chronicleOf({ folder, kind: "chronicle", limit: 2 });
    expect(result.rows.map((row) => row.chapter)).toEqual([1, 2]);
    expect(result.next).toEqual({ offset: 2 });
  });

  test("小さな作品は全部を返し、続きの印は立てない", () => {
    const folder = makeWork("小さな年表");
    const result = chronicleOf({ folder, kind: "chronicle" });
    expect(result.rows.length).toBe(3);
    expect(result.truncated).toBe(false);
    expect(result.next).toBeNull();
  });
});

