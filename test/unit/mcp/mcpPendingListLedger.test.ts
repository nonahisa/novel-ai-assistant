/**
 * `pending.list` が外部AIの台帳の案（`.aiwriter/pending-ledger/`。設計書6.87.24）も返す。
 *
 * 外部AIは `novel.propose kind: chapter・foreshadow・schedule` で案を置けるが、置いた案が
 * まだ残っているか（作者が採った・見送った）を読む口が無かった。
 *
 * **見張ること**
 * 1. 置いた案が、種類（chapter・foreshadow・schedule）・置いた時刻・置いたときの値・
 *    どの台帳を指すかと一緒に返る。文は提案パネルと同じ（`describeLedgerProposal`）
 * 2. 壊れた案・ファイル名と id が食い違う案は直さず「読めなかった」と返す
 *    （パネルにも並ばないので、MCP だけ「ある」と言わない）
 * 3. 読むだけ（作品フォルダーを1バイトも変えない）
 * 4. 大きさの上限（`READ_RESULT_TOKEN_BUDGET`）を超えない。続きの印で残りが読める
 */

let library: string;

function write(folder: string, relative: string, value: unknown): void {
  const target = nodePath.join(folder, relative);
  fs.mkdirSync(nodePath.dirname(target), { recursive: true });
  fs.writeFileSync(target, typeof value === "string" ? value : JSON.stringify(value, null, 2));
}

function makeWork(name: string): string {
  const folder = nodePath.join(library, name);
  write(folder, ".aiwriter/config.json", { schemaVersion: "1", workTitle: name });
  write(folder, ".aiwriter/external-access.json", {
    clients: [{ name: "claude-code", tools: ["*"], sampling: false }],
  });
  write(folder, "本文/001_灯.txt", "　港の灯が消えた夜、少年は防波堤の先に立っていた。\n　父はまだ帰らない。\n");
  write(folder, "本文/002_朝.txt", "　朝が来た。\n　少年は窓を開けた。\n");
  write(folder, "設定/章立て.json", {
    schemaVersion: "1",
    chapters: [{ name: "第一章　灯", startEpisodePath: "本文/001_灯.txt" }],
  });
  write(folder, "設定/foreshadows/foreshadow_0001.json", {
    schemaVersion: "0.1",
    id: "foreshadow_0001",
    label: "帰らない父の船",
    note: "",
    plantedChapter: 1,
    plantedQuote: "父はまだ帰らない。",
    status: "open",
    resolvedChapter: null,
    resolvedQuote: "",
    source: "author",
    autoGenerated: false,
    authorNotes: "",
    createdAt: "2026-09-12T00:00:00.000Z",
    updatedAt: "2026-09-12T00:00:00.000Z",
  });
  write(folder, "設定/スケジュール.json", {
    schemaVersion: "1",
    schedules: [
      {
        id: "sch_1",
        kind: "contest",
        name: "灯台賞",
        followsGoals: false,
        milestone: "2026-12-31",
        targetChars: null,
        steps: [
          { id: "stp_w", key: "write", label: "執筆", days: 30, due: null, status: "doing", doneAt: null, note: "" },
        ],
        serial: null,
        note: "",
        createdAt: "",
        updatedAt: "",
      },
    ],
  });
  return folder;
}

/** 3種類の案を、製品の置く口（`novel.propose`）で置く */
function placeThree(folder: string): void {
  novelPropose({
    folder,
    kind: "chapter",
    reason: "第2話から朝の場面に変わるため。",
    ledger: { episodeFile: "本文/002_朝.txt", chapterName: "第二章　朝" },
  });
  novelPropose({
    folder,
    kind: "foreshadow",
    reason: "第1話で父の不在が示されているため。",
    ledger: { foreshadowId: "foreshadow_0001", status: "intentional" },
  });
  novelPropose({
    folder,
    kind: "schedule",
    reason: "執筆に時間がかかりそうなため。",
    ledger: { schedule: "sch_1", step: "stp_w", days: 40 },
  });
}

/** 作品フォルダー全体の指紋。1バイトでも変われば変わる */
function fingerprint(folder: string): string {
  const hash = createHash("sha256");
  const walk = (dir: string): void => {
    for (const name of fs.readdirSync(dir).sort()) {
      const full = nodePath.join(dir, name);
      if (fs.statSync(full).isDirectory()) {
        walk(full);
        continue;
      }
      hash.update(nodePath.relative(folder, full));
      hash.update(fs.readFileSync(full));
    }
  };
  walk(folder);
  return hash.digest("hex");
}

/** 手で1件置く（多数・壊れた案の試験用） */
function writeProposal(folder: string, id: string, overrides: Record<string, unknown> = {}): void {
  write(folder, `.aiwriter/pending-ledger/${id}.json`, {
    schemaVersion: "1",
    id,
    createdAt: "2026-10-16T00:00:00.000Z",
    source: "external",
    client: "claude-code",
    reason: "理由",
    proposal: {
      type: "foreshadowAdd",
      label: `伏線 ${id}`,
      note: "",
      plantedChapter: 1,
      plantedQuote: "",
    },
    ...overrides,
  });
}

beforeEach(() => {
  library = fs.mkdtempSync(nodePath.join(os.tmpdir(), "novelai-pending-ledger-"));
  setExternalClientName("claude-code");
});

afterEach(() => {
  fs.rmSync(library, { recursive: true, force: true });
  setExternalClientName("");
});

describe("台帳の案を返す", () => {
  test("置いた3種類が、種類・時刻・置いたときの値・指す台帳と一緒に返る", () => {
    const folder = makeWork("三種");
    placeThree(folder);

    const result = pendingList({ folder });
    const ledger = result.ledgerProposals;
    expect(ledger.total).toBe(3);
    expect(ledger.unreadable).toEqual([]);
    expect(ledger.truncated).toBe(false);
    expect(ledger.next).toBeNull();
    expect(ledger.items.map((item) => item.kind).sort()).toEqual(["chapter", "foreshadow", "schedule"]);

    const chapter = ledger.items.find((item) => item.kind === "chapter")!;
    expect(chapter.proposalType).toBe("chapter");
    expect(chapter.file).toMatch(/^\.aiwriter\/pending-ledger\/chapter-[0-9a-f]+\.json$/);
    expect(chapter.createdAt).toMatch(/^\d{4}-\d{2}-\d{2}T/);
    expect(chapter.client).toBe("claude-code");
    expect(chapter.source).toBe("external");
    expect(chapter.reason).toBe("第2話から朝の場面に変わるため。");
    expect(chapter.target).toEqual({ ledger: "設定/章立て.json", startEpisodePath: "本文/002_朝.txt" });
    expect(chapter.placed).toEqual({ currentName: null });
    expect(chapter.proposed).toEqual({ name: "第二章　朝" });

    const foreshadow = ledger.items.find((item) => item.kind === "foreshadow")!;
    expect(foreshadow.proposalType).toBe("foreshadowStatus");
    expect(foreshadow.target).toEqual({
      ledger: "設定/foreshadows/",
      foreshadowId: "foreshadow_0001",
    });
    expect(foreshadow.placed).toEqual({ status: "open" });
    expect(foreshadow.proposed).toMatchObject({ status: "intentional" });

    const schedule = ledger.items.find((item) => item.kind === "schedule")!;
    expect(schedule.proposalType).toBe("scheduleStep");
    expect(schedule.target).toEqual({
      ledger: "設定/スケジュール.json",
      scheduleId: "sch_1",
      stepId: "stp_w",
    });
    expect(schedule.placed).toEqual({ days: 30 });
    expect(schedule.proposed).toEqual({ days: 40 });

    // 文は提案パネルと同じ関数を通す（写しを作らない）
    for (const item of ledger.items) {
      const file = parseLedgerProposalFile(
        JSON.parse(fs.readFileSync(nodePath.join(folder, item.file), "utf8"))
      );
      const view = describeLedgerProposal(file);
      expect(item.name).toBe(view.name);
      expect(item.changes).toEqual(view.changes);
      expect(item.summary).toBe(view.summary);
    }
  });

  test("並びは置いた時刻の順（提案パネルと同じ）", () => {
    const folder = makeWork("並び");
    writeProposal(folder, "foreshadowAdd-00000000000000b2", { createdAt: "2026-10-16T02:00:00.000Z" });
    writeProposal(folder, "foreshadowAdd-00000000000000a1", { createdAt: "2026-10-16T03:00:00.000Z" });
    writeProposal(folder, "foreshadowAdd-00000000000000c3", { createdAt: "2026-10-16T01:00:00.000Z" });
    const ids = pendingList({ folder }).ledgerProposals.items.map((item) => item.id);
    expect(ids).toEqual([
      "foreshadowAdd-00000000000000c3",
      "foreshadowAdd-00000000000000b2",
      "foreshadowAdd-00000000000000a1",
    ]);
  });

  test("作者が採った・見送った（ファイルが消えた）案は返らない", () => {
    const folder = makeWork("消えた");
    placeThree(folder);
    const first = pendingList({ folder }).ledgerProposals.items[0];
    fs.rmSync(nodePath.join(folder, first.file));
    const after = pendingList({ folder }).ledgerProposals;
    expect(after.total).toBe(2);
    expect(after.items.map((item) => item.id)).not.toContain(first.id);
  });

  test("置き場が無ければ空（承認待ちの件数にも数えない）", () => {
    const folder = makeWork("空");
    const result = pendingList({ folder });
    expect(result.ledgerProposals).toMatchObject({ total: 0, items: [], unreadable: [], truncated: false, next: null });
    expect(result.total).toBe(0);
  });

  test("壊れた案と、ファイル名と id が食い違う案は直さず「読めなかった」と返す", () => {
    const folder = makeWork("壊れ");
    placeThree(folder);
    write(folder, ".aiwriter/pending-ledger/chapter-0123456789abcdef.json", "{壊れている");
    // 中身は正しいが、ファイル名と id が違う（パネルも並べない）
    writeProposal(folder, "foreshadowAdd-00000000000000aa", { id: "foreshadowAdd-00000000000000bb" });
    const before = fingerprint(folder);

    const ledger = pendingList({ folder }).ledgerProposals;
    expect(ledger.total).toBe(3);
    expect(ledger.items).toHaveLength(3);
    expect(ledger.unreadable.map((entry) => entry.file).sort()).toEqual([
      ".aiwriter/pending-ledger/chapter-0123456789abcdef.json",
      ".aiwriter/pending-ledger/foreshadowAdd-00000000000000aa.json",
    ]);
    for (const entry of ledger.unreadable) expect(entry.message).not.toBe("");
    // 直していない・消していない
    expect(fingerprint(folder)).toBe(before);
  });

  test("読むだけ：作品フォルダーを1バイトも変えない", () => {
    const folder = makeWork("読むだけ");
    placeThree(folder);
    const before = fingerprint(folder);
    pendingList({ folder });
    pendingList({ folder, kind: "schedule" });
    expect(fingerprint(folder)).toBe(before);
  });
});

describe("絞り方", () => {
  test("kind: chapter・foreshadow・schedule で、その種類の案だけ。設定資料の案は空", () => {
    const folder = makeWork("種類");
    placeThree(folder);
    for (const kind of ["chapter", "foreshadow", "schedule"] as const) {
      const result = pendingListTool({ folder, kind });
      if (!("ledgerProposals" in result)) throw new Error("台帳の案の欄がありません");
      expect(result.ledgerProposals.items.map((item) => item.kind)).toEqual([kind]);
      expect(result.ledgerProposals.total).toBe(1);
      expect(result.items).toEqual([]);
      expect(result.narratorMoves.items).toEqual([]);
    }
  });

  test("kind に設定資料の種類を渡すと台帳の案は返さない", () => {
    const folder = makeWork("人物");
    placeThree(folder);
    expect(pendingList({ folder, kind: "character" }).ledgerProposals.items).toEqual([]);
  });

  test("source: external なら返す。ほかの出どころなら返さない", () => {
    const folder = makeWork("出どころ");
    placeThree(folder);
    expect(pendingList({ folder, source: "external" }).ledgerProposals.items).toHaveLength(3);
    expect(pendingList({ folder, source: "chat" }).ledgerProposals.items).toEqual([]);
    expect(pendingList({ folder, source: "extraction" }).ledgerProposals.items).toEqual([]);
  });
});

describe("大きさの上限と続きの印", () => {
  test("多いときは上限の手前で切り、ledgerOffset で残りを読める", () => {
    const folder = makeWork("多い");
    const long = "長い理由の文。".repeat(150);
    const ids: string[] = [];
    for (let index = 0; index < 40; index++) {
      const id = `foreshadowAdd-${index.toString(16).padStart(16, "0")}`;
      ids.push(id);
      writeProposal(folder, id, {
        reason: long,
        createdAt: `2026-10-16T00:00:${String(index).padStart(2, "0")}.000Z`,
      });
    }

    const read: string[] = [];
    let offset: number | undefined;
    for (let round = 0; round < 40; round++) {
      const result = pendingList({ folder, ledgerOffset: offset });
      expect(estimateResultTokens(result)).toBeLessThanOrEqual(READ_RESULT_TOKEN_BUDGET);
      expect(result.ledgerProposals.total).toBe(40);
      expect(result.ledgerProposals.offset).toBe(offset ?? 0);
      read.push(...result.ledgerProposals.items.map((item) => item.id));
      if (!result.ledgerProposals.next) {
        expect(result.ledgerProposals.truncated).toBe(false);
        break;
      }
      expect(result.ledgerProposals.truncated).toBe(true);
      expect(result.ledgerProposals.notices.join("")).toContain(`ledgerOffset: ${result.ledgerProposals.next.ledgerOffset}`);
      offset = result.ledgerProposals.next.ledgerOffset;
    }
    expect(offset).toBeDefined();
    expect(read).toEqual(ids);
  });

  test("1件だけで上限を超えても、その1件は返す（同じ所で止まらない）", () => {
    const folder = makeWork("巨大");
    writeProposal(folder, "foreshadowAdd-0000000000000001", { reason: "巨".repeat(20_000) });
    writeProposal(folder, "foreshadowAdd-0000000000000002", { createdAt: "2026-10-17T00:00:00.000Z" });
    const first = pendingList({ folder }).ledgerProposals;
    expect(first.items).toHaveLength(1);
    expect(first.next).toEqual({ ledgerOffset: 1 });
    expect(first.notices.join("")).toContain("目安を超えています");
    const second = pendingList({ folder, ledgerOffset: 1 }).ledgerProposals;
    expect(second.items.map((item) => item.id)).toEqual(["foreshadowAdd-0000000000000002"]);
  });
});

describe("許可と記録", () => {
  test("鍵は今の pending.list と同じ（台帳の種類でも鍵は変わらない）", () => {
    for (const kind of ["chapter", "foreshadow", "schedule", undefined]) {
      expect(permissionKeyOf("pending.list", undefined, kind)).toBe(permissionKeyOf("pending.list", undefined));
    }
    const folder = makeWork("鍵");
    expect(() => assertExternalAccessAllowed({ folder, kind: "chapter" }, "pending.list")).not.toThrow();
  });

  test("記録の重さはほかの承認待ちと同じ", () => {
    const folder = makeWork("重さ");
    expect(exposureOf("pending.list", { folder, kind: "schedule" })).toBe(exposureOf("pending.list", { folder }));
  });

  test("記録の一言は台帳の種類の呼び名（中身は残さない）", () => {
    const folder = makeWork("記録");
    expect(recordExternalAccess({ tool: "pending.list", args: { folder, kind: "foreshadow" }, ok: true })).toBe(true);
    const log = parseExternalAccessLog(
      fs.readFileSync(nodePath.join(folder, ".aiwriter", EXTERNAL_ACCESS_DIRECTORY, EXTERNAL_ACCESS_FILE), "utf8")
    );
    expect(log[0]).toMatchObject({ tool: "pending.list", key: "pending.list", detail: "承認待ちを読んだ（伏線の案）" });
  });
});
