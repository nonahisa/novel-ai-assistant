import { afterEach, beforeEach, describe, expect, test } from "vitest";
import fs from "node:fs";
import os from "node:os";
import nodePath from "node:path";
import { novelPropose } from "../../../src/mcp/tools/propose";
import {
  exposureOf,
  recordExternalAccess,
  setExternalClientName,
} from "../../../src/mcp/tools/accessLog";
import { assertExternalAccessAllowed } from "../../../src/mcp/tools/permission";
import { parseLedgerProposalFile } from "../../../src/models/ledgerProposal";

/**
 * 外部AIの「台帳の案」（章立て・伏線・予定の段）を判断待ちへ置く
 * （MCP `novel.propose` の `kind: chapter・foreshadow・schedule`。作者の裁定 2026-10-16 の5）。
 *
 * - 置くのは `.aiwriter/pending-ledger/` だけ。**台帳（設定/）は1バイトも変えない**
 * - 渡された値を信じない：本文に無い話・つなぎ合わせた引用・無い伏線・無い段は断る
 * - いまの台帳に当てて変わらない案は置かない
 * - 作者がまだ判断していない同じ相手への案があれば断る（上書きしない）
 *
 * 作品は一時フォルダーの作り物で、作者の作品の印には触らない。
 */

let library: string;

function write(folder: string, relative: string, value: unknown): void {
  const target = nodePath.join(folder, relative);
  fs.mkdirSync(nodePath.dirname(target), { recursive: true });
  fs.writeFileSync(target, typeof value === "string" ? value : JSON.stringify(value, null, 2));
}

function makeWork(name: string): string {
  const folder = nodePath.join(library, name);
  write(folder, ".aiwriter/config.json", { schemaVersion: "1", workTitle: name });
  write(folder, ".aiwriter/external-access.json", {
    clients: [{ name: "claude-code", tools: ["*"], sampling: false }],
  });
  write(folder, "本文/001_灯.txt", "　港の灯が消えた夜、少年は防波堤の先に立っていた。\n　父はまだ帰らない。\n");
  write(folder, "本文/002_朝.txt", "　朝が来た。\n　少年は窓を開けた。\n");
  write(folder, "本文/003_便り.txt", "　冬の終わりに便りが届いた。\n");
  write(folder, "設定/章立て.json", {
    schemaVersion: "1",
    chapters: [{ name: "第一章　灯", startEpisodePath: "本文/001_灯.txt" }],
  });
  write(folder, "設定/foreshadows/foreshadow_0001.json", {
    schemaVersion: "0.1",
    id: "foreshadow_0001",
    label: "帰らない父の船",
    note: "",
    plantedChapter: 1,
    plantedQuote: "父はまだ帰らない。",
    status: "open",
    resolvedChapter: null,
    resolvedQuote: "",
    source: "author",
    autoGenerated: false,
    authorNotes: "",
    createdAt: "2026-09-12T00:00:00.000Z",
    updatedAt: "2026-09-12T00:00:00.000Z",
  });
  write(folder, "設定/スケジュール.json", {
    schemaVersion: "1",
    schedules: [
      {
        id: "sch_1",
        kind: "contest",
        name: "灯台賞",
        followsGoals: false,
        milestone: "2026-12-31",
        targetChars: null,
        steps: [
          { id: "stp_w", key: "write", label: "執筆", days: 30, due: null, status: "doing", doneAt: null, note: "" },
          { id: "stp_r", key: "revise", label: "推敲", days: 10, due: null, status: "todo", doneAt: null, note: "" },
        ],
        serial: null,
        note: "",
        createdAt: "",
        updatedAt: "",
      },
    ],
  });
  return folder;
}

/** `設定/` の中身。台帳を変えていないことを確かめる */
function settingsSnapshot(folder: string): Record<string, string> {
  const result: Record<string, string> = {};
  const walk = (dir: string): void => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = nodePath.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else result[nodePath.relative(folder, full)] = fs.readFileSync(full, "utf8");
    }
  };
  walk(nodePath.join(folder, "設定"));
  return result;
}

function pendingFiles(folder: string): string[] {
  const dir = nodePath.join(folder, ".aiwriter", "pending-ledger");
  return fs.existsSync(dir) ? fs.readdirSync(dir) : [];
}

function readPending(folder: string, relative: string) {
  return parseLedgerProposalFile(JSON.parse(fs.readFileSync(nodePath.join(folder, relative), "utf8")));
}

beforeEach(() => {
  library = fs.mkdtempSync(nodePath.join(os.tmpdir(), "novelai-ledger-"));
  setExternalClientName("claude-code");
});

afterEach(() => {
  fs.rmSync(library, { recursive: true, force: true });
  setExternalClientName("");
});

describe("許可と記録", () => {
  test("鍵は novel.propose（設定資料の案と同じ）。\"*\" で通る", () => {
    const folder = makeWork("鍵");
    expect(() => assertExternalAccessAllowed({ folder, kind: "chapter" }, "novel.propose")).not.toThrow();
  });

  test("記録は何の案かだけ（章名を残さない）。原稿は外へ出ない", () => {
    const folder = makeWork("記録");
    expect(exposureOf("novel.propose", { folder, kind: "chapter" })).toBe("none");
    recordExternalAccess({
      tool: "novel.propose",
      args: { folder, kind: "chapter", ledger: { chapterName: "筋の書かれた章名" } },
      ok: true,
      result: {},
    });
    const log = fs.readFileSync(nodePath.join(folder, ".aiwriter", "history", "external.jsonl"), "utf8");
    expect(log).toContain("章立ての案を判断待ちへ置いた");
    expect(log).not.toContain("筋の書かれた章名");
  });
});

describe("kind: chapter", () => {
  test("新しい章の案を置く。章立ての台帳は変えない", () => {
    const folder = makeWork("章");
    const before = settingsSnapshot(folder);
    const result = novelPropose({
      folder,
      kind: "chapter",
      ledger: { episodeFile: "本文/003_便り.txt", chapterName: "第二章　便り" },
      reason: "第3話から季節と舞台が変わるため",
    });
    expect(result.file).toMatch(/^\.aiwriter\/pending-ledger\/chapter-[0-9a-f]+\.json$/);
    expect(settingsSnapshot(folder)).toEqual(before);
    const placed = readPending(folder, result.file);
    expect(placed.proposal).toEqual({
      type: "chapter",
      startEpisodePath: "本文/003_便り.txt",
      name: "第二章　便り",
      currentName: null,
    });
    expect(placed.client).toBe("claude-code");
    expect(result.changes.join("")).toContain("003_便り.txt");
  });

  test("その話から始まる章があれば改名の案になる。同じ名前なら置かない", () => {
    const folder = makeWork("改名");
    const result = novelPropose({
      folder,
      kind: "chapter",
      ledger: { episodeFile: "本文/001_灯.txt", chapterName: "序章　灯" },
      reason: "序章として扱うため",
    });
    expect(readPending(folder, result.file).proposal).toMatchObject({ currentName: "第一章　灯" });
    expect(() =>
      novelPropose({
        folder: makeWork("同名"),
        kind: "chapter",
        ledger: { episodeFile: "本文/001_灯.txt", chapterName: "第一章　灯" },
        reason: "同じ",
      })
    ).toThrow(/変えるものがありません/);
  });

  test("本文でないファイル・作品の外は断る", () => {
    const folder = makeWork("外");
    expect(() =>
      novelPropose({ folder, kind: "chapter", ledger: { episodeFile: "設定/章立て.json", chapterName: "x" }, reason: "r" })
    ).toThrow(/本文のファイルではありません/);
    expect(() =>
      novelPropose({ folder, kind: "chapter", ledger: { episodeFile: "../x.txt", chapterName: "x" }, reason: "r" })
    ).toThrow(/作品フォルダーの外/);
  });

  test("作者がまだ判断していない同じ話への案があれば断る（上書きしない）", () => {
    const folder = makeWork("重ね");
    const first = novelPropose({
      folder,
      kind: "chapter",
      ledger: { episodeFile: "本文/003_便り.txt", chapterName: "第二章　便り" },
      reason: "一つ目",
    });
    expect(() =>
      novelPropose({
        folder,
        kind: "chapter",
        ledger: { episodeFile: "本文/003_便り.txt", chapterName: "第二章　冬" },
        reason: "二つ目",
      })
    ).toThrow(/まだ判断していない/);
    expect(readPending(folder, first.file).reason).toBe("一つ目");
  });

  test("reason が空なら断る", () => {
    const folder = makeWork("理由なし");
    expect(() =>
      novelPropose({ folder, kind: "chapter", ledger: { episodeFile: "本文/003_便り.txt", chapterName: "x" }, reason: " " })
    ).toThrow(/reason/);
    expect(pendingFiles(folder)).toEqual([]);
  });

  test("章立ての台帳が壊れていたら断る（直さない）", () => {
    const folder = makeWork("壊れ");
    write(folder, "設定/章立て.json", "{壊れている");
    expect(() =>
      novelPropose({ folder, kind: "chapter", ledger: { episodeFile: "本文/003_便り.txt", chapterName: "x" }, reason: "r" })
    ).toThrow(/直していません/);
    expect(fs.readFileSync(nodePath.join(folder, "設定/章立て.json"), "utf8")).toBe("{壊れている");
  });
});

describe("kind: foreshadow", () => {
  test("新しい伏線の案。引用は本文に一続きで在るものだけ", () => {
    const folder = makeWork("伏線");
    const before = settingsSnapshot(folder);
    const result = novelPropose({
      folder,
      kind: "foreshadow",
      ledger: { label: "防波堤の先", note: "少年がそこで待つ理由", plantedChapter: 1, plantedQuote: "少年は防波堤の先に立っていた。" },
      reason: "第1話で強調されている",
    });
    expect(readPending(folder, result.file).proposal).toMatchObject({ type: "foreshadowAdd", label: "防波堤の先" });
    expect(settingsSnapshot(folder)).toEqual(before);

    // 離れた2文をつないだ引用は通さない
    expect(() =>
      novelPropose({
        folder,
        kind: "foreshadow",
        ledger: { label: "窓", plantedQuote: "朝が来た。少年は窓を開けた。" },
        reason: "r",
      })
    ).toThrow(/本文に見つかりません/);
  });

  test("同じ名の伏線が既にあれば、登録の案は断る", () => {
    const folder = makeWork("同名伏線");
    expect(() =>
      novelPropose({ folder, kind: "foreshadow", ledger: { label: "帰らない父の船" }, reason: "r" })
    ).toThrow(/既にあります/);
  });

  test("状態を変える案は、置いたときの状態を一緒に残す", () => {
    const folder = makeWork("状態");
    const result = novelPropose({
      folder,
      kind: "foreshadow",
      ledger: { foreshadowId: "foreshadow_0001", status: "resolved", resolvedChapter: 3, resolvedQuote: "冬の終わりに便りが届いた。" },
      reason: "第3話で父の便りが届く",
    });
    expect(readPending(folder, result.file).proposal).toEqual({
      type: "foreshadowStatus",
      foreshadowId: "foreshadow_0001",
      label: "帰らない父の船",
      fromStatus: "open",
      status: "resolved",
      resolvedChapter: 3,
      resolvedQuote: "冬の終わりに便りが届いた。",
    });
  });

  test("無い伏線・同じ状態・知らない状態は断る", () => {
    const folder = makeWork("状態断り");
    expect(() =>
      novelPropose({ folder, kind: "foreshadow", ledger: { foreshadowId: "foreshadow_9999", status: "resolved" }, reason: "r" })
    ).toThrow(/台帳にありません/);
    expect(() =>
      novelPropose({ folder, kind: "foreshadow", ledger: { foreshadowId: "foreshadow_0001", status: "open" }, reason: "r" })
    ).toThrow(/変えるものがありません/);
    expect(() =>
      novelPropose({ folder, kind: "foreshadow", ledger: { foreshadowId: "foreshadow_0001", status: "done" }, reason: "r" })
    ).toThrow(/open・resolved・intentional/);
  });
});

describe("kind: schedule", () => {
  test("段を名前で指して直す案。置いたときの値を残す。台帳は変えない", () => {
    const folder = makeWork("予定");
    const before = settingsSnapshot(folder);
    const result = novelPropose({
      folder,
      kind: "schedule",
      ledger: { schedule: "灯台賞", step: "推敲", due: "2026-12-20", days: 14 },
      reason: "推敲に2週間ほしい",
    });
    expect(readPending(folder, result.file).proposal).toEqual({
      type: "scheduleStep",
      scheduleId: "sch_1",
      scheduleName: "灯台賞",
      stepId: "stp_r",
      stepLabel: "推敲",
      afterStepId: null,
      before: { due: null, days: 10 },
      patch: { due: "2026-12-20", days: 14 },
    });
    expect(settingsSnapshot(folder)).toEqual(before);
  });

  test("段を足す案（省くと最後へ）。due・status は足す案では断る", () => {
    const folder = makeWork("足す");
    const result = novelPropose({
      folder,
      kind: "schedule",
      ledger: { schedule: "sch_1", label: "最終確認", days: 3 },
      reason: "応募前の確認",
    });
    expect(readPending(folder, result.file).proposal).toMatchObject({
      stepId: null,
      afterStepId: "stp_r",
      patch: { label: "最終確認", days: 3 },
    });
    expect(() =>
      novelPropose({ folder, kind: "schedule", ledger: { schedule: "sch_1", label: "x", days: 1, due: "2026-11-01" }, reason: "r" })
    ).toThrow(/due・status は渡せません/);
  });

  test("無いスケジュール・無い段は、選べるものを並べて断る", () => {
    const folder = makeWork("無い段");
    expect(() =>
      novelPropose({ folder, kind: "schedule", ledger: { schedule: "別の賞", step: "推敲", days: 1 }, reason: "r" })
    ).toThrow(/sch_1＝灯台賞/);
    expect(() =>
      novelPropose({ folder, kind: "schedule", ledger: { schedule: "灯台賞", step: "校正", days: 1 }, reason: "r" })
    ).toThrow(/stp_w＝執筆、stp_r＝推敲/);
  });

  test("形の合わない値（日数0・日付でない期日）は画面と同じ理由で断る", () => {
    const folder = makeWork("形");
    expect(() =>
      novelPropose({ folder, kind: "schedule", ledger: { schedule: "灯台賞", step: "推敲", days: 0 }, reason: "r" })
    ).toThrow(/1〜3650/);
    expect(() =>
      novelPropose({ folder, kind: "schedule", ledger: { schedule: "灯台賞", step: "推敲", due: "来月" }, reason: "r" })
    ).toThrow();
    expect(pendingFiles(folder)).toEqual([]);
  });

  test("スケジュールのファイルが無ければ断る（作らない）", () => {
    const folder = makeWork("予定なし");
    fs.rmSync(nodePath.join(folder, "設定", "スケジュール.json"));
    expect(() =>
      novelPropose({ folder, kind: "schedule", ledger: { schedule: "灯台賞", step: "推敲", days: 2 }, reason: "r" })
    ).toThrow(/作者が画面で作ります/);
    expect(fs.existsSync(nodePath.join(folder, "設定", "スケジュール.json"))).toBe(false);
  });
});
