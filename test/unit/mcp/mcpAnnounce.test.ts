import { afterEach, beforeEach, describe, expect, test } from "vitest";
import fs from "node:fs";
import os from "node:os";
import nodePath from "node:path";
import { novelPrompt, novelRun, novelValidate } from "../../../src/mcp/tools/features";
import { FEATURE_NAMES } from "../../../src/core/mcpFeatures";
import { announcePromptVersion } from "../../../src/prompts/announce";

/**
 * 更新告知文を外から呼ぶ（`novel.run` の `feature: announce`。棚卸しの9件目、2026-10-16）。
 *
 * - 材料は製品の［更新SNS告知文作成］と同じ（その話の本文・紹介文・前の話のあらすじ・
 *   前に出した告知）で、話の見出しも製品と同じ形
 * - 定型句・ハッシュタグ・URLはコードで付け、字数と言葉を製品と同じ検算に通す
 * - **生成だけ**：書くのは前に出した告知の履歴だけ（製品と同じ。作者の裁定 2026-10-16 夜の2）
 */

let folder: string;

function write(relative: string, value: unknown): void {
  const target = nodePath.join(folder, relative);
  fs.mkdirSync(nodePath.dirname(target), { recursive: true });
  fs.writeFileSync(target, typeof value === "string" ? value : JSON.stringify(value, null, 2));
}

function snapshot(): Record<string, string> {
  const result: Record<string, string> = {};
  const walk = (dir: string): void => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = nodePath.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else result[nodePath.relative(folder, full)] = fs.readFileSync(full, "utf8");
    }
  };
  walk(folder);
  return result;
}

beforeEach(() => {
  folder = fs.mkdtempSync(nodePath.join(os.tmpdir(), "novelai-announce-mcp-"));
  write(".aiwriter/config.json", {
    schemaVersion: "1",
    workTitle: "灯の町",
    manuscriptDir: "本文",
    settingsDir: "設定",
    createdAt: "2026-01-01T00:00:00.000Z",
    announce: { hashtags: ["創作", "＃小説"], workUrl: "" },
  });
  write("本文/001_灯.txt", "　港の灯が消えた夜、少年は防波堤の先に立っていた。\n");
  write("本文/002_便り.txt", "　冬の終わりに便りが届いた。\n// TODO 母の名前\n　少年は封を切った。\n");
  write("設定/chapter_synopses.json", {
    schemaVersion: "0.1",
    episodes: [
      { chapter: 1, fileName: "001_灯.txt", title: "灯", synopsis: "少年が防波堤で父の船を待つ。", sourceHash: "", model: null, promptVersion: null, autoGenerated: true, authorNotes: "", updatedAt: null },
    ],
  });
  write("設定/synopsis.md", "# 灯の町\n\n## 紹介文\n\n港町で父を待つ少年の、ひと冬の物語。\n");
  write(".aiwriter/cache/announcements.json", ["前に出した告知の言い回し"]);
});

afterEach(() => {
  fs.rmSync(folder, { recursive: true, force: true });
});

const RESPONSE = JSON.stringify({
  xPost: "冬の終わり、少年のもとに一通の便りが届く。",
  activityReport: "第2話を更新しました。".repeat(15),
  afterword: "読んでくださり、ありがとうございます。",
  spoilerCheck: "差出人は伏せた",
  confidence: "high",
});

describe("更新告知文（feature: announce）", () => {
  test("一覧に載っている", () => {
    expect(FEATURE_NAMES).toContain("announce");
  });

  test("プロンプト：製品と同じ材料と見出しで組み、版にも読者の印を混ぜる", () => {
    const prompt = novelPrompt({ folder, feature: "announce", filePath: "本文/002_便り.txt" }) as {
      userPrompt: string;
      episodeLabel: string;
      promptVersion: string;
      pastAnnouncementCount: number;
    };
    expect(prompt.episodeLabel).toBe("第2話「便り」");
    expect(prompt.userPrompt).toContain("第2話「便り」");
    expect(prompt.userPrompt).toContain("冬の終わりに便りが届いた");
    // シーンメモは製品と同じく落とす
    expect(prompt.userPrompt).not.toContain("母の名前");
    expect(prompt.userPrompt).toContain("港町で父を待つ少年");
    expect(prompt.userPrompt).toContain("少年が防波堤で父の船を待つ。");
    expect(prompt.userPrompt).toContain("前に出した告知の言い回し");
    expect(prompt.pastAnnouncementCount).toBe(1);
    expect(prompt.promptVersion).toBe(announcePromptVersion("none"));
  });

  test("filePath が無ければ名前を挙げて断る", () => {
    expect(() => novelPrompt({ folder, feature: "announce" })).toThrow(/filePath/);
  });

  test("検算：ハッシュタグ（揃えた形）とURLの目印をコードで付け、Xの重みで数える", () => {
    const result = novelValidate({
      folder,
      feature: "announce",
      filePath: "本文/002_便り.txt",
      response: RESPONSE,
    }) as {
      composedX: string;
      weightedLength: number;
      warnings: string[];
      note: string;
    };
    expect(result.composedX).toContain("第2話「便り」 更新しました");
    expect(result.composedX).toContain("#創作 #小説");
    expect(result.composedX).toContain("{URL}");
    expect(result.weightedLength).toBeGreaterThan(0);
    expect(result.note).toContain("投稿もしていません");
  });

  test("検算：指定の字数を超えた・材料の言葉が混ざった答えは、切らずに注意を返す", () => {
    const result = novelValidate({
      folder,
      feature: "announce",
      filePath: "本文/002_便り.txt",
      response: JSON.stringify({
        xPost: "あ".repeat(120),
        activityReport: "（まだありません）",
        afterword: "ありがとう",
        spoilerCheck: null,
        confidence: "low",
      }),
    }) as { xPost: string; warnings: string[] };
    expect(result.xPost).toHaveLength(120);
    expect(result.warnings.join("\n")).toContain("X用の本文が 120字");
    expect(result.warnings.join("\n")).toContain("（まだありません）");
  });

  test("読み取れない答えは断る", () => {
    expect(() =>
      novelValidate({ folder, feature: "announce", filePath: "本文/002_便り.txt", response: "告知です" })
    ).toThrow(/読み取れません/);
  });

  test("runner: claude はプロンプトを返すだけで、作品フォルダーに何も書かない", async () => {
    const before = snapshot();
    const result = (await novelRun({
      folder,
      feature: "announce",
      filePath: "本文/002_便り.txt",
      runner: "claude",
    })) as { runner: string; userPrompt: string };
    expect(result.runner).toBe("claude");
    expect(result.userPrompt).toContain("第2話「便り」");
    novelPrompt({ folder, feature: "announce", filePath: "本文/002_便り.txt" });
    expect(snapshot()).toEqual(before);
  });

  /*
    作者の裁定 2026-10-16 夜の2：外部AIが作った告知文も、製品の画面と同じく
    前に出した告知の履歴へ足す（採用したかどうかに関わらず。次の告知で同じ
    言い回しを避けさせるため）。書くのは履歴の1ファイルだけ
  */
  test("検算を通った告知文は、前に出した告知の履歴へ足す（履歴のほかは何も変えない）", () => {
    const before = snapshot();
    const result = novelValidate({
      folder,
      feature: "announce",
      filePath: "本文/002_便り.txt",
      response: RESPONSE,
    }) as { historyAdded: boolean; note: string };
    expect(result.historyAdded).toBe(true);
    expect(result.note).toContain("履歴へ足しました");

    const after = snapshot();
    const historyKey = nodePath.join(".aiwriter", "cache", "announcements.json");
    // 製品と同じ形（前のものの後ろへ、JSONの配列）
    expect(JSON.parse(after[historyKey])).toEqual([
      "前に出した告知の言い回し",
      "冬の終わり、少年のもとに一通の便りが届く。",
    ]);
    // 履歴のほかは1バイトも変わらない
    delete after[historyKey];
    const rest = { ...before };
    delete rest[historyKey];
    expect(after).toEqual(rest);

    // 次のプロンプトでは、足した告知も避ける対象に入る
    const prompt = novelPrompt({ folder, feature: "announce", filePath: "本文/002_便り.txt" }) as {
      userPrompt: string;
      pastAnnouncementCount: number;
    };
    expect(prompt.pastAnnouncementCount).toBe(2);
    expect(prompt.userPrompt).toContain("冬の終わり、少年のもとに一通の便りが届く。");
  });

  test("同じ答えを2回検算しても、履歴に2つは並ばない（製品と同じ重ね落とし）", () => {
    novelValidate({ folder, feature: "announce", filePath: "本文/002_便り.txt", response: RESPONSE });
    novelValidate({ folder, feature: "announce", filePath: "本文/002_便り.txt", response: RESPONSE });
    const history = JSON.parse(
      fs.readFileSync(nodePath.join(folder, ".aiwriter", "cache", "announcements.json"), "utf8")
    ) as string[];
    expect(history).toEqual(["前に出した告知の言い回し", "冬の終わり、少年のもとに一通の便りが届く。"]);
  });

  test("履歴がまだ無い作品では作る。製品と同じく直近20件だけを持つ", () => {
    fs.rmSync(nodePath.join(folder, ".aiwriter", "cache"), { recursive: true, force: true });
    novelValidate({ folder, feature: "announce", filePath: "本文/002_便り.txt", response: RESPONSE });
    const file = nodePath.join(folder, ".aiwriter", "cache", "announcements.json");
    expect(JSON.parse(fs.readFileSync(file, "utf8"))).toEqual([
      "冬の終わり、少年のもとに一通の便りが届く。",
    ]);

    write(".aiwriter/cache/announcements.json", Array.from({ length: 20 }, (_, i) => `告知${i}`));
    novelValidate({ folder, feature: "announce", filePath: "本文/002_便り.txt", response: RESPONSE });
    const history = JSON.parse(fs.readFileSync(file, "utf8")) as string[];
    expect(history).toHaveLength(20);
    expect(history[0]).toBe("告知1");
    expect(history[19]).toBe("冬の終わり、少年のもとに一通の便りが届く。");
  });

  test("読み取れない答えは履歴へ足さない", () => {
    const before = snapshot();
    expect(() =>
      novelValidate({ folder, feature: "announce", filePath: "本文/002_便り.txt", response: "告知です" })
    ).toThrow();
    expect(snapshot()).toEqual(before);
  });
});
