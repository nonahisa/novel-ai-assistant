import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { afterEach, describe, expect, test } from "vitest";
import {
  contradictionMaterial,
  contradictionPrompt,
} from "../../../src/mcp/tools/contradiction";

/**
 * MCP の矛盾検知も、組織・能力を材料に載せる（2026-11-15 作者の決定）。
 *
 * 測定の台本（`contradictionMaterial` を呼ぶ）はこの道を通るので、ここで
 * 載らないと、製品で直しても測りの数字が動かない。
 *
 * 台は答え付きの台（`test/fixtures/seeded/contradiction`）の写しへ、
 * 組織と能力を1件ずつ足したもの。**写しにだけ足す**（台そのものは
 * 送る材料の写し〔golden〕の元なので触らない）。
 */
const SEEDED = path.join(
  __dirname,
  "..",
  "..",
  "fixtures",
  "seeded",
  "contradiction"
);

const temps: string[] = [];
afterEach(() => {
  for (const dir of temps.splice(0)) {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

function workWithOrganization(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "novelai-contra-org-"));
  temps.push(dir);
  fs.cpSync(SEEDED, dir, { recursive: true });
  fs.mkdirSync(path.join(dir, "設定", "organizations"), { recursive: true });
  fs.mkdirSync(path.join(dir, "設定", "abilities"), { recursive: true });
  // 第1話の本文に「郵便局」も「自転車」も出る。第4話で初めて出る能力は、
  // 名前が出ていても第1話には載らない
  fs.writeFileSync(
    path.join(dir, "設定", "organizations", "org_0001.json"),
    JSON.stringify({
      schemaVersion: "0.1",
      id: "org_0001",
      name: "郵便局",
      aliases: [],
      description: "町にひとつだけある。窓口は夕方五時に閉まる",
      appearedChapters: [1],
      autoGenerated: false,
      authorNotes: "",
      updatedAt: "2026-11-15T00:00:00.000Z",
    }),
    "utf8"
  );
  fs.writeFileSync(
    path.join(dir, "設定", "abilities", "abil_0001.json"),
    JSON.stringify({
      schemaVersion: "0.1",
      id: "abil_0001",
      // 第1話の本文に出る語。能力としては作り物で、出た話の扱いだけを見る
      name: "自転車",
      aliases: [],
      limitation: "（台のための作り物）",
      appearedChapters: [4],
      autoGenerated: false,
      authorNotes: "",
      updatedAt: "2026-11-15T00:00:00.000Z",
    }),
    "utf8"
  );
  return dir;
}

describe("MCP の矛盾検知の材料に、組織・能力が載る", () => {
  test("本文に名前が出た組織は、材料とプロンプトに載る", () => {
    const folder = workWithOrganization();
    const material = contradictionMaterial({
      folder,
      filePath: "本文/001_九月の終わりの坂.txt",
      numCtx: 16384,
      contextWindow: 16384,
    });

    expect(material.settingsCount.organizations).toBe(1);
    expect(material.settingsCount.abilities).toBe(1);
    expect(material.chunks[0].organizationDetails).toContain("名前: 郵便局");
    // 第4話で初めて出る能力は、第1話の時点ではまだ分かっていない（6.10.3）
    expect(material.chunks[0].abilityDetails).toBe("");

    const prompt = contradictionPrompt({
      folder,
      filePath: "本文/001_九月の終わりの坂.txt",
      numCtx: 16384,
      contextWindow: 16384,
      categories: "light",
      suppression: "loose",
    });
    expect(prompt.chunks[0].userPrompt).toContain(
      "【組織設定】（本文に登場する組織のみ）\n名前: 郵便局"
    );
    expect(prompt.chunks[0].userPrompt).not.toContain("【能力設定】");
  });
});
