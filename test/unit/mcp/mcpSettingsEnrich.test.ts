/** 作り物の作品。人物は2人——抽出が作った美咲と、作者が確定させた宗一 */
function makeWork(): string {
  const folder = fs.mkdtempSync(nodePath.join(os.tmpdir(), "novelai-enrich-"));
  temporary.push(folder);
  const body = nodePath.join(folder, "本文");
  fs.mkdirSync(body, { recursive: true });
  fs.writeFileSync(nodePath.join(body, "001_港.txt"), EPISODE_1, "utf8");
  fs.writeFileSync(nodePath.join(body, "002_灯台.txt"), EPISODE_2, "utf8");

  const characters = nodePath.join(folder, "設定", "characters");
  fs.mkdirSync(characters, { recursive: true });
  const misaki = {
    schemaVersion: "0.1",
    id: "char_0001",
    name: "美咲",
    aliases: [],
    summary: "港町の娘。",
    appearedChapters: [1, 2],
    autoGenerated: true,
    authorNotes: "",
    updatedAt: "2026-09-12T00:00:00.000Z",
  };
  const soichi = {
    schemaVersion: "0.1",
    id: "char_0002",
    name: "宗一",
    aliases: [],
    summary: "美咲の兄。",
    personality: "作者が書いた性格",
    appearedChapters: [2],
    autoGenerated: false,
    authorNotes: "作者のメモ（外へ出さない）",
    updatedAt: "2026-09-12T00:00:00.000Z",
  };
  fs.writeFileSync(
    nodePath.join(characters, "char_0001.json"),
    JSON.stringify(misaki, null, 2),
    "utf8"
  );
  fs.writeFileSync(
    nodePath.join(characters, "char_0002.json"),
    JSON.stringify(soichi, null, 2),
    "utf8"
  );
  return folder;
}

function call(
  folder: string,
  options: Record<string, unknown>,
  extra: Partial<FeatureCallInput> = {}
): FeatureCallInput {
  return {
    folder,
    feature: "settingsEnrich" as FeatureCallInput["feature"],
    options,
    ...extra,
  };
}

/** 製品の `loadExcerptSources` と同じ割り方で、本文を出典つきにする（走査の順） */
function productSources(folder: string) {
  const body = nodePath.join(folder, "本文");
  return fs
    .readdirSync(body)
    .sort()
    .flatMap((fileName) => {
      const text = fs.readFileSync(nodePath.join(body, fileName), "utf8");
      const parsed = parseEpisodeFileName(fileName);
      const meta = parseEpisodeMetadata(text);
      return excerptSourcesOfEpisode(
        {
          filePath: nodePath.join(body, fileName),
          fileName,
          metaTitle: meta.title,
          subtitle: parsed.subtitle ?? meta.title,
          kind: parsed.kind,
          chapterStart: parsed.chapterStart,
          chapterEnd: parsed.chapterEnd,
        },
        text
      );
    });
}

function readCharacter(folder: string, file: string) {
  return parseCharacter(
    JSON.parse(
      fs.readFileSync(nodePath.join(folder, "設定", "characters", file), "utf8")
    )
  );
}

/** フォルダーの中身の指紋（書いていないことを確かめる） */
function fingerprint(folder: string): string {
  const entries: string[] = [];
  const walk = (dir: string) => {
    for (const name of fs.readdirSync(dir).sort()) {
      const full = nodePath.join(dir, name);
      if (fs.statSync(full).isDirectory()) walk(full);
      else entries.push(`${nodePath.relative(folder, full)}=${fs.readFileSync(full, "utf8")}`);
    }
  };
  walk(folder);
  return entries.join("\n");
}

