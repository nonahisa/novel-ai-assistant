describe("検算は製品と同じ関数を通る", () => {
  test("口調の指示の写し・無い話の引用・いまと同じ値・「不明」を落とす", () => {
    const folder = makeWork();
    const response = JSON.stringify({
      gender: "不明",
      summary: "港町の娘。",
      affiliation: null,
      role: "第17話から網元",
      personality: "明るく、ためらわずに動く（網を担いで先に出ていく）",
      speechStyle: SPEECH_STYLE_ASPECTS.slice(0, 3).join("・"),
      appearance: null,
      misattributed: [],
    });
    const result = novelValidate(
      call(folder, { name: "美咲" }, { response })
    ) as {
      proposals: Array<{ field: string; after: string; fillsBlank: boolean }>;
      dropped: {
        unknownCitations: Array<{ label: string; chapters: number[] }>;
        speechEchoes: number;
      };
    };

    expect(result.proposals.map((item) => item.field)).toEqual(["personality"]);
    expect(result.proposals[0].fillsBlank).toBe(true);
    expect(result.dropped.unknownCitations).toEqual([
      { label: "役割", chapters: [17] },
    ]);
    expect(result.dropped.speechEchoes).toBe(1);

    // **製品が通る関数と同じ答え**（写しを持っていれば、ここがずれる）
    const record = readCharacter(folder, "char_0001.json");
    const excerpts = collectMentionExcerpts(
      productSources(folder),
      searchTermsFor("character", record)
    );
    const parsed = parseEnrichResult(response);
    if (!parsed) throw new Error("応答を読めない");
    const product = checkEnrichProposals({
      kind: "character",
      record,
      customFields: [],
      parsed,
      excerptText: excerpts.map((excerpt) => excerpt.text).join("\n"),
      knownChapters: new Set([1, 2]),
    });
    expect(result.proposals.map((item) => [item.field, item.after])).toEqual(
      product.proposals.map((item) => [item.field.key, item.after])
    );
  });

  test("はじいた記述は本文と照合し、照合できないものは落として数える", () => {
    const folder = makeWork();
    const response = JSON.stringify({
      gender: null,
      summary: null,
      affiliation: null,
      role: null,
      personality: null,
      speechStyle: null,
      appearance: null,
      misattributed: [
        {
          belongsTo: "宗一",
          field: "personality",
          value: "無口",
          evidence: "宗一は黙って船を見ていた。",
        },
        {
          belongsTo: "宗一",
          field: "personality",
          value: "陽気",
          evidence: "本文に無い作り話の引用",
        },
      ],
    });
    const result = novelValidate(call(folder, { name: "美咲" }, { response })) as {
      misattributed: Array<{ belongsTo: string; value: string }>;
      dropped: { misattributed: number };
    };
    expect(result.misattributed.map((item) => item.value)).toEqual(["無口"]);
    expect(result.dropped.misattributed).toBe(1);
  });

  test("読めない応答は断る（空として流さない）", () => {
    const folder = makeWork();
    expect(() =>
      novelValidate(call(folder, { name: "美咲" }, { response: "わかりません" }))
    ).toThrow(/読み取れません/);
  });
});

describe("作者が書いた項目は提案の対象にしない", () => {
  test("確定した人物の、作者の値がある欄は承認待ちの案に入れない（空欄を埋める案は入れる）", () => {
    const folder = makeWork();
    const response = JSON.stringify({
      gender: "男性",
      summary: null,
      affiliation: null,
      role: null,
      personality: "寡黙で、船から目を離さない",
      speechStyle: null,
      appearance: null,
      // スキーマに無い欄が返っても、提案にはしない
      authorNotes: "AIが書き換えた作者メモ",
      misattributed: [],
    });
    const result = novelValidate(call(folder, { name: "宗一" }, { response })) as {
      autoGenerated: boolean;
      proposals: Array<{ field: string }>;
      proposeArgs: { changes: Record<string, unknown> } | null;
      notProposed: Array<{ field: string; reason: string }>;
    };
    expect(result.autoGenerated).toBe(false);
    // 画面と同じく、提案としては見せる（作者が自分で選ぶもの）
    expect(result.proposals.map((item) => item.field).sort()).toEqual(
      ["gender", "personality"].sort()
    );
    // 承認待ちへ置く案には、作者の値の置き換えを入れない
    expect(result.proposeArgs?.changes).toEqual({ gender: "男性" });
    expect(result.notProposed.map((item) => item.field)).toEqual(["personality"]);
    expect(result.notProposed[0].reason).toMatch(/作者/);

    const all = JSON.stringify(result);
    expect(all).not.toContain("AIが書き換えた作者メモ");
    expect(all).not.toContain("authorNotes");
  });

  test("提案できる項目の表に、作者メモ・資料用の補足・呼称・確定の印は無い", () => {
    for (const kind of ["character", "ability", "organization", "location", "world"] as const) {
      const keys = enrichableFields(kind).map((field) => field.key);
      for (const key of ["authorNotes", "exportNote", "addressTerms", "autoGenerated", "authorLocked", "id", "name"]) {
        expect(keys).not.toContain(key);
      }
    }
  });
});

describe("結果は資料へ直接書かない", () => {
  test("prompt・validate・run（claude と ollama）のどれも、作品フォルダーを1バイトも変えない", async () => {
    const folder = makeWork();
    const before = fingerprint(folder);
    const response = JSON.stringify({
      gender: "女性",
      summary: null,
      affiliation: null,
      role: null,
      personality: "明るく、ためらわずに動く",
      speechStyle: "一人称は「あたし」。語尾を伸ばす",
      appearance: null,
      misattributed: [],
    });

    novelPrompt(call(folder, { name: "美咲" }));
    novelValidate(call(folder, { name: "美咲" }, { response }));
    const claude = (await novelRun(
      call(folder, { name: "美咲" }, { runner: "claude" })
    )) as { runner: string; userPrompt: string };
    expect(claude.runner).toBe("claude");

    ollamaReply = response;
    const ollama = (await novelRun(
      call(folder, { name: "美咲" }, { runner: "ollama", model: "test-model" })
    )) as {
      runner: string;
      result: {
        proposals: Array<{ field: string }>;
        proposeArgs: {
          kind: string;
          recordKind: string;
          name: string;
          reason: string;
          changes: Record<string, unknown>;
        } | null;
      };
    };
    expect(ollama.runner).toBe("ollama");
    expect(ollama.result.proposals.map((item) => item.field)).toContain("speechStyle");
    // **呼び手が novel.propose へそのまま渡せる形**で返す（置くのは呼び手）
    expect(ollama.result.proposeArgs).toMatchObject({
      kind: "settings",
      recordKind: "character",
      name: "美咲",
      changes: {
        gender: "女性",
        personality: "明るく、ためらわずに動く",
        speechStyle: "一人称は「あたし」。語尾を伸ばす",
      },
    });
    expect(ollama.result.proposeArgs?.reason).toBeTruthy();

    expect(fingerprint(folder)).toBe(before);
    expect(fs.existsSync(nodePath.join(folder, ".aiwriter"))).toBe(false);
  });
});
