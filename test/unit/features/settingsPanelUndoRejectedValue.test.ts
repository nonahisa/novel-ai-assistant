import { beforeEach, describe, expect, test, vi } from "vitest";
import { SettingsPanel } from "../../../src/features/settingsPanel";
import { emptyCharacter, type Character } from "../../../src/models/character";

/**
 * 「誤りとして落とした値」の印を外す（作者の裁定、2026-09-26）。
 *
 * 0.89.8 で食い違いの値を［「…」は誤り（落とす）］で一度に落とせるようにした。
 * 落とした値は `rejectedValues` に残り、次の抽出でも外部AIの提案でも立て直さない。
 * **取り違えて押したとき、印を外す口がどこにも無かった。**
 *
 * ここで見るのは段取り——札が値ごとに並ぶこと、押した1件だけが外れること、
 * 本体と食い違いの記録は戻さないこと、先に外されていたら何もしないこと。
 */

const { generated } = vi.hoisted(() => ({
  generated: [] as Array<{ kinds?: readonly string[]; silent?: boolean }>,
}));

vi.mock("../../../src/features/generateSettingsDocs", () => ({
  generateSettingsDocs: (
    _work: unknown,
    options: { kinds?: readonly string[]; silent?: boolean } = {}
  ) => {
    generated.push(options);
    return Promise.resolve();
  },
}));

/** 第3話で「寡黙な騎士。」を誤りとして落としたあとの人物 */
function dropped(): Character {
  return {
    ...emptyCharacter("char_002", "プラム"),
    summary: "明るい見習い魔法使い。",
    appearedChapters: [3],
    authorNotes: "作者メモ",
    exportNote: "公開用注記",
    autoGenerated: false,
    rejectedValues: [
      {
        field: "summary",
        value: "寡黙な騎士。",
        chapters: [3],
        evidence: "エルシーは黙って剣を抜いた。",
        rejectedAt: "2026-09-26T00:00:00.000Z",
      },
      {
        field: "role",
        value: "リーダー格の男性。",
        chapters: [1],
        rejectedAt: "2026-09-26T00:00:00.000Z",
      },
    ],
  };
}

interface ReferenceLine {
  label: string;
  value: string;
  valueActions?: Array<{
    label: string;
    title: string;
    field: string;
    value: string;
    kind: string;
  }>;
}

interface PanelInnards {
  work: { id: string; title: string; folderPath: string };
  characters: Character[];
  abilities: unknown[];
  organizations: unknown[];
  locations: unknown[];
  worldItems: unknown[];
  customFields: unknown[];
  showAllAddresses: boolean;
  persist(kind: string, record: Character): Promise<void>;
  reloadAfterSave(kind: string, id: string, notice: string): Promise<void>;
  post(message: unknown): void;
  detailOf(kind: string, id: string): { reference: ReferenceLine[] } | undefined;
  handleUndoRejectedValue(id: string, field: string, value: string): Promise<void>;
}

function panelWith(character: Character) {
  const saved: Array<{ kind: string; record: Character }> = [];
  const notices: string[] = [];
  const posted: Array<{ type: string; message?: string }> = [];

  const panel = Object.create(SettingsPanel.prototype) as SettingsPanel;
  const inner = panel as unknown as PanelInnards;
  inner.work = { id: "w-1", title: "教科書チート", folderPath: "C:" };
  inner.characters = [character];
  inner.abilities = [];
  inner.organizations = [];
  inner.locations = [];
  inner.worldItems = [];
  inner.customFields = [];
  inner.showAllAddresses = false;
  // **人物の既存の保存経路（persist → saveOrUpdate）を通ることを見る**
  inner.persist = async (kind, record) => {
    saved.push({ kind, record });
  };
  inner.reloadAfterSave = async (_kind, _id, notice) => {
    notices.push(notice);
  };
  inner.post = (message) => {
    posted.push(message as { type: string; message?: string });
  };
  return { inner, saved, notices, posted };
}

beforeEach(() => {
  generated.length = 0;
});

describe("落とした値の行に［誤りの印を外す］を置く", () => {
  test("値ごとに札が並び、送る値は記録そのまま", () => {
    const { inner } = panelWith(dropped());

    const line = inner
      .detailOf("character", "char_002")!
      .reference.find((entry) => entry.label === "誤りとして落とした値（summary）");

    expect(line?.value).toBe("寡黙な騎士。（第3話）");
    expect(line?.valueActions).toEqual([
      {
        label: "誤りの印を外す",
        title: expect.stringContaining("「寡黙な騎士。」の誤りの印を外します"),
        field: "summary",
        value: "寡黙な騎士。",
        kind: "undoRejectedValue",
      },
    ]);
  });

  test("同じ項目に2つあれば、札に値の頭を添えて見分けられるようにする", () => {
    const character = dropped();
    character.rejectedValues!.push({
      field: "summary",
      value: "学院で最も古い図書館の司書を務める、物静かな老魔法使い。",
      chapters: [],
      rejectedAt: "x",
    });
    const { inner } = panelWith(character);

    const actions = inner
      .detailOf("character", "char_002")!
      .reference.find((entry) => entry.label === "誤りとして落とした値（summary）")!
      .valueActions!;

    expect(actions.map((action) => action.label)).toEqual([
      "「寡黙な騎士。」の誤りの印を外す",
      "「学院で最も古い図書館の司…」の誤りの印を外す",
    ]);
    expect(actions[1].value).toBe(
      "学院で最も古い図書館の司書を務める、物静かな老魔法使い。"
    );
  });
});

describe("押すと印を1件だけ外す", () => {
  test("押した1件だけが外れ、本体・作者の欄・確定の印は変えない", async () => {
    const { inner, saved, notices } = panelWith(dropped());

    await inner.handleUndoRejectedValue("char_002", "summary", "寡黙な騎士。");

    expect(saved).toHaveLength(1);
    expect(saved[0].kind).toBe("character");
    const record = saved[0].record;
    expect(record.rejectedValues?.map((entry) => entry.field)).toEqual(["role"]);
    expect(record.summary).toBe("明るい見習い魔法使い。");
    expect(record.conflicts).toEqual([]);
    expect(record.authorNotes).toBe("作者メモ");
    expect(record.exportNote).toBe("公開用注記");
    expect(record.autoGenerated).toBe(false);
    expect(notices[0]).toContain("誤りの印を外しました");
    expect(notices[0]).toContain("次の抽出でこの値がまた出れば、食い違いとして並びます");
    // 落とした値は資料集に載せていないので、作り直さない
    expect(generated).toEqual([]);
  });

  test("もう無い（別の窓で先に外された）なら、何も書かずに伝える", async () => {
    const { inner, saved, notices } = panelWith(dropped());

    await inner.handleUndoRejectedValue("char_002", "summary", "金髪");

    expect(saved).toEqual([]);
    expect(notices[0]).toContain("もうありません");
  });

  test("人物が消えていても、落ちずに伝える", async () => {
    const { inner, saved, posted } = panelWith(dropped());

    await inner.handleUndoRejectedValue("char_999", "summary", "寡黙な騎士。");

    expect(saved).toEqual([]);
    expect(posted[0]).toMatchObject({ type: "error" });
  });
});
