function fakeView() {
  return {
    webview: {
      options: {},
      html: "",
      cspSource: "vscode-webview:",
      onDidReceiveMessage: () => ({ dispose: () => undefined }),
      postMessage: () => Promise.resolve(true),
    },
    onDidDispose: () => ({ dispose: () => undefined }),
  };
}

function panelWithView(): ProposalPanel {
  const panel = new ProposalPanel();
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  panel.resolveWebviewView(fakeView() as any);
  return panel;
}

/** 画面のボタンを押したのと同じ（webviewからのメッセージ） */
async function press(
  panel: ProposalPanel,
  type: "apply" | "dismiss" | "applyAll",
  id?: string
): Promise<void> {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  await (panel as any).handleMessage(id ? { type, id } : { type });
}

function idsOf(panel: ProposalPanel): string[] {
  return (panel as unknown as { recordUpdates: Array<{ id: string }> }).recordUpdates.map(
    (entry) => entry.id
  );
}

function lines(): string[] {
  return logged.lines.map((entry) => entry.line);
}

beforeEach(() => {
  logged.lines = [];
  addForeshadow.mockClear();
  addForeshadow.mockImplementation(async () => ({}));
  saveOrUpdateForeshadow.mockClear();
  saveOrUpdateForeshadow.mockImplementation(async () => ({}));
});

describe("伏線の候補", () => {
  test("登録すると、作品のログへ1行残す", async () => {
    const panel = panelWithView();
    showForeshadowCandidates(panel, work, [candidate]);

    await press(panel, "apply", idsOf(panel)[0]);

    expect(lines()).toContain(
      "伏線の候補を登録：伏線「銀の懐中時計」 第3話で張られています（提案パネル）"
    );
    expect(logged.lines.every((entry) => entry.folder === work.folderPath)).toBe(true);
  });

  test("見送っても、作品のログへ1行残す", async () => {
    const panel = panelWithView();
    showForeshadowCandidates(panel, work, [candidate]);

    await press(panel, "dismiss", idsOf(panel)[0]);

    expect(lines()).toEqual([
      "伏線の候補を見送り：伏線「銀の懐中時計」 第3話で張られています（提案パネル）",
    ]);
  });

  test("登録に失敗したら、反映の行は書かない（失敗は logFailure が残す）", async () => {
    addForeshadow.mockImplementation(async () => {
      throw new Error("書き込めませんでした。");
    });
    const panel = panelWithView();
    showForeshadowCandidates(panel, work, [candidate]);

    await press(panel, "apply", idsOf(panel)[0]);

    expect(lines().some((line) => line.startsWith("伏線の候補を登録"))).toBe(false);
  });

  test("まとめて登録しても、1件ずつの行を残す", async () => {
    const panel = panelWithView();
    showForeshadowCandidates(panel, work, [
      candidate,
      { ...candidate, label: "赤い傘", chapter: 5, chunkHash: "hash-005" },
    ]);

    await press(panel, "applyAll");

    expect(lines()).toEqual([
      "伏線の候補を登録：伏線「銀の懐中時計」 第3話で張られています（提案パネル）",
      "伏線の候補を登録：伏線「赤い傘」 第5話で張られています（提案パネル）",
    ]);
  });
});

describe("伏線の回収", () => {
  test("回収済みにすると、張った話と回収の話を1行に残す", async () => {
    const panel = panelWithView();
    showForeshadowResolutions(panel, work, [proposal]);

    await press(panel, "apply", idsOf(panel)[0]);

    expect(lines()).toEqual([
      "伏線の回収を回収済みに：伏線「銀の懐中時計」 第3話で張った→第7話で回収（提案パネル）",
    ]);
  });

  test("見送ると、未回収のまま残したことを1行残す", async () => {
    const panel = panelWithView();
    showForeshadowResolutions(panel, work, [proposal]);

    await press(panel, "dismiss", idsOf(panel)[0]);

    expect(lines()).toEqual([
      "伏線の回収を見送り：伏線「銀の懐中時計」 第3話で張った→第7話で回収（提案パネル）",
    ]);
  });
});

describe("章立て", () => {
  /**
   * 材料の代役。章の台帳（`ChapterStore`）の保存は呼ばれたことにする
   * ——台帳への書き方は `proposeChapters.test.ts` が見ている
   */
  function material(current: ChapterMaterial["current"] = []): ChapterMaterial {
    const episodes = new Map<number, string>([
      [1, "001_旅立ち.txt"],
      [4, "004_峠.txt"],
      [6, "006_王都.txt"],
    ]);
    return {
      episodes: [],
      current,
      store: { save: vi.fn(async () => undefined) },
      set: {
        schemaVersion: "0.1",
        chapters: current.map((chapter) => ({
          name: chapter.name,
          startEpisodePath: chapter.startEpisodePath,
        })),
      },
      episodeOf: (number: number) => ({
        filePath: `${work.folderPath}/本文/${episodes.get(number)}`,
        fileName: episodes.get(number) ?? "",
      }),
      labelOf: (number: number) => `第${number}話`,
      rangeOf: () => new Set<number>(),
      startableAt: () => true,
    } as unknown as ChapterMaterial;
  }

  test("章にすると、章の名前と始まりの話を1行に残す", async () => {
    const panel = panelWithView();
    showChapterProposals(
      panel,
      work,
      material(),
      [{ name: "王都の章", startEpisode: 6, reason: "舞台が王都へ移る" }],
      {}
    );

    await press(panel, "apply", idsOf(panel)[0]);

    expect(lines()).toEqual(["章立てを章に：章「王都の章」 第6話から（提案パネル）"]);
  });

  test("区切りを動かした案は、動かす前の始まりも残す", async () => {
    const panel = panelWithView();
    showChapterProposals(
      panel,
      work,
      material([{ name: "峠の章", startEpisode: 4, startEpisodePath: "本文/004_峠.txt" }]),
      [{ name: "峠の章", startEpisode: 6, reason: "峠越えは第6話から" }],
      {}
    );

    await press(panel, "apply", idsOf(panel)[0]);

    expect(lines()).toEqual([
      "章立てを章に：章「峠の章」 第6話から（第4話から動かした）（提案パネル）",
    ]);
  });

  test("見送っても、作品のログへ1行残す", async () => {
    const panel = panelWithView();
    showChapterProposals(
      panel,
      work,
      material(),
      [{ name: "王都の章", startEpisode: 6, reason: "舞台が王都へ移る" }],
      {}
    );

    await press(panel, "dismiss", idsOf(panel)[0]);

    expect(lines()).toEqual(["章立てを見送り：章「王都の章」 第6話から（提案パネル）"]);
  });
});
