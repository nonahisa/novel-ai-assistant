import { describe, expect, test } from "vitest";
import {
  emptyForeshadow,
  foreshadowFileName,
  nextForeshadowId,
  parseForeshadow,
  type Foreshadow,
} from "../../src/models/foreshadow";

/**
 * 伏線の台帳（設計書6.35.1）。
 *
 * **作者が手で編集するJSONである。** 壊れていたら勝手に直さず、
 * 例外で止めて作者に知らせる（他の設定資料と同じ約束）。
 */

/** 最低限の形。ここから項目を欠けさせて、止まるかを見る */
function validRaw(): Record<string, unknown> {
  return {
    schemaVersion: "0.1",
    id: "foreshadow_001",
    label: "銀の懐中時計",
    note: "祖父の形見。由来がまだ語られていない",
    plantedChapter: 3,
    plantedQuote: "祖父は黙って銀の懐中時計を差し出した",
    status: "open",
    resolvedChapter: null,
    resolvedQuote: "",
    source: "author",
    autoGenerated: false,
    authorNotes: "第12話で使う",
    createdAt: "2026-08-28T00:00:00.000Z",
    updatedAt: "2026-08-28T00:00:00.000Z",
  };
}

describe("伏線のJSONを読む", () => {
  test("正しい形はそのまま読める", () => {
    const parsed = parseForeshadow(validRaw());

    expect(parsed.id).toBe("foreshadow_001");
    expect(parsed.label).toBe("銀の懐中時計");
    expect(parsed.plantedChapter).toBe(3);
    expect(parsed.status).toBe("open");
    expect(parsed.source).toBe("author");
    expect(parsed.authorNotes).toBe("第12話で使う");
  });

  test("省いた項目は既定値で埋まる", () => {
    // 手書きのJSONは項目が欠けている。**欠けただけで止めない**
    const parsed = parseForeshadow({
      id: "foreshadow_002",
      label: "割れた鏡",
    });

    expect(parsed.note).toBe("");
    expect(parsed.plantedChapter).toBeNull();
    expect(parsed.resolvedChapter).toBeNull();
    expect(parsed.status).toBe("open");
    expect(parsed.source).toBe("author");
    expect(parsed.authorNotes).toBe("");
  });

  test("idが無ければ止まる", () => {
    const raw = validRaw();
    delete raw.id;

    expect(() => parseForeshadow(raw)).toThrow(/id/);
  });

  test("labelが無ければ止まる", () => {
    // 見出しが無いと、一覧にも出せずファイル名も決まらない
    const raw = validRaw();
    delete raw.label;

    expect(() => parseForeshadow(raw)).toThrow(/label/);
  });

  test("labelが空文字なら止まる", () => {
    expect(() => parseForeshadow({ ...validRaw(), label: "   " })).toThrow(
      /label/
    );
  });

  test("idの形が違えば止まる", () => {
    // ファイル名とIDの突き合わせが効かなくなる
    expect(() => parseForeshadow({ ...validRaw(), id: "fore_001" })).toThrow(
      /id/
    );
  });

  test("statusの知らない値で止まる", () => {
    // **勝手に「open」へ倒さない。** 作者が書いた値を黙って捨てることになる
    expect(() =>
      parseForeshadow({ ...validRaw(), status: "未回収" })
    ).toThrow(/status/);
  });

  test("sourceの知らない値で止まる", () => {
    expect(() =>
      parseForeshadow({ ...validRaw(), source: "編集部" })
    ).toThrow(/source/);
  });

  test("話数が数字でなければ止まる", () => {
    expect(() =>
      parseForeshadow({ ...validRaw(), plantedChapter: "3" })
    ).toThrow(/plantedChapter/);
    expect(() =>
      parseForeshadow({ ...validRaw(), resolvedChapter: -1 })
    ).toThrow(/resolvedChapter/);
  });

  test("オブジェクトでなければ止まる", () => {
    expect(() => parseForeshadow([])).toThrow();
    expect(() => parseForeshadow(null)).toThrow();
  });
});

describe("伏線のファイル名", () => {
  function withLabel(id: string, label: string): Foreshadow {
    return emptyForeshadow(id, label);
  }

  test("foreshadow_001_ラベル.json の形になる", () => {
    expect(foreshadowFileName(withLabel("foreshadow_001", "銀の懐中時計"))).toBe(
      "foreshadow_001_銀の懐中時計.json"
    );
  });

  test("ファイル名に使えない記号と空白は落とす", () => {
    expect(
      foreshadowFileName(withLabel("foreshadow_002", "祖父の / 形見 ?"))
    ).toBe("foreshadow_002_祖父の形見.json");
  });

  test("記号だけのラベルなら、IDだけの名前にする", () => {
    // 落とした結果が空になっても、名前を作れなくならないようにする
    expect(foreshadowFileName(withLabel("foreshadow_003", "??"))).toBe(
      "foreshadow_003.json"
    );
  });

  test("長すぎるラベルは切り詰める", () => {
    const long = "あ".repeat(50);
    const name = foreshadowFileName(withLabel("foreshadow_004", long));

    expect(name).toBe(`foreshadow_004_${"あ".repeat(30)}.json`);
  });
});

describe("伏線のIDの採番", () => {
  test("空の台帳なら001から始まる", () => {
    expect(nextForeshadowId([])).toBe("foreshadow_001");
  });

  test("いちばん大きい番号の次を採る", () => {
    // 抜けた番号を埋め直すと、消したものと同じIDが復活する
    const existing = [
      emptyForeshadow("foreshadow_001", "あ"),
      emptyForeshadow("foreshadow_007", "い"),
      emptyForeshadow("foreshadow_003", "う"),
    ];

    expect(nextForeshadowId(existing)).toBe("foreshadow_008");
  });

  test("形の違うIDは番号として数えない", () => {
    const existing = [
      emptyForeshadow("foreshadow_002", "あ"),
      { ...emptyForeshadow("foreshadow_003", "い"), id: "temp" },
    ];

    expect(nextForeshadowId(existing)).toBe("foreshadow_003");
  });
});
