import { describe, expect, test } from "vitest";
import { mergeExtractedLocations } from "../../../src/core/settingsMerge";
import {
  emptyLocation,
  withOptionalRelations,
  type Location,
  type LocationRelation,
} from "../../../src/models/location";
import type { ExtractedLocation } from "../../../src/prompts/characterExtract";

/**
 * 位置関係のマージ（設計書6.93.3）。マージはAIでなくコードが行う。
 *
 * （種類, 相手）を鍵に和集合、方角・距離の値違いは食い違いへ、
 * 作者が固定した関係と確定した記録は触らない、相手のIDは並び順に依らない。
 */

function located(
  name: string,
  relations: ExtractedLocation["relations"],
  chapters = [3]
): { data: ExtractedLocation; chapters: number[] } {
  return {
    data: { name, evidence: `${name}の引用`, relations },
    chapters,
  };
}

function withRelations(
  id: string,
  name: string,
  relations: LocationRelation[],
  autoGenerated = true
): Location {
  return withOptionalRelations({ ...emptyLocation(id, name), autoGenerated }, relations);
}

const north: LocationRelation = {
  kind: "direction",
  target: "港",
  targetId: "loc_001",
  value: "北",
  chapters: [2],
  evidence: "学校は港の北に建っている",
  authorLocked: false,
};

describe("関係を足す", () => {
  test("新しい場所に関係を持たせ、相手のIDを引く", () => {
    const result = mergeExtractedLocations(
      [emptyLocation("loc_001", "港")],
      [
        located("学校", [
          { target: "港", kind: "direction", value: "北", evidence: "学校は港の北", chapters: [3] },
        ]),
      ]
    );
    const school = result.locations.find((item) => item.name === "学校");
    expect(school?.relations).toEqual([
      {
        kind: "direction",
        target: "港",
        targetId: "loc_001",
        value: "北",
        chapters: [3],
        evidence: "学校は港の北",
        authorLocked: false,
      },
    ]);
  });

  test("同じ関係は1つにまとめ、話数を足す", () => {
    const result = mergeExtractedLocations(
      [emptyLocation("loc_001", "港"), withRelations("loc_002", "学校", [north])],
      [
        located("学校", [
          { target: "港", kind: "direction", value: "北", evidence: "港の北の学校", chapters: [5] },
        ], [5]),
      ]
    );
    const school = result.locations.find((item) => item.id === "loc_002");
    expect(school?.relations).toHaveLength(1);
    expect(school?.relations?.[0].chapters).toEqual([2, 5]);
    // 先にあった根拠は残す
    expect(school?.relations?.[0].evidence).toBe("学校は港の北に建っている");
    expect(result.conflicts).toEqual([]);
  });

  test("相手のIDは答えの並び順に依らない（相手が後から足されても引ける）", () => {
    const relation = {
      target: "港町",
      kind: "within",
      value: null,
      evidence: "港町の外れに港がある",
      chapters: [3],
    };
    const forward = mergeExtractedLocations([], [
      located("港", [relation]),
      located("港町", []),
    ]);
    const backward = mergeExtractedLocations([], [
      located("港町", []),
      located("港", [relation]),
    ]);
    const idOf = (locations: Location[], name: string) =>
      locations.find((item) => item.name === name)?.id;
    const targetIdOf = (locations: Location[]) =>
      locations.find((item) => item.name === "港")?.relations?.[0].targetId;

    expect(targetIdOf(forward.locations)).toBe(idOf(forward.locations, "港町"));
    expect(targetIdOf(backward.locations)).toBe(idOf(backward.locations, "港町"));
  });

  test("台帳に無い相手はIDを持たない（名前だけで残す）", () => {
    const result = mergeExtractedLocations([], [
      located("学校", [
        { target: "港", kind: "adjacent", value: null, evidence: "学校は港に隣り合う", chapters: [3] },
      ]),
    ]);
    expect(result.locations[0].relations?.[0].targetId).toBeNull();
  });

  test("別名で書かれた自分自身への関係は外す", () => {
    const harbor = { ...emptyLocation("loc_001", "リヴェルス港"), aliases: ["港"] };
    const result = mergeExtractedLocations(
      [harbor, emptyLocation("loc_002", "港町")],
      [
        located("リヴェルス港", [
          // 台帳では「港」はこの場所自身の別名
          { target: "港", kind: "adjacent", value: null, evidence: "x", chapters: [3] },
          { target: "港町", kind: "within", value: null, evidence: "y", chapters: [3] },
        ]),
      ]
    );
    expect(
      result.locations.find((item) => item.id === "loc_001")?.relations?.map((r) => r.target)
    ).toEqual(["港町"]);
  });
});

describe("値が食い違ったら本体を変えず食い違いへ", () => {
  test("方角が違えば conflicts に両方の話数と根拠を残す", () => {
    const result = mergeExtractedLocations(
      [emptyLocation("loc_001", "港"), withRelations("loc_002", "学校", [north])],
      [
        located("学校", [
          { target: "港", kind: "direction", value: "南", evidence: "学校は港の南", chapters: [7] },
        ], [7]),
      ]
    );
    const school = result.locations.find((item) => item.id === "loc_002");
    expect(school?.relations?.[0].value).toBe("北");
    expect(school?.conflicts).toEqual([
      {
        field: "位置関係：港から見た方角",
        values: ["北", "南"],
        chapters: [],
        note: null,
        observations: [
          { value: "北", chapters: [2], evidence: "学校は港の北に建っている" },
          { value: "南", chapters: [7], evidence: "学校は港の南" },
        ],
      },
    ]);
    expect(result.conflicts).toEqual([
      { name: "学校", field: "位置関係：港から見た方角", values: ["北", "南"] },
    ]);
  });

  test("距離の食い違いは、方角の食い違いと別の項目にする", () => {
    const distance: LocationRelation = {
      ...north,
      kind: "distance",
      value: "徒歩10分",
    };
    const result = mergeExtractedLocations(
      [emptyLocation("loc_001", "港"), withRelations("loc_002", "学校", [north, distance])],
      [
        located("学校", [
          { target: "港", kind: "direction", value: "南", evidence: "a", chapters: [7] },
          { target: "港", kind: "distance", value: "徒歩1時間", evidence: "b", chapters: [7] },
        ], [7]),
      ]
    );
    const fields = result.locations
      .find((item) => item.id === "loc_002")
      ?.conflicts.map((entry) => entry.field);
    expect(fields).toEqual(["位置関係：港から見た方角", "位置関係：港からの距離"]);
  });
});

describe("作者の関係を壊さない（実装ルール2）", () => {
  test("作者が固定した関係は、値も話数も変えない", () => {
    const locked: LocationRelation = { ...north, authorLocked: true, chapters: [] };
    const result = mergeExtractedLocations(
      [emptyLocation("loc_001", "港"), withRelations("loc_002", "学校", [locked])],
      [
        located("学校", [
          { target: "港", kind: "direction", value: "南", evidence: "学校は港の南", chapters: [7] },
        ], [7]),
      ]
    );
    const school = result.locations.find((item) => item.id === "loc_002");
    expect(school?.relations).toEqual([locked]);
    expect(school?.conflicts).toEqual([]);
  });

  test("確定した記録（autoGenerated: false）には関係を足さない", () => {
    const result = mergeExtractedLocations(
      [withRelations("loc_002", "学校", [], false)],
      [
        located("学校", [
          { target: "港", kind: "direction", value: "北", evidence: "学校は港の北", chapters: [3] },
        ]),
      ]
    );
    const school = result.locations[0];
    // 空の欄も書き足さない
    expect(school).not.toHaveProperty("relations");
    // 登場話数の追記だけはする
    expect(school.appearedChapters).toEqual([3]);
  });

  test("確定した記録の関係のIDは、引き直さない", () => {
    const authored: LocationRelation = { ...north, targetId: null, authorLocked: true };
    const result = mergeExtractedLocations(
      [emptyLocation("loc_001", "港"), withRelations("loc_002", "学校", [authored], false)],
      [located("学校", [], [4])]
    );
    expect(result.locations.find((item) => item.id === "loc_002")?.relations).toEqual([
      authored,
    ]);
  });
});
