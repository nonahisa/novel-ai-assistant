import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { mergeExtractedCharacters } from "../../../src/core/characterMerge";
import {
  markPersonalityChange,
  restorePersonalityFacet,
} from "../../../src/core/personalityFacets";
import {
  factsRevealedAfter,
  recordAsOf,
} from "../../../src/core/settingsAsOf";
import {
  emptyCharacter,
  parseCharacter,
  type Character,
} from "../../../src/models/character";

/**
 * 性格を「面ごとに積む」（作者の裁定、2026-09-24 夜。縛りの洗い出し4番）。
 *
 * 以前は性格を外見と同じ「上書き型の1つの値」として扱っていたので、
 * 第1話で見えた面と第5話で見えた別の面が「作中の変化」として積まれ、
 * 本体は最後の話の一面に置き換わっていた。同じ話で2つの面が出れば
 * 「食い違い」として作者の判断待ちに止まっていた。
 *
 * 答え付きの台（`test/fixtures/seeded/contradiction`）の黒瀬千夏で試す。
 * 第1話では水筒を差し出して世話を焼き、第5話では相沢の変化をよく見ている
 * ——**どちらも同時に成り立つ面**で、変化ではない。
 */

const FIXTURE = join(
  __dirname,
  "../../fixtures/seeded/contradiction/設定/characters"
);

/** 台の人物を「AIが作ったばかりの記録」として読み込む（性格はまだ空） */
function aiGeneratedFromFixture(file: string): Character {
  const raw = JSON.parse(readFileSync(join(FIXTURE, file), "utf8")) as unknown;
  const character = parseCharacter(raw);
  return {
    ...character,
    personality: null,
    appearedChapters: [],
    autoGenerated: true,
  };
}

const CH1_FACET = "世話焼き（出がけの相沢に水筒を差し出す）";
const CH1_EVIDENCE = "「忘れてる。毎回言ってるでしょ」";
const CH5_FACET = "人の変化によく気づく（相沢が客の顔を見ていたと言い当てる）";
const CH5_EVIDENCE = "「お客さんの顔、見てた」";

describe("性格を面ごとに積む", () => {
  test("第1話と第5話で見えた別の面が、両方とも残る", () => {
    const chinatsu = aiGeneratedFromFixture("char_0002.json");

    const first = mergeExtractedCharacters([chinatsu], [
      {
        data: {
          name: "黒瀬 千夏",
          personality: CH1_FACET,
          evidence: CH1_EVIDENCE,
        },
        chapters: [1],
      },
    ]);
    const second = mergeExtractedCharacters(first.characters, [
      {
        data: { name: "千夏", personality: CH5_FACET, evidence: CH5_EVIDENCE },
        chapters: [5],
      },
    ]);
    const result = second.characters[0];

    // 本体（資料・紹介・AIへの材料が読む欄）に両方の面が載る
    expect(result.personality).toContain(CH1_FACET);
    expect(result.personality).toContain(CH5_FACET);
    // 面ごとに、どの話で見えたかと根拠を持つ
    expect(result.personalityFacets).toEqual([
      { value: CH1_FACET, chapters: [1], evidence: CH1_EVIDENCE },
      { value: CH5_FACET, chapters: [5], evidence: CH5_EVIDENCE },
    ]);
    // 起きていない「性格の変化」を作らない。食い違いとしても止めない
    expect(result.changes.filter((c) => c.field === "personality")).toEqual([]);
    expect(result.conflicts).toEqual([]);
    expect(second.folded).toEqual([]);
    expect(second.conflicts).toEqual([]);
  });

  test("同じ話の中で2つの面が見えても、食い違いで止めない", () => {
    const chinatsu = aiGeneratedFromFixture("char_0002.json");

    const result = mergeExtractedCharacters([chinatsu], [
      { data: { name: "黒瀬 千夏", personality: "よく喋る" }, chapters: [3] },
      { data: { name: "黒瀬 千夏", personality: "ふと黙り込む" }, chapters: [3] },
    ]);
    const merged = result.characters[0];

    expect(merged.conflicts).toEqual([]);
    expect(result.conflicts).toEqual([]);
    expect(merged.personalityFacets.map((f) => f.value)).toEqual([
      "よく喋る",
      "ふと黙り込む",
    ]);
    expect(merged.personality).toBe("よく喋る／ふと黙り込む");
  });

  test("同じ面が別の話にも出たら、話数だけを足す", () => {
    const character = emptyCharacter("char_001", "灯");

    const result = mergeExtractedCharacters([character], [
      { data: { name: "灯", personality: "冷静" }, chapters: [1] },
      { data: { name: "灯", personality: "冷静" }, chapters: [4] },
    ]);

    expect(result.characters[0].personality).toBe("冷静");
    expect(result.characters[0].personalityFacets).toEqual([
      { value: "冷静", chapters: [1, 4], evidence: null },
    ]);
  });

  test("詳しく書き直した面は1つにまとめる（別の面として増やさない）", () => {
    const character = emptyCharacter("char_001", "灯");

    const result = mergeExtractedCharacters([character], [
      { data: { name: "灯", personality: "臆病" }, chapters: [1] },
      { data: { name: "灯", personality: "臆病で人見知り" }, chapters: [2] },
      { data: { name: "灯", personality: "冷静" }, chapters: [3] },
    ]);

    expect(result.characters[0].personality).toBe("臆病で人見知り／冷静");
    expect(result.characters[0].personalityFacets.map((f) => f.chapters)).toEqual([
      [1, 2],
      [3],
    ]);
  });

  test("作者が確定させた人物には、面を足さない（登場話数の追記だけ）", () => {
    const character = emptyCharacter("char_001", "灯");
    character.autoGenerated = false;
    character.personality = "作者が書いた性格";

    const result = mergeExtractedCharacters([character], [
      { data: { name: "灯", personality: "AIの読み" }, chapters: [2] },
    ]);

    expect(result.characters[0].personality).toBe("作者が書いた性格");
    expect(result.characters[0].personalityFacets).toEqual([]);
    expect(result.characters[0].appearedChapters).toEqual([2]);
  });
});

describe("古い形の資料", () => {
  test("面の欄が無いJSONも読める", () => {
    const raw = JSON.parse(
      readFileSync(join(FIXTURE, "char_0001.json"), "utf8")
    ) as unknown;
    const character = parseCharacter(raw);

    expect(character.personalityFacets).toEqual([]);
    expect(character.personality).toBe(
      "人見知りで、窓口に立つと客と目を合わせられない。"
    );
  });

  test("壊れた面の欄は読み込みエラーにする（黙って空にしない）", () => {
    expect(() =>
      parseCharacter({
        id: "char_001",
        name: "灯",
        personalityFacets: [{ value: 1 }],
      })
    ).toThrow("personalityFacets");
  });

  test("以前「変化」として積まれた性格は、面へ移して年表から外す", () => {
    // 0.86.0 までのマージが作った形：第1話と第5話の性格が変化として並び、
    // 本体は第5話の値だけになっていた
    const character = emptyCharacter("char_001", "灯");
    character.personality = "臆病";
    character.changes = [
      {
        field: "personality",
        value: "面倒見がよい",
        chapters: [1],
        timepointId: null,
        note: null,
        evidence: "「ほら、水筒」",
        source: "extracted",
      },
      {
        field: "personality",
        value: "臆病",
        chapters: [5],
        timepointId: null,
        note: null,
        evidence: "「無理です」",
        source: "extracted",
      },
      {
        field: "appearance",
        value: "黒髪",
        chapters: [1],
        timepointId: null,
        note: null,
        evidence: null,
        source: "extracted",
      },
    ];

    // 今回の抽出に出てこなくても移す（年表から起きていない変化を消すため）
    const result = mergeExtractedCharacters([character], []);
    const migrated = result.characters[0];

    expect(migrated.personality).toBe("面倒見がよい／臆病");
    expect(migrated.personalityFacets).toEqual([
      { value: "面倒見がよい", chapters: [1], evidence: "「ほら、水筒」" },
      { value: "臆病", chapters: [5], evidence: "「無理です」" },
    ]);
    // 性格の「変化」は消え、外見の記録は触らない
    expect(migrated.changes.map((c) => c.field)).toEqual(["appearance"]);
    expect(result.changedIds).toEqual(["char_001"]);
    expect(result.personalityMigrated).toEqual(["灯"]);
  });

  test("同じ話で食い違いとして止まっていた性格も、面へ移す", () => {
    const character = emptyCharacter("char_001", "灯");
    character.personality = "よく喋る";
    character.conflicts = [
      {
        field: "personality",
        values: ["よく喋る", "ふと黙り込む"],
        chapters: [3],
        note: null,
        observations: [
          { value: "よく喋る", chapters: [3] },
          { value: "ふと黙り込む", chapters: [3], evidence: "千夏は黙った。" },
        ],
      },
    ];

    const migrated = mergeExtractedCharacters([character], []).characters[0];

    expect(migrated.conflicts).toEqual([]);
    expect(migrated.personality).toBe("よく喋る／ふと黙り込む");
    expect(migrated.personalityFacets[1]).toEqual({
      value: "ふと黙り込む",
      chapters: [3],
      evidence: "千夏は黙った。",
    });
  });

  test("作者が確定させた人物の古い記録は移さない", () => {
    const character = emptyCharacter("char_001", "灯");
    character.autoGenerated = false;
    character.personality = "臆病";
    character.changes = [
      {
        field: "personality",
        value: "臆病",
        chapters: [5],
        timepointId: null,
        note: null,
        evidence: null,
        source: "extracted",
      },
    ];

    const result = mergeExtractedCharacters([character], []);

    expect(result.characters[0]).toEqual(character);
    expect(result.changedIds).toEqual([]);
    expect(result.personalityMigrated).toEqual([]);
  });

  test("面だけ持っていて本体が空でない古い記録は、話を持たない面として扱う", () => {
    // 面の仕組みより前に入った本体の値は、次に面が来たときに最初の面になる
    const character = emptyCharacter("char_001", "灯");
    character.personality = "温厚";

    const merged = mergeExtractedCharacters([character], [
      { data: { name: "灯", personality: "頑固" }, chapters: [2] },
    ]).characters[0];

    expect(merged.personality).toBe("温厚／頑固");
    expect(merged.personalityFacets).toEqual([
      { value: "温厚", chapters: [], evidence: null },
      { value: "頑固", chapters: [2], evidence: null },
    ]);
  });
});

describe("作者が「作中で変わった」と決める", () => {
  /** 台の相沢春人：第3話では人見知り、第5話では客の顔をまっすぐ見る */
  function haruto(): Character {
    const character = aiGeneratedFromFixture("char_0001.json");
    return mergeExtractedCharacters([character], [
      {
        data: {
          name: "相沢 春人",
          personality: "人見知り",
          evidence: "伝票の枠線しか見ていなかった",
        },
        chapters: [3],
      },
      {
        data: { name: "相沢 春人", personality: "面倒見がよい" },
        chapters: [3],
      },
      {
        data: {
          name: "相沢 春人",
          personality: "客の目をまっすぐ見て話せる",
          evidence: "客の顔を、まっすぐ見ていた。",
        },
        chapters: [5],
      },
    ]).characters[0];
  }

  test("変わる前の面は過去の面になり、本体から外れ、変化として記録される", () => {
    const before = haruto();
    expect(before.personality).toBe(
      "人見知り／面倒見がよい／客の目をまっすぐ見て話せる"
    );

    const outcome = markPersonalityChange(
      before,
      "人見知り",
      "客の目をまっすぐ見て話せる"
    );
    expect(outcome).toBeDefined();
    const after = outcome!.character;

    expect(after.personality).toBe("面倒見がよい／客の目をまっすぐ見て話せる");
    expect(outcome!.bodyUpdated).toBe(true);
    expect(after.personalityFacets[0]).toMatchObject({
      value: "人見知り",
      supersededBy: "客の目をまっすぐ見て話せる",
    });
    // 年表・資料の「変化」は、作者が決めたものだけ。作者が認めた印を立てる
    const changes = after.changes.filter((c) => c.field === "personality");
    expect(changes.map((c) => [c.value, c.chapters, c.confirmed])).toEqual([
      ["人見知り", [3], true],
      ["客の目をまっすぐ見て話せる", [5], true],
    ]);
    // 作者が触ったのは性格の読み方だけ。人物全体を引き取ったことにはしない
    expect(after.autoGenerated).toBe(true);
    // 元の記録は書き換えない
    expect(before.personalityFacets[0].supersededBy).toBeUndefined();
  });

  test("決めたあとの抽出で同じ面がまた見えても、本体へ戻さない", () => {
    const changed = markPersonalityChange(
      haruto(),
      "人見知り",
      "客の目をまっすぐ見て話せる"
    )!.character;

    const again = mergeExtractedCharacters([changed], [
      { data: { name: "相沢 春人", personality: "人見知り" }, chapters: [4] },
    ]).characters[0];

    expect(again.personality).toBe("面倒見がよい／客の目をまっすぐ見て話せる");
    expect(again.personalityFacets[0].chapters).toEqual([3, 4]);
  });

  test("面に戻すと、本体へ戻る", () => {
    const changed = markPersonalityChange(
      haruto(),
      "人見知り",
      "客の目をまっすぐ見て話せる"
    )!.character;

    const restored = restorePersonalityFacet(changed, "人見知り");

    expect(restored).toBeDefined();
    expect(restored!.character.personality).toBe(
      "面倒見がよい／客の目をまっすぐ見て話せる／人見知り"
    );
    expect(restored!.character.personalityFacets[0].supersededBy).toBeUndefined();
  });

  test("本体が手で書き換えられていたら、本体には触らずに知らせる", () => {
    const edited = { ...haruto(), personality: "作者が書き直した性格" };

    const outcome = markPersonalityChange(
      edited,
      "人見知り",
      "客の目をまっすぐ見て話せる"
    );

    expect(outcome!.bodyUpdated).toBe(false);
    expect(outcome!.character.personality).toBe("作者が書き直した性格");
  });

  test("無い面を指定したら何もしない", () => {
    expect(markPersonalityChange(haruto(), "存在しない面", "人見知り")).toBeUndefined();
    expect(markPersonalityChange(haruto(), "人見知り", "人見知り")).toBeUndefined();
  });
});

describe("その話の時点の性格（矛盾検知・資料の巻き戻し）", () => {
  test("まだ見えていない面は、その話の時点の材料に入れない", () => {
    const chinatsu = mergeExtractedCharacters(
      [aiGeneratedFromFixture("char_0002.json")],
      [
        { data: { name: "黒瀬 千夏", personality: CH1_FACET }, chapters: [1] },
        { data: { name: "黒瀬 千夏", personality: CH5_FACET }, chapters: [5] },
      ]
    ).characters[0];

    expect(recordAsOf(chinatsu, ["personality"], 3).personality).toBe(CH1_FACET);
    expect(recordAsOf(chinatsu, ["personality"], 5).personality).toBe(
      `${CH1_FACET}／${CH5_FACET}`
    );
    expect(factsRevealedAfter(chinatsu, ["personality"], 3)).toEqual([
      { field: "personality", value: CH5_FACET, chapter: 5 },
    ]);
  });

  test("作者が変化と決めた面は、変わる前の話ではまだ本体にある", () => {
    const character = emptyCharacter("char_001", "灯");
    const merged = mergeExtractedCharacters([character], [
      { data: { name: "灯", personality: "臆病" }, chapters: [1] },
      { data: { name: "灯", personality: "勇敢" }, chapters: [8] },
    ]).characters[0];
    const changed = markPersonalityChange(merged, "臆病", "勇敢")!.character;

    expect(recordAsOf(changed, ["personality"], 3).personality).toBe("臆病");
    expect(recordAsOf(changed, ["personality"], 8).personality).toBe("勇敢");
  });
});
