import { describe, expect, test } from "vitest";
import { findExecutionClaim } from "../../../src/core/chatExecutionClaim";

/**
 * 相談のAIが、操作を実行したふりをする（0.86.10 の担当の報告）。
 *
 * 相談のAIは操作を動かせない（返せるのは文章と、作者が押す実行ボタンだけ）。
 * それでも旧名で頼まれた gemma4:26b は「診断を実行します」と答えた。
 * P-21 には 3.13 から「実行したふりをしないこと」と書いてあるが守られない
 * （頼むだけでは足りない。実装ルール3）。**答えの言い切りをコードで見張る。**
 *
 * 見逃しと誤検出の両方を測る（CLAUDE.md の繰り返し起きた失敗2）。
 */

describe("実行したと言い切る答えを見つける", () => {
  const claims = [
    // 0.86.10 の担当の報告の形（26b、旧名「ターゲット読者診断」を頼まれて）
    "承知いたしました。ターゲット読者診断を実行します。",
    // 3.13 のきっかけ（作者の実機報告、2026-09-21 23:10）
    "実行します。完了したら結果をお知らせします。",
    "誤字脱字の検知を開始しました。しばらくお待ちください。",
    "では、設定資料の抽出を始めます。",
    "ただいま診断中です。",
    "伏線の検知を行います。終わり次第、結果をお伝えします。",
    "かしこまりました、冒頭診断を実行いたしました。",
  ];
  for (const reply of claims) {
    test(`見つける：${reply}`, () => {
      expect(findExecutionClaim(reply)).toBeDefined();
    });
  }

  test("見つけた文を返す（作者へ見せる一言に使う）", () => {
    expect(
      findExecutionClaim("承知いたしました。ターゲット読者診断を実行します。結果をご覧ください")
    ).toBe("ターゲット読者診断を実行します");
  });
});

describe("操作の案内・できないという断りは、言い切りと取り違えない", () => {
  const guides = [
    "下の「ターゲット読者」を押すと、診断を実行します。",
    "詳細メニューの『自己校正』→『読者診断』→『ターゲット読者』から実行できます。",
    "私はこの拡張機能の操作を実行できません。押すのは作者です。",
    "ボタンを押すと抽出が始まります。",
    "実行すると、提案パネルに指摘が並びます。",
    "まず設定資料の抽出を実行してください。",
    "誤字脱字検知を実行しましょう。",
    "実行しません。",
    "この話の主人公は、終盤で作戦を実行しますが、動機が弱く見えます。",
  ];
  for (const reply of guides) {
    test(`見つけない：${reply}`, () => {
      expect(findExecutionClaim(reply)).toBeUndefined();
    });
  }
});
