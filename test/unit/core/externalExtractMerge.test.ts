/**
 * 外部AIの抽出を、製品と同じ順で資料にする（`replayExtraction`。2026-10-02）。
 *
 * **見張るのはパリティ（同じ答えの列から、製品と同じ資料ができること）。**
 * 比べる相手は、切り出す前の `features/extractCharacters.ts` と
 * `features/extractSettings.ts` の `persist` が並べていた手順そのもの
 * （下の `productPath`）。片方だけ直ると、外部AIで抽出した作品だけ資料の
 * 中身が変わる。番号の採り方は並び順に依るので、ここが並びの検算にもなる。
 */

function chunkOf(filePath: string, chapter: number, text: string): Chunk {
  const sources = episodeBodySources(filePath, text, {
    chapterStart: chapter,
    chapterEnd: chapter,
  });
  return chunksOfSources(sources, { maxChars: 4000 })[0];
}

