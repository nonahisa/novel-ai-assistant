import { describe, expect, test } from "vitest";
import { searchTermsFor } from "../../../src/core/settingsEnrichCheck";
import { parseCharacter } from "../../../src/models/character";

function person(id: number, name: string, aliases: string[] = []) {
  return parseCharacter({
    schemaVersion: "0.1",
    id: `char_${String(id).padStart(4, "0")}`,
    name,
    aliases,
    appearedChapters: [1],
    autoGenerated: true,
    authorNotes: "",
    updatedAt: "2026-10-02T00:00:00.000Z",
  });
}

/*
  教科書チート（2026-10-02）：「フォー・シーゲン」の「シーゲン」が一家の別人も含めて
  294回当たり、本人の「フォー」（3回）の場面が抜粋から落ちた
*/
describe("再読込の検索語から家名を外す", () => {
  const four = person(1, "フォー・シーゲン");
  const family = [
    four,
    person(2, "ユニィ・シーゲン"),
    person(3, "シーゲン子爵"),
    person(4, "リシャス・シーゲン"),
  ];

  test("一家で共有する家名は引かず、名とフルネームは引く", () => {
    const terms = searchTermsFor("character", four, family);

    expect(terms).toContain("フォー・シーゲン");
    expect(terms).toContain("フォー");
    expect(terms).not.toContain("シーゲン");
  });

  test("家名を共有する人物が他に居なければ、切り出した部分はそのまま引く", () => {
    const alone = person(5, "ウニト・ベクタ");

    const terms = searchTermsFor("character", alone, [alone, person(6, "宗一")]);

    expect(terms).toEqual(["ウニト・ベクタ", "ウニト", "ベクタ"]);
  });

  test("作者が別名に書いた家名は引く", () => {
    const called = person(7, "フォー・シーゲン", ["シーゲン"]);

    const terms = searchTermsFor("character", called, [called, ...family.slice(1)]);

    expect(terms).toContain("シーゲン");
  });

  test("人物の一覧を渡さなければ、これまでと同じ（世界観・相談の道）", () => {
    expect(searchTermsFor("character", four)).toEqual([
      "フォー・シーゲン",
      "フォー",
      "シーゲン",
    ]);
  });
});
