import { describe, expect, test } from "vitest";
import { PHOTO_PARAGRAPH_SCRIPT } from "../../../src/core/photoParagraphs";

/**
 * 写真から起こした文を、段落ごとにつなぐ（設計書6.117.12）。
 *
 * 作者の指摘（2026-10-15）：ノートの行に合わせて改行されているが、段落の
 * 切れ目以外に改行はいらない。AIにはノートの行のまま書き起こさせ（写真と
 * 見比べやすい）、つなぐのはコードが行う。
 *
 * つなぐ処理は画面（WebView）の中で動くので、素の JS の文字列で持っている。
 * ここでは**画面に埋め込むのと同じ文字列**を評価して試す。
 */
type Join = (text: string) => string;

function load(): Join {
  return new Function(`${PHOTO_PARAGRAPH_SCRIPT}\nreturn joinPhotoParagraphs;`)() as Join;
}

const join = load();

/** 改行と空白（全角を含む）を除いた字の並び。つないでも字が変わらないことを見る */
function letters(text: string): string {
  return text.replace(/\s/g, "");
}

function expectSameLetters(source: string): string {
  const joined = join(source);
  expect(letters(joined)).toBe(letters(source));
  return joined;
}

describe("段落ごとにつなぐ", () => {
  test("行の頭が字下げなら、そこで段落を分ける（全角空白・半角空白・タブ）", () => {
    const source = [
      "　朝の光が窓から差し込んで、部屋の",
      "隅に置いた鉢植えを照らしていた。私",
      "はしばらくそれを眺めていたが、やが",
      "て立ち上がった。",
      "　外は思ったより寒かった。息が白く",
      "なり、指先がすぐに冷えていくのが分",
      "かった。",
      " 半角の字下げでも段落になる。そうで",
      "なければ困る。",
      "\tタブの字下げでも段落になる。そうで",
      "なければ困るのだ。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      [
        "　朝の光が窓から差し込んで、部屋の隅に置いた鉢植えを照らしていた。私はしばらくそれを眺めていたが、やがて立ち上がった。",
        "　外は思ったより寒かった。息が白くなり、指先がすぐに冷えていくのが分かった。",
        " 半角の字下げでも段落になる。そうでなければ困る。",
        "\tタブの字下げでも段落になる。そうでなければ困るのだ。",
      ].join("\n")
    );
  });

  test("「で始まる行（会話）は、そこで段落を分ける", () => {
    const source = [
      "　彼女はしばらく黙っていたが、やがて",
      "顔を上げてこちらを見た。",
      "「本当にそれでいいの？　あなたは後悔",
      "しないの」",
      "『それは本の題名だ』と私は言いかけて",
      "やめた。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      [
        "　彼女はしばらく黙っていたが、やがて顔を上げてこちらを見た。",
        "「本当にそれでいいの？　あなたは後悔しないの」",
        "『それは本の題名だ』と私は言いかけてやめた。",
      ].join("\n")
    );
  });

  test("行の途中で終わっている行（目に見えて短い行）のあとで段落を分ける", () => {
    // 字下げも会話も無い書き方。短い行が段落の終わり
    const source = [
      "雨が降り始めたのは夕方のことだった。",
      "駅までの道はすでに濡れていて、私は",
      "傘を持ってこなかったことを悔やんだ。",
      "仕方なく走った。",
      "駅に着いたときには、肩も背中もすっ",
      "かり濡れてしまっていた。電車はまだ",
      "来ていなかった。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      [
        "雨が降り始めたのは夕方のことだった。駅までの道はすでに濡れていて、私は傘を持ってこなかったことを悔やんだ。仕方なく走った。",
        "駅に着いたときには、肩も背中もすっかり濡れてしまっていた。電車はまだ来ていなかった。",
      ].join("\n")
    );
  });

  test("」』で終わる行のあとで段落を分ける（行の長さが揃っていても）", () => {
    const source = [
      "　私は彼の顔を見て、思わず「待って」",
      "と言いそうになった。それほどに彼の",
      "顔は青ざめていた。私は黙ったまま、",
      "その場に立ち尽くしていた。『春の雪』",
      "あの本のことを、彼はまだ覚えていた。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      [
        "　私は彼の顔を見て、思わず「待って」",
        "と言いそうになった。それほどに彼の顔は青ざめていた。私は黙ったまま、その場に立ち尽くしていた。『春の雪』",
        "あの本のことを、彼はまだ覚えていた。",
      ].join("\n")
    );
  });

  test("空行はそのまま段落の区切りとして残す", () => {
    const source = [
      "　一つ目の段落の始まりで、ここから",
      "続きの行へとつながっていく文章だ。",
      "",
      "　二つ目の段落の始まりで、ここから",
      "続きの行へとつながっていく文章だ。",
      "",
      "",
      "　三つ目。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      [
        "　一つ目の段落の始まりで、ここから続きの行へとつながっていく文章だ。",
        "",
        "　二つ目の段落の始まりで、ここから続きの行へとつながっていく文章だ。",
        "",
        "",
        "　三つ目。",
      ].join("\n")
    );
  });

  test("〓（読めない字）を含む行も、同じ規則でつなぐ", () => {
    const source = [
      "　その日の〓〓は、いつもより少し早",
      "く目が覚めた。窓の外では〓が鳴いて",
      "いた。",
      "〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓",
      "〓〓〓で終わる行。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      [
        "　その日の〓〓は、いつもより少し早く目が覚めた。窓の外では〓が鳴いていた。",
        "〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓〓で終わる行。",
      ].join("\n")
    );
  });

  test("英字どうしがつながる所だけ、半角空白を1つ入れる（字は変わらない）", () => {
    const source = [
      "　彼が口にしたのは、Good morning",
      "everyone という一言だけで、その声は",
      "思ったより低く、部屋の奥まで響いた",
      "ように感じられた。私はただうなずき",
      "Hello と返すことしかできなかった。",
    ].join("\n");
    const joined = expectSameLetters(source);
    expect(joined).toBe(
      "　彼が口にしたのは、Good morning everyone という一言だけで、その声は思ったより低く、部屋の奥まで響いたように感じられた。私はただうなずきHello と返すことしかできなかった。"
    );
  });

  test("行が1つだけなら、そのまま返す", () => {
    expect(join("　ただ一行だけの書き起こし。")).toBe("　ただ一行だけの書き起こし。");
    expect(join("")).toBe("");
  });

  test("短い行ばかりのページ（会話の続き）でも、字下げ・括弧の規則で分ける", () => {
    const source = [
      "「うん」",
      "「そう」",
      "「明日も来る？」",
      "「たぶん」",
      "　沈黙。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(source);
  });

  test("短い行ばかりで規則に当たらない行は、つないでよい（揃っていれば途中で終わったとは見ない）", () => {
    const source = ["朝の光が", "差し込んで", "部屋を満たす", "そんな日に"].join("\n");
    expect(expectSameLetters(source)).toBe("朝の光が差し込んで部屋を満たすそんな日に");
  });

  test("1行の字数が揺れる手書きの地の文だけのページで、揺れでは切らない", () => {
    // 手書きのノートは1行の字数が揃わない（±2〜3字）。どれも段落の途中
    const source = [
      "　夏の終わりの午後、私は古い家の縁側に",
      "座って、庭の向こうに広がる田んぼを眺",
      "めていた。風が吹くたびに稲の穂が揺れ、",
      "遠くの山の端に白い雲がゆっくりと流れ",
      "ていくのが見えた。祖母が生きていた頃",
      "には、この縁側でよく西瓜を食べたも",
      "のだと、ぼんやり思い出していた。",
    ].join("\n");
    expect(expectSameLetters(source)).toBe(
      "　夏の終わりの午後、私は古い家の縁側に座って、庭の向こうに広がる田んぼを眺めていた。風が吹くたびに稲の穂が揺れ、遠くの山の端に白い雲がゆっくりと流れていくのが見えた。祖母が生きていた頃には、この縁側でよく西瓜を食べたものだと、ぼんやり思い出していた。"
    );
  });

  test("行が2つだけなら、長いほうを基準に短い行を見る", () => {
    expect(join("一行目はここで終わり。\n二行目はずっと長く続いていく文章になっている。")).toBe(
      "一行目はここで終わり。\n二行目はずっと長く続いていく文章になっている。"
    );
    expect(join("二行目へ続いていく長い文章の一行目で、\nここまで。")).toBe(
      "二行目へ続いていく長い文章の一行目で、ここまで。"
    );
  });

  test("いろいろな行の並びで、改行と空白のほかは一字も変わらない", () => {
    // 字下げ・括弧・〓・英字・空行・長さの違う行を混ぜた並びを、決まった種から作る
    const pieces = ["あ", "漢", "〓", "「", "」", "』", "　", " ", "a", "Z", "1", "。", "𠮷"];
    let seed = 12345;
    const next = (max: number): number => {
      seed = (seed * 1103515245 + 12345) % 2147483648;
      return seed % max;
    };
    for (let round = 0; round < 300; round++) {
      const lines: string[] = [];
      const count = 1 + next(12);
      for (let line = 0; line < count; line++) {
        let text = "";
        const length = next(22);
        for (let at = 0; at < length; at++) text += pieces[next(pieces.length)];
        lines.push(text);
      }
      expectSameLetters(lines.join(next(2) === 0 ? "\n" : "\r\n"));
    }
  });

  test("CRLF の改行も扱い、行末の空白は残したままつなぐ（字は変わらない）", () => {
    const source = "　行末に空白のある行で、ここから続く　\r\n文章の二行目になっている行だ。";
    const joined = expectSameLetters(source);
    expect(joined).toBe("　行末に空白のある行で、ここから続く　文章の二行目になっている行だ。");
  });
});
