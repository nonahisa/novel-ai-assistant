import { describe, expect, test } from "vitest";
import {
  applyCharacterEdits,
  describeRelationEditHint,
  editedRelations,
  formatRelationsForEdit,
  SettingsEditError,
} from "../../../src/core/settingsEdit";
import { buildRelationGraph, incomingRelations } from "../../../src/core/relationGraph";
import { mergeExtractedCharacters } from "../../../src/core/characterMerge";
import { emptyCharacter, type Character } from "../../../src/models/character";

/**
 * 人物の関係欄を、設定資料パネルで直せるようにする（作者の依頼「B3」、2026-09-22 未明）。
 *
 * 作者の作品で、マイナの関係に「ターナ＝父の娘」（正しくは母）と誤りが
 * 入っていたが、**直す手段が画面にも MCP にも無かった**——関係欄は
 * 設定資料パネルに出ていなかった。
 *
 * 見張ること：
 *
 * 1. **書いたとおりに入り、そのまま読み戻せる**（保存するたびに並びや中身が
 *    変わると、触っていない関係まで「変わった」ことになる）
 * 2. **読めない行は黙って捨てずに断る**（捨てると、作者が書いた関係が消える）
 * 3. **作者が直した関係を、次の抽出が戻さない**（規則2。作者が保存した人物は
 *    `autoGenerated: false` になり、抽出は登場話数の追記しかしない——
 *    ほかの欄と同じ保護に乗る）
 * 4. **相関図が直した関係を描く**（図は人物レコードから毎回組み立てる）
 */

function character(
  id: string,
  name: string,
  extra: Partial<Character> = {}
): Character {
  return { ...emptyCharacter(id, name), ...extra };
}

describe("関係欄の書式（formatRelationsForEdit / editedRelations）", () => {
  test("1行に1つ「相手=関係」で出し、そのまま読み戻せる", () => {
    const relations = [
      { name: "ターナ", relation: "父の娘" },
      { name: "リナ", relation: "友人" },
    ];
    const text = formatRelationsForEdit(relations);
    expect(text).toBe("ターナ=父の娘\nリナ=友人");
    expect(editedRelations(relations, text)).toEqual(relations);
  });

  test("書き換えた行だけが変わる。並びは書いた順", () => {
    const relations = [
      { name: "ターナ", relation: "父の娘" },
      { name: "リナ", relation: "友人" },
    ];
    expect(editedRelations(relations, "ターナ=母\nリナ=友人")).toEqual([
      { name: "ターナ", relation: "母" },
      { name: "リナ", relation: "友人" },
    ]);
  });

  test("全角の＝も区切りとして読む。前後の空白と空行は落とす", () => {
    expect(editedRelations([], "  ターナ ＝ 母 \n\n リナ=友人\n")).toEqual([
      { name: "ターナ", relation: "母" },
      { name: "リナ", relation: "友人" },
    ]);
  });

  test("区切りは最初の＝だけ（関係の中の＝は残す）", () => {
    expect(editedRelations([], "ターナ=母=育ての親")).toEqual([
      { name: "ターナ", relation: "母=育ての親" },
    ]);
  });

  test("まったく同じ行は1つに畳む", () => {
    expect(editedRelations([], "ターナ=母\nターナ=母")).toEqual([
      { name: "ターナ", relation: "母" },
    ]);
  });

  test("同じ相手でも関係が違えば両方残す（片方を捨てるのは作者の判断）", () => {
    expect(editedRelations([], "ターナ=母\nターナ=師匠")).toEqual([
      { name: "ターナ", relation: "母" },
      { name: "ターナ", relation: "師匠" },
    ]);
  });

  test("空にすれば関係は無くなる（消すのは作者の操作）", () => {
    expect(
      editedRelations([{ name: "ターナ", relation: "母" }], "  \n")
    ).toEqual([]);
  });

  test("渡されなければ触らない", () => {
    const relations = [{ name: "ターナ", relation: "母" }];
    expect(editedRelations(relations, undefined)).toBe(relations);
  });

  test("＝の無い行・片側が空の行は、行を挙げて断る（黙って捨てない）", () => {
    expect(() => editedRelations([], "ターナ=母\nリナ 友人")).toThrow(
      SettingsEditError
    );
    expect(() => editedRelations([], "ターナ=母\nリナ 友人")).toThrow(/2行目/);
    expect(() => editedRelations([], "リナ 友人")).toThrow(/リナ 友人/);
    expect(() => editedRelations([], "=母")).toThrow(SettingsEditError);
    expect(() => editedRelations([], "ターナ=")).toThrow(SettingsEditError);
  });
});

describe("作者が直した関係（applyCharacterEdits）", () => {
  test("関係を直すと入り、作者が確定させた人物になる", () => {
    const minna = character("char_002", "マイナ", {
      relations: [{ name: "ターナ", relation: "父の娘" }],
    });
    const edited = applyCharacterEdits(minna, { relations: "ターナ=母" });
    expect(edited.relations).toEqual([{ name: "ターナ", relation: "母" }]);
    expect(edited.autoGenerated).toBe(false);
  });

  test("関係欄を渡さない保存では、関係は変わらない", () => {
    const minna = character("char_002", "マイナ", {
      relations: [{ name: "ターナ", relation: "父の娘" }],
    });
    const edited = applyCharacterEdits(minna, { role: "弟子" });
    expect(edited.relations).toEqual([{ name: "ターナ", relation: "父の娘" }]);
  });

  test("直した関係を、次の抽出が「父の娘」で戻さない", () => {
    const minna = applyCharacterEdits(
      character("char_002", "マイナ", {
        relations: [{ name: "ターナ", relation: "父の娘" }],
      }),
      { relations: "ターナ=母" }
    );
    const result = mergeExtractedCharacters(
      [minna],
      [
        {
          chapters: [5],
          data: {
            name: "マイナ",
            relations: [{ name: "ターナ", relation: "父の娘" }],
          },
        },
      ]
    );
    const after = result.characters.find((item) => item.id === "char_002");
    expect(after?.relations).toEqual([{ name: "ターナ", relation: "母" }]);
    // 登場話数の追記だけは行う（規則2）
    expect(after?.appearedChapters).toContain(5);
  });
});

describe("相手側の関係（incomingRelations / describeRelationEditHint）", () => {
  const minna = character("char_002", "マイナ", {
    aliases: ["マイナちゃん"],
    relations: [{ name: "ターナ", relation: "父の娘" }],
  });
  const tana = character("char_001", "ターナ", {
    relations: [
      { name: "マイナちゃん", relation: "娘" },
      { name: "リナ", relation: "生徒" },
    ],
  });
  const rina = character("char_003", "リナ", {
    relations: [{ name: "マイナ", relation: "友人" }],
  });

  test("別名で書かれていても、この人物を指す相手側の関係を集める", () => {
    expect(incomingRelations([minna, tana, rina], "char_002")).toEqual([
      { fromId: "char_001", fromName: "ターナ", relation: "娘" },
      { fromId: "char_003", fromName: "リナ", relation: "友人" },
    ]);
  });

  test("自分の関係・ほかの人物を指す関係は入らない", () => {
    expect(incomingRelations([minna, tana, rina], "char_003")).toEqual([
      { fromId: "char_001", fromName: "ターナ", relation: "生徒" },
    ]);
  });

  test("説明に書き方と、相手側の記録（読むだけ）を並べる", () => {
    const hint = describeRelationEditHint("マイナ", [
      { fromName: "ターナ", relation: "娘" },
    ]);
    expect(hint).toContain("相手=関係");
    expect(hint).toContain("ターナの記録: マイナ（この人物）=娘");
    // 相手側は自動で直さない——そのことを言う
    expect(hint).toContain("相手側");
  });

  test("相手側の記録が無ければ、書き方だけ", () => {
    const hint = describeRelationEditHint("マイナ", []);
    expect(hint).toContain("相手=関係");
    expect(hint).not.toContain("の記録:");
  });
});

describe("相関図は直した関係を描く", () => {
  test("直す前の言葉が消え、直した言葉が載る", () => {
    const tana = character("char_001", "ターナ");
    const minna = character("char_002", "マイナ", {
      relations: [{ name: "ターナ", relation: "父の娘" }],
    });
    const before = buildRelationGraph([tana, minna]);
    expect(before.edges[0].labels.map((label) => label.text)).toEqual(["父の娘"]);

    const edited = applyCharacterEdits(minna, { relations: "ターナ=母" });
    const after = buildRelationGraph([tana, edited]);
    expect(after.edges[0].labels.map((label) => label.text)).toEqual(["母"]);
  });
});
