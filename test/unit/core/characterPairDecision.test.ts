/**
 * 重複の候補の1組について、作者が決めたことを書く core（設計書6.5.4
 * 「設定資料パネルで一覧から片づける」。作者の依頼 2026-10-19）。
 *
 * 詳細メニューの「重複をまとめる」と設定資料パネルの候補の欄が、同じここを通る。
 */

function person(id: string, name: string, overrides: Partial<Character> = {}): Character {
  return { ...emptyCharacter(id, name), ...overrides };
}

/** 呼ばれた順を控える偽のストア */
function recordingStore(failAt?: { op: "retire" | "save"; nth: number }) {
  const calls: string[] = [];
  const saved: Character[] = [];
  let retires = 0;
  let saves = 0;
  return {
    calls,
    saved,
    async retire(id: string): Promise<string> {
      retires++;
      if (failAt?.op === "retire" && failAt.nth === retires) throw new Error("退避できません");
      calls.push(`retire:${id}`);
      return `回復/${id}.json`;
    },
    async save(character: Character): Promise<void> {
      saves++;
      if (failAt?.op === "save" && failAt.nth === saves) throw new Error("書けません");
      calls.push(`save:${character.id}`);
      saved.push(character);
    },
    async saveOrUpdate(character: Character): Promise<void> {
      calls.push(`saveOrUpdate:${character.id}`);
      saved.push(character);
    },
  };
}

describe("まとめる", () => {
  test("残す側を退避 → まとめた内容を作る → 取り下げ側を退避、の順で書く", async () => {
    const store = recordingStore();
    const keep = person("char_001", "三門太志");
    const absorb = person("char_002", "太志", { authorNotes: "作者のメモ" });

    const applied = await applyCharacterUnify(store, keep, absorb, [keep, absorb], {
      pending: memoryPendingStore(),
    });

    expect(store.calls).toEqual(["retire:char_001", "save:char_001", "retire:char_002"]);
    expect(applied.unified.aliases).toContain("太志");
    // 作者が書いた文章は失わない（規則2。中身の決まりは characterUnify と同じ）
    expect(applied.unified.authorNotes).toContain("作者のメモ");
    expect(applied.absorbRecoveryPath).toBe("回復/char_002.json");
  });

  test("作るところで失敗したら、取り下げ側には触らず、残す側の退避先を添えて投げる", async () => {
    const store = recordingStore({ op: "save", nth: 1 });
    const keep = person("char_001", "三門太志");
    const absorb = person("char_002", "太志");

    const error = await applyCharacterUnify(store, keep, absorb, [keep, absorb], {
      pending: memoryPendingStore(),
    }).catch(
      (caught: unknown) => caught
    );

    expect(error).toBeInstanceOf(CharacterUnifyError);
    expect((error as CharacterUnifyError).stage).toBe("save_unified");
    expect(store.calls).toEqual(["retire:char_001"]);
    const text = describeUnifyFailure(error as CharacterUnifyError, "三門太志", "太志");
    expect(text.modal).toBe(true);
    expect(text.message).toContain("回復/char_001.json");
  });

  test("取り下げ側だけ退避できなければ、まとめた内容は残っていると伝える", async () => {
    const store = recordingStore({ op: "retire", nth: 2 });
    const keep = person("char_001", "三門太志");
    const absorb = person("char_002", "太志");

    const error = (await applyCharacterUnify(store, keep, absorb, [keep, absorb], {
      pending: memoryPendingStore(),
    }).catch(
      (caught: unknown) => caught
    )) as CharacterUnifyError;

    expect(error.stage).toBe("retire_absorbed");
    expect(describeUnifyFailure(error, "三門太志", "太志").message).toContain(
      "まとめた内容は保存しましたが、「太志」を取り下げられませんでした"
    );
  });

  test("読み込めないファイルがあれば断る文を返し、無ければ空", () => {
    expect(describeDecisionBlockedByLoadErrors([])).toBe("");
    expect(describeDecisionBlockedByLoadErrors([{ file: "char_009.json" }])).toContain(
      "char_009.json"
    );
  });
});

describe("別人にする", () => {
  test("2人の distinctFrom に互いを足し、中身には触らない", async () => {
    const store = recordingStore();
    const a = person("char_001", "密倉文佳", { authorNotes: "メモ", autoGenerated: false });
    const b = person("char_002", "春原月夜");

    const plan = await applyCharacterDistinct(store, a, b);

    expect(store.calls).toEqual(["saveOrUpdate:char_001", "saveOrUpdate:char_002"]);
    expect(plan.first.distinctFrom).toEqual([{ name: "春原月夜", id: "char_002" }]);
    expect(plan.second.distinctFrom).toEqual([{ name: "密倉文佳", id: "char_001" }]);
    expect(plan.first.authorNotes).toBe("メモ");
    expect(plan.first.autoGenerated).toBe(false);
    expect(plan.strippedAliases).toEqual([]);
  });

  test("自分の別名に相手の名前があれば外す（「自分の別名は別人だ」を作らない）", () => {
    const a = person("char_001", "密倉文佳", { aliases: ["文佳さん", "お嬢様"] });
    const b = person("char_002", "文佳");

    const plan = planDistinctPair(a, b);

    expect(plan.first.aliases).toEqual(["お嬢様"]);
    expect(plan.strippedAliases).toEqual([
      { id: "char_001", name: "密倉文佳", aliases: ["文佳さん"] },
    ]);
  });

  test("既に互いを指していれば、同じ記録を足さない", () => {
    const a = person("char_001", "アジャン", {
      distinctFrom: [{ name: "アジャーノ", id: "char_002" }],
    });
    const b = person("char_002", "アジャーノ");

    const plan = planDistinctPair(a, b);

    expect(plan.first.distinctFrom).toHaveLength(1);
    expect(plan.second.distinctFrom).toEqual([{ name: "アジャン", id: "char_001" }]);
  });

  test("同じ名前の2人は断る（書くと、次の抽出でどちらにも当たらなくなる）", () => {
    const a = person("char_001", "お母さん");
    const b = person("char_002", "お母さん");

    expect(distinctPairRefusal(a, b)).toContain("先に片方の名前を書き分けてください");
    expect(() => planDistinctPair(a, b)).toThrow("どちらにも当たらなくなります");
  });

  test("別人にした組は、重複の候補から消える", () => {
    const a = person("char_001", "ギルドマスター");
    const b = person("char_002", "ギルマス");
    expect(findMergeCandidates([a, b])).toHaveLength(1);

    const plan = planDistinctPair(a, b);

    expect(findMergeCandidates([plan.first, plan.second])).toEqual([]);
  });
});

describe("まとめたあとの反映待ち（作者の裁定 2026-10-22。巻き戻りの穴）", () => {
  /** 反映待ちをディスクの代わりに記憶で持つ口 */
  function pendingWith(initial: PendingUpdate[]) {
    const files = new Map(initial.map((update) => [update.filePath, update]));
    return {
      files,
      async loadAll() {
        return { updates: [...files.values()], errors: [] };
      },
      async stage(
        characters: Character[],
        options: { source?: PendingUpdate["source"]; kind?: PendingUpdate["kind"]; reason?: string } = {}
      ) {
        for (const character of characters) {
          const filePath = `pending/${character.id}.json`;
          files.set(filePath, { character, filePath, ...options });
        }
      },
      async discard(filePath: string) {
        files.delete(filePath);
      },
    };
  }

  test("まとめる前の残す側の丸写しが反映待ちに残っていても、反映でまとめが巻き戻らない", async () => {
    const store = recordingStore();
    const keep = person("char_001", "三門太志", { appearedChapters: [1] });
    const absorb = person("char_002", "太志", { authorNotes: "作者のメモ", appearedChapters: [2] });
    // 抽出が積んだ、まとめる前の「三門太志」の丸写し（紹介だけ新しい）
    const pending = pendingWith([
      {
        character: { ...keep, summary: "寡黙な青年" },
        filePath: "pending/char_001.json",
        source: "chat",
      },
    ]);

    const applied = await applyCharacterUnify(store, keep, absorb, [keep, absorb], { pending });

    // 承認の画面に並ぶ差分。まとめを崩す変化（別名から「太志」を外す等）が無く、
    // AIが足した紹介だけが残っていること
    const review = assembleCharacterReview([...pending.files.values()], [applied.unified], []);
    expect(review.items).toHaveLength(1);
    const fields = review.items[0].diff.changes.map((change) => change.label);
    expect(fields).toEqual(["紹介"]);
    // 出どころは引き継ぐ
    expect(review.items[0].update.source).toBe("chat");
    expect(applied.pending).toMatchObject({ discarded: 0, rebased: 1 });
  });

  test("取り下げた側の反映待ちは捨て、ほかの人物の反映待ちには触らない", async () => {
    const store = recordingStore();
    const keep = person("char_001", "三門太志");
    const absorb = person("char_002", "太志");
    const other = person("char_003", "密倉文佳");
    const pending = pendingWith([
      { character: { ...absorb, summary: "眠そう" }, filePath: "pending/char_002.json" },
      { character: { ...other, summary: "書店員" }, filePath: "pending/char_003.json" },
      // 新規案は仮の id なので、まとめた2人とは結ばない
      { character: person("char_000", "春原月夜"), filePath: "pending/new_春原月夜.json", kind: "creation" },
    ]);

    const applied = await applyCharacterUnify(store, keep, absorb, [keep, absorb, other], { pending });

    expect([...pending.files.keys()].sort()).toEqual([
      "pending/char_003.json",
      "pending/new_春原月夜.json",
    ]);
    expect(applied.pending).toMatchObject({ discarded: 1, rebased: 0 });
  });

  test("反映待ちが読めなくても、まとめ自体は成り立ったまま件数と理由を返す", async () => {
    const store = recordingStore();
    const keep = person("char_001", "三門太志");
    const absorb = person("char_002", "太志");
    const pending = {
      async loadAll(): Promise<{ updates: PendingUpdate[]; errors: Array<{ file: string; message: string }> }> {
        return { updates: [], errors: [{ file: "char_001.json", message: "壊れています" }] };
      },
      async stage() {},
      async discard() {},
    };

    const applied = await applyCharacterUnify(store, keep, absorb, [keep, absorb], { pending });

    expect(store.calls).toEqual(["retire:char_001", "save:char_001", "retire:char_002"]);
    expect(applied.pending.unreadable).toEqual(["char_001.json"]);
  });
});
