import { describe, expect, test } from "vitest";
import {
  readCharLimit,
  type CharLimitReading,
} from "../../../src/core/contestCharLimit";

/**
 * 公募の「字数」の書き方を、下限・上限の字数へ読み替える（設計書6.3.6.1）。
 *
 * 書き方は募集ごとにばらばらで、同じ意味でも「400字詰原稿用紙で70枚以上150枚以下」
 * 「40字×30行　100ページ以上200ページ以内」「8万～20万字程度」と形が違う。
 * **読めないものを推測で埋めない**のがいちばん大事で、下の「読めない」の表は
 * 「読めた」の表と同じくらい大事である（何でも数にする実装が満点にならないように）。
 */

function range(min: number | null, max: number | null, converted = false): CharLimitReading {
  return { kind: "range", min, max, converted };
}

describe("読める書き方", () => {
  const cases: [string, CharLimitReading][] = [
    // 原稿用紙の枚数（400字詰）
    ["400字詰原稿用紙で70枚以上150枚以下", range(28000, 60000, true)],
    ["400字詰原稿用紙10枚から80枚以内で、タテ書きとする。", range(4000, 32000, true)],
    ["本文400字詰縦書原稿用紙50枚以内", range(null, 20000, true)],
    ["30〜100枚（400字詰原稿用紙換算）", range(12000, 40000, true)],
    ["400字詰め原稿用紙25〜30枚換算", range(10000, 12000, true)],
    ["400字×15枚以内", range(null, 6000, true)],
    ["400字詰原稿用紙換算で、350枚以上", range(140000, null, true)],
    ["400字詰原稿用紙換算で100枚程度から300枚までとする。", range(40000, 120000, true)],
    ["400字詰原稿用紙350枚以上650枚程度", range(140000, 260000, true)],
    ["400字詰め（20字×20字）原稿用紙、30枚から90枚以内。", range(12000, 36000, true)],
    ["400字詰め原稿用紙（テキストデータの場合は20字×20行換算）50枚以上250枚以内。", range(20000, 100000, true)],
    ["400字詰め原稿用紙（縦書き）で30枚～60枚", range(12000, 24000, true)],
    // 1枚（1ページ）あたりの字×行
    ["40字×30行の縦書き　100ページ以上200ページ以内", range(120000, 240000, true)],
    ["1枚あたり40字×32行で換算して100枚以上130枚以内", range(128000, 166400, true)],
    ["42字×34行　70～150枚", range(99960, 214200, true)],
    ["40字×30行、10頁まで", range(null, 12000, true)],
    ["1ページ40字×40行　90～162.5枚相当", range(144000, 260000, true)],
    ["1ページ40字×32行 100枚以上160枚以内", range(128000, 204800, true)],
    ["A4用紙（横置き）1枚20字×20行の縦書き。30枚～50枚。", range(12000, 20000, true)],
    ["縦書き・一段組みとし、データ原稿の場合は必ず一行30字×40行で作成し、115～185枚。", range(138000, 222000, true)],
    // 換算の2つの書き方が同じ字数を指すなら読める（近い換算は同じと見る）
    ["40字×40行換算で10～20枚（400字詰原稿用紙40～80枚相当）", range(16000, 32000, true)],
    // 字数そのもの
    ["8万～20万字程度", range(80000, 200000)],
    ["本文8万～20万字程度。400字詰め原稿用紙換算で200～500枚程度。", range(80000, 200000)],
    ["5,000〜10,000字", range(5000, 10000)],
    ["4,000字以内", range(null, 4000)],
    ["3万2千字以内", range(null, 32000)],
    ["5千字～3万2千字以内", range(5000, 32000)],
    ["1〜3万字程度の短編小説、または連載用の中編・長編小説", range(10000, 30000)],
    ["2,000文字以内", range(null, 2000)],
    ["2,000文字以内（原稿用紙にすると5枚分以内）", range(null, 2000)],
    ["5万文字以上", range(50000, null)],
    ["8万文字〜上限なし", range(80000, null)],
    ["8万文字以上（上限なし）", range(80000, null)],
    ["8万文字以上～文字数制限無し", range(80000, null)],
    ["1,000文字以上、5,000文字以下", range(1000, 5000)],
    ["2,000字〜15,000文字以内", range(2000, 15000)],
    ["10,000字以内とします。下限はありません。", range(null, 10000)],
    ["文字数の下限は500文字以上とし、上限はありません。", range(500, null)],
    ["４,000字以上100,000字以下", range(4000, 100000)],
    ["１０万文字以上１５万字以下", range(100000, 150000)],
    ["1,000文字（全角）以上", range(1000, null)],
    ["100~5,000文字以内", range(100, 5000)],
    ["400〜800文字程度", range(400, 800)],
    ["本編15,000字以内／500字程度の要約必須", range(null, 15000)],
    ["2,000文字～6,000文字以内", range(2000, 6000)],
    ["5,000字以上", range(5000, null)],
    ["8,000文字未満", range(null, 7999)],
  ];

  test.each(cases)("%s", (text, expected) => {
    expect(readCharLimit(text)).toEqual(expected);
  });
});

describe("制限が無い書き方", () => {
  test.each([
    "制限なし",
    "不問",
    "文字数に規定はございません。",
    "文字数の下限、上限はありません。",
    "制限は設けない。",
    "投稿可能な文字数であれば不問",
    "不問。ただし出版するには分量が足りない作品は大賞の選考で不利となります。",
  ])("%s", (text) => {
    expect(readCharLimit(text)).toEqual({ kind: "none" });
  });
});

describe("読めない書き方（推測で埋めない）", () => {
  test.each([
    // 目安の1点だけ——下限か上限か決められない
    "10,000字程度",
    "2000字程度",
    "2800字（400字詰め原稿用紙7枚）",
    "400字詰め原稿用紙10枚",
    // 部門ごと・話ごとの規定——どれを当てるかは作者が決める
    "小説部門：400字詰め原稿用紙30枚以上50枚以内　児童文学部門：400字詰め原稿用紙7枚以上20枚以内",
    "各話2,000文字以上8,000文字未満／第1話〜第20話の合計60,000文字以上",
    "各エピソード2,000文字以上、8,000文字未満で合計10エピソード以上。",
    // 2つの換算が食い違う
    "400字詰め原稿用紙5枚以上30枚以内、または40文字×28行設定で3枚以上20枚以内（A4サイズ縦書き出力）",
    "縦書き、1段組、40字×40行で90枚以上(上限なし)、文字数は50000文字以上とします。",
    // 字数ではないもの・1枚の字数が分からないもの
    "10話以上のオリジナル連載作品",
    "400字詰め原稿用紙13枚目で完結（13枚目の半分は超えること。縦書き）。",
    "1ページ＝42文字×34行で設定",
    "【応募原稿テンプレート】30枚程度（文字数24,000字程度）",
    "第1話の脚本。 プロット、脚本、小説など、形式・分量は自由です。",
    "",
  ])("%s", (text) => {
    expect(readCharLimit(text).kind).toBe("unreadable");
  });

  test("読めない理由を添える（作者が原文を見て決めるため）", () => {
    const reading = readCharLimit("小説部門：30枚以内　児童文学部門：20枚以内");
    expect(reading.kind).toBe("unreadable");
    if (reading.kind === "unreadable") expect(reading.reason.length).toBeGreaterThan(0);
  });

  test("字数の記載が無ければ読めない（null も同じ）", () => {
    expect(readCharLimit(null).kind).toBe("unreadable");
    expect(readCharLimit(undefined).kind).toBe("unreadable");
  });
});

describe("字数でない数を拾わない", () => {
  test("あらすじ・タイトル・梗概の字数は、本文の規定に数えない", () => {
    expect(
      readCharLimit("作品本文は3万2千字以内（改行・スペースを含む） あらすじは400字程度")
    ).toEqual(range(null, 32000));
    expect(
      readCharLimit("タイトル：60文字以内 あらすじ：800文字以内 本文8万字以上13万字以下")
    ).toEqual(range(80000, 130000));
    expect(
      readCharLimit("1ページ目に1,000字以内のあらすじを記載 各部門50,000～70,000字（段落、改行を含む）")
    ).toEqual(range(50000, 70000));
  });

  test("A4・第1回のような数は字数と読まない", () => {
    expect(readCharLimit("A4判で1万字以上")).toEqual(range(10000, null));
  });
});
