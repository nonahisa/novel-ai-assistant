/**
 * 同じ資料を引き継いでいるなら、重ならない変更は訊かずに合わせる（作者の裁定、2026-10-01 案3）。
 *
 * 作者の言葉：「設定資料については、デスクトップなどで作成したものを引き継いでいる
 * ものと考えます。であれば、設定資料作成日が同じであれば何も出さず、衝突した時だけ
 * 最新優先か聞く、作者が書き換えた項目は更新しないで良さそう」。
 *
 * 作成の印は `createdAt`（伏線・予定などが持つ）。持たない資料（人物など）は、
 * **共通の祖先に同じファイルがあること**を引き継ぎの印にする（祖先が無い＝
 * 両方で別々に作った、は今までどおりの規則で扱う）。
 */
describe("案3：同じ資料を引き継いでいるとき", () => {
  /** 伏線1件ぶんのJSON。`createdAt` を持つ。既定はAIが見つけたもの */
  function 伏線(input: {
    note?: string;
    authorNotes?: string;
    plannedResolveChapter?: number | null;
    createdAt?: string;
    updatedAt?: string;
  }): string {
    return JSON.stringify(
      {
        schemaVersion: "0.2",
        id: "foreshadow_001",
        label: "銀の懐中時計",
        note: input.note ?? "祖父の形見",
        plantedChapter: 2,
        plantedQuote: "懐中時計",
        status: "open",
        resolvedChapter: null,
        resolvedQuote: "",
        plannedResolveChapter: input.plannedResolveChapter ?? null,
        source: "ai",
        autoGenerated: true,
        authorNotes: input.authorNotes ?? "",
        createdAt: input.createdAt ?? "2026-09-01T00:00:00.000Z",
        updatedAt: input.updatedAt ?? "2026-09-01T00:00:00.000Z",
      },
      null,
      2
    );
  }

  /** 決めた結果の中身。訊く（conflict）なら undefined */
  function 採った中身(
    decision: ReturnType<typeof decideSettingsConflict>,
    ours: string,
    theirs: string
  ): Record<string, unknown> | undefined {
    if (decision.side === "conflict") return undefined;
    const text =
      decision.side === "merged"
        ? decision.text
        : decision.side === "ours"
          ? ours
          : theirs;
    return JSON.parse(text) as Record<string, unknown>;
  }

  test("作成日が同じで、変えた項目が重ならなければ、両方を合わせて訊かない", () => {
    // こちらでは作者メモを書いた。向こうでは AI の読み（note）が変わった
    const ours = 伏線({ authorNotes: "第8話で回収する", updatedAt: "2026-09-03T00:00:00.000Z" });
    const theirs = 伏線({ note: "祖父の形見。止まったまま", updatedAt: "2026-09-05T00:00:00.000Z" });
    const decision = decideSettingsConflict({ base: 伏線({}), ours, theirs });

    expect(decision.side).toBe("merged");
    const merged = 採った中身(decision, ours, theirs);
    expect(merged?.authorNotes).toBe("第8話で回収する");
    expect(merged?.note).toBe("祖父の形見。止まったまま");
    // 更新時刻は新しいほう
    expect(merged?.updatedAt).toBe("2026-09-05T00:00:00.000Z");
    // 項目の並びは元のまま（差分を最小にする）
    expect(Object.keys(merged ?? {})).toEqual(Object.keys(JSON.parse(伏線({})) as object));
  });

  test("作者の書いた別々の項目なら、両方で変えても訊かない", () => {
    // 作者メモはこちら、回収予定は向こう。**同じ項目ではない**ので衝突ではない
    const ours = 伏線({ authorNotes: "こちらのメモ", updatedAt: "2026-09-03T00:00:00.000Z" });
    const theirs = 伏線({ plannedResolveChapter: 8, updatedAt: "2026-09-04T00:00:00.000Z" });
    const decision = decideSettingsConflict({ base: 伏線({}), ours, theirs });

    const merged = 採った中身(decision, ours, theirs);
    expect(merged?.authorNotes).toBe("こちらのメモ");
    expect(merged?.plannedResolveChapter).toBe(8);
  });

  test("片方は保存し直しただけなら、変えた側の中身を採って訊かない", () => {
    const ours = 伏線({ updatedAt: "2026-09-09T00:00:00.000Z" });
    const theirs = 伏線({ note: "向こうの読み", updatedAt: "2026-09-05T00:00:00.000Z" });
    const decision = decideSettingsConflict({ base: 伏線({}), ours, theirs });

    expect(採った中身(decision, ours, theirs)?.note).toBe("向こうの読み");
  });

  test("同じ作者の項目を両方で違う値に変えたら、訊く", () => {
    const decision = decideSettingsConflict({
      base: 伏線({}),
      ours: 伏線({ authorNotes: "こちらのメモ" }),
      theirs: 伏線({ authorNotes: "むこうのメモ" }),
    });

    expect(decision.side).toBe("conflict");
  });

  test("作成日が違えば、別々に作った資料なので訊く", () => {
    const decision = decideSettingsConflict({
      base: 伏線({}),
      ours: 伏線({ createdAt: "2026-09-02T00:00:00.000Z", note: "こちら" }),
      theirs: 伏線({ createdAt: "2026-09-03T00:00:00.000Z", note: "むこう" }),
    });

    expect(decision.side).toBe("conflict");
    expect(decision.reason).toContain("作成日");
  });

  test("作者が確定させた側の値は、相手のAIの読みで書き換えない", () => {
    // こちらで作者が確定（autoGenerated: false）して紹介文を直した。
    // 向こうは確定前のまま、AI の抽出で紹介文が変わり、登場話数が増えた
    const ours = 人物({
      summary: "作者が直した紹介",
      autoGenerated: false,
      updatedAt: "2026-09-03T00:00:00.000Z",
    });
    const theirs = 人物({
      summary: "AIの読み直し",
      appearedChapters: [1, 2, 3],
      updatedAt: "2026-09-09T00:00:00.000Z",
    });
    const decision = decideSettingsConflict({ base: 人物({ summary: "もとの紹介" }), ours, theirs });

    // **時刻では負けていても、作者の値を残す**。訊きもしない（作者の手は片側だけ）
    const merged = 採った中身(decision, ours, theirs);
    expect(merged?.summary).toBe("作者が直した紹介");
    expect(merged?.autoGenerated).toBe(false);
    // 登場話数の追記だけは、確定したレコードにも入ってよい（CLAUDE.md）
    expect(merged?.appearedChapters).toEqual([1, 2, 3]);
  });

  test("両方で作者が確定させて違う値にしたら、訊く", () => {
    const decision = decideSettingsConflict({
      base: 人物({ summary: "もと" }),
      ours: 人物({ summary: "こちらで書いた", autoGenerated: false }),
      theirs: 人物({ summary: "むこうで書いた", autoGenerated: false }),
    });

    expect(decision.side).toBe("conflict");
  });

  test("AIの読みどうしが同じ項目で食い違うなら、新しいほうを採って訊かない（規則1と同じ）", () => {
    const decision = decideSettingsConflict({
      base: 人物({ summary: "もと" }),
      ours: 人物({ summary: "こちらの読み", updatedAt: "2026-09-03T00:00:00.000Z" }),
      theirs: 人物({ summary: "むこうの読み", updatedAt: "2026-09-05T00:00:00.000Z" }),
    });

    expect(decision.side).toBe("theirs");
  });
});
