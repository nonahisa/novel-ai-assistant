import { describe, expect, test } from "vitest";
import { mergeExtractedCharacters } from "../../../src/core/characterMerge";
import { unifyCharacters } from "../../../src/core/characterUnify";
import {
  planCharacterSeparation,
  planDistinctPair,
} from "../../../src/core/characterSeparate";
import { mergeExtractedLocations } from "../../../src/core/settingsMerge";
import { emptyCharacter, parseCharacter, type Character } from "../../../src/models/character";
import { emptyLocation } from "../../../src/models/location";

/**
 * 別名の読み（設計書6.42.2）は作者のデータ。AIの抽出・マージは書かない・消さない。
 * 別名が人物の間を動く操作（まとめる・分ける・別人と覚える）では、読みも別名に
 * ついて動き、迷子にならない。
 */

function person(id: string, name: string, extra: Partial<Character> = {}): Character {
  return { ...emptyCharacter(id, name), ...extra };
}

describe("AIの抽出", () => {
  test("既にある人物の別名の読みを消さない（作者が確定した人物でも、AIが作った人物でも）", () => {
    for (const autoGenerated of [true, false]) {
      const existing = person("char_001", "灯", {
        aliases: ["姫君"],
        aliasReadings: { 姫君: "ひめぎみ" },
        autoGenerated,
      });
      const result = mergeExtractedCharacters([existing], [
        { data: { name: "灯", aliases: ["姫君", "灯ちゃん"], summary: "灯台守の娘" }, chapters: [3] },
      ]);
      expect(result.characters[0].aliasReadings).toEqual({ 姫君: "ひめぎみ" });
    }
  });

  test("AIの答えに別名の読みが混じっていても書かない", () => {
    const smuggled = { name: "東雲", aliases: ["白雲"], aliasReadings: { 白雲: "はくうん" } };
    const result = mergeExtractedCharacters([], [
      { data: smuggled as unknown as { name: string; aliases: string[] }, chapters: [1] },
    ]);
    expect(result.characters[0].aliasReadings).toBeUndefined();
  });

  test("場所などの抽出も、別名の読みを消さない", () => {
    const place = {
      ...emptyLocation("loc_001", "霧ヶ峰"),
      aliases: ["北の峰"],
      aliasReadings: { 北の峰: "きたのみね" },
    };
    const result = mergeExtractedLocations(
      [place],
      [{ data: { name: "霧ヶ峰", aliases: ["峰"], summary: "高原" }, chapters: [2] }]
    );
    expect(result.locations[0].aliasReadings).toEqual({ 北の峰: "きたのみね" });
  });
});

describe("まとめる", () => {
  test("両方の別名の読みを引き継ぎ、吸収した名前の読みはその別名の読みになる", () => {
    const keep = person("char_001", "灯", {
      reading: "あかり",
      aliases: ["姫君"],
      aliasReadings: { 姫君: "ひめぎみ" },
    });
    const absorb = person("char_002", "東雲灯", {
      reading: "しののめあかり",
      aliases: ["白雲", "姫君"],
      aliasReadings: { 白雲: "しらくも", 姫君: "ひめ" },
    });
    const { unified } = unifyCharacters(keep, absorb);
    expect(unified.aliasReadings).toEqual({
      // 残す側が勝つ
      姫君: "ひめぎみ",
      東雲灯: "しののめあかり",
      白雲: "しらくも",
    });
  });
});

describe("分ける", () => {
  test("切り出した別名の読みは、新しい人物の名前の読みになり、元からは消える", () => {
    const source = person("char_001", "灯", {
      aliases: ["北辰", "北辰さん", "白雲"],
      aliasReadings: { 北辰: "ほくしん", 北辰さん: "ほくしんさん", 白雲: "しらくも" },
    });
    const plan = planCharacterSeparation(source, "北辰", [source]);
    expect(plan.created.reading).toBe("ほくしん");
    expect(plan.original.aliasReadings).toEqual({ 白雲: "しらくも" });
    // 一緒に移した別名（敬称違い）の読みも一緒に移る
    expect(plan.created.aliasReadings).toEqual({ 北辰さん: "ほくしんさん" });
  });

  test("別人と覚えて外した別名の読みも消える", () => {
    const a = person("char_001", "灯", { aliases: ["東雲"], aliasReadings: { 東雲: "しののめ" } });
    const b = person("char_002", "東雲");
    const plan = planDistinctPair(a, b);
    expect(plan.first.aliasReadings).toBeUndefined();
  });

  test("保存の検証（parseCharacter）は、別名に無い読みを残さない", () => {
    const stale = person("char_001", "灯", { aliases: [], aliasReadings: { 姫君: "ひめぎみ" } });
    expect(parseCharacter(stale).aliasReadings).toBeUndefined();
  });
});
