import { describe, expect, test } from "vitest";
import { readDeadlines, upcomingDeadline } from "../../../src/core/contestDeadline";

/**
 * 公募の締切の書き方から、日付（YYYY-MM-DD）だけを取り出す（設計書6.3.6.1）。
 * 時刻は捨てる——作品目標の締切は日付しか持たない（`models/workGoals`）。
 * **読めなければ空を返す**（作者に入れてもらう）。
 */

describe("締切の日付を読む", () => {
  test.each([
    ["2026年9月30日（水）23:59", ["2026-09-30"]],
    ["2026/10/31", ["2026-10-31"]],
    ["2027年1月8日(金) 23:59", ["2027-01-08"]],
    // 27時は「翌日の3時」だが、書かれた日付のまま持つ（早めに倒れるので害が無い）
    ["2026年9月16日(水) 27:59:59", ["2026-09-16"]],
    ["WEB応募：2027年1月8日 23:59", ["2027-01-08"]],
    ["第77回：2026年10月26日", ["2026-10-26"]],
    ["2026年9月30日（参加者募集期間）", ["2026-09-30"]],
    ["2026年10月末日", ["2026-10-31"]],
    ["2027年2月末日23:59", ["2027-02-28"]],
    ["２０２６年１１月３０日", ["2026-11-30"]],
    ["第77回：2026/10/26 必着 第78回：2027/1/27 必着", ["2026-10-26", "2027-01-27"]],
    ["2026-12-31", ["2026-12-31"]],
  ])("%s", (text, expected) => {
    expect(readDeadlines(text)).toEqual(expected);
  });

  test.each(["随時募集", "毎月20日", "設けていない。選考は随時行う。", "", "2026年2月30日"])(
    "読めない：%s",
    (text) => {
      expect(readDeadlines(text)).toEqual([]);
    }
  );

  test("null・undefined は読めない", () => {
    expect(readDeadlines(null)).toEqual([]);
    expect(readDeadlines(undefined)).toEqual([]);
  });
});

describe("これからの締切を選ぶ", () => {
  test("今日より前の日付は選ばない（今日は選ぶ）", () => {
    expect(upcomingDeadline(["2026-10-26", "2027-01-27"], "2026-10-27")).toBe("2027-01-27");
    expect(upcomingDeadline(["2026-10-26"], "2026-10-26")).toBe("2026-10-26");
  });

  test("いちばん近いものを選ぶ（書かれた順ではなく）", () => {
    expect(upcomingDeadline(["2027-01-27", "2026-10-26"], "2026-09-23")).toBe("2026-10-26");
  });

  test("すべて過ぎていれば選ばない", () => {
    expect(upcomingDeadline(["2026-09-01"], "2026-09-23")).toBeNull();
    expect(upcomingDeadline([], "2026-09-23")).toBeNull();
  });
});
