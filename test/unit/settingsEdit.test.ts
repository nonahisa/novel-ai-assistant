import { describe, expect, test } from "vitest";
import {
  applyAbilityEdits,
  applyCharacterEdits,
  applyLocationEdits,
  appendAiNote,
  editedAliases,
  removeAiNote,
  SettingsEditError,
} from "../../src/core/settingsEdit";
import { emptyCharacter } from "../../src/models/character";
import { emptyAbility } from "../../src/models/ability";
import { emptyLocation } from "../../src/models/location";
import { parseAiNotes } from "../../src/models/aiNote";

describe("作者による書き換え", () => {
  test("書き換えたレコードは以後の抽出で上書きされないようにする", () => {
    const character = emptyCharacter("char_001", "灯");
    expect(character.autoGenerated).toBe(true);

    const edited = applyCharacterEdits(character, { role: "主人公" });

    // 作者が確定させたものをAIが戻すと、直した意味がなくなる
    expect(edited.autoGenerated).toBe(false);
    expect(edited.role).toBe("主人公");
  });

  test("AIの提案を反映しただけなら作者確定にしない", () => {
    // 作者確定にすると、その人物は以後の抽出から締め出され、
    // 書き進めても情報が増えなくなる
    const character = emptyCharacter("char_001", "灯");

    const edited = applyCharacterEdits(
      character,
      { personality: "冷静沈着" },
      { authorConfirmed: false }
    );

    expect(edited.personality).toBe("冷静沈着");
    expect(edited.autoGenerated).toBe(true);
  });

  test("一度確定させた記録はAIの反映で取り消さない", () => {
    const character = {
      ...emptyCharacter("char_001", "灯"),
      autoGenerated: false,
    };

    const edited = applyCharacterEdits(
      character,
      { personality: "冷静沈着" },
      { authorConfirmed: false }
    );

    expect(edited.autoGenerated).toBe(false);
  });

  test("能力と場所も同じ扱いにする", () => {
    const ability = applyAbilityEdits(
      emptyAbility("abil_001", "神術"),
      { cost: "寿命" },
      { authorConfirmed: false }
    );
    const location = applyLocationEdits(
      emptyLocation("loc_001", "図書塔"),
      { region: "王都" },
      { authorConfirmed: false }
    );

    expect(ability.autoGenerated).toBe(true);
    expect(location.autoGenerated).toBe(true);
  });

  test("空欄にした項目は未設定（null）にする", () => {
    const character = {
      ...emptyCharacter("char_001", "灯"),
      role: "主人公",
    };

    const edited = applyCharacterEdits(character, { role: "  " });

    // 空文字のまま持つと、資料に空の「役割:」が出てしまう
    expect(edited.role).toBeNull();
  });

  test("渡されなかった項目は触らない", () => {
    const character = {
      ...emptyCharacter("char_001", "灯"),
      role: "主人公",
      personality: "無鉄砲",
    };

    const edited = applyCharacterEdits(character, { role: "副主人公" });

    expect(edited.personality).toBe("無鉄砲");
  });

  test("名前を空にしようとしたら止める", () => {
    const character = emptyCharacter("char_001", "灯");

    // 名前が消えるとファイル名がIDだけになり、Gitの差分で判別できなくなる
    expect(() => applyCharacterEdits(character, { name: "   " })).toThrow(
      SettingsEditError
    );
  });

  test("作者メモは空文字を許す", () => {
    const character = {
      ...emptyCharacter("char_001", "灯"),
      authorNotes: "あとで書く",
    };

    const edited = applyCharacterEdits(character, { authorNotes: "" });

    expect(edited.authorNotes).toBe("");
  });

  test("別名は読点・カンマ・改行のどれで区切ってもよい", () => {
    expect(editedAliases([], "灯、ともり\nトモリ,灯")).toEqual([
      "灯",
      "ともり",
      "トモリ",
    ]);
  });

  test("能力と場所も同じ扱いにする", () => {
    const ability = applyAbilityEdits(emptyAbility("abil_001", "神術"), {
      cost: "寿命を1年",
    });
    const location = applyLocationEdits(emptyLocation("loc_001", "図書塔"), {
      region: "王都",
    });

    expect(ability.cost).toBe("寿命を1年");
    expect(ability.autoGenerated).toBe(false);
    expect(location.region).toBe("王都");
    expect(location.autoGenerated).toBe(false);
  });
});

describe("AI掘り下げの追記", () => {
  const now = new Date("2026-08-08T12:00:00.000Z");

  test("承認したメモを末尾に足す", () => {
    const character = emptyCharacter("char_001", "灯");

    const updated = appendAiNote(
      character,
      {
        topic: "生い立ち",
        text: "第3話の回想から、幼少期を辺境で過ごしたと読める。",
        model: "gemma4:e4b",
        source: "deep_dive",
      },
      now
    );

    expect(updated.aiNotes).toHaveLength(1);
    expect(updated.aiNotes[0]).toEqual({
      id: "note_001",
      createdAt: "2026-08-08T12:00:00.000Z",
      topic: "生い立ち",
      text: "第3話の回想から、幼少期を辺境で過ごしたと読める。",
      model: "gemma4:e4b",
      source: "deep_dive",
    });
  });

  test("既存の項目は書き換えない", () => {
    const character = {
      ...emptyCharacter("char_001", "灯"),
      role: "主人公",
      personality: "無鉄砲",
      authorNotes: "作者のメモ",
    };

    const updated = appendAiNote(
      character,
      { topic: "", text: "推測です。", model: "m", source: "deep_dive" },
      now
    );

    // 掘り下げは本文の逐語照合ができないため、抽出した事実に混ぜない
    expect(updated.role).toBe("主人公");
    expect(updated.personality).toBe("無鉄砲");
    expect(updated.authorNotes).toBe("作者のメモ");
  });

  test("追記してもIDが重ならない", () => {
    let character = emptyCharacter("char_001", "灯");
    for (let i = 0; i < 3; i++) {
      character = appendAiNote(
        character,
        { topic: "", text: `${i}`, model: "m", source: "deep_dive" },
        now
      );
    }

    expect(character.aiNotes.map((note) => note.id)).toEqual([
      "note_001",
      "note_002",
      "note_003",
    ]);
  });

  test("削除しても残りのIDは振り直さない", () => {
    let character = emptyCharacter("char_001", "灯");
    for (let i = 0; i < 3; i++) {
      character = appendAiNote(
        character,
        { topic: "", text: `${i}`, model: "m", source: "deep_dive" },
        now
      );
    }

    const removed = removeAiNote(character, "note_002");

    expect(removed.aiNotes.map((note) => note.id)).toEqual([
      "note_001",
      "note_003",
    ]);
    // 振り直すと、次の追記が既存IDと衝突する
    const appended = appendAiNote(
      removed,
      { topic: "", text: "4", model: "m", source: "deep_dive" },
      now
    );
    expect(appended.aiNotes.at(-1)?.id).toBe("note_004");
  });

  test("空の内容は追記しない", () => {
    expect(() =>
      appendAiNote(emptyCharacter("char_001", "灯"), {
        topic: "",
        text: "   ",
        model: "m",
        source: "deep_dive",
      })
    ).toThrow(SettingsEditError);
  });
});

describe("掘り下げメモのJSON検証", () => {
  test("未指定なら空配列にする", () => {
    expect(parseAiNotes(undefined)).toEqual([]);
  });

  test("欠けた項目は既定値で補う", () => {
    expect(parseAiNotes([{ id: "note_001", text: "本文" }])).toEqual([
      {
        id: "note_001",
        createdAt: "",
        topic: "",
        text: "本文",
        model: "",
        source: "deep_dive",
      },
    ]);
  });

  test("壊れていたら勝手に直さず止める", () => {
    // 作者が手で編集して壊した可能性がある。黙って捨てると編集が消える
    expect(() => parseAiNotes([{ id: "note_001" }])).toThrow();
    expect(() => parseAiNotes([{ id: "bad", text: "x" }])).toThrow();
    expect(() => parseAiNotes("メモ")).toThrow();
  });
});
