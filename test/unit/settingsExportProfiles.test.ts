const OPTIONS = { workTitle: "灯の塔", authorName: "野中ひさ", at: AT };

function build(
  audience: ExportAudience,
  chapter: number | null = null,
  data: SettingsExportData = baseData()
): string {
  return buildExportMarkdown(audience, data, { ...OPTIONS, chapter });
}

