/**
 * 設定資料の提供先別エクスポート（設計書6.75）。
 *
 * **渡す相手によって、出してよい情報が違う。** イラストの発注書に
 * 結末の伏線や内面の掘り下げが混ざっていては困るし、レビュー依頼に
 * 経歴を全部付ける必要もない。
 *
 * ここで確かめるのは3つ。
 *
 * 1. **型ごとに、出る項目と出ない項目**——判断は項目の種類だけで行う
 *    （値の中身を見て決めない）ので、表のとおりに出ることが全てである
 * 2. **冒頭の明記**——渡された側が「これで全部」と誤解しないこと
 * 3. **第N話まで**——先の話で分かった値・後から出てくる人物が混ざらないこと
 */

const AT = new Date(2026, 8, 5, 14, 30, 0);

function change(field: string, value: string, chapters: number[]): RecordChange {
  return {
    field,
    value,
    chapters,
    timepointId: null,
    note: null,
    evidence: null,
    source: "extracted",
  };
}

