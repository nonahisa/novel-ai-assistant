/**
 * 改行が CRLF の原稿でも LF の原稿でも、用語の色・右クリックの設定資料・ルビと傍点・
 * 下の欄の字数が正しく働く（画面の自動テスト、設計書6.113・6.34.5・6.25。実機確認
 * リスト F-27・F-28・F-32・F-35 を 2026-10-04 に移した）。
 *
 * 何を見張るか：
 * - **用語の色が正しい語に載る**（0.24.8 まで、CRLF の原稿では1行ごとに1字ずつ
 *   後ろへずれた）。見た目ではなく、色を付けた範囲（Custom Highlight API の
 *   `novelai-term-character`）が指す字が、人物の名前そのものかで測る
 * - **右クリックの「設定資料を見る」が、押した語の資料を出す**。本文から開いた
 *   設定資料パネルは一覧を畳んで出し、開いたままで別の語を右クリックしても
 *   その語へ切り替わる。作者が一覧を開いたあと、ふつうの道で開けば一覧が出ている
 * - **ルビ・傍点が振れる**（CRLF の原稿で「本文が変わった」と誤って断られていた）。
 *   振ったあとも改行は CRLF のまま。**見本の話は .md にする**——.txt では傍点の
 *   書き方がサイトごとに違うので、傍点は「.md で使えます」と断るのが正しい
 *   （ルビは .txt でも振れる）
 * - **下の欄に「作品／このファイル／この話で今日」が出て、保存すると今日の量が増える**
 */
