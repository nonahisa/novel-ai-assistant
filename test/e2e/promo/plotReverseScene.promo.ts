/**
 * Discord「機能紹介」用の広報素材：プロット逆算（作者の依頼 2026-10-22）。
 * features.md の文：各話あらすじを材料に、ログライン・テーマ・世界観・舞台・人称・行動原理・あらすじ・主要人物を設定/plot.md へ書く。
 *
 * **本物のAIは呼ばない。** 偽の Ollama が、プロット逆算のスキーマに合う答えを返す。各話あらすじは作り物を置いておく。
 * 走らせ方：`npx vitest run -c vitest.promo.config.mts test/e2e/promo/plotReverseScene.promo.ts`
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { test } from "vitest";
import { passLocalAiGate } from "../support/fakeOllama";
import { runCommand } from "../support/quickInput";
import { waitUntil } from "../support/wait";
import { notificationTexts, pickQuickPickRow, quickPickRows, quickPickTitle } from "../support/workbenchDom";
import { recordFeature } from "./support/featureScene";

const EPISODES = [
  { name: "001_雨の駅.txt", text: "　終電を逃した駅のホームに、雨の音だけが残っていた。\n　ミナは切符を握ったまま、坂の上を見上げる。\n　駅員の宗次が声をかけた。\n" },
  { name: "002_白い傘.txt", text: "　宗次は傘を差し出した。ミナは待合室で朝を待った。\n" },
  { name: "003_坂の上の町.txt", text: "　朝、ミナは傘を返しに坂を上った。町には、古い写真館があった。\n" },
];

function synopsisEntry(chapter: number, fileName: string, title: string, synopsis: string): Record<string, unknown> {
  return { chapter, fileName, title, synopsis, sourceHash: `promo-${chapter}`, model: null, promptVersion: null, autoGenerated: false, authorNotes: "", emotion: null, updatedAt: null };
}

const ANSWER = JSON.stringify({
  logline: "終電を逃した女性が、雨の駅で出会った駅員の傘をきっかけに、坂の上の町で自分の居場所を見つける。",
  theme: "人に頼ることで、居場所は見つかる",
  motif: ["雨", "傘", "駅"],
  worldview: "小さな駅と、坂の上の古い町。時間がゆっくり流れる現代の地方。",
  setting: "山あいの小さな駅と、坂の上の町",
  narrativePerson: "三人称・ミナに寄り添う視点",
  protagonistMotive: "ひとりで抱え込む癖を手放し、誰かに頼れるようになりたい",
  outline: ["雨の夜、終電を逃したミナが駅員の宗次に出会う", "宗次が傘を貸し、ミナは待合室で朝を待つ", "朝、傘を返しに坂の上の町へ向かう"],
  mainCharacters: [
    { name: "ミナ", summary: "終電を逃した乗客。人に頼るのが苦手" },
    { name: "宗次", summary: "駅員。口数は少ないが面倒見がよい" },
  ],
  notes: null,
});

test("プロット逆算の広報素材を撮る", async () => {
  await recordFeature({
    name: "plot-reverse",
    subtitle: "プロット逆算 — 各話あらすじから、プロットを組み立てる",
    workTitle: "雨の駅",
    episodes: EPISODES,
    prepareWork: async ({ workFolder }) => {
      await mkdir(path.join(workFolder, "設定"), { recursive: true });
      await writeFile(
        path.join(workFolder, "設定", "chapter_synopses.json"),
        JSON.stringify(
          {
            schemaVersion: "0.1",
            episodes: [
              synopsisEntry(1, "001_雨の駅.txt", "雨の駅", "終電を逃したミナが、駅員の宗次と出会う。"),
              synopsisEntry(2, "002_白い傘.txt", "白い傘", "宗次の貸した傘で、ミナは朝を迎える。"),
              synopsisEntry(3, "003_坂の上の町.txt", "坂の上の町", "ミナは傘を返しに、坂の上の町へ向かう。"),
            ],
          },
          null,
          2
        ),
        "utf8"
      );
    },
    fakeAnswer: () => ANSWER,
    fakeModels: ["gemma4:e4b", "gemma4:26b"],
    snapAt: 13,
    play: async ({ page }, caption) => {
      await caption("各話あらすじから、プロットを逆算する");
      await page.waitForTimeout(2_500);
      await runCommand(page, "プロット逆算");
      let confirmed = false;
      await waitUntil(
        async () => {
          await passLocalAiGate(page);
          const title = (await quickPickTitle(page)) ?? "";
          if (title !== "") {
            const rows = await quickPickRows(page);
            if (rows.some((row) => row.label === "実行")) {
              await page.waitForTimeout(2_000);
              await pickQuickPickRow(page, "実行");
              confirmed = true;
            } else if (rows.length > 0 && !confirmed) {
              await pickQuickPickRow(page, rows[0].label);
            }
          }
          return confirmed;
        },
        "実行の確認に答える",
        60_000
      );
      await caption("AIの呼び出しは1回。作者が書いた項目は書き換えない");
      await waitUntil(
        async () => {
          await passLocalAiGate(page);
          const texts = await notificationTexts(page);
          return texts.some((text) => text.includes("書き足しました"));
        },
        "書き足した報告が出る",
        120_000
      );
      await caption("ログライン・テーマ・あらすじなどが plot.md へ入る");
      await page.waitForTimeout(2_000);
      await page.getByText("プロットを開く").first().click();
      await page.waitForTimeout(5_000);
    },
  });
});
