/**
 * Discord「機能紹介」用の広報素材：年表（作者の依頼 2026-10-22）。
 * features.md の文：1行が1話で、登場人物・作中の変化・あらすじが並ぶ。作中時期を割り当てると、時系列順に並べ替えられる。
 *
 * 人物・あらすじ・作中の時間の記録は、製品が読む形で起こす前に置く（広報用の作り物。AI は呼ばない）。
 * 走らせ方：`npx vitest run -c vitest.promo.config.mts test/e2e/promo/timelineScene.promo.ts`
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { test } from "vitest";
import type { Frame } from "playwright-core";
import { emptyCharacter, type Character } from "../../../src/models/character";
import { runCommand } from "../support/quickInput";
import { defaultCharactersFolder, writeCharactersTo } from "../support/settingsFixture";
import { waitUntil } from "../support/wait";
import { pickQuickPickRow, quickPickRows, quickPickTitle } from "../support/workbenchDom";
import { recordFeature } from "./support/featureScene";

const EPISODES = [
  { name: "001_雨の駅.txt", text: "　終電を逃したミナは、駅員の宗次に声をかけられた。\n" },
  { name: "002_白い傘.txt", text: "　宗次は傘を差し出した。ミナは待合室で朝を待った。\n" },
  { name: "003_十年前の駅.txt", text: "　十年前、まだ若かった宗次は、この駅で最後の汽車を見送った。\n" },
];

function change(field: string, value: string, chapters: number[]): Character["changes"][number] {
  return { field, value, chapters, timepointId: null, note: null, evidence: null, source: "author", confirmed: true };
}

function cast(): Character[] {
  const mina: Character = {
    ...emptyCharacter("char_001", "ミナ"),
    role: "終電を逃した乗客",
    autoGenerated: false,
    appearedChapters: [1, 2],
    changes: [change("personality", "人に頼るのが苦手", [1]), change("personality", "駅員を頼れるようになった", [2])],
  };
  const souji: Character = {
    ...emptyCharacter("char_002", "宗次"),
    role: "駅員",
    autoGenerated: false,
    appearedChapters: [1, 2, 3],
    changes: [change("appearance", "若い駅員", [3]), change("appearance", "制帽の中年の駅員", [1])],
  };
  return [mina, souji];
}

function synopsisEntry(chapter: number, fileName: string, title: string, synopsis: string): Record<string, unknown> {
  return { chapter, fileName, title, synopsis, sourceHash: `promo-${chapter}`, model: null, promptVersion: null, autoGenerated: false, authorNotes: "", emotion: null, updatedAt: null };
}

async function chronicleFrame(page: import("playwright-core").Page): Promise<Frame | undefined> {
  for (const frame of page.frames()) {
    const has = await frame.evaluate(() => document.getElementById("byTimeline") !== null && document.getElementById("sections") !== null).catch(() => false);
    if (has) return frame;
  }
  return undefined;
}

test("年表の広報素材を撮る", async () => {
  await recordFeature({
    name: "timeline",
    subtitle: "年表 — 話ごとの出来事を、時系列でも並べる",
    workTitle: "雨の駅",
    episodes: EPISODES,
    prepareWork: async ({ workFolder }) => {
      await writeCharactersTo(defaultCharactersFolder(workFolder), cast());
      await mkdir(path.join(workFolder, "設定"), { recursive: true });
      await writeFile(
        path.join(workFolder, "設定", "chapter_synopses.json"),
        JSON.stringify(
          {
            schemaVersion: "0.1",
            episodes: [
              synopsisEntry(1, "001_雨の駅.txt", "雨の駅", "終電を逃したミナが、駅員の宗次と出会う。"),
              synopsisEntry(2, "002_白い傘.txt", "白い傘", "宗次の貸した傘で、ミナは朝を迎える。"),
              synopsisEntry(3, "003_十年前の駅.txt", "十年前の駅", "若き日の宗次が、最後の汽車を見送った夜。"),
            ],
          },
          null,
          2
        ),
        "utf8"
      );
      await writeFile(
        path.join(workFolder, "設定", "timeline.json"),
        JSON.stringify(
          {
            schemaVersion: "0.1",
            lines: [{ id: "ln_001", label: "本編", kind: "main", canonical: true, branchFrom: null, note: "" }],
            timepoints: [
              { id: "tp_001", lineId: "ln_001", label: "十年前・最後の汽車", absolute: null, note: "" },
              { id: "tp_002", lineId: "ln_001", label: "雨の夜", absolute: null, note: "" },
              { id: "tp_003", lineId: "ln_001", label: "翌朝", absolute: null, note: "" },
            ],
            episodes: [
              { filePath: "本文/001_雨の駅.txt", timepointId: "tp_002", note: "" },
              { filePath: "本文/002_白い傘.txt", timepointId: "tp_003", note: "" },
              { filePath: "本文/003_十年前の駅.txt", timepointId: "tp_001", note: "" },
            ],
          },
          null,
          2
        ),
        "utf8"
      );
    },
    fakeModels: ["gemma4:e4b", "gemma4:26b"],
    snapAt: 11,
    play: async ({ page }, caption) => {
      await caption("1行が1話。登場人物・変化・あらすじが並ぶ");
      await page.waitForTimeout(1_000);
      await runCommand(page, "年表");
      let frame: Frame | undefined;
      let picked = false;
      await waitUntil(
        async () => {
          if (!picked && (await quickPickTitle(page)) !== undefined) {
            const rows = await quickPickRows(page);
            if (rows.length > 0) {
              await pickQuickPickRow(page, rows[0].label);
              picked = true;
            }
          }
          return (frame = await chronicleFrame(page)) !== undefined;
        },
        "年表が開く",
        30_000
      );
      const f = frame as Frame;
      await waitUntil(async () => (await f.locator("#sections tbody tr").count()) >= 3, "年表に3話が並ぶ", 20_000);
      await page.waitForTimeout(4_000);
      await caption("作中の時期を割り当てると、時系列順に並べ替えられる");
      await f.locator("#byTimeline").click();
      await page.waitForTimeout(5_000);
    },
  });
});
