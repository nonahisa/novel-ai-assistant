/**
 * Discord「機能紹介」用の広報素材：名前点検（作者の依頼 2026-10-22）。
 * features.md の文：響きの近い名前を、強さと理由をつけて並べる（AI不要）。「候補を出す」で新しい名前を10件出す。
 *
 * 人物の記録は製品が読む形で起こす前に置く（広報用の作り物）。**本物のAIは呼ばない**（偽の Ollama が候補を返す）。
 * 走らせ方：`npx vitest run -c vitest.promo.config.mts test/e2e/promo/nameCheckScene.promo.ts`
 */
import { test } from "vitest";
import type { Frame } from "playwright-core";
import { emptyCharacter, type Character } from "../../../src/models/character";
import { nameFakeRespond } from "../look/nameLookSupport";
import { nameCheckFrame, suggestNamesFor } from "../support/nameCheckPanel";
import { runCommand } from "../support/quickInput";
import { defaultCharactersFolder, writeCharactersTo } from "../support/settingsFixture";
import { waitUntil } from "../support/wait";
import { pickQuickPickRow, quickPickRows, quickPickTitle } from "../support/workbenchDom";
import { recordFeature } from "./support/featureScene";

function cast(): Character[] {
  const rows = [
    ["宗次", "そうじ", "男性", "駅員"],
    ["総司", "そうじ", "男性", "旅の医者"],
    ["ミナ", "みな", "女性", "終電を逃した乗客"],
    ["美奈", "みな", "女性", "宿の娘"],
    ["白瀬灯", "しらせあかり", "女性", "写真家"],
  ];
  return rows.map(([name, reading, gender, role], i) => ({
    ...emptyCharacter(`char_00${i + 1}`, name),
    reading,
    gender,
    role,
    autoGenerated: false,
    appearedChapters: [1],
  }));
}

test("名前点検の広報素材を撮る", async () => {
  let asked = 0;
  await recordFeature({
    name: "name-check",
    subtitle: "名前点検 — 響きの近い名前を見つける",
    workTitle: "雨の駅",
    episodes: [{ name: "001_雨の駅.txt", text: "　宗次は傘を差し出した。ミナは待合室で朝を待った。総司と美奈が、遅れて駅に着いた。\n" }],
    prepareWork: async ({ workFolder }) => {
      await writeCharactersTo(defaultCharactersFolder(workFolder), cast());
    },
    fakeAnswer: (request) => {
      asked++;
      return nameFakeRespond(request);
    },
    fakeModels: ["gemma4:e4b", "gemma4:26b"],
    snapAt: 6,
    play: async (session, caption) => {
      const { page } = session;
      await caption("響きの近い名前を、強さと理由つきで並べる");
      await page.waitForTimeout(1_000);
      await runCommand(page, "名前点検");
      let frame: Frame | undefined;
      let picked = false;
      await waitUntil(
        async () => {
          if (!picked && (await quickPickTitle(page)) !== undefined) {
            const rows = await quickPickRows(page);
            if (rows.length > 0) {
              await pickQuickPickRow(page, rows[0].label);
              picked = true;
            }
          }
          return (frame = await nameCheckFrame(page)) !== undefined;
        },
        "名前点検のパネルが開く",
        30_000
      );
      const f = frame as Frame;
      await waitUntil(async () => (await f.locator("[data-suggest]").count()) >= 5, "人物が並ぶ", 15_000);
      await page.waitForTimeout(4_000);
      await caption("「候補を出す」で、新しい名前を10件");
      const before = asked;
      await suggestNamesFor(session, f, "char_005", "指定なし", () => asked > before);
      await f.locator("#candidates-char_005").scrollIntoViewIfNeeded();
      await page.waitForTimeout(4_000);
    },
  });
});
