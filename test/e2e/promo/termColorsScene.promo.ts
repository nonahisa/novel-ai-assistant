const EPISODE = "001_白い切符.txt";
const TEXT = [
  "　白川駅の改札を抜けると、雨はもう上がっていた。",
  "　ミナは切符を握ったまま、旧市街へ続く坂を見上げる。",
  "　「遅かったな」",
  "　ベンチの灰谷が、読みかけの本を閉じた。",
  "　ミナは答えず、彼の隣に腰を下ろした。",
  "",
].join("\n");

const CHARACTERS: Character[] = [
  { ...emptyCharacter("char_001", "ミナ"), reading: "みな", summary: "終電のあとの駅に降り立つ、物語の語り手。", role: "主人公", appearedChapters: [1], autoGenerated: false },
  { ...emptyCharacter("char_002", "灰谷"), reading: "はいたに", summary: "駅のベンチで本を読みながら、誰かを待っている青年。", role: "案内人", appearedChapters: [1], autoGenerated: false },
];
const LOCATIONS: Location[] = [
  { ...emptyLocation("loc_001", "白川駅"), reading: "しらかわえき", summary: "終電が出たあとも明かりの消えない、小さな駅。", appearedChapters: [1], autoGenerated: false },
  { ...emptyLocation("loc_002", "旧市街"), reading: "きゅうしがい", summary: "坂の上に広がる古い町並み。時計台がある。", appearedChapters: [1], autoGenerated: false },
];

async function wordPosition(frame: Frame, word: string): Promise<{ x: number; y: number }> {
  const position = await frame.evaluate((text) => {
    const compose = document.getElementById("compose");
    if (!compose) return undefined;
    const walker = document.createTreeWalker(compose, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const at = (node.textContent ?? "").indexOf(text);
      if (at < 0) continue;
      const range = document.createRange();
      range.setStart(node, at);
      range.setEnd(node, at + text.length);
      const rect = range.getBoundingClientRect();
      const box = compose.getBoundingClientRect();
      return { x: rect.left + rect.width / 2 - box.left, y: rect.top + rect.height / 2 - box.top };
    }
    return undefined;
  }, word);
  if (!position) throw new Error(`「${word}」が見つかりません`);
  return position;
}

async function tipName(frame: Frame): Promise<string | undefined> {
  return frame.evaluate(() => {
    const tip = document.getElementById("tip");
    return tip && tip.classList.contains("open") ? (tip.querySelector(".tip-name")?.textContent ?? "") : undefined;
  });
}

test("用語の色分けの広報素材を撮る", async () => {
  let frame!: Frame;
  await recordFeature({
    name: "term-colors",
    subtitle: "用語の色分け — 人物・場所",
    workTitle: "白い切符",
    episodes: [{ name: EPISODE, text: TEXT }],
    snapAt: 8,
    prepareWork: async ({ workFolder }) => {
      await writeCharactersTo(defaultCharactersFolder(workFolder), CHARACTERS);
      const folder = path.join(workFolder, DEFAULT_SETTINGS_DIR, "locations");
      await mkdir(folder, { recursive: true });
      for (const location of LOCATIONS) await writeFile(path.join(folder, locationFileName(location)), `${JSON.stringify(location, null, 2)}\n`, "utf8");
    },
    open: async ({ page }) => {
      frame = await openEpisode(page, EPISODE, "腰を下ろした");
    },
    play: async ({ page }, caption) => {
      await waitUntil(
        async () =>
          frame.evaluate(() => {
            const reg = (globalThis as unknown as { CSS?: { highlights?: Map<string, unknown> } }).CSS?.highlights;
            return !!reg?.get("novelai-term-character") && !!reg?.get("novelai-term-location");
          }),
        "色が付く",
        30_000
      );
      await page.mouse.move(640, 690);
      await caption("人物は青、場所は緑。登場する名前に色が付く");
      await page.waitForTimeout(3_500);
      for (const word of ["灰谷", "白川駅"]) {
        const pos = await wordPosition(frame, word);
        await frame.locator("#compose").hover({ position: pos });
        await waitUntil(async () => (await tipName(frame)) === word, `「${word}」のチップ`, 10_000);
        await caption("合わせると、設定の要点が出る");
        await page.waitForTimeout(2_800);
      }
      await frame.locator("#compose").click({ position: await wordPosition(frame, "ミナ"), button: "right" });
      await waitUntil(async () => frame.evaluate(() => document.getElementById("menu")?.classList.contains("open") === true), "品書き", 10_000);
      await caption("右クリックで、設定資料を開ける");
      await page.waitForTimeout(3_500);
    },
  });
});
