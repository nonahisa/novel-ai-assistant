/** 名前の候補の頼み（P-45）か */
export function isPlotNamesRequest(request: FakeOllamaRequest): boolean {
  return request.user.includes("名前の候補") && /id：\d+/.test(request.user);
}

/**
 * 名前の候補の頼みへの偽の答え。頼みの文に並んだ人物の id ごとに候補を返す
 * （1人目は `FIRST_CANDIDATES`、2人目からは別の名前）。系統は頼みの文の指定に合わせる
 */
export function plotNamesAnswer(request: FakeOllamaRequest): string {
  const origin = /origin と、各候補の origin には「(.+?)」/.exec(request.user)?.[1] ?? "和風";
  const ids = [...request.user.matchAll(/id：(\d+)/g)].map((match) => match[1]);
  const people = ids.map((id, index) => ({
    id,
    candidates: (index === 0 ? FIRST_CANDIDATES : OTHER_CANDIDATES[(index - 1) % OTHER_CANDIDATES.length]).map((entry) => ({ ...entry, origin })),
  }));
  return JSON.stringify({ origin, people });
}

/** 起こす前に、人物と plot.md を置く（`LaunchOptions.prepareWork` から呼ぶ） */
export async function preparePlotWork(workFolder: string, characters: readonly Character[], plot = ROLE_PLOT): Promise<void> {
  await writeCharactersTo(defaultCharactersFolder(workFolder), characters);
  await mkdir(path.join(workFolder, "設定"), { recursive: true });
  await writeFile(path.join(workFolder, "設定", "plot.md"), plot, "utf8");
}

/** プロットモードのパネル（目印は「主要登場人物の名前」の見出し `#namesHeading`） */
export async function plotPanelFrame(page: Page): Promise<Frame | undefined> {
  for (const frame of page.frames()) {
    const has = await frame
      .evaluate(() => document.getElementById("namesHeading") !== null && document.getElementById("headings") !== null)
      .catch(() => false);
    if (has) return frame;
  }
  return undefined;
}

/** 左の列の作品の右クリック「プロットモード」で開き、［名前の候補を出す］が出るまで待つ */
export async function openPlotMode(session: E2ESession, workTitle = E2E_WORK_TITLE): Promise<Frame> {
  const { page } = session;
  await showSidebar(page, workTitle);
  await expandTreeRow(page, workTitle);
  /*
    **一覧が描き直している最中に右クリックしない**（`waitTreeSettled` の説明）。作品を2つ登録する件
    （plotModeAiEntrances の2件目）は、登録した直後に裏の走査で一覧が描き直され、ノートPCで2回に1回
    「プロットモードのパネルが開く」を30秒待って落ちた（2026-10-12）。品書きが指していた行が消えると、
    命令に作品が渡らず黙って終わるか、作品を選ぶ画面が出る形になる
  */
  await waitTreeSettled(page);
  await treeContextMenu(page, workTitle, "プロットモード");
  let panel: Frame | undefined;
  await waitUntil(async () => (panel = await plotPanelFrame(page)) !== undefined, "プロットモードのパネルが開く", 30_000).catch(async (error: unknown) => {
    // 作品を選ぶ画面が出たのか・黙って終わったのか・別の列に何か開いたのかを、離れた機械でも読めるように添える
    const rows = await quickPickRows(page).catch(() => []);
    throw new Error(
      `${String(error)}（選ぶ画面の行：${JSON.stringify(rows.map((row) => `${row.label}${row.description ? ` ― ${row.description}` : ""}`))}` +
        `／タブ（＊が前）：${JSON.stringify(await describeTabs(page))}／左の列の行：${JSON.stringify(await treeRowLabels(page).catch(() => []))}）` +
        `${await quickInputWaitContext(page)}`
    );
  });
  if (!panel) throw new Error("プロットモードのパネルが見つかりません");
  const found = panel;
  await waitUntil(async () => (await found.locator("[data-suggest-names]").count()) > 0, "プロットモードに［名前の候補を出す］が出る", 30_000);
  return found;
}

/**
 * ［名前の候補を出す］を押し、人物を選ぶ画面（全員選ばれたまま［OK］）と系統を選ぶ画面（`originRow`）を通す。
 * **AI への頼みが届いたところで戻る**（`requested` が真になるまで）。答えが返るまでの画面を見たい件は、
 * 戻ったあとに見て、それから偽の AI の答えを解く
 */
export async function startNameSuggest(
  session: E2ESession,
  plot: Frame,
  requested: () => boolean,
  /*
    既定は先頭の「指定なし（作品に合わせる）」。現代の話なので和風に見立てられる（`core/nameOriginFit.ts`）。
    「和風」の行を名前で押すと、行の探し方（行の字のどこかに含む）が、説明に「和風」を含む
    「指定なし」の行に当たりうる
  */
  originRow = "指定なし"
): Promise<{ titles: string[] }> {
  const { page } = session;
  const titles: string[] = [];
  await plot.locator("[data-suggest-names]").click();
  await waitUntil(
    async () => {
      await passLocalAiGate(page);
      const title = (await quickPickTitle(page)) ?? "";
      if (title !== "" && titles[titles.length - 1] !== title) titles.push(title);
      if (title.includes("名前の候補を出す人物")) {
        await acceptQuickPick(page);
      } else if (title.includes("名前の系統")) {
        await pickQuickPickRow(page, originRow);
      } else if (title === "") {
        // 料金などの確認が窓で出たら、進める（手元のAIでは出ないはず。出たら文を落ちた文に残すため名乗る）
        const dialog = await dialogText(page);
        if (dialog !== undefined) throw new Error(`名前の候補を出す途中で、思わぬ確認の窓が出ました：${dialog.replace(/\s+/g, " ").slice(0, 200)}`);
      }
      return requested();
    },
    "人物と系統を選んで、名前の候補の頼みが偽のAIへ届く",
    60_000
  ).catch(async (error: unknown) => {
    throw new Error(`${String(error)}（通った選ぶ画面：${JSON.stringify(titles)}／名前の欄の一文：${JSON.stringify(await plot.locator("#namesNote").innerText().catch(() => ""))}）${await quickInputWaitContext(page)}`);
  });
  return { titles };
}

/** 人物ごとの候補が並び、［名前の候補を出す］が押せる形に戻るまで待つ */
export async function waitNameResults(plot: Frame, page?: Page): Promise<void> {
  await waitUntil(
    async () => (await plot.locator(".name-person").count()) > 0 && (await plot.locator("[data-suggest-names]").isEnabled()),
    "人物ごとの名前の候補が並ぶ",
    60_000
  ).catch(async (error: unknown) => {
    // 選ぶ画面が開いたまま（人物・系統を選ぶ途中で止まった）か、断りの知らせで止まったかを文で分ける
    const button = await plot
      .locator("[data-suggest-names]")
      .isEnabled()
      .then((enabled) => (enabled ? "押せる" : "押せない"))
      .catch(() => "見つからない");
    throw new Error(
      `${String(error)}（名前の欄：${JSON.stringify((await plot.locator("#nameResults").innerText().catch(() => "")).replace(/\s+/g, " ").slice(0, 400))}／一文：${JSON.stringify(await plot.locator("#namesNote").innerText().catch(() => ""))}` +
        `／［名前の候補を出す］：${button}）${page ? await quickInputWaitContext(page) : ""}`
    );
  });
}

export function plotFile(session: E2ESession): string {
  return path.join(session.workFolder, "設定", "plot.md");
}

export async function readPlot(session: E2ESession): Promise<string> {
  return (await readFile(plotFile(session), "utf8")).replace(/\r\n/g, "\n");
}

/**
 * plot.md を素のエディターで開いて全文を入れ替え、Ctrl+S で保存する（作者が書き換えて保存するのと同じ）。
 * ファイルが `text` になるまで待つ（保存からの反映は、その保存の合図で走る）
 */
export async function rewritePlotAndSave(session: E2ESession, text: string): Promise<void> {
  const { page } = session;
  await quickOpen(page, "plot.md");
  /*
    **前の列に限らず探す。** プロットモードは plot.md を列1、パネルを列2に置く（`features/plotModePanel.ts`）。
    パネルを押したあとは列2が前の列で、Ctrl+P で plot.md を選ぶと、既に開いている列1の plot.md が前に出るだけで
    焦点は列2の WebView に残ることがある（2026-10-12 ノートPC 1.141.0。列1に plot.md の字が見えているのに、
    前の列だけを見ていたこの待ちが15秒で落ちた）。見つけたら押して、その列へ焦点を移す
  */
  const lines = page.locator(".editor-group-container .monaco-editor .view-lines", { hasText: "主要登場人物" }).filter({ visible: true }).first();
  await waitUntil(async () => (await lines.count()) > 0, "plot.md が素のエディターで開く", 15_000).catch(async (error: unknown) => {
    /*
      2026-10-12 ノートPC（1.141.0）の plotRenamePending 1件目で、Ctrl+P で開いたのにここで15秒待って落ちた。
      見当がつかなかったので、次に落ちたときに分けられるよう、列ごとのタブ（どれが前か）・各列に見えている
      素のエディターの字の頭・列の幅・窓と選ぶ画面と知らせを添える。plot.md が「前の列でない列」に開いた／
      提案パネルなどの面が plot.md の上へ戻ってきた／素のエディターでない画面で開いた、のどれかを分けたい
    */
    const groups = await readTabState(page).catch(() => []);
    const shown = await page
      .evaluate(() =>
        Array.from(document.querySelectorAll(".editor-group-container")).map((group, index) => {
          const box = (group as HTMLElement).getBoundingClientRect();
          const text = Array.from(group.querySelectorAll(".monaco-editor .view-lines"))
            .map((node) => (node as HTMLElement).innerText)
            .join("⏎")
            .replace(/\s+/g, " ")
            .slice(0, 60);
          return `列${index + 1}${group.classList.contains("active") ? "（前）" : ""} 幅${Math.round(box.width)}：「${text}」`;
        })
      )
      .catch(() => [] as string[]);
    const tabs = describeGroups(groups);
    throw new Error(
      `${String(error)}（タブ（＊が前）：${JSON.stringify(tabs)}／素のエディターの字：${JSON.stringify(shown)}）${await quickInputWaitContext(page)}`
    );
  });
  await lines.click();
  /*
    押したあと、焦点が plot.md の素のエディターに載るまで待つ。WebView に焦点を取り返されたまま Ctrl+A と
    打ち込みを送ると、字が WebView へ流れ、次の「保存される」の待ちで原因の読めない形で落ちるため
  */
  await waitUntil(
    async () =>
      page.evaluate(() => {
        const editor = document.activeElement?.closest(".monaco-editor");
        return (editor?.querySelector(".view-lines") as HTMLElement | null | undefined)?.innerText.includes("主要登場人物") === true;
      }),
    "押したあと、焦点が plot.md の素のエディターに載る",
    5_000
  ).catch(async (error: unknown) => {
    const focus = await page.evaluate(() => {
      const active = document.activeElement as HTMLElement | null;
      return active ? `${active.tagName.toLowerCase()}${active.className ? "." + String(active.className).split(" ").slice(0, 2).join(".") : ""}` : "なし";
    });
    throw new Error(`${String(error)}（焦点：${focus}／タブ（＊が前）：${JSON.stringify(await describeTabs(page))}）${await quickInputWaitContext(page)}`);
  });
  await page.keyboard.press("Control+KeyA");
  await page.keyboard.insertText(text);
  await page.keyboard.press("Control+KeyS");
  await waitUntil(async () => (await readPlot(session)) === text, "書き換えた plot.md が保存される", 15_000).catch(async (error: unknown) => {
    throw new Error(`${String(error)}（ファイル：${JSON.stringify(await readPlot(session).catch(() => "読めない"))}）`);
  });
}

/** 列ごとのタブを「列1（前）：名前＊・名前」の形にする（＊はその列で前に出ているタブ）。落ちた文に添える */
function describeGroups(groups: Awaited<ReturnType<typeof readTabState>>): string[] {
  return groups.map(
    (group, index) => `列${index + 1}${group.active ? "（前）" : ""}：${group.tabs.map((tab) => `${tab.name}${tab.active ? "＊" : ""}`).join("・")}`
  );
}

async function describeTabs(page: Page): Promise<string[]> {
  return describeGroups(await readTabState(page).catch(() => []));
}

/** 承認待ち（`.aiwriter/pending-characters/*.json`）の中身。ファイル名 → 字 */
export async function pendingCharacterFiles(session: E2ESession): Promise<Map<string, string>> {
  const folder = path.join(session.workFolder, ".aiwriter", "pending-characters");
  const files = new Map<string, string>();
  for (const name of (await readdir(folder).catch(() => [] as string[])).filter((entry) => entry.endsWith(".json"))) {
    files.set(name, await readFile(path.join(folder, name), "utf8").catch(() => ""));
  }
  return files;
}

/** 承認待ちのうち、`text` を含むもののファイル名 */
export async function pendingFilesMentioning(session: E2ESession, text: string): Promise<string[]> {
  return [...(await pendingCharacterFiles(session))].filter(([, body]) => body.includes(text)).map(([name]) => name);
}

/** 「設定資料更新分反映」を開いて、提案パネルの面を返す（承認待ちが並ぶまで待つ） */
export async function openUpdates(session: E2ESession, expectText: string): Promise<Frame> {
  const { page } = session;
  await clearNotifications(page);
  await runCommand(page, "設定資料更新分反映");
  let panel: Frame | undefined;
  await waitUntil(
    async () => (panel = await proposalPanelFrame(page)) !== undefined && (await panel.locator(".issue", { hasText: expectText }).count()) > 0,
    `「設定資料更新分反映」に「${expectText}」の案が並ぶ`,
    30_000
  ).catch(async (error: unknown) => {
    const text = panel ? await panel.evaluate(() => document.body.innerText).catch(() => "") : "（提案パネルが開いていません）";
    throw new Error(`${String(error)}（提案パネル：${JSON.stringify(text.replace(/\s+/g, " ").slice(0, 500))}）`);
  });
  if (!panel) throw new Error("提案パネルが見つかりません");
  return panel;
}

/** 資料の人物の記録（`設定/characters`）の名前の一覧 */
export async function characterNames(session: E2ESession): Promise<string[]> {
  const folder = path.join(session.workFolder, "設定", "characters");
  const names: string[] = [];
  for (const name of (await readdir(folder).catch(() => [] as string[])).filter((entry) => entry.endsWith(".json"))) {
    const record = JSON.parse(await readFile(path.join(folder, name), "utf8").catch(() => "{}")) as { name?: string };
    if (record.name) names.push(record.name);
  }
  return names.sort();
}
