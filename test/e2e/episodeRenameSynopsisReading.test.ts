/**
 * 話の名前が変わっても、各話あらすじと読みの辞書がついてくる（画面の自動テスト、設計書6.68.2・6.42.1・6.113。
 * 0.127.0）。実機確認リスト 0.127.0 の「幕間.txt のような話数の無い話と、話数のある話の…」の項目の
 * 「残り」4つを機械へ移したもの（F2 と .md 化の道は episodeRenameLedgerFollow の3・4件目が見ている）。
 * 単体テストは test/unit/cross/episodeRenameSynopsisReading.test.ts。
 *
 * 見張るのは次の4つ：
 *
 * 1. **右クリック「ファイル名にサブタイトルを付ける」**：
 *    - 話数のある話（`001.txt`）：知らせに「読みの辞書1件」、辞書は新しい名前へ移る。
 *      あらすじは**話数で引く**ので行は動かさない（知らせに「各話あらすじ」は出ない。
 *      `renameUnnumberedSynopses` が話数のある行を名前で動かさない作り）
 *    - 話数の無い話（`幕間.txt`）：題を【タイトル】から読むので改名でき、知らせに
 *      「各話あらすじ1件」「読みの辞書1件」、あらすじは新しい名前を指す
 *    - 話数も【タイトル】も無い話（`閑話.txt`）：題を読めず「サブタイトルを読み取れませんでした」で止まり、
 *      名前も記録も変わらない
 * 2. **話の挿入と削除**：「この話の前に挿入」で後ろの話の番号がずれると、あらすじ（話数とファイル名）と
 *    読みの辞書が同じ話についていく。挿入した話を「この話を削除」（話数を詰める）で消すと、元の並びへ戻る
 * 3. **削除した話の読みが、詰めた次の話に効かない**：番号だけの名前（`002.txt`）を消して `003.txt` が
 *    `002.txt` へ詰まると、消えた話の辞書は控え（`.removed.json`）へ退き、新しい `002.txt` の読み上げには効かない
 * 4. **新しい名前の面で、読みが実際に当たる**：挿入で `002.txt` が `003.txt` になったあと、`003.txt` を
 *    原稿エディターで開くと、読み上げの列に「読みの辞書：1件」が出て、読み上げの声に渡る文が辞書の読みになる
 *
 * **声は偽物に替える**（readAloudMark と同じ。音は出ない）。AI は呼ばない。GitHub も呼ばない。
 * 作品は Git にしない（挿入・削除のあとの「名前だけのコミット」の問いは出ない）。
 * 削除したファイルは作者の機械のごみ箱へ入る（製品は `useTrash: true`。episodeDeleteTrash と同じ）。
 */
