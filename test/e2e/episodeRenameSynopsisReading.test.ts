/* ── 見本（作り物の作品） ── */

interface SynopsisRow {
  chapter: number | null;
  fileName: string;
  synopsis: string;
  authorNotes: string;
}

interface ReadingFile {
  episode: string;
  entries: Array<{ word: string; quote: string; reading: string; source?: string }>;
}

/** 各話あらすじの1行（作者が書き直した行。中身は変えずに指し先だけが変わることを見る） */
function synopsisRow(fileName: string, chapter: number | null, synopsis: string): Record<string, unknown> {
  return {
    chapter,
    fileName,
    title: null,
    synopsis,
    sourceHash: "h",
    model: null,
    promptVersion: null,
    autoGenerated: false,
    authorNotes: `${synopsis}のメモ`,
    emotion: null,
    updatedAt: null,
  };
}

/** 読みの辞書の置き場の名前（`core/readingDictionaryStore.ts`：相対パスの区切りを __ にした名前） */
function dictionaryName(fileName: string): string {
  return `本文__${fileName}.json`;
}

function dictionary(fileName: string, reading: string): ReadingFile & { version: number } {
  return {
    version: 1,
    episode: `本文/${fileName}`,
    // `source` は読み込みの形の検査が必ず見る（無いと壊れた辞書として読み込みが止まり、付け替えも失敗に回る。core/readingDictionary.ts）
    entries: [{ word: "十分", quote: "十分に", reading, source: "author" }],
  };
}

/** 起こす前に、あらすじと読みの辞書を置く */
function launchWith(synopses: Array<Record<string, unknown>>, dictionaries: Array<{ fileName: string; reading: string }>) {
  return {
    ...SIDEBAR_LAUNCH,
    prepareWork: async ({ workFolder }: { workFolder: string }) => {
      await mkdir(path.join(workFolder, "設定"), { recursive: true });
      if (synopses.length > 0) {
        await writeFile(
          path.join(workFolder, "設定", "chapter_synopses.json"),
          `${JSON.stringify({ schemaVersion: "0.1", episodes: synopses }, null, 2)}\n`,
          "utf8"
        );
      }
      await mkdir(path.join(workFolder, ".aiwriter", "readings"), { recursive: true });
      for (const item of dictionaries) {
        await writeFile(
          path.join(workFolder, ".aiwriter", "readings", dictionaryName(item.fileName)),
          `${JSON.stringify(dictionary(item.fileName, item.reading), null, 2)}\n`,
          "utf8"
        );
      }
    },
  };
}

/* ── 読む道具（書き戻しは退避→作り直しで一瞬ファイルが無いので、fileSettle の口で読む） ── */

async function synopsisRows(session: E2ESession): Promise<SynopsisRow[]> {
  const set = await readListedJson<{ episodes: SynopsisRow[] }>(path.join(session.workFolder, "設定", "chapter_synopses.json"));
  return set?.episodes ?? [];
}

async function readingFile(session: E2ESession, name: string): Promise<ReadingFile | undefined> {
  return readListedJson<ReadingFile>(path.join(session.workFolder, ".aiwriter", "readings", name), 1_000);
}

async function readingFolder(session: E2ESession): Promise<string[]> {
  return (await readdir(path.join(session.workFolder, ".aiwriter", "readings")).catch(() => [] as string[])).filter((name) => !name.includes(".novelai-")).sort();
}

/** 本文フォルダーの話（書き込み途中の一時ファイルは拾わない） */
async function episodeFiles(session: E2ESession): Promise<string[]> {
  return (await readdir(session.manuscriptFolder).catch(() => [] as string[])).filter((name) => name.endsWith(".txt") && !name.includes(".novelai-")).sort();
}

/** あらすじを「話数:ファイル名:あらすじ:メモ」の形で並べる（比べやすく、落ちた文にそのまま出せる） */
async function synopsisSummary(session: E2ESession): Promise<string[]> {
  return (await synopsisRows(session).catch(() => [] as SynopsisRow[]))
    .map((row) => `${String(row.chapter)}:${row.fileName}:${row.synopsis}:${row.authorNotes}`)
    .sort();
}

/** 読みの辞書を「置き場:中の episode:読み」の形で並べる */
async function readingSummary(session: E2ESession): Promise<string[]> {
  const out: string[] = [];
  for (const name of await readingFolder(session)) {
    const file = await readingFile(session, name).catch(() => undefined);
    out.push(`${name}:${file?.episode ?? "読めない"}:${file?.entries.map((entry) => entry.reading).join("/") ?? ""}`);
  }
  return out;
}

/** ステータスバーと右下の知らせの字（サブタイトルの改名の完了は帯に6秒だけ、挿入・削除は右下に出る） */
async function noticeLines(page: Page): Promise<string[]> {
  return [...(await statusBarTexts(page)), ...(await notificationTexts(page))];
}

async function waitNotice(page: Page, needle: string, what: string): Promise<string> {
  let found = "";
  await waitUntil(
    async () => {
      found = (await noticeLines(page)).find((text) => text.includes(needle)) ?? "";
      return found !== "";
    },
    what,
    20_000
  ).catch(async (error: unknown) => {
    throw new Error(`${String(error)}（いまの知らせ：${JSON.stringify(await noticeLines(page))}／確認の窓：${(await dialogText(page)) ?? "なし"}）`);
  });
  return found;
}

/** 本文フォルダーが `expected` の並びになるまで待つ。落ちたら今の並び・窓・知らせを添える */
async function waitEpisodeFiles(session: E2ESession, expected: string[], what: string): Promise<void> {
  await waitUntil(async () => JSON.stringify(await episodeFiles(session)) === JSON.stringify(expected), what, 20_000).catch(async (error: unknown) => {
    throw new Error(
      `${String(error)}（いまの話：${JSON.stringify(await episodeFiles(session))}／窓：${(await dialogText(session.page)) ?? "なし"}／知らせ：${JSON.stringify(await noticeLines(session.page))}）`
    );
  });
}

/** あらすじと読みの辞書が `expected` になるまで待つ（付け替えは知らせのあとに書き終わることがある） */
async function waitRecords(session: E2ESession, expected: { synopses?: string[]; readings: string[] }, what: string): Promise<void> {
  const matches = async () =>
    (expected.synopses === undefined || JSON.stringify(await synopsisSummary(session)) === JSON.stringify([...expected.synopses].sort())) &&
    JSON.stringify(await readingSummary(session)) === JSON.stringify([...expected.readings].sort());
  await waitUntil(matches, what, 20_000).catch(async (error: unknown) => {
    throw new Error(`${String(error)}（いまのあらすじ：${JSON.stringify(await synopsisSummary(session))}／いまの読みの辞書：${JSON.stringify(await readingSummary(session))}）`);
  });
}

/** 作品一覧を出して作品を開き、話が並ぶまで待つ */
async function showWork(page: Page, firstHead: string): Promise<void> {
  await showSidebar(page, E2E_WORK_TITLE);
  // 横の「AIに相談」が下半分を取ると、木の下のほうの行が描かれない（episodeDeleteTrash と同じ手当て）
  await collapseSidebarPane(page, "AIに相談");
  await expandTreeRow(page, E2E_WORK_TITLE);
  await waitUntil(async () => (await treeRowLabels(page)).some((label) => label.startsWith(firstHead)), `作品の下に「${firstHead}」の行が並ぶ`);
  await waitTreeSettled(page);
}

/** 確認の窓（画面の中に描いたもの）の文が `needle` を含むまで待つ。落ちたらいまの窓を添える */
async function waitDialog(page: Page, needle: string, label: string): Promise<string> {
  let text = "";
  await waitUntil(async () => (text = (await dialogText(page)) ?? "").includes(needle), label, 20_000).catch(async (error: unknown) => {
    throw new Error(`${String(error)}（いまの窓：${JSON.stringify(text)}／知らせ：${JSON.stringify(await noticeLines(page))}）${await quickInputWaitContext(page)}`);
  });
  return text;
}

/** 話の行（名前が `head` で始まる行）の右クリック「この話の前に挿入」で、サブタイトル `subtitle` の話を差し込む */
async function insertBefore(page: Page, head: string, subtitle: string): Promise<void> {
  await waitTreeSettled(page);
  await treeContextMenu(page, head, "この話の前に挿入");
  await waitForQuickInput(page, "この話の前に挿入", 30_000).catch(async (error: unknown) => {
    throw new Error(`${String(error)}（知らせ：${JSON.stringify(await noticeLines(page))}／確認の窓：${(await dialogText(page)) ?? "なし"}）${await quickInputWaitContext(page)}`);
  });
  await answerInput(page, subtitle);
  await waitDialog(page, "話数を付け替えます", "付け替えの確認の窓が出る");
  await pressDialogButton(page, "付け替える");
}

/** 話の行の右クリック「この話を削除」で、［話数を詰める］→［削除する］と押す */
async function deleteAndRenumber(page: Page, head: string, fileName: string): Promise<void> {
  await waitTreeSettled(page);
  await treeContextMenu(page, head, "この話を削除");
  await waitDialog(page, "あとの話の話数を詰めますか", "「話数を詰めますか」の問いが出る");
  await pressDialogButton(page, EPISODE_DELETE_CHOICES.renumber);
  const confirm = await waitDialog(page, "話数を詰めます", "「話数を詰める」で付け替えの確認が出る");
  expect(confirm, `付け替えの確認：${confirm}`).toContain(fileName);
  await pressDialogButton(page, "削除する");
}

/* ── 読み上げ（声は偽物。readAloudMark.test.ts と同じ作り） ── */

/** 面の中の声を偽物に替える（読む文を `__e2eSpoken` へ控える。音は出ない） */
async function installFakeVoice(frame: Frame): Promise<void> {
  await frame.evaluate(() => {
    const spoken: string[] = [];
    (window as unknown as { __e2eSpoken: string[] }).__e2eSpoken = spoken;
    class FakeUtterance {
      text: string;
      lang = "";
      rate = 1;
      voice: unknown = null;
      onend: (() => void) | null = null;
      onerror: ((event: { error: string }) => void) | null = null;
      constructor(text: string) {
        this.text = text;
      }
    }
    const fake = {
      speaking: false,
      paused: false,
      getVoices: () => [{ name: "E2E 日本語", lang: "ja-JP" }],
      speak: (utterance: FakeUtterance) => {
        spoken.push(utterance.text);
      },
      cancel: () => undefined,
      pause: () => undefined,
      resume: () => undefined,
      addEventListener: () => undefined,
    };
    Object.defineProperty(window, "SpeechSynthesisUtterance", { value: FakeUtterance, configurable: true, writable: true });
    Object.defineProperty(window, "speechSynthesis", { value: fake, configurable: true });
  });
}

async function spoken(frame: Frame): Promise<string[]> {
  return frame.evaluate(() => (window as unknown as { __e2eSpoken?: string[] }).__e2eSpoken ?? []);
}

async function aloudDictNote(frame: Frame): Promise<string> {
  return (await frame.locator("#aloudDict").innerText().catch(() => "")).trim();
}

/**
 * 話を原稿エディターで開き、読み上げの列を出して `caretAfter` の文から読ませる。
 * 列の横の辞書の一言と、偽の声が最初に受けた文を返す。
 *
 * 辞書の一言は列を開いたときに拡張機能へ様子を訊いて出る（`aloudDictAsk("status")`）。
 * 辞書が無い話では空のままなので、「出た」を待たずに［読む］の結果で見分ける
 */
async function readAloudFrom(page: Page, fileName: string, marker: string, caretAfter: string): Promise<{ note: string; firstSpoken: string; frame: Frame }> {
  const frame = await openEpisode(page, fileName, marker);
  await installFakeVoice(frame);
  await frame.locator("#aloudToggle").click();
  await waitUntil(async () => !(await frame.locator("#aloudPlay").isDisabled()), "［▶ 読む］が押せる（偽の日本語の声が見つかる）", 15_000).catch(
    async (error: unknown) => {
      throw new Error(`${String(error)}（列の注：${JSON.stringify(await frame.locator("#aloudNote").innerText().catch(() => ""))}）`);
    }
  );
  await placeCaretAfter(frame, caretAfter);
  await frame.locator("#aloudPlay").click();
  await waitUntil(async () => (await spoken(frame)).length > 0, "偽の声が最初の文を受ける", 15_000).catch(async (error: unknown) => {
    throw new Error(
      `${String(error)}（列の注：${JSON.stringify(await frame.locator("#aloudNote").innerText().catch(() => ""))}／辞書の一言：${JSON.stringify(await aloudDictNote(frame))}）`
    );
  });
  return { note: await aloudDictNote(frame), firstSpoken: (await spoken(frame))[0] ?? "", frame };
}

/* ── 1. 右クリック「ファイル名にサブタイトルを付ける」 ── */

test("右クリック「ファイル名にサブタイトルを付ける」で、話数のある話は読みの辞書が、幕間はあらすじと読みの辞書が新しい名前へついてきて、題の読めない話は止まって何も変えない", async () => {
  const header = (title: string) => `【タイトル】\n${title}\n\n【本文】\n　十分に待った。\n`;
  await withVsCode(
    "改名の記録追従（サブタイトル）",
    [
      { name: "001.txt", text: header("湖畔の誓い") },
      { name: "幕間.txt", text: header("星の夜") },
      // 話数も【タイトル】も無い話。題を読むところが無い
      { name: "閑話.txt", text: "　十分に待った。\n" },
    ],
    async (session) => {
      const { page } = session;
      await showWork(page, "第1話");

      /* ── 話数のある話 ── */
      await treeContextMenu(page, "第1話", "ファイル名にサブタイトルを付ける");
      await waitDialog(page, "ファイル名を変えます", "名前を変える確認の窓が出る（001.txt）");
      await pressDialogButton(page, "変える");
      await waitEpisodeFiles(session, ["001_湖畔の誓い.txt", "幕間.txt", "閑話.txt"], "001.txt が 001_湖畔の誓い.txt になる");
      const numbered = await waitNotice(page, "001_湖畔の誓い.txt に変えました", "知らせに「001_湖畔の誓い.txt に変えました」が出る");
      expect(numbered, "話数のある話の知らせ").toContain("読みの辞書1件");
      // 話数のある行は話数で引くので名前では動かさない（動かすと別のフォルダーの同じ名前を巻き込む。6.68.2）
      expect(numbered, "話数のある話のあらすじは名前で付け替えない作り").not.toContain("各話あらすじ");
      await waitRecords(
        session,
        {
          synopses: ["1:001.txt:一話のあらすじ:一話のあらすじのメモ", "null:幕間.txt:幕間のあらすじ:幕間のあらすじのメモ", "null:閑話.txt:閑話のあらすじ:閑話のあらすじのメモ"],
          readings: [
            `${dictionaryName("001_湖畔の誓い.txt")}:本文/001_湖畔の誓い.txt:じっぷん`,
            `${dictionaryName("幕間.txt")}:本文/幕間.txt:じっぷん`,
            `${dictionaryName("閑話.txt")}:本文/閑話.txt:じっぷん`,
          ],
        },
        "読みの辞書が 001_湖畔の誓い.txt へ移り、あらすじの行は話数1のまま"
      );
      await clearNotifications(page);

      /* ── 話数の無い話（【タイトル】から題を読む） ── */
      await waitTreeSettled(page);
      // 幕間.txt と閑話.txt は、どちらも木の行の名前が「幕間」で始まる（種別が同じ）。題で見分ける
      await treeContextMenu(page, { head: "幕間", contains: "星の夜" }, "ファイル名にサブタイトルを付ける");
      await waitDialog(page, "ファイル名を変えます", "名前を変える確認の窓が出る（幕間.txt）");
      await pressDialogButton(page, "変える");
      await waitEpisodeFiles(session, ["001_湖畔の誓い.txt", "幕間_星の夜.txt", "閑話.txt"], "幕間.txt が 幕間_星の夜.txt になる");
      const interlude = await waitNotice(page, "幕間_星の夜.txt に変えました", "知らせに「幕間_星の夜.txt に変えました」が出る");
      expect(interlude, "幕間の知らせ").toContain("各話あらすじ1件");
      expect(interlude, "幕間の知らせ").toContain("読みの辞書1件");
      await waitRecords(
        session,
        {
          synopses: ["1:001.txt:一話のあらすじ:一話のあらすじのメモ", "null:幕間_星の夜.txt:幕間のあらすじ:幕間のあらすじのメモ", "null:閑話.txt:閑話のあらすじ:閑話のあらすじのメモ"],
          readings: [
            `${dictionaryName("001_湖畔の誓い.txt")}:本文/001_湖畔の誓い.txt:じっぷん`,
            `${dictionaryName("幕間_星の夜.txt")}:本文/幕間_星の夜.txt:じっぷん`,
            `${dictionaryName("閑話.txt")}:本文/閑話.txt:じっぷん`,
          ],
        },
        "幕間のあらすじと読みの辞書が 幕間_星の夜.txt を指す（作者のメモはそのまま）"
      );
      await clearNotifications(page);

      /* ── 話数も【タイトル】も無い話 ── */
      await waitTreeSettled(page);
      // 閑話.txt の行も名前は「幕間」で始まり、題が無い（行の名前に「星の夜」を含まないほう）
      await treeContextMenu(page, { head: "幕間", lacks: "星の夜" }, "ファイル名にサブタイトルを付ける");
      const refused = await waitNotice(page, "閑話.txt からサブタイトルを読み取れませんでした", "題の読めない話で「サブタイトルを読み取れませんでした」が出る");
      expect(refused).toContain("閑話.txt");
      await holdsFor(
        async () =>
          (await dialogText(page)) === undefined &&
          JSON.stringify(await episodeFiles(session)) === JSON.stringify(["001_湖畔の誓い.txt", "幕間_星の夜.txt", "閑話.txt"]),
        "題の読めない話は、確認の窓を出さず名前も変えない",
        3_000
      ).catch(async (error: unknown) => {
        throw new Error(`${String(error)}（窓：${(await dialogText(page)) ?? "なし"}／いまの話：${JSON.stringify(await episodeFiles(session))}）`);
      });
      expect(await readingSummary(session), "題の読めない話の読みの辞書は動かない").toContain(`${dictionaryName("閑話.txt")}:本文/閑話.txt:じっぷん`);
      expect(await synopsisSummary(session), "題の読めない話のあらすじは動かない").toContain("null:閑話.txt:閑話のあらすじ:閑話のあらすじのメモ");
    },
    launchWith(
      [synopsisRow("001.txt", 1, "一話のあらすじ"), synopsisRow("幕間.txt", null, "幕間のあらすじ"), synopsisRow("閑話.txt", null, "閑話のあらすじ")],
      [
        { fileName: "001.txt", reading: "じっぷん" },
        { fileName: "幕間.txt", reading: "じっぷん" },
        { fileName: "閑話.txt", reading: "じっぷん" },
      ]
    )
  );
}, 300_000);

/* ── 2. 話の挿入と削除 ── */

test("話の挿入で後ろの話の番号がずれると、各話あらすじと読みの辞書が同じ話についていき、挿入した話を削除して詰めると元の名前へ戻る", async () => {
  await withVsCode(
    "改名の記録追従（挿入と削除）",
    [
      { name: "001.txt", text: "　一話の本文。\n" },
      { name: "002.txt", text: "　二話でも十分に待った。\n" },
      { name: "003.txt", text: "　三話でも十分に待った。\n" },
    ],
    async (session) => {
      const { page } = session;
      await showWork(page, "第1話");

      /* ── 第2話の前に挿入：002→003、003→004 ── */
      await insertBefore(page, "第2話", "割り込み");
      let inserted = "";
      await waitUntil(
        async () => {
          const files = await episodeFiles(session);
          inserted = files.find((name) => name.startsWith("002") && name.includes("割り込み")) ?? "";
          return inserted !== "" && files.includes("003.txt") && files.includes("004.txt") && !files.includes("002.txt");
        },
        "002.txt と 003.txt が 003.txt・004.txt へずれ、割り込みの話ができる",
        20_000
      ).catch(async (error: unknown) => {
        throw new Error(`${String(error)}（いまの話：${JSON.stringify(await episodeFiles(session))}／窓：${(await dialogText(page)) ?? "なし"}／知らせ：${JSON.stringify(await noticeLines(page))}）`);
      });
      const afterInsert = await waitNotice(page, "件の話数を付け替えました", "挿入の知らせが出る");
      expect(afterInsert, "挿入の知らせ").toContain("各話あらすじ2件");
      expect(afterInsert, "挿入の知らせ").toContain("読みの辞書2件");
      await waitRecords(
        session,
        {
          synopses: ["3:003.txt:二話のあらすじ:二話のあらすじのメモ", "4:004.txt:三話のあらすじ:三話のあらすじのメモ"],
          readings: [`${dictionaryName("003.txt")}:本文/003.txt:じっぷん`, `${dictionaryName("004.txt")}:本文/004.txt:じゅうぶん`],
        },
        "挿入のあと、元の第2話・第3話のあらすじと読みの辞書が 003.txt・004.txt を指す（002.txt の辞書は残らない）"
      );
      // 付け替えのあとの知らせ・窓を払う（削除の知らせと取り違えないため）
      if ((await dialogText(page)) !== undefined) await page.keyboard.press("Escape");
      await clearNotifications(page);

      /* ── 挿入した話を削除して詰める：003→002、004→003 ── */
      // 木の行の名前は「第N話」で始まる（ファイル名ではない）。挿入した話は第2話の位置に入る
      const insertedHead = "第2話";
      await waitUntil(async () => (await treeRowLabels(page)).some((label) => label.startsWith(insertedHead)), `作品一覧に「${inserted}」の行が出る`, 20_000);
      await deleteAndRenumber(page, insertedHead, inserted);
      await waitEpisodeFiles(session, ["001.txt", "002.txt", "003.txt"], "割り込みの話が消え、003.txt・004.txt が 002.txt・003.txt へ戻る");
      const afterDelete = await waitNotice(page, "件の話数を付け替えました", "削除の知らせが出る");
      expect(afterDelete, "削除の知らせ").toContain("各話あらすじ2件");
      expect(afterDelete, "削除の知らせ").toContain("読みの辞書2件");
      // 割り込みの話には辞書もあらすじも無いので、「消えた話の…が残っています」は出ない
      expect(afterDelete, "削除の知らせ").not.toContain("残っています");
      await waitRecords(
        session,
        {
          synopses: ["2:002.txt:二話のあらすじ:二話のあらすじのメモ", "3:003.txt:三話のあらすじ:三話のあらすじのメモ"],
          readings: [`${dictionaryName("002.txt")}:本文/002.txt:じっぷん`, `${dictionaryName("003.txt")}:本文/003.txt:じゅうぶん`],
        },
        "削除して詰めたあと、あらすじと読みの辞書が元の 002.txt・003.txt を指す"
      );
    },
    launchWith(
      [synopsisRow("002.txt", 2, "二話のあらすじ"), synopsisRow("003.txt", 3, "三話のあらすじ")],
      [
        { fileName: "002.txt", reading: "じっぷん" },
        { fileName: "003.txt", reading: "じゅうぶん" },
      ]
    )
  );
}, 300_000);

/* ── 3. 削除した話の読みが、詰めた次の話に効かない ── */

test("番号だけの名前の話を削除して詰めると、消えた話の読みの辞書は控えへ退き、同じ名前へ詰まった次の話の読み上げには効かない", async () => {
  /*
    消えた 002.txt と、詰まってきた元の 003.txt が**同じ名前**（002.txt）になる形でないと、控えへ退く道を
    通らない（サブタイトルの違う名前なら、置き場の名前がもとから違う）。元の 003.txt には辞書を置かない——
    置くと付け替えで新しい 002.txt の辞書が上書きされ、消えた話の読みが残っていても見えなくなる
  */
  await withVsCode(
    "改名の記録追従（削除した話の読み）",
    [
      { name: "001.txt", text: "　一話の本文。\n" },
      { name: "002.txt", text: "　二話でも十分に待った。\n" },
      { name: "003.txt", text: "　三話でも十分に待った。\n" },
    ],
    async (session) => {
      const { page } = session;
      await showWork(page, "第1話");

      await deleteAndRenumber(page, "第2話", "002.txt");
      await waitEpisodeFiles(session, ["001.txt", "002.txt"], "002.txt が消え、003.txt が 002.txt へ詰まる");
      const notice = await waitNotice(page, "件の話数を付け替えました", "削除の知らせが出る");
      expect(notice, "削除の知らせ").toContain("消えた話の読みの辞書が1件残っています");

      // ファイル：消えた話の辞書は控えの名前で残り、002.txt の名前の辞書は無い
      await waitRecords(
        session,
        { readings: [`本文__002.txt.removed.json:本文/002.txt:じっぷん`] },
        "消えた話の辞書が「本文__002.txt.removed.json」へ退き、新しい 002.txt の辞書は無い"
      );

      // 画面：新しい 002.txt（元の 003.txt）を読み上げても、消えた話の読み（じっぷん）は当たらない
      const { note, firstSpoken } = await readAloudFrom(page, "002.txt", "三話でも十分に待った", "三話でも十分");
      expect(firstSpoken, `声に渡った文：${JSON.stringify(firstSpoken)}`).toContain("三話でも");
      expect(firstSpoken, `消えた話の読みが詰めた次の話に効いている（声に渡った文：${JSON.stringify(firstSpoken)}）`).not.toContain("じっぷん");
      expect(firstSpoken, `声に渡った文：${JSON.stringify(firstSpoken)}`).toContain("十分");
      expect(note, `列の辞書の一言：${JSON.stringify(note)}`).not.toContain("読みの辞書：");
    },
    launchWith([], [{ fileName: "002.txt", reading: "じっぷん" }])
  );
}, 300_000);

/* ── 4. 新しい名前の面で、読みが実際に当たる ── */

test("挿入で名前がずれた話を原稿エディターで開くと、読み上げの列に「読みの辞書：1件」が出て、声に渡る文が辞書の読みになる", async () => {
  await withVsCode(
    "改名の記録追従（新しい名前の面で読み）",
    [
      { name: "001.txt", text: "　一話の本文。\n" },
      { name: "002.txt", text: "　朝の駅は静かだった。\n　二話でも十分に待った。\n" },
    ],
    async (session) => {
      const { page } = session;
      await showWork(page, "第1話");

      await insertBefore(page, "第2話", "割り込み");
      await waitUntil(
        async () => {
          const files = await episodeFiles(session);
          return files.includes("003.txt") && !files.includes("002.txt");
        },
        "002.txt が 003.txt へずれる",
        20_000
      ).catch(async (error: unknown) => {
        throw new Error(`${String(error)}（いまの話：${JSON.stringify(await episodeFiles(session))}／窓：${(await dialogText(page)) ?? "なし"}）`);
      });

      // ファイル：辞書が新しい名前（003.txt）へ移っている
      await waitRecords(
        session,
        { readings: [`${dictionaryName("003.txt")}:本文/003.txt:じっぷん`] },
        "読みの辞書が 003.txt へ移る"
      );
      /*
        **製品が挿入した話を開き終えるまで待ってから、003.txt を開く。** 製品は「名前の変更だけを
        独立したコミットにしますか？」（答えるまで他を触れない窓）に答えたあとで、挿入した話
        （002_割り込み.txt）を開く（extension.ts の novelai.insertEpisode）。窓を閉じてすぐ 003.txt を
        開くと、あとから開いた挿入の話が前に出て、003.txt の面が後ろへ回る（2026-11-07 ノートPC）。
        作者は窓に答えるまで別の話を開けないので、作者の画面では起きない順番である。
        窓は置き場の様子を読んでから出るので、待っている間に出てきたらそのつど閉じる
      */
      await waitUntil(
        async () => {
          if ((await dialogText(page)) !== undefined) await page.keyboard.press("Escape");
          return tabNamesInclude((await editorGroupTabs(page)).flat(), "002_割り込み.txt");
        },
        "挿入した話（002_割り込み.txt）のタブが開く",
        20_000
      ).catch(async (error: unknown) => {
        throw new Error(`${String(error)}（タブ：${JSON.stringify(await editorGroupTabs(page))}／窓：${(await dialogText(page)) ?? "なし"}）`);
      });
      await clearNotifications(page);

      // 画面：新しい名前の面で、辞書が引け、読みが声に渡る（本文の字は「十分」のまま）
      const { firstSpoken, frame } = await readAloudFrom(page, "003.txt", "二話でも十分に待った", "二話でも十分");
      // 辞書の一言は拡張機能からの答えで出る（列を開いた時の問い合わせ）。届くまで待つ
      let note = "";
      await waitUntil(async () => (note = await aloudDictNote(frame)).includes("読みの辞書："), "読み上げの列に「読みの辞書：N件」が出る", 15_000).catch(
        async (error: unknown) => {
          throw new Error(`${String(error)}（列の辞書の一言：${JSON.stringify(note)}／声に渡った文：${JSON.stringify(firstSpoken)}）`);
        }
      );
      expect(note, `列の辞書の一言：${JSON.stringify(note)}`).toContain("読みの辞書：1件");
      // 句（十分に）が本文に見つからなければ「本文に見当たらない」が添えられる
      expect(note, `列の辞書の一言：${JSON.stringify(note)}`).not.toContain("見当たらない");
      expect(firstSpoken, `声に渡った文：${JSON.stringify(firstSpoken)}`).toContain("じっぷん");
      expect(firstSpoken, `声に渡った文：${JSON.stringify(firstSpoken)}`).not.toContain("十分");
    },
    launchWith([], [{ fileName: "002.txt", reading: "じっぷん" }])
  );
}, 300_000);
