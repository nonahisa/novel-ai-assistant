/**
 * 別名を別の人物に分ける前に、その呼び名が元の人物への呼びかけにしか出ないなら、確認の窓の頭で知らせる
 * （画面の自動テスト、設計書6.5.8・6.113。0.130.2。作者の裁定 2026-11-06 夕「③も足す（分ける前に断る）」）。
 *
 * 見張ること（実機確認リスト F-13 の 2026-11-06 の裁定の行「窓の頭にこの1段が出るか」を機械へ移したもの）：
 * - 本文で台詞の呼びかけ（「お嬢様、お茶が入りました」）にしか出ない「お嬢様」を分けようとすると、
 *   確認の窓の見出し「「お嬢様」を、別の人物として分けますか？」のすぐ下、何が起きるかの箇条書きより前に
 *   「この呼び名は「密倉文佳」への呼びかけに見えます（本文の「お嬢様」1か所が…）」が出る
 * - 本当に別の人物として地の文に出る「庭師」（前後1行に元の人物の名前も別名も無い）を分けようとしても、
 *   この知らせは出ない。どちらも本文に1度は出る（0回だと「見るものが無い」で出ないだけで、見分けにならない）
 * - どちらも分けずに閉じる（Esc）。人物のファイルは変わらない
 *
 * 目安そのもの（呼びかけの形・前後1行）は単体テスト `core/separateAliasUsage.test.ts` が見ている。
 * ここで見るのは**本物の設定資料パネルから押したとき、窓にその文が出るか**。**AI は呼ばない。**
 */
import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import type { Frame, Page } from "playwright-core";
import { expect, test } from "vitest";
import { emptyCharacter, type Character } from "../../src/models/character";
import { defaultCharactersFolder, settingsListRows, settingsPanelFrame, writeCharactersTo } from "./support/settingsFixture";
import { withVsCode, type E2ESession, type LaunchOptions } from "./support/vscodeApp";
import { waitUntil } from "./support/wait";
import { closeDialog, dialogText, pressWorkbenchKey } from "./support/workbenchDom";

const OPEN_SETTINGS_KEY = "ctrl+alt+shift+f1";
const OPEN_SETTINGS_PRESS = "Control+Alt+Shift+F1";

const ORIGINAL = "密倉文佳";
const EPISODE = {
  name: "001_お屋敷.txt",
  text: [
    "密倉文佳は窓の外を見た。",
    // 「お嬢様」は台詞の中の呼びかけ（すぐ後が「、」）。前後の行にも元の人物の名前がある
    "「お嬢様、お茶が入りました」",
    "密倉文佳は頷いた。",
    "",
    "",
    // 「庭師」は地の文で、前後1行に「密倉文佳」も「お嬢様」も無い（本当に別の人物として出る）
    "庭師は裏の畑で鍬を振るっていた。",
    "夕暮れまで、誰も来なかった。",
    "",
  ].join("\n"),
};

const launchOptions: LaunchOptions = {
  keybindings: [{ key: OPEN_SETTINGS_KEY, command: "novelai.openSettingsPanel" }],
  // 人物は起こす前に置く（起きてから書くと「外で変更されました」の知らせが出ることがある）
  prepareWork: async ({ workFolder }) => {
    await writeCharactersTo(defaultCharactersFolder(workFolder), [
      { ...emptyCharacter("char_001", ORIGINAL), aliases: ["お嬢様", "庭師"], autoGenerated: false },
    ]);
  },
};

/** 人物のファイルの中身（名前ごとの別名） */
async function aliasesOnDisk(session: E2ESession): Promise<Record<string, string[]>> {
  const folder = defaultCharactersFolder(session.workFolder);
  const result: Record<string, string[]> = {};
  for (const file of (await readdir(folder).catch(() => [])).filter((name) => name.endsWith(".json"))) {
    const raw = await readFile(path.join(folder, file), "utf8").catch(() => "");
    if (!raw) continue;
    const character = JSON.parse(raw) as Character;
    result[character.name] = character.aliases;
  }
  return result;
}

/** 設定資料パネルを開き、元の人物を選んで、詳細に「別人にする呼び名」の札が並ぶまで */
async function openOriginal(page: Page, session: E2ESession): Promise<Frame> {
  await pressWorkbenchKey(page, OPEN_SETTINGS_PRESS);
  let panel: Frame | undefined;
  await waitUntil(async () => (panel = await settingsPanelFrame(session)) !== undefined, "設定資料パネルが開く", 30_000);
  if (!panel) throw new Error("設定資料パネルの面が見つかりません");
  const frame = panel;
  await waitUntil(async () => (await settingsListRows(frame)).some((row) => row.includes(ORIGINAL)), `一覧に「${ORIGINAL}」が並ぶ`, 15_000);
  await frame.locator("#list .item", { hasText: ORIGINAL }).first().click();
  const chips = separateChips(frame);
  await waitUntil(async () => (await chips.count()) >= 2, "詳細に「別人にする呼び名」の札が2つ並ぶ", 15_000).catch(async (error: unknown) => {
    const detail = await frame.evaluate(() => document.getElementById("detail")?.innerText ?? "").catch(() => "");
    throw new Error(`${String(error)}（詳細の字：${JSON.stringify(detail.slice(0, 600))}）`);
  });
  return frame;
}

function separateChips(frame: Frame) {
  return frame.locator("#detail .chips", { hasText: "別人にする呼び名" }).locator(".chip");
}

/** 「別人にする呼び名」の `alias` の札を押し、分けるかの確認の窓の字を返す */
async function askToSeparate(page: Page, frame: Frame, alias: string): Promise<string> {
  await separateChips(frame).filter({ hasText: alias }).first().click();
  let text = "";
  await waitUntil(async () => (text = (await dialogText(page)) ?? "").includes("別の人物として分けますか"), `「${alias}」を分けるかの確認の窓が出る`, 15_000).catch(
    (error: unknown) => {
      throw new Error(`${String(error)}（いまの窓：${JSON.stringify(text)}）`);
    }
  );
  return text;
}

test("呼びかけにしか出ない別名「お嬢様」を分けようとすると確認の窓の頭に「この呼び名は「密倉文佳」への呼びかけに見えます」が出て、地の文で別の人物として出る「庭師」では出ない", async () => {
  await withVsCode(
    "分ける前の呼びかけの知らせ",
    [EPISODE],
    async (session) => {
      const { page } = session;
      const before = await aliasesOnDisk(session);
      expect(before[ORIGINAL]).toEqual(["お嬢様", "庭師"]);
      const frame = await openOriginal(page, session);

      /* ── 呼びかけだけの「お嬢様」：知らせが出る ── */
      const addressed = await askToSeparate(page, frame, "お嬢様");
      const heading = addressed.indexOf("「お嬢様」を、別の人物として分けますか？");
      const notice = addressed.indexOf(`この呼び名は「${ORIGINAL}」への呼びかけに見えます`);
      const firstBullet = addressed.indexOf("・「お嬢様」という名前だけの人物ができます");
      expect(heading, `窓の字：${addressed}`).toBeGreaterThanOrEqual(0);
      expect(notice, `呼びかけの知らせが窓にありません。窓の字：${addressed}`).toBeGreaterThan(heading);
      expect(firstBullet, `窓の字：${addressed}`).toBeGreaterThan(notice);
      // 見出しと知らせの間に、ほかの段が挟まっていない（説明の頭に出ている）
      expect(addressed.slice(heading + "「お嬢様」を、別の人物として分けますか？".length, notice).trim(), `窓の字：${addressed}`).toBe("");
      expect(addressed).toContain(`本文の「お嬢様」1か所が、どれも「${ORIGINAL}」に呼びかけているか、「${ORIGINAL}」と同じ所に出ています`);
      expect(addressed).toContain("別の人物なら、このまま分けてください。");
      // 止めはしない：分けるボタンはそのまま並ぶ
      const buttons = (await page.locator(".monaco-dialog-box .monaco-button").allInnerTexts()).map((label) => label.trim());
      expect(buttons, `窓のボタン：${JSON.stringify(buttons)}`).toEqual(expect.arrayContaining(["分ける", "分ける（この記録はAIに書き換えさせない）"]));
      await closeDialog(page);

      /* ── 地の文で別の人物として出る「庭師」：知らせは出ない ── */
      const separate = await askToSeparate(page, frame, "庭師");
      expect(separate, `窓の字：${separate}`).toContain("「庭師」を、別の人物として分けますか？");
      expect(separate, `窓の字：${separate}`).toContain("・「庭師」という名前だけの人物ができます");
      expect(separate, `「庭師」で呼びかけの知らせが出ました。窓の字：${separate}`).not.toContain("呼びかけに見えます");
      await closeDialog(page);

      // どちらも分けていない：人物のファイルは変わらない
      expect(await aliasesOnDisk(session)).toEqual(before);
    },
    launchOptions
  );
}, 180_000);
