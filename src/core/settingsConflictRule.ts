import { DEFAULT_SETTINGS_DIR } from "../models/types";

/**
 * 設定資料のJSONが両方で書き換えられたとき、どちらを残すかを決める（設計書5.5.18）。
 *
 * 作者の指示（2026-09-10）：「設定資料ファイルは作者が書き換えた部分が
 * 変わっていなければ、時系列的に新しいほうに自動で合わせてください」。
 *
 * ## なぜ機械が決めてよいのか
 *
 * 5.5.4は「どちらが正しいかを機械が決めない」としていた。**安全側だが、
 * 行き止まりだった**——作者本人が「技術者しか解決できない難易度」と判断した。
 *
 * 決めてよい根拠は、**設定資料の大半がAIの抽出結果である**ことにある。
 * 抽出は同じ本文から何度でもやり直せるので、片側を残しても失われるのは
 * 「もう一度抽出すれば戻るもの」だけである。**失われては困るのは作者が
 * 手で書いた部分**（`authorNotes`・`exportNote`・呼称の固定など）なので、
 * **そこが両側で同じなら、新しいほうへ揃えてよい。**
 *
 * ## 決めないもの
 *
 * 作者が書いた部分が両側で違うときは決めない。ここを緩めると、作者が手で
 * 書いた値をもう一方の端末の読みが押し流す（CLAUDE.md「作者が書いたデータを
 * 上書きしない」）。**決めなかったものは、作者に1件ずつ選んでもらう。**
 *
 * ここは純粋関数だけを置く（vscodeにもgitにもファイルにも触らない）。
 * 版を取り出すのは `features/resolveDivergence.ts` の役目である。
 */

/**
 * 保存のたびに必ず変わる項目と、追記しかされない項目。
 *
 * **「作者が書いた部分」から外す。** 外さないと、`autoGenerated: false` の
 * レコードは保存時刻が違うだけで「作者が両方で書き換えた」ことになり、
 * すべてが作者への問いになる。登場話数（`appearedChapters`）は抽出が
 * 追記するだけの配列で、`autoGenerated: false` のレコードでもAIが触ってよい
 * 唯一の項目である（CLAUDE.md）。
 */
const VOLATILE_KEYS = ["updatedAt", "appearedChapters"] as const;

/** 種別を問わず、作者が手で書く項目（models/character.ts ほか全種別が持つ） */
const AUTHOR_KEYS = ["authorNotes", "exportNote", "autoGenerated"] as const;

/** 人物だけが持つ、作者の判断の記録（設計書6.5.8・6.18） */
const CHARACTER_AUTHOR_KEYS = ["distinctFrom", "changes"] as const;

export type SettingsConflictDecision =
  | { side: "ours" | "theirs"; reason: string }
  | { side: "conflict"; reason: string };

/**
 * 設定資料のJSONか（gitが返すリポジトリ相対パス）。
 *
 * **`設定/` の下にある `.json` だけを見る。** 置き場の名前は作品ごとに
 * 変えられるが（`settingsDir`）、gitのパスからは作品の設定を引けない。
 * 既定の名前に当たらないものは規則の対象にせず、作者へ回す——
 * **決められないものを決めたことにしないほうが安全である。**
 */
export function isSettingsJsonPath(filePath: string): boolean {
  // Windowsの区切り（\）を / に揃える。符号で書くのは、正規表現の中の
  // 円記号が読みにくいためである
  const normalized = filePath.replace(/[\u005C]/g, "/");
  if (!normalized.toLowerCase().endsWith(".json")) return false;

  const segments = normalized.split("/");
  // 拡張機能の作業場所は設定資料ではない（`externalChanges.ts` と同じ線引き）
  if (segments.includes(".aiwriter")) return false;
  if (segments.includes(".novelai-recovery")) return false;
  // AI向けのスキーマは生成物。書き換えても次の生成で消える
  if (segments.includes("_schema")) return false;

  return segments.includes(DEFAULT_SETTINGS_DIR);
}

/**
 * どちらを残すか決める。
 *
 * @param input `base` は共通の祖先（`git show :1:path`）。無いこともある
 *   （両方で新しく作られたレコードなど）。あるときだけ規則2が効く
 */
export function decideSettingsConflict(input: {
  base?: string;
  ours: string;
  theirs: string;
}): SettingsConflictDecision {
  const ours = parseRecord(input.ours);
  const theirs = parseRecord(input.theirs);
  if (!ours || !theirs) {
    // **壊れたJSONを勝手に直さない**（CLAUDE.md）。読めないものは作者へ回す
    return {
      side: "conflict",
      reason: "JSONとして読めないため、どちらを残すか決められません",
    };
  }

  const oursAuthor = authorParts(ours);
  const theirsAuthor = authorParts(theirs);

  // 規則1：作者が書いた部分が同じなら、時系列で新しいほうへ揃える
  if (sameValue(oursAuthor, theirsAuthor)) {
    return byUpdatedAt(ours, theirs);
  }

  // 規則2：共通の祖先から動いたのが片側だけなら、動いたほうを残す。
  // **もう一方は「触っていない」ので、捨てても作者の手は失われない**
  const base = input.base === undefined ? undefined : parseRecord(input.base);
  if (base) {
    const baseAuthor = authorParts(base);
    const oursMoved = !sameValue(baseAuthor, oursAuthor);
    const theirsMoved = !sameValue(baseAuthor, theirsAuthor);
    if (oursMoved && !theirsMoved) {
      return {
        side: "ours",
        reason: "作者が書いた部分を変えたのは、この端末の側だけです",
      };
    }
    if (theirsMoved && !oursMoved) {
      return {
        side: "theirs",
        reason: "作者が書いた部分を変えたのは、別の環境の側だけです",
      };
    }
  }

  // 規則3：両方で作者の手が入っている。**機械は決めない**
  return {
    side: "conflict",
    reason: "作者が書いた部分が両方で違います",
  };
}

/** 更新時刻の新しいほう。取れないときは、この端末の側を残す */
function byUpdatedAt(
  ours: Record<string, unknown>,
  theirs: Record<string, unknown>
): SettingsConflictDecision {
  const oursAt = timeOf(ours.updatedAt);
  const theirsAt = timeOf(theirs.updatedAt);

  if (oursAt !== undefined && theirsAt !== undefined && oursAt !== theirsAt) {
    return oursAt > theirsAt
      ? {
          side: "ours",
          reason: "作者が書いた部分は同じで、この端末の側が新しいためです",
        }
      : {
          side: "theirs",
          reason: "作者が書いた部分は同じで、別の環境の側が新しいためです",
        };
  }

  // 時刻が無い・同じなら順序を決められない。**中身はどちらもAIの抽出結果**
  // なので、取り込んだ側で上書きするより、いま画面に出ているものを残す
  return {
    side: "ours",
    reason:
      "作者が書いた部分は同じで、更新時刻では新しいほうを決められないため、" +
      "この端末の側を残しました",
  };
}

/**
 * 「作者が書いた部分」を取り出す。
 *
 * ここが**この規則のすべて**である。広く取りすぎるとAIの抽出結果の違いまで
 * 作者への問いになり（前の設計がそうだった）、狭く取りすぎると作者の手が
 * 消える。**AIが触らないと約束している範囲**を、そのまま境界にする。
 */
function authorParts(record: Record<string, unknown>): unknown {
  // 作者が確定させたレコードは、登場話数の追記以外AIが触らない（CLAUDE.md）。
  // つまり**それ以外の違いは、すべて作者の手による**
  if (record.autoGenerated === false) return withoutVolatile(record);
  // 伏線は出どころを持つ。作者が入れたものは全体が作者のもの（設計書6.35.1）
  if (record.source === "author") return withoutVolatile(record);

  // 1件1ファイルのレコードでないもの（`custom_fields.json`・`keep_words.json`・
  // `ability_system.json` のような台帳）は、**作者が直に書く場所**である。
  // 形を決め打ちできないので、更新時刻を除いた全体を作者のものとみなす
  if (typeof record.id !== "string") return withoutVolatile(record);

  const parts: Record<string, unknown> = {};
  for (const key of AUTHOR_KEYS) parts[key] = record[key] ?? null;
  for (const key of CHARACTER_AUTHOR_KEYS) parts[key] = record[key] ?? null;
  // 作者が固定した呼称は変えない（CLAUDE.md）。固定していないものは
  // 抽出のたびに増えるので、ここでは見ない
  parts.lockedAddressTerms = lockedAddressTerms(record.addressTerms);
  return parts;
}

/** 保存のたびに変わる項目・追記されるだけの項目を落とす */
function withoutVolatile(record: Record<string, unknown>): unknown {
  const rest: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(record)) {
    if ((VOLATILE_KEYS as readonly string[]).includes(key)) continue;
    rest[key] = value;
  }
  return rest;
}

/** `authorLocked: true` の呼称だけを、順序に依存しない形で取り出す */
function lockedAddressTerms(value: unknown): unknown {
  if (!Array.isArray(value)) return null;
  const locked = value.filter(
    (entry): entry is Record<string, unknown> =>
      typeof entry === "object" &&
      entry !== null &&
      (entry as Record<string, unknown>).authorLocked === true
  );
  // 並び順は抽出のたびに変わりうる。**順序の違いを作者の手と読まない**
  return locked.map((entry) => stableText(entry)).sort();
}

function parseRecord(text: string): Record<string, unknown> | undefined {
  try {
    const value: unknown = JSON.parse(text);
    if (typeof value !== "object" || value === null || Array.isArray(value)) {
      return undefined;
    }
    return value as Record<string, unknown>;
  } catch {
    return undefined;
  }
}

/** 更新時刻を比べられる数にする。読めなければ undefined */
function timeOf(value: unknown): number | undefined {
  if (typeof value !== "string" || value.trim() === "") return undefined;
  const at = Date.parse(value);
  return Number.isNaN(at) ? undefined : at;
}

/** 中身が同じか。**項目の並び順の違いを、値の違いと読まない** */
function sameValue(left: unknown, right: unknown): boolean {
  return stableText(left) === stableText(right);
}

/** 項目名で並べ直したJSON。比較のためだけに使う */
function stableText(value: unknown): string {
  return JSON.stringify(value, (_key, inner: unknown) => {
    if (
      typeof inner !== "object" ||
      inner === null ||
      Array.isArray(inner)
    ) {
      return inner;
    }
    const sorted: Record<string, unknown> = {};
    for (const key of Object.keys(inner as Record<string, unknown>).sort()) {
      sorted[key] = (inner as Record<string, unknown>)[key];
    }
    return sorted;
  });
}
