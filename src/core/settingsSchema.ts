import { SUMMARY_MAX_CHARS } from "./summaryLimit";

/**
 * 設定資料の構造を、他のツールやAIが読める形で書き出す。
 *
 * 作者は別のプラグインのAI（Copilot・Claude Code など）に
 * 設定資料の更新を頼むことがある。相手は `設定/` のJSONを直接読み書きできるが、
 * **構造を知らなければ推測で書き、こちらの検証で弾かれる。**
 *
 * そこで機械可読なJSON Schemaと、日本語の注意書きを置く。
 * 注意書きのほうが重要で、「作者メモは書き換えない」のような約束は
 * スキーマでは表せない。
 *
 * **型定義とずれないよう、テストで突き合わせている**
 * （`test/unit/settingsSchema.test.ts`）。モデルに項目を足して
 * ここを忘れると、テストが項目名を名指しで落とす。
 * 抽出側で同じ取りこぼしを2度やっているので、同じ形で守る。
 */

export const SCHEMA_DIR = "_schema";

export interface GeneratedSchemaFile {
  fileName: string;
  content: string;
}

/** 全レコードに共通する項目。1件ずつ書くと必ずどれかを書き忘れる */
