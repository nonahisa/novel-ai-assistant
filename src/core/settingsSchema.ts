function schemaOf(
  title: string,
  idPattern: string,
  extra: Record<string, unknown>
): Record<string, unknown> {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title,
    type: "object",
    properties: { ...commonProperties(idPattern), ...extra },
    required: ["id", "name"],
    // 知らない項目は書かせない。書いても読み込み時に落ちるだけで、
    // 書いた側は成功したと思い込む
    additionalProperties: false,
  };
}

