export function abilitySchema(): Record<string, unknown> {
  return schemaOf("能力", "^abil_\\d+$", {
    category: { type: ["string", "null"], description: "作品側の分類語" },
    description: { type: ["string", "null"] },
    cost: { type: ["string", "null"], description: "発動に必要な代償" },
    limitation: { type: ["string", "null"], description: "使えない条件" },
    userNames: {
      type: "array",
      items: { type: "string" },
      description: "使い手の人物名",
    },
    userIds: {
      type: "array",
      items: { type: "string", pattern: "^char_\\d+$" },
      description: "使い手の人物ID。名前から解決されるので手で書かなくてよい",
    },
  });
}

