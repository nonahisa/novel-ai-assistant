import { abbreviateTitle } from "./abbreviateTitle";

/**
 * 作品一覧の1行の名前（label）を組む。**印を題の前に置く**
 * （精査 R14、作者の裁定 2026-09-26。設計書6.1.2）。
 *
 * ## なぜ前なのか
 *
 * VS Code の木の行は「名前 → 説明（description）」の順に1行へ並び、
 * 幅が足りないと**後ろから切れる**。印（同期の「記録待ち1」、競合、
 * 読み込めない）を説明の後ろへ添えていたので、長い題では印が行の外へ
 * 押し出されて読めなかった（実機確認 F-11、2026-09-21：題を20字で
 * 省略しても、サイドバーの既定幅では「17ファイル / …」で止まる）。
 *
 * 印は「いま手当てが要る」ことを知らせるもので、字数より先に目に入る
 * べきものである。**名前の頭に置けば、題がどれだけ長くても必ず見える。**
 * アイコンで表す案もあったが、アイコンは1つしか置けず（競合と同期が重なると
 * 片方が消える）、数も言葉も載らない——矢印を言葉と数字に変えた理由
 * （`gitSyncStatusText.ts`）がそのまま当てはまる。
 *
 * ## 形
 *
 * `［⚠競合1件・記録待ち2］題名…`。印どうしは全角の中黒でつなぐ（同期の印の
 * 中の区切りと同じ）。**題と分けるのに［］を使う**——作品名の頭には
 * 【書籍化】のような隅付き括弧がよく付くので、それと取り違えない括弧にした。
 *
 * **題の省略（20字）は変えない。** 印が長くても題の上限は同じで、行が
 * 切れるときは題の後ろ側が切れる（全文と印の意味はホバーで読む）。
 */
export function workRowLabel(
  title: string,
  marks: readonly (string | undefined)[]
): string {
  const shown = marks.filter(
    (mark): mark is string => typeof mark === "string" && mark.length > 0
  );
  const name = abbreviateTitle(title);
  return shown.length > 0 ? `［${shown.join("・")}］${name}` : name;
}
