/**
 * 縦書きで立てる半角数字の run を決める規則（原稿エディタの「組んで書く」面）。
 *
 * 縦書きは `text-orientation: mixed` で組んでいるので、半角の英数字は
 * **まとまりごと横に寝る**。「3月5日」の 3 や 5 が寝ると、日本語の行の中に
 * 横向きの字が点々と混ざって読みにくい。1〜2文字なら `text-combine-upright`
 * で1文字ぶんの幅へ立てられる（作者の依頼、2026-09-12
 * 「半角数字1、2文字は縦書き時縦中横にしてほしい。3文字以降は現行通り」）。
 *
 * **EPUB（`epubXhtml.ts` の `applyTateChuYoko`）も同じ規則である**（0.74.8〜、
 * 作者の裁定「EPUB も揃える」）。2026-09-21 までは「あちらは !? も立て、型番も
 * 外さない」と別の決まりだったが、いまは EPUB がこの `TCY_RUN_PATTERN` をそのまま使う。
 *
 * VS Code APIに依存しない。**規則の定義はこのファイルだけに置く**——
 * 画面（webview）側へは `TCY_RUN_PATTERN` の文字列がそのまま埋め込まれる
 * （`manuscriptEditorHtml.ts`）。写しを置くと、片方だけが直る日が必ず来る。
 */

/**
 * 立てる run の見つけ方。
 *
 * - `[0-9A-Za-z!?]{1,2}` … 半角の英数字と「!」「?」が1〜2文字。**3文字以上は立てない**（1文字ぶんの
 *   幅に収まらず、かえって読みにくい）。前後を数字で挟まれた run は
 *   前後の言明で落ちるので、「123」からは1件も出ない
 * - `(?<![!-~｡-ﾟ])` / `(?![!-~｡-ﾟ])` … **直前・直後が半角文字なら立てない。**
 *   `!-~` は ASCII の表示文字すべて（英数字・記号）、`｡-ﾟ` は半角カナ。
 *   **半角の空白だけは含めない**——`3 月` のような区切りは「半角文字の
 *   文字列の中」ではないため
 *
 * **なぜ半角文字全般なのか**（作者の指定、2026-09-15
 * 「半角数字が半角文字の文字列中に含まれている場合は、縦中横を発動しないでください」）。
 * 2026-09-12 の時点では英字だけを見ていた（`F5`・`A-13`・`B_7` の型番対策）。
 * だが半角の並びは型番だけではない——`12:30`（時刻）・`1/2`（分数）・
 * `3.14`（小数）・`(5)`・`#1`・`No.1` のように、**記号で繋がった半角の
 * まとまりの中にある数字も、そこだけ立つと読めなくなる。**
 * 立てるのは「日本語の行に、ぽつんと混ざった半角数字」だけでよい。
 *
 * **英字も立てる**（作者の裁定、2026-09-21「半角2文字は縦中横と言ったつもりでした」）。
 * 実機で `R4` が寝て `11` だけ立つのを見た作者が「英数字の並び1〜2文字（R4・OK・F5）も
 * 立てる。記号で繋がるもの（A-13）は寝たまま」と決めた。前後の言明はそのままなので、
 * `A-13`・`No.1`・`v2.0`・`abc`（3文字）は今までどおり寝る。
 * **「!」「?」も立てる**（作者の報告、2026-09-21「半角⁉も縦中横になっていません」）。これで
 * EPUB（`epubXhtml.ts` の `applyTateChuYoko`）と**同じ規則**になったので、EPUB はこの文字列をそのまま使う。
 *
 * 後読み（`(?<=`）は VS Code の webview（Chromium）でも Node でも使える。
 */
export const TCY_RUN_PATTERN =
  "(?<![!-~\\uFF61-\\uFF9F])[0-9A-Za-z!?]{1,2}(?![!-~\\uFF61-\\uFF9F])";

/** 立てる run の位置（`start` 以上 `end` 未満） */
export interface TcyRun {
  start: number;
  end: number;
}

/**
 * 1行（あるいは任意の文字列）から、縦中横にする run の位置を拾う。
 *
 * **ルビ記法の中も、ほかの平文と同じに扱う**（`{漢字|かんじ}` の読みの側を
 * 特別扱いしない）。表記ゆれ検知の既存の規則（`notationVariants.ts` の
 * `findOccurrences`）も記法を剥がさずに数えており、そちらに揃えてある。
 * 組んで書く面では、ルビ・傍点は部品として先に切り分けられてから
 * この関数へ来るので、記法の記号そのものが run に混ざることもない。
 */
export function tcyRuns(text: string): TcyRun[] {
  const runs: TcyRun[] = [];
  if (!text) return runs;

  const pattern = new RegExp(TCY_RUN_PATTERN, "g");
  for (;;) {
    const match = pattern.exec(text);
    if (match === null) break;
    runs.push({ start: match.index, end: match.index + match[0].length });
  }
  return runs;
}
