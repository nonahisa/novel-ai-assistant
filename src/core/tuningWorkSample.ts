/**
 * AIチューニングの「仕事に近い形の測定」に使う、**製品に同梱する短い文**
 * （設計書6.49.9。作者の判断、2026-09-26）。
 *
 * ## なぜ要るか
 *
 * 待ち時間は、合言葉を書き写させた時間の3倍で決めていた（6.49.3）。
 * 合言葉の答えは数トークンしかなく、**実際の機能は答えが長い。** しかも
 * 答えの長さに対する時間の伸び方はモデルによって違う（GPU と CPU に
 * 分けて載る 26b は、書き出しが極端に遅い）。3倍では当たらない。
 *
 * そこで、**誤字脱字検知と同じプロンプト・同じ形式の強制**で、この文を
 * 読ませて答えを書かせる。答えの長さが実際の機能と同じ種類になるので、
 * 測った時間がそのまま「この機械でこのモデルを使うと、1000字あたり
 * 何秒かかるか」の見込みになる。
 *
 * ## 作者の作品は使わない
 *
 * 測定のために原稿を外（クラウドのAI）へ送らない。作品が無くても
 * 測れるようにする（読める長さの測定と同じ約束）。**文はこの製品のために
 * 書いた創作で、誤りをわざと混ぜてある**——誤りが無い文では指摘の一覧が
 * 空になり、答えの短い測定に戻ってしまう。
 *
 * **ここに置いた誤りの答え合わせはしない。** 精度を測る段は別に足す
 * （そのときにこの一覧を使えるよう、置いた誤りは下に書き出してある）。
 *
 * VS Code API に依存しない。
 */

