/**
 * プロットの「主要登場人物」に書かれた呼び名が、**名前か、役名か**を見分ける
 * （設計書6.4.8「名前の候補を出す」。作者の依頼、2026-09-25）。
 *
 * 構想の段階では、人物を「主人公：〜」「ヒロイン：〜」「班長：〜」のように
 * **役割の言葉だけ**で書き並べることが多い。名前を付ける段になったとき、
 * どの行がまだ名前の無い人物かを拾うのがここの仕事である。
 *
 * ## AIを使わない
 *
 * 役名かどうかは、言葉の一覧と語尾の形だけで見分ける。**迷うものは
 * 「迷う」として返し、対象に含めて作者に外させる**（依頼の決まり）。
 * 取りこぼして黙るより、1つ余計に出して外してもらうほうが作者の手は止まらない。
 *
 * ## 名前を足した形「役名（名前）」
 *
 * 名前を選んだあと、plot.md の行は「主人公（相馬 誠）：〜」の形になる
 * （`plotNameTargets.ts`。なぜこの形かは設計書6.4.8）。**外側が役名のときだけ、
 * 括弧の中を名前として読む**（`splitRoleAnnotation`）。「灯（あかり）」のように
 * 外側が名前なら、括弧の中は読みか注記であって、ここでは割らない。
 *
 * VS Code API に依存しない（単体テストの対象）。
 */

/** 役名の見立て。role＝役割の言葉と言い切れる、unsure＝名前かもしれない */
export type RoleNameKind = "role" | "unsure";

export interface RoleNameVerdict {
  kind: RoleNameKind;
  /** なぜそう見たか。作者へそのまま見せる */
  reason: string;
}

/**
 * 役割・立場・続柄・種族など、**それだけでは固有名にならない言葉**。
 *
 * 全部を並べることはできないので、語尾の形（下の `ROLE_SUFFIX`）と
 * 組み合わせて拾う。**ここに無い言葉は取りこぼしうる**——そのときは
 * 作者が行を「役名（名前）」の形に手で直せば済む。
 */
const ROLE_WORDS: ReadonlySet<string> = new Set([
  // 物語の中の立ち位置
  "主人公", "語り手", "ヒロイン", "ヒーロー", "相棒", "相方", "ライバル",
  "敵", "味方", "黒幕", "悪役", "ボス", "ラスボス", "モブ", "脇役", "仲間",
  // 間柄
  "友人", "親友", "幼馴染", "幼なじみ", "恋人", "婚約者", "師匠", "弟子",
  "先輩", "後輩", "同僚", "上司", "部下", "新人", "新入り", "新米",
  "父", "母", "父親", "母親", "兄", "姉", "弟", "妹", "祖父", "祖母",
  "息子", "娘", "夫", "妻", "叔父", "叔母", "伯父", "伯母", "従兄", "従姉",
  // 年頃・人の呼び方
  "少年", "少女", "青年", "老人", "老婆", "老爺", "子供", "子ども", "幼女",
  "男", "女", "男性", "女性", "彼", "彼女",
  // 役職
  "社長", "部長", "課長", "係長", "班長", "店長", "隊長", "団長", "村長",
  "町長", "市長", "校長", "会長", "委員長", "艦長", "船長", "所長", "局長",
  "組長", "親方", "棟梁", "監督", "司令", "上官", "主任",
  // 職業・身分
  "先生", "教師", "担任", "生徒", "学生", "医者", "医師", "看護師", "刑事",
  "警官", "探偵", "助手", "犯人", "店主", "主人", "執事", "メイド", "侍女",
  "受付嬢", "商人", "職人", "騎士", "兵士", "傭兵", "魔女", "魔法使い",
  "王", "王様", "女王", "王子", "王女", "姫", "姫様", "皇帝", "聖女", "巫女",
  "神", "女神", "マスター", "ギルドマスター", "ファン", "客", "依頼人",
  "依頼主", "配信者", "視聴者", "作業員",
  // 人でないもの
  "魔物", "怪物", "化け物", "モンスター", "魔王", "竜", "ドラゴン", "精霊",
  "妖精", "悪魔", "天使", "幽霊", "吸血鬼", "猫", "犬",
]);

/**
 * 語尾で役名と言い切れる形。「冒険者」「配信者」「作業員」「受付係」
 * 「敷設業者」「宿屋」「魔法使い」。**名前がこの字で終わることはほとんど無い。**
 */
const ROLE_SUFFIX = /(?:者|員|係|担当|業者|屋|使い|役|職人)$/u;

/**
 * 語尾が役職・呼び名の形だが、**名前にもある**もの（「班長」と「信長」、
 * 「店主」と「悠主」、「老人」と「勇人」）。対象に含めて、作者に外させる。
 */
const UNSURE_SUFFIX = /(?:長|士|師|官|主|王|姫|嬢|娘|人|様|さん|くん|君|ちゃん|殿)$/u;

/** 「男A」「刺客2」のような、名前を伏せた呼び方の印 */
const PLACEHOLDER_MARK = /[A-ZＡ-Ｚa-zａ-ｚ0-9０-９]$/u;

/**
 * その呼び名は役名か。**名前に見えるなら undefined**。
 *
 * - 一覧にある言葉 → 役名
 * - 「の」を含む（「向こうの業者」「謎の男」）→ 役名（呼び名の形。
 *   `nameOriginFit.ts` も「の」を含む呼び名を名前として数えない）
 * - 役名の語尾（者・員・係…）→ 役名
 * - 名前にもある語尾（長・人・主…）・英数字で終わる → 迷う
 */
export function classifyRoleName(value: string): RoleNameVerdict | undefined {
  const name = value.trim().replace(/^\*{1,2}|\*{1,2}$/gu, "").trim();
  if (!name) return undefined;
  // 姓と名を空白・中黒で分けて書いたもの（「相馬 誠」）は名前である
  if (/[\s　・･＝=]/u.test(name)) return undefined;

  if (ROLE_WORDS.has(name)) {
    return { kind: "role", reason: "役割を表す言葉です" };
  }
  // ひらがなだけの名前（「このみ」「ののか」）にも「の」は入るので、
  // ひらがな以外の字を含むときだけ見る
  if (name.includes("の") && !/^[\p{Script=Hiragana}ー]+$/u.test(name)) {
    return { kind: "role", reason: "「〜の〜」の呼び名です" };
  }
  if (ROLE_SUFFIX.test(name)) {
    return { kind: "role", reason: "役割を表す語尾です" };
  }
  // 一覧の言葉で終わる（「新人配信者」「女騎士」「元騎士」）。
  // **漢字を含む言葉だけで見る**——カタカナの言葉で見ると、「ステファン」が
  // 「ファン」で終わるので役名になってしまう
  for (const word of ROLE_WORDS) {
    if ([...word].length >= 2 && /\p{Script=Han}/u.test(word) && name.endsWith(word)) {
      return { kind: "role", reason: `「${word}」で終わる呼び名です` };
    }
  }
  if (PLACEHOLDER_MARK.test(name)) {
    return { kind: "unsure", reason: "英字・数字で終わる呼び方です（名前か役名か迷います）" };
  }
  if (UNSURE_SUFFIX.test(name)) {
    return { kind: "unsure", reason: "役職の語尾ですが、名前にもある形です" };
  }
  return undefined;
}

/**
 * 「役名（名前）」を割る。**外側が役名のときだけ**割り、そうでなければ undefined。
 *
 * 「灯（あかり）」「アレン（仮）」は外側が名前なので割らない——括弧の中は
 * 読みか注記である。「主人公（相馬 誠）」は外側が役名なので、中を名前として返す。
 */
export function splitRoleAnnotation(
  value: string
): { role: string; name: string } | undefined {
  const matched = /^(.+?)[ 　]*[（(]([^（）()]+)[）)]$/u.exec(value.trim());
  if (!matched) return undefined;
  const role = matched[1].trim();
  const name = matched[2].trim();
  if (!role || !name) return undefined;
  if (!classifyRoleName(role)) return undefined;
  // 中身も役名なら、名前を足した形ではない（「魔物（ファン）」）
  if (classifyRoleName(name)?.kind === "role") return undefined;
  return { role, name };
}

/** 役名に名前を足した形。**この形は `splitRoleAnnotation` と対になる** */
export function formatRoleAnnotation(role: string, name: string): string {
  return `${role}（${name}）`;
}
