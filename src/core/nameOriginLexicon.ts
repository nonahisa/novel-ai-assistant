const ORIGINS_BY_NAME: ReadonlyMap<string, readonly NameOrigin[]> = (() => {
  const map = new Map<string, NameOrigin[]>();
  for (const [origins, names] of TYPICAL_NAMES) {
    const list: readonly NameOrigin[] = typeof origins === "string" ? [origins] : origins;
    for (const name of names) {
      map.set(name, [...(map.get(name) ?? []), ...list]);
    }
  }
  return map;
})();

/**
 * 名前をつなぎの記号で部分に分ける（「ジャン＝ピエール」「ハンス・ギヨーム」）。
 * 名と姓のどちらかが別の系統なら、その名前は札と合っていない。
 */
function partsOf(name: string): string[] {
  return name.split(/[・･＝=\s]+/u).filter(Boolean);
}

/**
 * 系統の札と、名前の中身が合っていないと**はっきり言える**なら、その理由（作者へ見せる文）。
 * 言えなければ undefined（表に無い名前は何も言わない）。
 *
 * @param origin 揃える系統（`fitNameCandidates` が決めたもの）。**架空語と未定のときは
 *   実在の名前の表を当てない**——架空の言葉の名前が、たまたま実在の名前と同じでも構わない。
 *   英語の言葉は、どの系統でも名前ではないので見る
 */
export function originMismatchReason(
  name: string,
  origin: NameOrigin | undefined
): string | undefined {
  for (const part of partsOf(name)) {
    if (ENGLISH_COMMON_WORDS.has(part)) {
      return `英語の言葉で、人の名前に見えません（${part}）`;
    }
    if (origin === undefined || origin === "架空語") continue;
    const origins = ORIGINS_BY_NAME.get(part);
    if (origins && !origins.includes(origin)) {
      return `系統（${origin}）の名前に見えません（${part}は${origins.join("・")}でよく使う名前です）`;
    }
  }
  return undefined;
}
