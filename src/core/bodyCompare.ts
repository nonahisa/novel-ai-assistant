/**
 * 本文どうしを比べる（設計書6.100の下ごしらえ、0.69.10）。
 *
 * ## なぜ「比べる前に文字を揃える」が要るのか
 *
 * 同じ作品のなろう版とアルファポリス版を突き合わせたところ、
 * **そのままでは87話しか一致せず、文字を揃えると105話が一致した**
 * （2026-09-19、実データで測定）。
 *
 * 原因は `～`（全角チルダ U+FF5E）と `〜`（波ダッシュ U+301C）の食い違いで、
 * **Shift_JIS（CP932）を通すと入れ替わる**、日本語の古典的な落とし穴である。
 * Unicode の規格どおりに変換する処理系と、Windows の慣習どおりに変換する
 * 処理系があり、**投稿サイトによってどちらで書き出すかが違う。**
 *
 * 同じ組が他にもある（負符号・双柱・emダッシュ・セント記号など）。
 * **どれも「作者が直した」ものではない**ので、比べる前に揃える。
 *
 * ## 揃えるのは、この組だけである
 *
 * 全角半角や送り仮名まで畳むと、**作者が推敲して直したことまで「同じ」と
 * 言ってしまう**（設計書6.100：「どちらも作者が意図して書いた版である」）。
 * ここで畳むのは、**文字コードの変換で機械が勝手に入れ替える組**に限る。
 *
 * ## いまの使い道と、これからの使い道
 *
 * いまは**「同じ話かどうか」の判定**にだけ使う（取り込みで、話番号が
 * 重複したときに中身まで同じかを見る。`episodeNumberCheck.ts`）。
 * 設計書6.100（同じ作品を複数サイトの記録で束ねる）の照合も、
 * ここを通す——**写しを作ると、突き合わせの基準が2つになる。**
 *
 * VS Code API には依存しない。
 */

/**
 * CP932 と Unicode のあいだで入れ替わる組。**左を右へ揃える。**
 *
 * どちらへ揃えるかは比較には関係しない（両方が同じ側へ寄ればよい）ので、
 * **JIS X 0208 の規格どおりの字**を残す側に決めてある。
 *
 * | 揃える先 | 入れ替わる相手 | 何の字か |
 * |---|---|---|
 * | `〜` U+301C | `～` U+FF5E | 波ダッシュ／全角チルダ |
 * | `−` U+2212 | `－` U+FF0D | 負符号／全角ハイフンマイナス |
 * | `‖` U+2016 | `∥` U+2225 | 双柱／平行 |
 * | `―` U+2015 | `—` U+2014 | 横線／emダッシュ |
 * | `¢` U+00A2 | `￠` U+FFE0 | セント |
 * | `£` U+00A3 | `￡` U+FFE1 | ポンド |
 * | `¬` U+00AC | `￢` U+FFE2 | 否定 |
 *
 * **生の文字では書かない。** どの字なのかがコード上で見分けられないため
 * （`～` と `〜` は多くのフォントで見分けが付かない）、エスケープで書く。
 */
const CP932_VARIANTS: ReadonlyMap<string, string> = new Map([
  ["～", "〜"],
  ["－", "−"],
  ["∥", "‖"],
  ["—", "―"],
  ["￠", "¢"],
  ["￡", "£"],
  ["￢", "¬"],
]);

/** 入れ替わる側をまとめて拾う（1文字ずつ回すより速く、意図も読める） */
const CP932_VARIANT_PATTERN = new RegExp(
  `[${[...CP932_VARIANTS.keys()].join("")}]`,
  "g"
);

/**
 * 比べるために文字を揃える。**原稿には書き戻さない。**
 *
 * ここが返すのは**比較用の影**であって、作者の本文ではない。
 * 戻り値をそのままファイルへ書くと、作者が選んだ字が黙って変わる
 * （実装ルール1・2）。
 *
 * 揃えるもの：
 *
 * 1. CP932 で入れ替わる組（上の表）
 * 2. 改行コード（Shift_JIS 版は CRLF、UTF-8 版は LF で降りてくる）
 * 3. 行末の空白と、前後の空行
 *
 * **途中の空行は残す。** 段落の切れ目は作者が置いたものである。
 */
export function foldTextForComparison(text: string): string {
  return text
    .replace(/\r\n?/g, "\n")
    .replace(CP932_VARIANT_PATTERN, (char) => CP932_VARIANTS.get(char) ?? char)
    // 行末の空白だけを落とす（行頭の字下げは本文の一部なので触らない）
    .replace(/[ \t　]+$/gm, "")
    .replace(/^\n+/, "")
    .replace(/\n+$/, "");
}

/**
 * 2つの本文は同じものか。
 *
 * **「同じ」と言えるのは、文字を揃えたうえで一字一句合うときだけ**である。
 * 似ている度合い（一致率）は設計書6.100の照合が要るもので、ここでは扱わない
 * ——取り込みの重複判定は「**落としても何も失わないか**」を決めるための
 * 問いなので、**少しでも違えば違う**と答えなければならない。
 */
export function isSameBodyText(left: string, right: string): boolean {
  return foldTextForComparison(left) === foldTextForComparison(right);
}
