/**
 * 説明や入力欄の例に使う、**架空の作品と人物**（作者の指定、2026-09-13
 * 「メニューのチップ説明等にでる登場人物名は、架空作品の登場人物名にしてください」）。
 *
 * ## なぜ実在の作品の人物を使わないか
 *
 * 開発では作者の作品を実データとして使っており、その人物名がそのまま
 * 説明文やプロンプトの例に残っていた。3つ困る。
 *
 * 1. **配る先は作者だけではない。** ほかの人の画面に、見覚えのない
 *    誰かの名前が例として出る
 * 2. **AIが例に引きずられる。** プロンプトへ実在の人物名を書くと、
 *    その名前や設定が答えの中に混ざって返ってくることがある
 *    （CLAUDE.md「繰り返し起きた失敗」3番。指示の言葉が答えの中身として返る）
 * 3. **作品の中身が、製品の一部として配られてしまう**
 *
 * ## 1か所に置く
 *
 * **写しを作らない。** 例の人物が画面とプロンプトで違うと、読む人には
 * 別々の話に見える。ここを直せば全部が変わる。
 *
 * `test/unit/core/exampleNames.test.ts` が、実在の作品の人物名が
 * 画面の文字列とプロンプトへ入り込んでいないかを見張る。
 *
 * VS Code APIに依存しない。
 */

