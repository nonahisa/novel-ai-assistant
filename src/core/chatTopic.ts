import { selectGuideBundles, type GuideBundle } from "./guideSelect";

/**
 * 相談が「創作の相談」か「操作の相談」かを見分ける。
 *
 * ## なぜ要るのか（2026-09-13）
 *
 * 相談へ渡す「使い方の説明」は、説明の束こそ絞られていたが、**目次
 * （全操作の名前、2,293字）は無条件で毎回乗っていた。** 実測すると、
 * 創作の相談（「主人公の動機が弱い気がします」）では2,293字すべてが目次で、
 * 説明は0字——つまり**全部が無駄**だった。EPUBエディターも投稿キットも
 * IME辞書も、名前だけが毎回送られていたことになる。
 *
 * 作者の指摘（2026-09-13）：「今は不要な記事の内容まで一括で乗っていそうな
 * 気配を感じています」。そこで話題を見分け、創作の相談には目次を送らない。
 *
 * ## 見分け方——束選びを借りる
 *
 * 材料は既にある。`guideSelect.ts` の `selectGuideBundles` が、質問と説明を
 * 文字2つ組みで突き合わせ、当たりが `MIN_HITS` 以上の束を選んでいる。
 * **束が1つでも選ばれたなら、その質問は操作の説明に当たっている**——
 * これが操作の相談である素直な証拠になる。同じ突き合わせをここへ書き写すと
 * 二重管理になるので、**仕組みは借りるだけ**にする。
 *
 * 束が選ばれなかったときに、言い回し（「どこから」「ボタン」など）を見る。
 * ただし**言い回しだけでは `howto` にしない。** 「これ、どうすればいい？」は
 * 操作の話か作品の話か、この一文からは決められない。言い回しが当たったら
 * `unknown` に留め、目次は送る（下記）。
 *
 * ## 迷ったら目次を送る側へ倒す
 *
 * 判定を外したときの損は左右で釣り合わない。
 * - 操作の相談を `craft` と誤れば、**答えられなくなる**（操作名を1つも知らない）
 * - 創作の相談を `unknown` と誤っても、**2,293字が無駄になるだけ**
 * だから迷いは必ず `unknown`（＝目次を送る）へ倒す。`craft` と言い切るのは
 * 「束にも当たらず、操作を尋ねる言い回しも無い」ときだけである。
 *
 * VS Code APIに依存しない。
 */
export type ChatTopic =
  /** 作品の相談。操作の目次は要らない */
  | "craft"
  /** この拡張機能の操作の相談。目次も説明も要る */
  | "howto"
  /** どちらとも決められない。目次は送る */
  | "unknown";

/**
 * 操作を尋ねているときの言い回し。
 *
 * **一覧はここだけに置く。** 選んだ理由は次のとおり。
 *
 * - **場所を訊く形**（どこから・どこに・どこで・どこ？）——「誤字脱字の検知は
 *   どこから」。作品の相談で「どこ」と言うときは「この場面のどこが」のように
 *   直前に語が付くので、助詞付きの形だけを採る
 * - **手順を訊く形**（どうやって・どうすれば・やり方・方法・手順・使い方）
 * - **「どう」単独は入れない。** 「どう思いますか」「どう書き出すか迷っています」は
 *   作品の相談の言い回しそのもので、入れると創作の相談が軒並み `unknown` になり、
 *   節約が消える（実測10問のうち2問が当たった）
 * - **画面の部品の名前**（ボタン・メニュー・押す・クリック・タブ・画面）——
 *   作品の話には出てこない語。「場面」はあるが「画面」は無い
 * - **動かないという訴え**（出てこない・表示されない・効かない・動かない）——
 *   不具合の訴えも操作の相談である。目次が無いと場所すら答えられない
 * - **「設定」は入れない。** 小説では「世界設定」「設定を練る」が日常語で、
 *   入れると創作の相談を拾ってしまう。操作としての設定（設定資料・設定管理）は
 *   漢字2文字で説明の束に当たるので、束選びの側で拾える
 * - **「できますか」「教えて」「とは」も入れない。** 「もっと良くできますか」
 *   「テーマとは」のように、作品の相談で普通に使われる
 *
 * `core/chatIntent.ts` にも質問の言い回しの一覧があるが、あちらが見分けるのは
 * 「頼みか、質問か」（起動ボタンを出すかどうか）で、**問いが違う**。
 * あちらには「なぜ」「できますか」「とは」が入っており、そのまま借りると
 * 作品の相談まで操作寄りに倒れる。用途が違うものを無理に1つにしない。
 */
const HOWTO_PHRASES = [
  // 場所を訊く
  "どこから",
  "どこに",
  "どこで",
  "どこですか",
  "どこ？",
  "どこ?",
  // 手順を訊く
  "どうやって",
  "どうやる",
  "どうすれば",
  "どうしたら",
  "どうすると",
  "どのように",
  "やり方",
  "方法",
  "手順",
  "使い方",
  "操作",
  // 画面の部品
  "ボタン",
  "メニュー",
  "クリック",
  "タブ",
  "画面",
  "押す",
  "押せ",
  "押し",
  // 動かないという訴え
  "出てこない",
  "表示されない",
  "表示されま",
  "効かない",
  "動かない",
  "見当たらない",
  // 投稿サイトのバックアップ。相談パネルへ落とす入口は隠し機能で、知っているのは
  // 使い方の節だけ（`prompts/workChat.ts` v3.20）。「カクヨムのバックアップを
  // 取り込みたい」は漢字の2文字組みを1つも持たず、束にも当たらないので、
  // ここで拾わないと節ごと外れて答えられない（2026-09-24）。作品の話には出ない語
  "バックアップ",
] as const;

/**
 * 話題を見分ける。
 *
 * `bundles` を渡すと、束選び（`selectGuideBundles`）の結果も材料にする。
 * **渡すのが本筋である**——渡さないと言い回しだけの判定になり、機能名で
 * 聞かれただけの質問（「EPUBに表紙を入れるには」）を `howto` と言い切れない。
 *
 * 直前の作者の発言も材料にする。「それはどこ？」のような追い質問は、
 * それ自体には機能名が入っていない。**話題は直前の発言が持っている。**
 */
export function detectChatTopic(input: {
  question: string;
  /** 直前の作者の発言。無ければ空 */
  recentAuthorTurns?: string[];
  /** 使い方の説明の束（`features/featureGuide.ts` の `buildGuideBundles()`） */
  bundles?: readonly GuideBundle[];
}): ChatTopic {
  const bundles = input.bundles ?? [];
  if (bundles.length > 0) {
    const selection = selectGuideBundles({
      question: input.question,
      recentAuthorTurns: input.recentAuthorTurns,
      bundles: [...bundles],
    });
    // 束に当たったということは、質問の語が操作の説明の中にある。
    // 判定をここで写さず、選び手の結果をそのまま証拠として使う
    if (selection.selected.length > 0) return "howto";
  }

  const sources = [input.question, ...(input.recentAuthorTurns ?? [])];
  for (const source of sources) {
    if (HOWTO_PHRASES.some((phrase) => source.includes(phrase))) {
      // 操作を訊いている気配はあるが、どの操作かは分からない。
      // 目次を落として答えられなくなるより、載せて無駄になるほうがよい
      return "unknown";
    }
  }

  return "craft";
}
