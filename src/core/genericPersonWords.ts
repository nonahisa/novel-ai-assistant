/**
 * 誰にでも使える呼び方の一覧（設計書6.5.9）。
 *
 * 代名詞（一人称・二人称・三人称）と家族関係語を持つ。**どちらも
 * 「その語が一致したからといって同じ人物とは限らない」**種類の語である。
 *
 * ## なぜ1か所に置くか
 *
 * 同じ語を、次の2つが別々の目的で使う。写しを作ると、片方にだけ語を
 * 足したときに「抽出では弾くのに、統合候補では根拠になる」という
 * 食い違いが起きる（実機確認A-18で、実際に片方だけ手当てされていた）。
 *
 * - `characterExtractionValidation.ts`：代名詞だけの名前のレコードを弾く
 * - `characterMerge.ts`：呼び名の一致を「同一人物の根拠」に数えない
 *
 * ## プロンプトとの関係
 *
 * `prompts/characterExtract.ts` の【登場人物の抽出ルール】は
 * 「一人称・二人称などの代名詞、汎用的な役職語、家族関係語…は
 * 人物レコードを作らないこと」と禁じている。**ここはその語の一覧である。**
 * プロンプト側は語を並べていない（並べると指示語がそのまま答えとして
 * 返ってくる。CLAUDE.md「繰り返し起きた失敗」3番）ので、
 * 文言そのものを共有することはできない。**同じものを指していることを、
 * 設計書6.5.9とこのコメントに書いておく。**
 *
 * VSCode APIにもファイル操作にも依存しない。並びは自由に足してよい
 * （照合する側が正規化してから比べる）。
 */

