/**
 * プロット（`設定/plot.md`）の初期テンプレート。
 *
 * 新規作品を「プロットから始める」で作ったときと、あとから
 * 「プロットを作る」を実行したときの両方で使う。2か所に書くと、
 * 片方だけ項目を足したときに作品によって形が変わる。
 *
 * 見出しは設計書6.4のプロットモードで扱う項目に合わせてある。
 * プロットモード（専用の入力画面）は未実装だが、**先に見出しを固定して
 * おけば、あとから画面を付けても作者が書いた内容がそのまま使える**。
 */
export function buildPlotTemplate(title: string): string {
  return [
    `# ${title}`,
    "",
    "## タイトル",
    "",
    "## ログライン",
    "<!-- 誰が / どんな状況で / 何を目指し / 何が障害か を一文で -->",
    "",
    "## テーマ",
    "",
    "## モチーフ",
    "",
    "## 世界観",
    "",
    "## 舞台",
    "",
    "## 人称",
    "<!-- 一人称 / 三人称一元 / 三人称多元 -->",
    "",
    "## 主人公の行動原理",
    "",
    "## あらすじ",
    "- ",
    "",
    "## 主要登場人物",
    "- ",
    "",
  ].join("\n");
}
