/**
 * 項目が「同時に1つしか成り立たない」ものかどうかの表（設計書6.88.6）。
 *
 * ## なぜ要るのか
 *
 * 区間の照合（`attributeIntervals.ts`）は、どの項目も**排他**——つまり
 * 「同じ時期に値は1つ」——として扱っていた。所在や髪の色ならそれでよいが、
 * **所持品はいくつでも同時に成り立つ**。合羽も、郵便の束も、松葉杖も、
 * ギプスも、同じ日に同時に持っている。それを排他として突き合わせると、
 * **互いに矛盾している**ことになって候補が爆発する。
 *
 * 2026-09-18 の測定がまさにそれで、**候補11件がすべて「所持品」**だった
 * （本命は1件も出ず、判定は11件すべてを「そもそも食い違っていない」で
 * 落とした）。判定を126回も走らせた原因でもある。
 *
 * ## 表に無い項目は「同時に成り立つ」側に倒す
 *
 * **項目名はAIが自由に付ける。** 実測では「台詞」「発言」「行動」「診断」の
 * ような、そもそも値を比べる意味の無い名前が次々に出てきた（第1段の
 * 出力174件のうち、半分近くがこの手の名前である）。表に無いものを
 * 排他に倒すと、**それが全部候補になる**——この台で数えると95件のうち79件が
 * これだった。
 *
 * 一方この製品は「**迷ったら出さない**」で通してきた（`contradictionMatch.ts`
 * の冒頭）。誤検出は、作者を本文ではなくこちらの推測を直しに行かせる。
 * 測定でも誤検出0を保ってきた。**見逃しはこの表へ名前を足せば取り返せるが、
 * 誤検出は取り返せない**ので、表に無いものは候補にしない側へ倒す。
 *
 * ## 「同時に成り立つ」側も名前を書いておく
 *
 * 既定がそちらなので、`multiple` の並びは動きを変えない。**それでも書く**
 * ——ここに名前があることが「調べたうえで非排他だと決めた」印になり、
 * あとから既定を変えたくなったときも、この並びは非排他のまま残る。
 *
 * VS Code APIに依存しない（LLMも使わない）。
 */

/** 同時に1つだけか、いくつでも成り立つか */
