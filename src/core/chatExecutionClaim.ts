/**
 * 相談のAIが、操作を**実行したふり**をしていないかを見る（設計書6.27。
 * 0.86.10 の担当の報告）。
 *
 * 相談のAIは、この拡張機能の操作を動かせない。返せるのは文章と、作者が押す
 * 実行ボタン（`run`）だけである。P-21 には 3.13 から「実行したふりをしないこと」
 * と書いてあるが、旧名で頼まれた gemma4:26b は「診断を実行します」と答えた。
 * 作者は待つだけになり、何も始まらない。**頼むだけでは守られない**（実装ルール3）
 * ので、答えの言い切りをコードで見張り、見つけたら作者へ断りを添える
 * （`features/workChatPanel.ts`）。答えそのものは書き換えない——AIが何と
 * 言ったかは作者に見えているほうがよい。
 *
 * ## 何を「言い切り」とみなすか
 *
 * **文の終わり**で、自分が動かした・動かしている・結果を知らせる、と言う形だけ。
 * - 「〜を実行します／実行しました／実行いたします」「開始しました」
 * - 「診断中です」「抽出を始めます」「検知を行います」
 * - 「完了したら（終わり次第）結果をお知らせします」「しばらくお待ちください」
 *
 * **見ないもの**（誤検出の側。どれも実際の答えに出る言い方）：
 * - 押す場所の案内（「押すと診断を実行します」「〜から実行できます」）
 * - 勧め・できないという断り（「実行してください」「実行しましょう」「実行できません」）
 * - 文の途中（「作戦を実行しますが、動機が弱い」）と、作品の中の出来事
 *   （主人公・人物・場面の話）
 *
 * VS Code API に依存しない。
 */

/** 自分が動かした・動かしている、と言い切る文末 */
const CLAIM_ENDINGS: readonly RegExp[] = [
  /(?:実行|開始|起動)(?:いたします|いたしました|します|しました|しております|しています|中です)$/u,
  /(?:診断|検知|抽出|解析|分析|処理|点検|検査|チェック)(?:を)?(?:行い|おこない)(?:ます|ました)$/u,
  /(?:診断|検知|抽出|解析|分析|処理|点検|検査|チェック)(?:を)?(?:始め|開始し)(?:ます|ました)$/u,
  /(?:診断|検知|抽出|解析|分析|処理|点検|検査|チェック)(?:中です|しています|しております)$/u,
  /(?:完了|終了|終わり)(?:し)?(?:たら|次第|ましたら|しだい).{0,30}(?:知らせ|報告|お伝え|連絡)(?:いた)?(?:します|しますね)$/u,
  /(?:しばらく|少々)お待ち(?:ください|下さい)$/u,
];

/**
 * 案内・勧め・断りの印。**文のどこかにあれば、言い切りとみなさない**
 * （「押すと実行します」は、押したら起きることの案内である）。
 */
const GUIDANCE_MARKS =
  /押す|押し|押せ|押下|ボタン|クリック|選ぶと|選んで|選択すると|メニュー|パレット|すると|したら|すれば|できます|できません|でき(?:る|ない)|してください|して下さい|しましょう|お勧め|おすすめ|勧め/u;

/**
 * 作品の中の出来事を話している印。相談は作品の相談もするので、人物が
 * 「作戦を実行します」と言っても操作の話ではない
 */
const STORY_MARKS = /主人公|登場人物|人物|彼ら|彼女|彼は|彼が|作中|物語|場面|シーン|第[0-9０-９一二三四五六七八九十]+話|キャラ/u;

/**
 * 作者へ添える断り。**何も始まっていないこと**と、**次に何をすればよいか**を言う
 * （実装ルール5の「次に取れる操作を1つ示す」と同じ考え）。
 */
export function describeExecutionClaim(claim: string): string {
  const quoted = claim.length > 40 ? `${claim.slice(0, 39)}…` : claim;
  return (
    `この返事には「${quoted}」とありますが、相談のAIは操作を動かせないため、` +
    "何も始まっていません。操作は、メニューやボタンを押して始めてください" +
    "（押す場所が分からなければ「その操作はどこ？」と尋ねてください）。"
  );
}

/**
 * 実行したと言い切っている文。無ければ undefined。
 *
 * 返す文は作者への断りに引く（「『〜を実行します』とありますが」）。
 */
export function findExecutionClaim(reply: string): string | undefined {
  const sentences = reply
    .split(/[。！？!?\n]+/u)
    .map((sentence) => sentence.trim())
    // 文頭の相づち（「承知いたしました、」）は落とさない。言い切りは文末で見る
    .filter(Boolean);
  for (const sentence of sentences) {
    const body = sentence.replace(/[、，,\s]+$/u, "");
    if (GUIDANCE_MARKS.test(body) || STORY_MARKS.test(body)) continue;
    if (CLAIM_ENDINGS.some((pattern) => pattern.test(body))) return body;
  }
  return undefined;
}
