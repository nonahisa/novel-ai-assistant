/**
 * 相談パネルの「聞き方の例」（作者の要望、2026-09-22
 * 「AI相談の例に『この作品を好む読者はどんな層？』を追加しましょうか」）。
 *
 * ## なぜ例が要るのか
 *
 * 相談パネルには「できること」（AI機能の札）はあるが、**どう聞けばよいか**
 * を示すものが無かった。空の入力欄の前で、何を打てば何が返るのかは分からない。
 *
 * ## 押しても送らない
 *
 * 札を押すと**入力欄に入るだけ**にする。そのまま送ると、直す気の無い
 * 言い回しでAIを呼ぶことになり（クラウドならそのまま料金になる）、
 * 作者が「自分の作品の言葉」へ書き換える隙も無くなる。
 *
 * ## 手順書きに当たる言い方だけを置く
 *
 * 例を押した瞬間に「画面で案内してもらう」が出てほしい。そのためには
 * `core/procedures.ts` の `selectProcedure` に当たる必要があり、当たりの
 * 判定は**漢字2文字の組み**で行う（`core/guideSelect.ts` の
 * `isEvidenceGram`）。だから、
 *
 * - 「次の話のプロットを考えたい」は**漢字2字の組みが1つも無い**ので当たらない
 * - 「ターゲットシートを見せて」も同じ理由で当たらない
 *
 * **当たらない言い方は置かない。** 押しても案内が出ない札は、
 * 「押しても何も起きない」と同じに見える。
 * `test/unit/core/chatExamples.test.ts` が全部の例を `selectProcedure` へ通す。
 *
 * ## `vscode` を持ち込まない
 *
 * 並びは設定にも画面にも依存しないので、`core` に置いて単体テストで測る。
 */

/**
 * いつでも出す例。
 *
 * **3〜5つに留める。** 入力欄の上に置くので、増やすほど会話の場が
 * 下から押し上げられる。
 */
export const CHAT_EXAMPLES: readonly string[] = [
  // 作者の依頼そのもの（「この作品を好む読者はどんな層？」）
  "この作品を好む読者はどんな層？",
  "誤字脱字を直したい",
  "矛盾を洗いたい",
  "投稿の準備をしたい",
];

/**
 * 読者像をまだ決めていないときだけ足す例（設計書6.91）。
 *
 * 決めたあとに出し続けると、済んだ仕事を勧めることになる。
 */
export const READER_TARGET_EXAMPLE = "読者型を決めたい";

/**
 * 画面に並べる例を決める。
 *
 * @param input.readerTargetDiagnosed 読者像が決まっているか。
 *   読めなかったとき（台帳が無い・壊れている）は「まだ」と同じ扱いでよい
 *   ——勧める札が1つ増えるだけで、押さなければ何も起きない
 */
export function chatExamplesFor(input: {
  readerTargetDiagnosed: boolean;
}): readonly string[] {
  if (input.readerTargetDiagnosed) return CHAT_EXAMPLES;
  return [...CHAT_EXAMPLES, READER_TARGET_EXAMPLE];
}
