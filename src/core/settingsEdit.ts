/**
 * 世界観の書き換え。
 *
 * 分類は決まった7種のどれかなので、知らない値が来たら**現在の値を残す**。
 * 画面からは選択肢で送ってくるが、他のツールが編集した内容が
 * そのまま流れてくる経路もあり得る。想定外の値で保存すると、
 * 読み込み時に検証で落ちて作者がJSONを直す羽目になる。
 */
export function applyWorldItemEdits(
  item: WorldItem,
  edits: RecordEdits,
  options?: EditOptions
): WorldItem {
  return {
    ...item,
    name: editedName(item.name, edits.name),
    aliases: editedAliases(item.aliases, edits.aliases),
    category: editedWorldCategory(item.category, edits.category),
    description: nullableText(item.description, edits.description),
    authorNotes: plainText(item.authorNotes, edits.authorNotes),
    exportNote: plainText(item.exportNote, edits.exportNote),
    autoGenerated: nextAutoGenerated(item.autoGenerated, options),
  };
}

function editedWorldCategory(
  current: WorldCategory,
  edited: string | undefined
): WorldCategory {
  if (edited === undefined) return current;
  const value = edited.trim();
  const matched = WORLD_CATEGORIES.find((category) => category === value);
  return matched ?? current;
}

