/** aiNotes を持つレコードの共通形 */
interface WithAiNotes {
  aiNotes: AiNote[];
}

export interface NewAiNote {
  topic: string;
  text: string;
  model: string;
  source: AiNoteSource;
}

/**
 * 承認された掘り下げメモを追記する。
 * 既存のメモは並べ替えず、末尾に足すだけにする。
 */
export function appendAiNote<T extends WithAiNotes>(
  record: T,
  note: NewAiNote,
  now: Date = new Date()
): T {
  const text = note.text.trim();
  if (!text) {
    throw new SettingsEditError("追記する内容が空です。");
  }
  const appended: AiNote = {
    id: nextAiNoteId(record.aiNotes),
    createdAt: now.toISOString(),
    topic: note.topic.trim(),
    text,
    model: note.model,
    source: note.source,
  };
  return { ...record, aiNotes: [...record.aiNotes, appended] };
}

export function removeAiNote<T extends WithAiNotes>(record: T, noteId: string): T {
  return {
    ...record,
    aiNotes: record.aiNotes.filter((note) => note.id !== noteId),
  };
}

/**
 * 名前は空にできない。
 * 空のまま保存を通すとファイル名がIDだけになり、
 * 作者がGitの差分で何の変更か判別できなくなる。
 */
function editedName(current: string, edited: string | undefined): string {
  if (edited === undefined) return current;
  const value = edited.trim();
  if (!value) {
    throw new SettingsEditError("名前は空にできません。");
  }
  return value;
}

/**
 * 別名から選ばれた名前を、名前と別名で入れ替える（設計書6.5.6）。
 *
 * 作者の指示（2026-08-23）：「設定資料の名前欄を別名から選択可能にして
 * ください」。
 *
 * ## 入れ替えであって、上書きではない
 *
 * 「マルキオ」を正式名称にしたとき、**元の「マルキオ・イークェス」が
 * 消えてはいけない。** 消すと本文の照合から外れ、用語ハイライトも
 * IME辞書も、その呼び方を拾わなくなる。元の名前は別名へ移す。
 *
 * ## 打ち間違いの直しと、見分ける
 *
 * 名前が変わったからといって、いつも元の名前を別名へ入れてよいわけでは
 * ない。「太史」→「太志」のような**打ち間違いの修正**では、誤った名前が
 * 別名として残ってしまう。
 *
 * **元から別名にあった名前が選ばれたときだけ入れ替える。** それが
 * 「別名から選んだ」ということである。
 *
 * @param previousAliases 編集前の別名。ここに新しい名前があれば「選択」
 * @param nextAliases 作者が入力欄で編集したあとの別名
 */
export function swapNameWithAlias(
  previousName: string,
  nextName: string,
  previousAliases: readonly string[],
  nextAliases: readonly string[]
): { name: string; aliases: string[] } {
  const name = nextName.trim();
  const previous = previousName.trim();
  const aliases = [...nextAliases];

  if (!name || name === previous) return { name, aliases };
  // 元から別名にあったものが選ばれたときだけ入れ替える
  if (!previousAliases.some((alias) => alias.trim() === name)) {
    return { name, aliases };
  }

  const without = aliases.filter((alias) => alias.trim() !== name);
  // **元の名前を失わない。** すでに別名にあるなら足さない
  const withPrevious = without.some((alias) => alias.trim() === previous)
    ? without
    : [previous, ...without];
  return { name, aliases: withPrevious.filter((alias) => alias.trim()) };
}

/** 空欄は「未設定」を意味する。空文字ではなく null で持つ */
function nullableText(
  current: string | null,
  edited: string | undefined
): string | null {
  if (edited === undefined) return current;
  const value = edited.trim();
  return value ? value : null;
}

/**
 * チェックの状態を反映する。
 * 画面に出ていない項目（能力・場所には無い）は undefined で届くので触らない。
 */
function editedFlag(current: boolean, edited: string | undefined): boolean {
  if (edited === undefined) return current;
  return edited === "1";
}

/** authorNotes / exportNote は空文字を許す（null にしない） */
function plainText(current: string, edited: string | undefined): string {
  if (edited === undefined) return current;
  return edited.trim();
}

/** 読点・改行・カンマのどれで区切っても同じように扱う */
export function editedAliases(
  current: string[],
  edited: string | undefined
): string[] {
  if (edited === undefined) return current;
  const parts = edited
    .split(/[、,\n]/)
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
  return [...new Set(parts)];
}

type Relation = { name: string; relation: string };

/**
 * 関係欄に出す形。**1行に1つ「相手=関係」**（作者の依頼「B3」、2026-09-22 未明）。
 *
 * 承認待ちの差分（`characterDiff`）も「ターナ=母」の形で見せているので、
 * 作者が画面ごとに別の書き方を覚えずに済む。
 *
 * 別名のような読点区切りにしないのは、**関係の言葉そのものに読点が入る**
 * から（「幼なじみ、のちに婚約者」）。行で区切れば、中身は何でも書ける。
 */
export function formatRelationsForEdit(relations: readonly Relation[]): string {
  return relations.map((entry) => `${entry.name}=${entry.relation}`).join("\n");
}

/**
 * 関係欄の入力を読む。渡されなければ触らない。
 *
 * - 区切りは**最初の**「=」か「＝」（関係の中の＝は残す）。前後の空白と空行は落とす
 * - **まったく同じ行だけ**畳む。同じ相手でも関係が違えば両方残す——
 *   片方を捨てるのは作者の判断で、コードが決めることではない（`dedupeRelations` と同じ立場）
 * - **読めない行は、行番号と中身を挙げて止める。** 黙って捨てると、作者が書いた
 *   関係が保存のたびに消える
 * - **相手側の関係は変えない。** 関係はそれぞれの人物のレコードから見た言葉で
 *   （「母」の相手側は「娘」）、逆の言葉はコードには決められない
 */
export function editedRelations(
  current: Relation[],
  edited: string | undefined
): Relation[] {
  if (edited === undefined) return current;
  const result: Relation[] = [];
  const seen = new Set<string>();
  const lines = edited.split(/\r?\n/);
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index].trim();
    if (!line) continue;
    const at = line.search(/[=＝]/);
    const name = at < 0 ? "" : line.slice(0, at).trim();
    const relation = at < 0 ? "" : line.slice(at + 1).trim();
    if (!name || !relation) {
      throw new SettingsEditError(
        `関係の${index + 1}行目「${line}」が読めません。` +
          "1行に1つ「相手=関係」の形で書いてください（例：ターナ=母）。"
      );
    }
    // 区切りにNULを使うのは、名前にも関係にも現れない文字だから。
    // ソースには生のNULを置かずエスケープで書く
    const key = `${name}\u0000${relation}`;
    if (seen.has(key)) continue;
    seen.add(key);
    result.push({ name, relation });
  }
  return result;
}

/**
 * 関係欄の下に添える説明。書き方と、**相手側の記録**（読むだけ）を並べる。
 *
 * 相手側を並べるのは、片側だけ直して向かい側の誤りに気づかない、を防ぐため。
 * **こちらから相手側は書き換えない**（`editedRelations` の注を参照）——
 * 直すときは相手の人物を開いて直す。
 */
export function describeRelationEditHint(
  name: string,
  incoming: ReadonlyArray<{ fromName: string; relation: string }>
): string {
  const lines = [
    "1行に1つ「相手=関係」の形で書きます（例：ターナ=母）。関係はこの人物から見た相手の続柄・立場です。",
  ];
  if (incoming.length > 0) {
    lines.push(
      "相手側の記録（ここでは変わりません。直すときは相手の人物を開きます）："
    );
    for (const entry of incoming) {
      lines.push(`・${entry.fromName}の記録: ${name}（この人物）=${entry.relation}`);
    }
  }
  return lines.join("\n");
}
