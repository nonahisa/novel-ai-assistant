/**
 * 作者がパネル上で書き換えた内容をレコードへ反映する。
 *
 * 反映するのは作者が触れる項目だけにする。
 * 登場話数や抽出根拠のような「本文から機械的に求まる値」を
 * 画面から編集できるようにすると、次の抽出で戻されて混乱するため。
 *
 * **作者が自分で書き換えたレコードは autoGenerated を false にする。**
 * 作者が確定させたものはAIの再抽出で上書きしない、という
 * 既存の約束（CLAUDE.md）に合わせるため。
 *
 * ただし**AIの提案をそのまま採用した場合は false にしない**（`EditOptions`）。
 * 中身はAIが書いたもので、作者が確定させた記述ではない。
 * false にすると、その人物は以後の抽出から締め出され、
 * 書き進めても情報が増えなくなる。
 */

export interface RecordEdits {
  name?: string;
  /** 一覧に出す短い紹介。SUMMARY_MAX_CHARS を超える分はコード側で切る */
  summary?: string;
  gender?: string;
  affiliation?: string;
  reading?: string;
  /** 読点・改行区切りの別名 */
  aliases?: string;
  role?: string;
  personality?: string;
  appearance?: string;
  category?: string;
  description?: string;
  cost?: string;
  limitation?: string;
  region?: string;
  /** 組織の上位組織 */
  parent?: string;
  authorNotes?: string;
  exportNote?: string;
  /**
   * モブ・集団として扱うか。チェックの状態を "1"（入）か ""（切）で受け取る。
   * 他の項目と同じ経路で保存するため、真偽値ではなく文字列で持つ。
   */
  isMob?: string;
  /** 作者が足した項目。キーは項目定義の key */
  customFields?: Record<string, string>;
}

export class SettingsEditError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SettingsEditError";
  }
}

export interface EditOptions {
  /**
   * 作者が自分で書いた内容か。
   *
   * true なら `autoGenerated` を false にし、以後の抽出で上書きされなくする。
   *
   * **AIの提案をそのまま採用した場合は false にする。** 中身はAIが書いたもので、
   * 作者が確定させた記述ではない。true にすると、その人物は以後の抽出から
   * 締め出され、書き進めても情報が増えなくなる。
   * 一度でも作者が確定させた記録は、AIの反映では取り消さない。
   */
  authorConfirmed?: boolean;
}

/** 反映後の autoGenerated を決める */
function nextAutoGenerated(
  current: boolean,
  options: EditOptions | undefined
): boolean {
  if (options?.authorConfirmed === false) return current;
  return false;
}

export function applyCharacterEdits(
  character: Character,
  edits: RecordEdits,
  options?: EditOptions
): Character {
  return {
    ...character,
    name: editedName(character.name, edits.name),
    // 作者が書いた紹介文も長さは揃える。一覧の見た目が崩れるため
    summary: clampSummary(nullableText(character.summary, edits.summary)),
    gender: nullableText(character.gender, edits.gender),
    affiliation: nullableText(character.affiliation, edits.affiliation),
    reading: nullableText(character.reading, edits.reading),
    aliases: editedAliases(character.aliases, edits.aliases),
    role: nullableText(character.role, edits.role),
    personality: nullableText(character.personality, edits.personality),
    appearance: nullableText(character.appearance, edits.appearance),
    authorNotes: plainText(character.authorNotes, edits.authorNotes),
    exportNote: plainText(character.exportNote, edits.exportNote),
    // 作者がここで外したモブ判定は、次の抽出で戻されない。
    // 作者が保存したレコードは autoGenerated が false になり、
    // mergeExtractedCharacters が登場話数の追記しか行わなくなるため
    isMob: editedFlag(character.isMob, edits.isMob),
    customFields: editedCustomFields(character.customFields, edits.customFields),
    autoGenerated: nextAutoGenerated(character.autoGenerated, options),
  };
}

/**
 * 作者が足した項目の入力欄を、既定の項目と同じ仕組みで扱うための印。
 *
 * 画面側は key の中身を見ずにそのまま送り返してくるので、
 * 分解は拡張機能側だけで行う。
 */
export const CUSTOM_FIELD_PREFIX = "custom:";

/** 画面から返ってきた編集内容を、追加項目と既定の項目に分ける */
export function toRecordEdits(raw: Record<string, string>): RecordEdits {
  const edits: Record<string, string> = {};
  const customFields: Record<string, string> = {};
  for (const [key, value] of Object.entries(raw)) {
    if (key.startsWith(CUSTOM_FIELD_PREFIX)) {
      customFields[key.slice(CUSTOM_FIELD_PREFIX.length)] = value;
    } else {
      edits[key] = value;
    }
  }
  const result = edits as RecordEdits;
  // 追加項目が1つも無いときに空の {} を渡すと、
  // 「渡されなかった項目は触らない」という約束が崩れる
  if (Object.keys(customFields).length > 0) {
    result.customFields = customFields;
  }
  return result;
}

/**
 * 作者が足した項目の値を反映する。
 *
 * 渡されなかったキーは触らない。画面に出ていない項目
 * （定義を消したあとも値だけ残っているもの）を、
 * 保存のたびに巻き添えで消さないため。
 */
export function editedCustomFields(
  current: Record<string, string>,
  edits: Record<string, string> | undefined
): Record<string, string> {
  if (edits === undefined) return current;
  const next = { ...current };
  for (const [key, value] of Object.entries(edits)) {
    const text = value.trim();
    if (text) {
      next[key] = text;
    } else {
      delete next[key];
    }
  }
  return next;
}

