/**
 * 能力・場所の抽出結果を既存レコードへマージする。
 *
 * 人物と同じ方針で、統合はAIではなくコードが行い、
 * 作者が書いた値は上書きしない。食い違いは conflicts に残して
 * 作者の判断を待つ。
 */

/** 同一とみなせるか判断がつかない組。自動では統合しない */
export interface SettingMergeCandidate {
  names: [string, string];
  reason: "contains";
}

export interface AbilityMergeResult {
  abilities: Ability[];
  added: string[];
  updated: string[];
  changedIds: string[];
  conflicts: Array<{ name: string; field: string; values: string[] }>;
  mergeCandidates: SettingMergeCandidate[];
}

export interface LocationMergeResult {
  locations: Location[];
  added: string[];
  updated: string[];
  changedIds: string[];
  conflicts: Array<{ name: string; field: string; values: string[] }>;
}

export interface OrganizationMergeResult {
  organizations: Organization[];
  added: string[];
  updated: string[];
  changedIds: string[];
  conflicts: Array<{ name: string; field: string; values: string[] }>;
}

export function mergeExtractedAbilities(
  existing: Ability[],
  extracted: Array<{ data: ExtractedAbility; chapters: number[] }>
): AbilityMergeResult {
  // 作者が管理している元レコードを壊さないよう複製してから触る
  const result: Ability[] = existing.map((item) => structuredClone(item));
  const added: string[] = [];
  const updated: string[] = [];
  const changedIds = new Set<string>();
  const conflicts: AbilityMergeResult["conflicts"] = [];

  for (const item of extracted) {
    const incoming = item.data;
    const name = incoming.name?.trim();
    if (!name) continue;

    const match = findByAppellation(
      result,
      [name, ...(incoming.aliases ?? [])],
      normalizeAbilityName
    );

    if (!match) {
      const created = emptyAbility(nextAbilityId(result), name);
      applyAbility(created, incoming, item.chapters, conflicts);
      result.push(created);
      added.push(created.name);
      changedIds.add(created.id);
      continue;
    }

    // 作者が確定させたレコードはAIで書き換えない。話数の追記だけ行う
    if (!match.autoGenerated) {
      const before = match.appearedChapters.length;
      match.appearedChapters = mergeChapters(
        match.appearedChapters,
        item.chapters
      );
      if (match.appearedChapters.length !== before) {
        updated.push(match.name);
        changedIds.add(match.id);
      }
      continue;
    }

    if (applyAbility(match, incoming, item.chapters, conflicts)) {
      if (!updated.includes(match.name)) updated.push(match.name);
      changedIds.add(match.id);
    }
  }

  return {
    abilities: result,
    added,
    updated,
    changedIds: [...changedIds],
    conflicts,
    mergeCandidates: findAbilityMergeCandidates(result),
  };
}

