/**
 * 人物の所属から、まだ登録されていない組織を作る。
 *
 * AIは人物の affiliation には所属名を入れるのに、組織としては出さないことがある。
 * そのままだと、資料で所属ごとにまとめているのに組織一覧が空になる。
 * **名前だけを作り、説明は入れない。** 本文に根拠のない説明を足さないため。
 */
export function organizationsFromAffiliations(
  existing: Organization[],
  affiliations: string[]
): OrganizationMergeResult {
  const result: Organization[] = existing.map((item) => structuredClone(item));
  const added: string[] = [];
  const changedIds = new Set<string>();

  for (const raw of affiliations) {
    const name = raw.trim();
    if (!name) continue;
    if (findByAppellation(result, [name], normalizeOrganizationName)) continue;

    const created = emptyOrganization(nextOrganizationId(result), name);
    result.push(created);
    added.push(created.name);
    changedIds.add(created.id);
  }

  return {
    organizations: result,
    added,
    updated: [],
    changedIds: [...changedIds],
    conflicts: [],
  };
}

function applyOrganization(
  target: Organization,
  incoming: ExtractedOrganization,
  chapters: number[],
  conflicts: OrganizationMergeResult["conflicts"]
): boolean {
  let changed = false;

  changed = mergeAliases(target, incoming.name, incoming.aliases) || changed;
  changed = fillOrConflict(target, "reading", incoming.reading, conflicts) || changed;
  // カタカナならコード側で確実に作る。漢字だけAIの推定に委ねる
  const derivedReading = fillReading(target.reading, target.name);
  if (derivedReading !== target.reading) {
    target.reading = derivedReading;
    changed = true;
  }
  changed =
    fillOrConflict(target, "summary", clampSummary(incoming.summary), conflicts) ||
    changed;
  changed = fillOrConflict(target, "parent", incoming.parent, conflicts) || changed;
  changed =
    fillOrConflict(target, "category", incoming.category, conflicts) || changed;
  changed =
    fillOrConflict(target, "description", incoming.description, conflicts) || changed;

  if (!target.evidence && incoming.evidence) {
    target.evidence = incoming.evidence;
    changed = true;
  }

  const before = target.appearedChapters.length;
  target.appearedChapters = mergeChapters(target.appearedChapters, chapters);
  if (target.appearedChapters.length !== before) changed = true;

  return changed;
}

function applyAbility(
  target: Ability,
  incoming: ExtractedAbility,
  chapters: number[],
  conflicts: AbilityMergeResult["conflicts"]
): boolean {
  let changed = false;

  changed = mergeAliases(target, incoming.name, incoming.aliases) || changed;
  changed = fillOrConflict(target, "reading", incoming.reading, conflicts) || changed;
  // カタカナならコード側で確実に作る。漢字だけAIの推定に委ねる
  const derivedReading = fillReading(target.reading, target.name);
  if (derivedReading !== target.reading) {
    target.reading = derivedReading;
    changed = true;
  }
  // 紹介文の長さはコード側で確かめる。プロンプトの指示だけでは守られない
  changed =
    fillOrConflict(target, "summary", clampSummary(incoming.summary), conflicts) ||
    changed;
  changed = fillOrConflict(target, "category", incoming.category, conflicts) || changed;
  changed =
    fillOrConflict(target, "description", incoming.description, conflicts) || changed;
  changed = fillOrConflict(target, "cost", incoming.cost, conflicts) || changed;
  changed =
    fillOrConflict(target, "limitation", incoming.limitation, conflicts) || changed;

  for (const user of incoming.userNames ?? []) {
    const trimmed = user.trim();
    if (trimmed && !target.userNames.includes(trimmed)) {
      target.userNames.push(trimmed);
      changed = true;
    }
  }

  if (!target.evidence && incoming.evidence) {
    target.evidence = incoming.evidence;
    changed = true;
  }

  const before = target.appearedChapters.length;
  target.appearedChapters = mergeChapters(target.appearedChapters, chapters);
  if (target.appearedChapters.length !== before) changed = true;

  return changed;
}

