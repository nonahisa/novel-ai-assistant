/** 別名は和集合。照合に使われた別表記も残す */
function mergeAliases(
  target: { name: string; aliases: string[] },
  incomingName: string | undefined,
  incomingAliases: string[] | undefined
): boolean {
  let changed = false;
  const aliases = new Set(target.aliases);
  const name = incomingName?.trim();
  if (name && name !== target.name && !aliases.has(name)) {
    aliases.add(name);
    changed = true;
  }
  for (const alias of incomingAliases ?? []) {
    const trimmed = alias.trim();
    if (trimmed && trimmed !== target.name && !aliases.has(trimmed)) {
      aliases.add(trimmed);
      changed = true;
    }
  }
  target.aliases = [...aliases];
  return changed;
}

/**
 * 空なら埋め、既存値と違えば conflicts に記録する。
 * 設定側と本文側のどちらが正しいかはAIには判断できないため、
 * 既存の記述を消さずに作者へ委ねる。
 */
function fillOrConflict<T extends { name: string; conflicts: Array<{
  field: string;
  values: string[];
  chapters: number[];
  note: string | null;
}> }>(
  target: T,
  field: keyof T & string,
  incoming: string | null | undefined,
  conflicts: Array<{ name: string; field: string; values: string[] }>
): boolean {
  const value = incoming?.trim();
  if (!value) return false;

  const current = target[field] as unknown as string | null;
  if (!current) {
    (target as Record<string, unknown>)[field] = value;
    return true;
  }
  if (current === value) return false;
  // 短い記述が長い記述に含まれる場合は詳細な方を採る
  if (value.includes(current)) {
    (target as Record<string, unknown>)[field] = value;
    return true;
  }
  if (current.includes(value)) return false;

  const already = target.conflicts.find((entry) => entry.field === field);
  if (already) {
    if (!already.values.includes(value)) {
      already.values.push(value);
      conflicts.push({ name: target.name, field, values: already.values });
      return true;
    }
    return false;
  }

  target.conflicts.push({
    field,
    values: [current, value],
    chapters: [],
    note: null,
  });
  conflicts.push({ name: target.name, field, values: [current, value] });
  return true;
}

function findByAppellation<T extends { name: string; aliases: string[] }>(
  list: T[],
  appellations: string[],
  normalize: (value: string) => string
): T | undefined {
  const keys = new Set(appellations.map(normalize).filter(Boolean));
  return list.find((item) =>
    [item.name, ...item.aliases]
      .map(normalize)
      .some((candidate) => keys.has(candidate))
  );
}

/**
 * 一方が他方を完全に含む能力名を候補として挙げる。
 *
 * 「聖紋神術」と「聖紋神術の同時発動」のように、
 * 使い方が独立した能力として登録されることがある（実データで確認）。
 * ただし「炎槍」と「大炎槍」のように別能力のこともあるため、
 * 自動では統合せず作者に判断を委ねる。
 */
export function findAbilityMergeCandidates(
  abilities: Ability[]
): SettingMergeCandidate[] {
  const candidates: SettingMergeCandidate[] = [];

  for (let i = 0; i < abilities.length; i++) {
    for (let j = i + 1; j < abilities.length; j++) {
      const a = abilities[i];
      const b = abilities[j];
      if (sharesAppellation(a, b)) continue;

      const found = appellationPairs(a, b).some(([shorter, longer]) =>
        isContainedName(shorter, longer)
      );
      if (found) {
        candidates.push({ names: [a.name, b.name], reason: "contains" });
      }
    }
  }
  return candidates;
}

/** shorter が longer に完全に含まれるか。短すぎる語は誤検出の元なので除く */
export function isContainedName(shorter: string, longer: string): boolean {
  if (shorter.length < 3) return false;
  if (shorter.length >= longer.length) return false;
  return longer.includes(shorter);
}

function sharesAppellation(
  a: { name: string; aliases: string[] },
  b: { name: string; aliases: string[] }
): boolean {
  const keys = new Set(
    [a.name, ...a.aliases].map(normalizeAbilityName)
  );
  return [b.name, ...b.aliases]
    .map(normalizeAbilityName)
    .some((name) => keys.has(name));
}

/** 2件の呼称の総当たりを、短い方・長い方の順で返す */
function appellationPairs(
  a: { name: string; aliases: string[] },
  b: { name: string; aliases: string[] }
): Array<[string, string]> {
  const pairs: Array<[string, string]> = [];
  for (const left of [a.name, ...a.aliases]) {
    for (const right of [b.name, ...b.aliases]) {
      pairs.push(left.length <= right.length ? [left, right] : [right, left]);
    }
  }
  return pairs;
}

function mergeChapters(existing: number[], incoming: number[]): number[] {
  const set = new Set(existing);
  for (const chapter of incoming) {
    if (Number.isSafeInteger(chapter)) set.add(chapter);
  }
  return [...set].sort((a, b) => a - b);
}
