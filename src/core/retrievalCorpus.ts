/**
 * 切り方は葉の部品（`passages.ts`）へ移した。**ここからも今までどおり
 * 使える形で出し直す**——呼び出し側を一斉に書き換えると、写し間違いが
 * 「片方だけ切り方が違う」という気づきにくい形で残る。
 */
export { PASSAGE_CHARS, PASSAGE_OVERLAP, splitPassages } from "./passages";

/**
 * 検索の対象になる材料を、出どころ付きで集める。
 *
 * ## 出どころを必ず持たせる理由
 *
 * 設定資料とあらすじは、**本文からAIが作ったもの**である。
 * 実データで確かめたところ、ある作品の設定資料33件はすべて
 * `autoGenerated: true` で、作者が書いた記述は0件だった。
 * つまり3つの経路は同じ本文から同じ種類のAIが作った子どもで、
 * 抽出時の間違いはそのまま設定資料にも入っている。
 *
 * 実際、設定資料が「ばあさんは文佳の祖母」と書いていたが、
 * 本文に「祖母」は一度も出てこなかった。本文だけで検索したときは
 * 出なかった誤りが、設定資料を混ぜた途端にAIの答えへ入り込んだ。
 *
 * **だから「複数から出たから正しい」とは扱えない。**
 * 出どころを持たせ、AIにも見せ、食い違ったら本文を上に置く。
 * 作者が書いた `authorNotes` だけが本当の意味で独立した経路になる。
 */

export type RetrievalSource = "本文" | "設定資料" | "あらすじ";

export interface RetrievalItem {
  /** 索引の中で一意。内容が同じでも場所が違えば別 */
  id: string;
  source: RetrievalSource;
  /** 「第12話 再会」「登場人物: 太志」など、AIに示す出典 */
  label: string;
  text: string;
  /** 内容のハッシュ。変わっていない材料を作り直さないために使う */
  hash: string;
  /** 作者が自分で書いた記述を含むか。含むならAIの抽出とは独立している */
  authorWritten: boolean;
}

export interface CorpusResult {
  items: RetrievalItem[];
  /** 競合マーカーがあって読めなかったファイル */
  conflicted: string[];
}

export async function buildRetrievalCorpus(
  work: WorkEntry
): Promise<CorpusResult> {
  const items: RetrievalItem[] = [];

  const manuscript = await loadExcerptSources(work);
  for (const source of manuscript.sources) {
    splitPassages(source.text).forEach((text, index) => {
      items.push(makeItem("本文", `${source.label}#${index}`, source.label, text, false));
    });
  }

  items.push(...(await collectSettings(work)));
  items.push(...(await collectSynopses(work)));

  return { items, conflicted: manuscript.conflicted };
}

async function collectSettings(work: WorkEntry): Promise<RetrievalItem[]> {
  const items: RetrievalItem[] = [];

  let customFields: CustomFieldDefinition[] = [];
  try {
    customFields = (await new CustomFieldStore(work).load()).fields;
  } catch {
    // 追加項目が読めなくても、標準の項目だけで検索はできる
  }

  try {
    const loaded = await new CharacterStore(work).loadAll();
    for (const character of loaded.characters) {
      items.push(
        makeItem(
          "設定資料",
          `character/${character.id}`,
          `登場人物: ${character.name}`,
          describeCharacter(character, customFields),
          hasAuthorText(character.authorNotes, character.autoGenerated)
        )
      );
    }
  } catch {
    // 設定資料が無い作品もある。無ければ本文だけで検索する
  }

  // 種別ごとにまとめて読む。1種別が壊れていても他は使えるようにする
  await pushRecords(items, () => createAbilityStore(work).loadAll(), (ability) => ({
    id: `ability/${ability.id}`,
    label: `能力: ${ability.name}`,
    text: describeAbility(ability),
    authorWritten: hasAuthorText(ability.authorNotes, ability.autoGenerated),
  }));

  await pushRecords(items, () => createOrganizationStore(work).loadAll(), (org) => ({
    id: `organization/${org.id}`,
    label: `組織: ${org.name}`,
    text: describeOrganization(org),
    authorWritten: hasAuthorText(org.authorNotes, org.autoGenerated),
  }));

  await pushRecords(items, () => createLocationStore(work).loadAll(), (location) => ({
    id: `location/${location.id}`,
    label: `場所: ${location.name}`,
    text: describeLocation(location),
    authorWritten: hasAuthorText(location.authorNotes, location.autoGenerated),
  }));

  await pushRecords(items, () => createWorldStore(work).loadAll(), (item) => ({
    id: `world/${item.id}`,
    label: `世界観: ${item.name}`,
    text: describeWorldItem(item),
    authorWritten: hasAuthorText(item.authorNotes, item.autoGenerated),
  }));

  return items;
}

/**
 * 1種別ぶんを読んで足す。
 *
 * **1種別の失敗で全体を止めない。** 設定資料は作者が手で編集できるので、
 * 1つのファイルが壊れていることがある。そのために相談が使えなくなるのは重い。
 */
async function pushRecords<T>(
  items: RetrievalItem[],
  load: () => Promise<{ records: T[] }>,
  render: (record: T) => {
    id: string;
    label: string;
    text: string;
    authorWritten: boolean;
  }
): Promise<void> {
  try {
    const loaded = await load();
    for (const record of loaded.records) {
      const rendered = render(record);
      items.push(
        makeItem(
          "設定資料",
          rendered.id,
          rendered.label,
          rendered.text,
          rendered.authorWritten
        )
      );
    }
  } catch {
    // その種別は諦めて続ける
  }
}

async function collectSynopses(work: WorkEntry): Promise<RetrievalItem[]> {
  try {
    const set = await new SynopsisStore(work).load();
    return set.episodes
      .filter((episode) => episode.synopsis.trim())
      .map((episode) => {
        const label =
          episode.chapter !== null
            ? `第${episode.chapter}話のあらすじ`
            : `${episode.fileName}のあらすじ`;
        return makeItem(
          "あらすじ",
          `synopsis/${episode.fileName}`,
          label,
          `${label}\n${episode.synopsis}`,
          // 作者が書き直したあらすじは、AIの抽出とは独立した記述
          episode.autoGenerated === false
        );
      });
  } catch {
    return [];
  }
}

function hasAuthorText(
  authorNotes: string | undefined,
  autoGenerated: boolean
): boolean {
  return Boolean(authorNotes?.trim()) || autoGenerated === false;
}

function makeItem(
  source: RetrievalSource,
  id: string,
  label: string,
  text: string,
  authorWritten: boolean
): RetrievalItem {
  return {
    id: `${source}:${id}`,
    source,
    label,
    text,
    hash: hashText(text),
    authorWritten,
  };
}

export function hashText(text: string): string {
  return sha1Text(text).slice(0, 24);
}
