import type { Character, PersonalityFacet } from "../models/character";
import {
  mergeChangeLists,
  type RecordChange,
} from "../models/jsonValidation";

/**
 * 性格を「面ごとに積む」（作者の裁定、2026-09-24 夜。設計書6.5.10）。
 *
 * ## なぜ積むか
 *
 * 性格は外見と違い、**同時に成り立つ面を重ねて描かれる。** 第1話で
 * 「無愛想だが面倒見はよい」、第5話で「臆病」と読めたら、変わったのでは
 * なく別の面が見えただけである。以前のマージは性格を外見と同じ上書き型の
 * 1つの値として扱っていたので、
 *
 * - 違う話の値 →「作中の変化」として積まれ、本体は最後の話の一面に置き換わる
 *   （年表や紹介に、起きていない「性格の変化」が載る）
 * - 同じ話の中の2つの面 →「食い違い」として作者の判断待ちに止まる
 *
 * という形で、正しく読めた面を資料から押し流していた（縛りの洗い出し4番）。
 *
 * ## 本当に変わったもの
 *
 * 「臆病 → 勇敢になった」のような本当の変化もある。ただしそれを本文から
 * コードで見分けるのは難しい。**既定は積み、変化かどうかは作者が決める**
 * （設定資料パネルの「作中の変化にする」。`markPersonalityChange`）。
 *
 * ## 本体の値
 *
 * `personality` には、過去の面を除いた面を「／」でつないだ文章を持つ。
 * 資料・紹介・AIへの材料・用語の色分けはどれも本体を読むので、
 * 読む側を1つも書き換えずに全部の面が出る。
 *
 * **本体は「足す」「詳しくする」だけで組み直さない。** 作者や外の道具が
 * 本体を書き換えていても、その文章を消さずに面を足すためである
 * （CLAUDE.md 規則2）。作者が確定させた人物（`autoGenerated: false`）には、
 * そもそもマージが面を足さない。
 *
 * VS Code APIに依存しない。
 */

/** 本体で面をつなぐ記号 */
export const PERSONALITY_SEPARATOR = "／";

/** 比べるときは空白を無視する（「冷静 で」と「冷静で」を別の面にしない） */
function comparable(text: string): string {
  return text.replace(/\s+/g, "");
}

function sortedChapters(chapters: readonly number[]): number[] {
  return [
    ...new Set(chapters.filter((chapter) => Number.isSafeInteger(chapter))),
  ].sort((a, b) => a - b);
}

function firstChapter(chapters: readonly number[]): number {
  return chapters.length > 0 ? Math.min(...chapters) : -1;
}

/** 過去の面（作者が「変わった」と決めた面）を除いたもの */
export function activeFacets(
  facets: readonly PersonalityFacet[]
): PersonalityFacet[] {
  return facets.filter((facet) => !facet.supersededBy);
}

/** 面を本体の文章にする。1つも無ければ null */
export function composePersonality(
  facets: readonly PersonalityFacet[]
): string | null {
  const values = activeFacets(facets).map((facet) => facet.value);
  return values.length > 0 ? values.join(PERSONALITY_SEPARATOR) : null;
}

/**
 * 本体が、面をつないだものそのままか。
 *
 * **偽なら、本体は面の外で書き換えられている**（作者が手で直した・外の道具が
 * 書いた）。そのときは面から本体を組み立て直さない——書き換えた文章を消す
 * ことになる。巻き戻し（`personalityAsOf`）も面ではなく本体を信じる。
 */
export function isBodyComposedOfFacets(character: {
  personality: string | null;
  personalityFacets?: readonly PersonalityFacet[];
}): boolean {
  const facets = character.personalityFacets ?? [];
  if (facets.length === 0) return false;
  return (character.personality ?? null) === composePersonality(facets);
}

/** 本体を区切りで割る。区切りの前後の空白は落とす */
function segmentsOf(body: string | null): string[] {
  if (!body) return [];
  return body
    .split(PERSONALITY_SEPARATOR)
    .map((segment) => segment.trim())
    .filter((segment) => segment.length > 0);
}

/**
 * 本体へ面を足す。**既に文章の中にあれば足さない**（本体を書き換えた人が、
 * 同じことを別の区切りで書いていることがある）。
 */
function appendToBody(body: string | null, value: string): string {
  if (!body || !body.trim()) return value;
  if (comparable(body).includes(comparable(value))) return body;
  return `${body}${PERSONALITY_SEPARATOR}${value}`;
}

/**
 * 本体の中の1つの面を、詳しく書き直したものへ差し替える。
 * 区切りで割った1つとして見つからなければ、差し替えずに足す
 * （文章の途中を部分一致で書き換えると、別の面の言葉を壊しかねない）。
 */
function refineInBody(
  body: string | null,
  from: string,
  to: string
): string {
  const segments = segmentsOf(body);
  const index = segments.findIndex(
    (segment) => comparable(segment) === comparable(from)
  );
  if (index < 0) return appendToBody(body, to);
  segments[index] = to;
  return segments.join(PERSONALITY_SEPARATOR);
}

/**
 * 本体から1つの面を外す。区切りで割った1つとして見つからなければ
 * undefined（本体が書き換えられているので、こちらでは触らない）。
 */
function removeFromBody(
  body: string | null,
  value: string
): string | null | undefined {
  const segments = segmentsOf(body);
  const kept = segments.filter(
    (segment) => comparable(segment) !== comparable(value)
  );
  if (kept.length === segments.length) return undefined;
  return kept.length > 0 ? kept.join(PERSONALITY_SEPARATOR) : null;
}

/**
 * 抽出した性格を、面として人物へ足す。**渡したレコードを書き換える**
 * （マージの `applyExtracted` と同じ作法）。何か変わったら true。
 *
 * - 同じ面 → 話数だけ足す（根拠が無かった面には根拠を添える）
 * - 既存の面を詳しく書き直したもの（「臆病」→「臆病で人見知り」）→ 1つにまとめる
 *   （別の面として増やすと、同じ面が言い換えのたびに積み上がる）
 * - 既存の面に含まれるもの → その面の話数だけ足す
 * - それ以外 → 新しい面として足し、本体の末尾へつなぐ
 *
 * 過去の面（作者が「変わった」と決めた面）にまた当たったときは、話数を
 * 足すだけで本体へは戻さない——戻すのは作者の判断（`restorePersonalityFacet`）。
 *
 * 値が意味を持つか（「記述なし」でないか）は呼び出し側で確かめてから渡す。
 */
export function addPersonalityFacet(
  target: Character,
  value: string,
  chapters: readonly number[],
  evidence: string | null
): boolean {
  if (!target.personalityFacets) target.personalityFacets = [];
  const holder: FacetHolder = {
    facets: target.personalityFacets,
    body: target.personality,
  };
  const changed = addFacetTo(holder, value, chapters, evidence);
  target.personality = holder.body;
  return changed;
}

/**
 * 面の一覧と、それをつないだ本体の組。性格と口調（2026-09-25）が同じ規則で
 * 積むので、項目の名前から切り離して持つ。`addFacetTo` が直に書き換える。
 */
export interface FacetHolder {
  facets: PersonalityFacet[];
  body: string | null;
}

/**
 * 面を1つ足す（規則は `addPersonalityFacet` の説明のとおり）。
 * **渡した組を書き換える。** 何か変わったら true。
 */
export function addFacetTo(
  holder: FacetHolder,
  value: string,
  chapters: readonly number[],
  evidence: string | null
): boolean {
  const text = value.trim();
  if (!text) return false;
  const quote = evidence?.trim() || null;
  const dated = sortedChapters(chapters);

  // 面の仕組みより前に入った本体の値は、話を持たない最初の面にする。
  // 捨てると、以前に読めた値が次の抽出で本体から消える
  seedFacetsFromBody(holder);

  const facets = holder.facets;
  const key = comparable(text);
  const same = facets.find((facet) => comparable(facet.value) === key);
  if (same) return noteFacet(same, dated, quote);

  const contained = facets.find((facet) => comparable(facet.value).includes(key));
  if (contained) return noteFacet(contained, dated, quote);

  const refined = facets.find((facet) => key.includes(comparable(facet.value)));
  if (refined) {
    const from = refined.value;
    refined.value = text;
    refined.chapters = sortedChapters([...refined.chapters, ...dated]);
    // 書き直したほうの根拠を添える。値と根拠が食い違ったまま残さない
    if (quote) refined.evidence = quote;
    if (!refined.supersededBy) {
      holder.body = refineInBody(holder.body, from, text);
    }
    return true;
  }

  facets.push({ value: text, chapters: dated, evidence: quote });
  holder.body = appendToBody(holder.body, text);
  return true;
}

/** 既にある面へ話数と根拠を足す。何か変わったら true */
function noteFacet(
  facet: PersonalityFacet,
  chapters: readonly number[],
  evidence: string | null
): boolean {
  let changed = false;
  const merged = sortedChapters([...facet.chapters, ...chapters]);
  if (merged.length !== facet.chapters.length) {
    facet.chapters = merged;
    changed = true;
  }
  // 最初に読んだ一節を残す（取り違えを見抜く手掛かりが揺れないように）
  if (evidence && !facet.evidence) {
    facet.evidence = evidence;
    changed = true;
  }
  return changed;
}

/** 面が空で本体にだけ値があるなら、その値を話を持たない面にする */
function seedFacetsFromBody(holder: FacetHolder): void {
  if (holder.facets.length > 0) return;
  for (const segment of segmentsOf(holder.body)) {
    holder.facets.push({ value: segment, chapters: [], evidence: null });
  }
}

/**
 * 以前のマージが作った形を、面の形へ移す（古い形の資料の扱い）。
 * 移すものが無ければ undefined。**渡したレコードは書き換えない。**
 *
 * 0.86.0 までのマージは、性格を
 * - 違う話の値 → `changes`（作中の変化）に積み、本体を最後の話の値にする
 * - 同じ話の値 → `conflicts`（食い違い）にして作者の判断を待つ
 * としていた。どちらも、同時に成り立つ別の面だった見込みが高い
 * （作者の裁定）。**抽出が積んだ記録だけ**を面へ移し、年表から外す。
 *
 * **作者が決めた記録（`source: "author"`・`confirmed`）は変化として残す。**
 * 作者が「変わった」と認めたもので、こちらが面に戻してよいものではない。
 * その値も面に並べ、いちばん後ろの話のもの以外は過去の面にする。
 *
 * **作者が確定させた人物（`autoGenerated: false`）には使わない。**
 * 呼び出し側で除くこと（CLAUDE.md 規則2）。
 */
export function migratePersonalityFacets(
  character: Character
): Character | undefined {
  if ((character.personalityFacets ?? []).length > 0) return undefined;

  const isPersonality = (change: RecordChange): boolean =>
    change.field === "personality";
  const decidedByAuthor = (change: RecordChange): boolean =>
    change.source === "author" || change.confirmed === true;

  const extracted = character.changes.filter(
    (change) => isPersonality(change) && !decidedByAuthor(change)
  );
  const decided = character.changes.filter(
    (change) => isPersonality(change) && decidedByAuthor(change)
  );
  const conflict = character.conflicts.find(
    (entry) => entry.field === "personality"
  );
  // **移すものが無ければ触らない。** 本体だけを持つ古い記録まで毎回
  // 書き換えると、抽出のたびに全員が「更新」として承認待ちに並ぶ
  if (extracted.length === 0 && !conflict) return undefined;

  const collected: PersonalityFacet[] = [];
  const collect = (
    value: string,
    chapters: readonly number[],
    evidence: string | null | undefined
  ): void => {
    const text = value.trim();
    if (!text) return;
    const found = collected.find(
      (facet) => comparable(facet.value) === comparable(text)
    );
    if (found) {
      found.chapters = sortedChapters([...found.chapters, ...chapters]);
      found.evidence = found.evidence ?? (evidence?.trim() || null);
      return;
    }
    collected.push({
      value: text,
      chapters: sortedChapters(chapters),
      evidence: evidence?.trim() || null,
    });
  };

  for (const change of [...extracted, ...decided]) {
    collect(change.value, change.chapters, change.evidence);
  }
  if (conflict) {
    const observations = conflict.observations ?? [];
    for (const observation of observations) {
      collect(observation.value, observation.chapters, observation.evidence);
    }
    // 話数の記録が無い古い食い違いの値も拾う（値だけでも面として残す）
    for (const value of conflict.values) collect(value, [], null);
  }
  // 本体が記録のどれとも違う（詳しく書き直されていた等）なら、それも面にする
  const body = character.personality?.trim();
  if (body && !collected.some((facet) => comparable(facet.value) === comparable(body))) {
    const refined = collected.find((facet) =>
      comparable(body).includes(comparable(facet.value))
    );
    if (refined) refined.value = body;
    else if (!collected.some((facet) => comparable(facet.value).includes(comparable(body)))) {
      collect(body, [], null);
    }
  }

  // 古い順に並べる（話を持たない面は「それ以前」なので先頭）
  const facets = [...collected].sort(
    (left, right) => firstChapter(left.chapters) - firstChapter(right.chapters)
  );

  // 作者が認めた変化：いちばん後ろの話の値以外は、過去の面にする
  const decidedInOrder = [...decided].sort(
    (left, right) =>
      Math.max(-1, ...left.chapters) - Math.max(-1, ...right.chapters)
  );
  const latestDecided = decidedInOrder[decidedInOrder.length - 1];
  if (latestDecided) {
    for (const change of decided) {
      if (comparable(change.value) === comparable(latestDecided.value)) continue;
      const facet = facets.find(
        (entry) => comparable(entry.value) === comparable(change.value)
      );
      if (facet) facet.supersededBy = latestDecided.value.trim();
    }
  }

  return {
    ...character,
    personality: composePersonality(facets),
    personalityFacets: facets,
    // 抽出が積んだ性格の「変化」は面へ移したので外す。作者の決めた変化は残す
    changes: character.changes.filter(
      (change) => !(isPersonality(change) && !decidedByAuthor(change))
    ),
    conflicts: character.conflicts.filter(
      (entry) => entry.field !== "personality"
    ),
  };
}

/** 作者の操作の結果 */
export interface PersonalityDecision {
  /** 操作したあとの人物。**元のレコードは書き換えない** */
  character: Character;
  /**
   * 本体（`personality`）も書き換えたか。
   *
   * 偽なら、本体が面の外で書き換えられていて、どこを直せばよいか
   * 決められなかった。作者へ「性格の欄は手で直してください」と伝える
   */
  bodyUpdated: boolean;
}

function copyFacets(facets: readonly PersonalityFacet[]): PersonalityFacet[] {
  return facets.map((facet) => ({ ...facet, chapters: [...facet.chapters] }));
}

/**
 * 作者が「この面から、あの面へ作中で変わった」と決める。
 * どちらかの面が見つからない・同じ面を指したときは undefined（何もしない）。
 *
 * - 変わる前の面は**過去の面**になり、本体から外れる（記録には残る）
 * - 両方の面を、作者が認めた変化（`confirmed`）として `changes` へ記録する。
 *   年表・資料の「変化」に載るのは、こうして作者が決めたものだけになる
 *
 * `autoGenerated` は変えない。作者が触ったのは性格の読み方であって、
 * 人物全体を引き取ったわけではない（食い違いの昇格と同じ考え方）。
 */
export function markPersonalityChange(
  character: Character,
  beforeValue: string,
  afterValue: string
): PersonalityDecision | undefined {
  const facets = copyFacets(character.personalityFacets ?? []);
  const before = facets.find(
    (facet) => comparable(facet.value) === comparable(beforeValue)
  );
  const after = facets.find(
    (facet) => comparable(facet.value) === comparable(afterValue)
  );
  if (!before || !after || before === after) return undefined;
  if (before.supersededBy || after.supersededBy) return undefined;

  before.supersededBy = after.value;
  const removed = removeFromBody(character.personality, before.value);
  const toChange = (facet: PersonalityFacet): RecordChange => ({
    field: "personality",
    value: facet.value,
    chapters: [...facet.chapters],
    timepointId: null,
    note: null,
    evidence: facet.evidence,
    source: "extracted",
    confirmed: true,
  });

  return {
    character: {
      ...character,
      personalityFacets: facets,
      personality: removed === undefined ? character.personality : removed,
      changes: mergeChangeLists(character.changes, [
        toChange(before),
        toChange(after),
      ]),
    },
    bodyUpdated: removed !== undefined,
  };
}

/**
 * 過去の面を、いまも成り立つ面へ戻す（押し間違いの取り消し）。
 * その面が無い・過去の面でなければ undefined。
 *
 * **変化の記録（`changes`）は消さない。** 作者が一度認めた記録を、
 * 別の操作のついでに落とすと規則2に反する。要らなければ、パネルの
 * 「誤りを落とす」で作者が落とす。
 */
export function restorePersonalityFacet(
  character: Character,
  value: string
): PersonalityDecision | undefined {
  const facets = copyFacets(character.personalityFacets ?? []);
  const facet = facets.find(
    (entry) => comparable(entry.value) === comparable(value)
  );
  if (!facet || !facet.supersededBy) return undefined;
  delete facet.supersededBy;
  const personality = appendToBody(character.personality, facet.value);
  return {
    character: { ...character, personalityFacets: facets, personality },
    bodyUpdated: personality !== character.personality,
  };
}

/** 面の最初に見えた話。話を持たない面は「それ以前」（0扱い） */
function firstSeen(facet: PersonalityFacet): number {
  return facet.chapters.length > 0 ? Math.min(...facet.chapters) : 0;
}

/**
 * 第N話の時点で見えていた性格（設計書6.10.3の巻き戻しを、面で行う）。
 *
 * **面で巻き戻せないときは undefined**（呼び出し側は変化の記録で巻き戻す）。
 * 面が無い古い資料と、本体が面の外で書き換えられている資料がそれに当たる
 * ——後者で面から組み立てると、作者の書いた本体を黙って無視する。
 *
 * - まだ見えていない面（最初に見えた話がNより後）は入れない
 * - 過去の面は、変わった先の面がNまでに見えていれば入れない
 *   （まだ変わっていない話では、その面が本体にあった）
 */
export function personalityAsOf(
  record: {
    personality: string | null;
    personalityFacets?: readonly PersonalityFacet[];
  },
  chapter: number
): string | null | undefined {
  if (!isBodyComposedOfFacets(record)) return undefined;
  const facets = record.personalityFacets ?? [];
  const seenBy = (facet: PersonalityFacet): boolean => firstSeen(facet) <= chapter;
  const visible = facets.filter((facet) => {
    if (!seenBy(facet)) return false;
    if (!facet.supersededBy) return true;
    const successor = facets.find(
      (entry) => comparable(entry.value) === comparable(facet.supersededBy ?? "")
    );
    // 変わった先の面が見当たらなければ、過去の面のまま外す
    return successor !== undefined && !seenBy(successor);
  });
  return visible.length > 0
    ? visible.map((facet) => facet.value).join(PERSONALITY_SEPARATOR)
    : null;
}

/**
 * 第N話より**あと**で見えた面（設計書6.10.4）。面で扱えないときは undefined。
 */
export function personalityRevealedAfter(
  record: {
    personality: string | null;
    personalityFacets?: readonly PersonalityFacet[];
  },
  chapter: number
): Array<{ value: string; chapter: number }> | undefined {
  if (!isBodyComposedOfFacets(record)) return undefined;
  return (record.personalityFacets ?? [])
    .filter((facet) => facet.chapters.length > 0 && firstSeen(facet) > chapter)
    .map((facet) => ({ value: facet.value, chapter: firstSeen(facet) }));
}
