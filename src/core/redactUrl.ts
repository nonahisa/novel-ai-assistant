/**
 * URLに埋め込まれた資格情報を落とす。
 *
 * GitHubは「トークンをURLに書く」形（`https://<トークン>@github.com/...`）を
 * 案内することがあり、作者がそのまま貼ることがある。そのURLは
 * **リモートの登録・送信・取り寄せのたびにログへ書かれる**ので、
 * 作者がログを貼って助けを求めた時点で漏れる。
 *
 * **消すのは `//` のあとの資格情報だけ。** 文中の `@` をまとめて潰すと、
 * コミットする人のメールアドレスまで消えてログが読めなくなる。
 *
 * 形（`***@`）は残す——「鍵が埋め込まれたURLだった」ことが分かるほうが、
 * 認証まわりの失敗を追うときに役に立つ。
 */
const URL_CREDENTIAL = /([A-Za-z][A-Za-z0-9+.-]*:\/\/)[^/\s@]+@/g;

/**
 * 伏せたことを示す印。
 *
 * **アスタリスク3つを文字列にじかに書かない。** 画面へ出す文言に
 * Markdownの強調が混ざっていないかを見張る検査
 * （`test/unit/plainTextUi.test.ts`）が、`**` を含む文字列を拾うためである。
 * ここでの意味は強調ではなく伏せ字なので、組み立てて渡す。
 */
const MASK = "*".repeat(3);

export function redactUrlCredentials(text: string): string {
  return text.replace(URL_CREDENTIAL, `$1${MASK}@`);
}
