export const SETUP_PROMPT_NAME = "setup";
export const SETUP_PROMPT_TITLE = "小説の執筆環境をセットアップ";
export const SETUP_PROMPT_DESCRIPTION =
  "統合小説執筆環境（VS Code 拡張機能）の初期設定を、作者に聞き取りながら順に進めます。" +
  "最初の作品の作成・登録と、使うAIの準備まで。";

/** 段の説明の1行（表から引く） */
function stepLine(step: SetupStep): string {
  const def = SETUP_STEPS.find((entry) => entry.step === step);
  if (!def) throw new Error(`手順書が知らない段を指しています: ${step}`);
  const args = def.accepts.length > 0 ? `。引数：${def.accepts.join("・")}` : "";
  return `- \`step: "${def.step}"\`（${def.label}）——${def.purpose}${args}`;
}

