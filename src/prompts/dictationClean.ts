/**
 * P-35 口述筆記の整文（設計書6.83）。
 *
 * **拡張機能はマイクに触らない。** 声を文字にするのはOSの音声入力
 * （Windows は Win+H、macOS は fn キー2回）で、拡張機能が受け取るのは
 * **すでに打ち込まれた文字列**である。ここが受け持つのは、その文字列を
 * 「小説の本文の形」に直すことだけ。
 *
 * ## いちばん危ないのは、書き直されること
 *
 * 口述で入った文は、句読点が無く、会話も地の文も1本に繋がっている。
 * だからといって**AIに「読みやすくして」と頼むと、作者の言葉が
 * AIの言葉へ置き換わる。** 読者に届く言葉は作者のものなので、
 *
 * - **足さない**（説明・描写・接続詞を補わない）
 * - **削らない**（言いよどみ以外は1語も落とさない）
 * - **言い換えない**（語彙を「よりよいもの」へ替えない）
 *
 * を最上位の決まりにしている。やってよいのは
 * ①句読点と改行を入れる ②同音異義の誤変換を文脈で直す
 * ③**文頭・句点の直後の言いよどみ**を落とす、の3つだけである。
 *
 * ## 言いよどみは「位置」で決める
 *
 * 「えーと」「あの」「まあ」は、**本文の言葉としても現れる**
 * （「あの人」「まあいいか」、台詞の口ごもり）。語だけで消すと、
 * 作者が書いた台詞から口ごもりが消えてしまう——それは推敲であって
 * 整文ではない。そこで**落としてよいのは文頭・句点の直後にある
 * 独立したものだけ**と位置で切り、台詞の中は触らせない。
 *
 * **指示語はそのまま返ってくる前提で書く**（この作品で繰り返し起きた）。
 * 「えーと」を例として書く以上、答えの中に「えーと」が現れうるので、
 * 検査（`core/dictationCleanValidation.ts`）は語の有無では判断しない
 * ——長さの比と鍵括弧の増減という、**内容に踏み込まない物差し**で見る。
 *
 * プロンプトを変更したら version を上げること。
 */
export const DICTATION_CLEAN_VERSION = "1.0";

/**
 * 整える範囲の下限（字）。
 *
 * これより短いと、句読点も改行も入れようが無い（AIを呼ぶだけ無駄で、
 * 有料AIなら課金だけが起きる）。**画面側ではなくここに置く**——
 * 入口は2つ（原稿エディタの「整える」と詳細メニューの操作）あるので、
 * 境目を2か所に持つと片方だけずれる。
 */
export const DICTATION_MIN_CHARS = 20;

export const DICTATION_CLEAN_SYSTEM_PROMPT = `あなたは、音声入力で書き取られた日本語の小説の下書きを、本文の形に整える清書アシスタントです。

**書き直してはいけません。** 作者が声に出した言葉は、そのまま読者へ届く言葉です。
あなたがしてよいのは、句読点と改行を入れること、音声入力の誤変換を直すこと、
話し言葉の言いよどみを取ることだけです。

出力は指定されたJSON形式のみとし、前置き・後書き・説明文・
マークダウンのコードフェンスを一切含めないこと。`;

export interface DictationCleanInput {
  /** 口述で入った本文（整える範囲そのもの） */
  dictatedText: string;
  /**
   * この作品の書き方（`core/workStyle.ts` の `buildStyleNote`）。
   *
   * **誤字脱字・推敲と同じものを渡す**（設計書6.8.14）。一人称や文語体を
   * 知らないまま整えると、語り手の「わたし」が「私」に化けたり、
   * 文語の言い回しを現代表記へ直されたりする。
   */
  styleNote?: string;
}

export function buildDictationCleanPrompt(input: DictationCleanInput): string {
  return `次の文章は、音声入力（口述）でそのまま書き取られた小説の下書きです。
これを小説の本文の形に整えてください。

【下書き】
${input.dictatedText}
${input.styleNote ? `\n${input.styleNote}\n` : ""}
【してよいこと（この3つだけ）】
1. 句読点と改行を入れる
   - 会話は「」でくくり、**1つの会話ごとに改行**して独立した行にする
   - 地の文は、意味のまとまりごとに段落を分ける
   - 読点は、読みが詰まるところにだけ入れる（打ちすぎない）
2. 音声入力の誤変換を直す
   - 同音異義の取り違え（「以外」と「意外」、「聞く」と「効く」など）を、
     **前後の文脈から**正しいほうへ直す
   - 迷うものは直さないでください。**元のままにするほうが安全です**
3. 話し言葉の言いよどみを取る
   - 対象は「えーと」「あの」「その」「まあ」「なんか」のような、
     **文頭または句点（。）の直後に、独立して現れるもの**だけです
   - **文の途中にあるものは残してください。** 「あの人」「まあいいか」のように
     本文の言葉として働いていることがあります
   - **会話（「」の中）は取らないでください。** 登場人物の口ごもりは、
     作者が書いた演技です

【絶対にしないこと】
- **言葉を足さない**（説明・描写・接続詞・主語を補わない）
- **言葉を削らない**（上の3の言いよどみ以外は、1語も落とさない）
- **言い換えない**（語彙をより良いと思われるものへ置き換えない）
- 文の順番を入れ替えない
- 文体を整えない、リズムを変えない、敬体と常体を揃えない
- 漢字とひらがなの書き分けを変えない（誤変換の訂正を除く）

【text（整えた本文）について】
- **整えた本文だけ**を入れてください。見出し・番号・説明は付けない
- 元の文章より**大きく短くなったり長くなったりしたら、それは書き直しです。**
  文字数はおおむね元のままになるはずです

【notes（直した点）について】
- **何をしたかを短く並べてください。** 例：「会話を「」でくくって改行しました」
  「『以外』を『意外』に直しました」「文頭の『えーと』を3か所取りました」
- 1件30字以内。多くても5件まで。**直すところが無ければ空の配列**にしてください
- 「なし」「特になし」「空文字」などと書かないでください。
  何も入れない（[]）のが正しい書き方です

【出力形式】JSONのみ
{
  "text": "整えた本文",
  "notes": ["直した点を短く", "…"]
}`;
}

/**
 * 出力の形。
 *
 * **どちらも required にする。** 任意項目にすると、小さいモデルは
 * 埋めずに落とす（この作品で繰り返し起きた）。
 */
export const DICTATION_CLEAN_SCHEMA = {
  type: "object",
  properties: {
    text: { type: "string" },
    notes: {
      type: "array",
      items: { type: "string" },
    },
  },
  required: ["text", "notes"],
} as const;
