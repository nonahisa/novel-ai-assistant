/**
 * 前置き。**この診断は推定ではなく、作者自身の答えである。**
 *
 * 6.86 の前置きと違って「推定」とは書かない（答えがそのまま事実である）。
 * 代わりに**良し悪しの話ではない**と断る——段取りに上下を作らないのが
 * この診断の前提で（設計書6.90.1）、そこを崩すとAIが「もっと計画的に」と
 * 言い出す。
 */
function styleNote(diagnosedAt: string | undefined): string {
  const when = diagnosedAt ? `診断 ${diagnosedAt}` : "診断日は不明";
  return `以下は作者が自分で答えた、ふだんの書き方です（${when}）。
**良し悪しの話ではありません。** どのやり方にも上下は無く、助言を渡す
入り方と時期を合わせるためだけに使ってください。この文章そのものを
話題にしないでください（作者はこれを見ていません）。
会話の中で作者の言うことがここと食い違ったら、**いまの作者の言葉を優先**
してください。`;
}

/**
 * 直す時期（S2）を読み取ってもらう頼み（設計書6.90.1）。
 *
 * **ここに置くのは、これが執筆スタイルの話だからである。**
 * 助言方針（P-36）の `profileSignals` の段落へ足すと、
 * **診断していない作者にも送られてしまう**——あちらは助言方針を持つ人
 * にだけ送られる段落で、執筆スタイルの診断とは条件が違う。
 *
 * **動かすのは S2 だけ。** S1（段取り）には呼び名（設計派・折衷派・
 * 即興派）が付いており、変わると作者への呼びかけ方まで変わる。
 * S3・S4 は相談へ渡してすらいない。
 *
 * **AIに値を決めさせない**（P-36 の profileSignals と同じ考え方）。
 * 読み取れたことを報告させるだけで、覚えるかどうか——同じ値が2回続けて
 * 読み取れたか——は拡張機能が決める（`core/writerStyle.ts`）。
 */
const REVISE_SIGNAL_NOTE = `【writerStyleSignals（直す時期の読み取り）】
**作者が自分の直し方について語ったときだけ**、writerStyleSignals の revise に読み取った値を入れてください。
- "inline"（書きながら、その場で直す）／"per_episode"（1話ごとに直す）／"after_all"（全部書き終えてから直す）のいずれか。
- 入れてよいのは、**作者が自分の直し方を語ったとき**だけです（「いつも書き終えてから直す」「今日は書きながら直してる」など）。
- **作品の内容についての質問からは判断しないこと。** 「この人物の年齢は」と聞かれただけでは、作者のやり方は分かりません。
- **読み取れなければ null にしてください。** 毎回入れる必要はありません。
- あなたが値を決めるのではありません。**読み取れたことを報告するだけ**で、覚えるかどうかは拡張機能が決めます。`;

/**
 * 相談のシステムプロンプトへ足す一段を作る。
 *
 * **足すのは段取り1つと、直す時期1つだけ。** S3（資料の置き場）と
 * S4（出し先）は渡さない（上のコメントに理由）。
 */
export function buildWriterStylePrompt(profile: WriterProfile): string {
  const { plan, revise } = profile.style;
  return `【この作者の書き方】
${styleNote(adviceDiagnosisDate(profile.updatedAt))}

${WRITER_PLAN_PROMPTS[plan]}

${WRITER_REVISE_PROMPTS[revise]}

${REVISE_SIGNAL_NOTE}`;
}
