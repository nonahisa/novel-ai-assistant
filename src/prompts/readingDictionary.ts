/**
 * P-50 読み上げの読みの辞書（設計書6.42.1）。
 *
 * ## 何をさせるか
 *
 * 読み上げ（音読推敲）の声は、**読みが2通り以上ある語**を取り違える
 * （「その音」を「そのおん」、時間の「十分以上」を「じゅうぶんいじょう」）。
 * 声の側では直らないので、その話の本文をAIに読ませ、**取り違えやすい語だけ**を
 * 「その語を含む本文の句」と「その場所での読み」で返させる。
 *
 * ## 句で返させる理由
 *
 * 同じ語でも文で読みが変わる（十分＝じっぷん／じゅうぶん）。語だけを返させると
 * どの「十分」の話か分からないので、**本文の連続した引用**を一緒に返させ、
 * コードが本文と照合して当てる場所を決める（`core/readingDictionary.ts`）。
 *
 * ## 拾わせないもの
 *
 * 読みが1通りしかない語・人名・作者がルビを振った所。拾わせすぎると一覧が
 * 長くなるうえ、声が正しく読んでいた語を辞書の読み違いで壊す。
 *
 * **指示語はそのまま返ってくる前提で書く**（この作品で繰り返し起きた）。
 * 読みの欄に「ひらがな」「読み」が入って返ることを、検算が捨てる。
 *
 * プロンプトを変更したら version を上げること。
 */
export const READING_DICTIONARY_VERSION = "1.0";

/**
 * 1回に送る本文の上限（字）。
 *
 * 1話（数千字）をまとめて送ると、小さいモデルは前半だけを見て終える。
 * 行の切れ目で区切って送る（`core/readingDictionary.ts` の `readingChunksOf`）。
 */
export const READING_DICTIONARY_CHUNK_CHARS = 2000;

/**
 * 例に挙げる語。**ここだけが持つ**（プロンプトと設計書の例を揃える）。
 * 例は答えとして返ってきてよい（本文にあれば正しい答えである）。
 */
export const READING_DICTIONARY_EXAMPLES = [
  "十分（じっぷん／じゅうぶん）",
  "音（おと／おん）",
  "一日（ついたち／いちにち）",
  "人気（にんき／ひとけ）",
  "上手（じょうず／うわて）",
  "大家（おおや／たいか）",
  "生物（せいぶつ／なまもの）",
  "風車（ふうしゃ／かざぐるま）",
  "今日（きょう／こんにち）",
  "何人（なんにん／なにじん）",
] as const;

export const READING_DICTIONARY_SYSTEM_PROMPT = `あなたは、日本語の小説を音声で読み上げる前に、読み間違えやすい語を確かめる校閲者です。
読み上げの声は、読みが2通り以上ある語を、文脈を見ずに取り違えます。
あなたの仕事は、そうした語を本文から見つけ、その場所での正しい読みを示すことだけです。

出力は指定されたJSON形式のみとし、前置き・後書き・説明文・
マークダウンのコードフェンスを一切含めないこと。`;

export interface ReadingDictionaryInput {
  /** 送る本文（1区切り） */
  text: string;
}

export function buildReadingDictionaryPrompt(input: ReadingDictionaryInput): string {
  return `次の本文から、**読みが2通り以上あり、文脈によって読みが変わる語**を探し、
その場所での正しい読みを答えてください。

【本文】
${input.text}

【探す語の例】
${READING_DICTIONARY_EXAMPLES.map((example) => `- ${example}`).join("\n")}
- 例えば「十分以上待った」の十分は時間なので「じっぷん」、「それで十分だ」の十分は「じゅうぶん」です

【答えに入れないもの】
- 読みが1通りしかない語（「学校」「歩く」など）
- 人名・地名などの固有名詞
- ルビ（｜漢字《かんじ》や {漢字|かんじ} の形）が振ってある語
- 迷う語。**確かなものだけ**を入れてください。無ければ空の配列にします

【各項目の書き方】
- word：その語（本文に書かれているとおりの字）
- quote：その語を含む、本文からそのまま写した短い句（6〜20字ほど）。
  **本文の字を1字も変えずに写してください。** 句の中に改行を入れないでください。
  word だけを quote にしないでください（前後の字を含めます）
- reading：その場所での word の読み。**ひらがなだけ**で書きます。
  quote 全体ではなく、word の部分だけの読みです

【出力形式】JSONのみ
{
  "items": [
    { "word": "十分", "quote": "十分以上待った", "reading": "じっぷん" }
  ]
}`;
}

/**
 * 出力の形。
 *
 * **項目の欄はすべて required にする。** 任意にすると小さいモデルは
 * 埋めずに落とす（この作品で繰り返し起きた）。
 */
export const READING_DICTIONARY_SCHEMA = {
  type: "object",
  properties: {
    items: {
      type: "array",
      items: {
        type: "object",
        properties: {
          word: { type: "string" },
          quote: { type: "string" },
          reading: { type: "string" },
        },
        required: ["word", "quote", "reading"],
      },
    },
  },
  required: ["items"],
} as const;
