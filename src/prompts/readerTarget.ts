/**
 * P-38 ターゲット読者の実像を読む（設計書6.91）
 *
 * 作者の依頼（2026-09-13）：「作者の分類と同じように、ターゲット読者の
 * 分類も行えないでしょうか？」
 *
 * ## なぜAIに読ませるのか
 *
 * 宣言（9問）だけでは**願望が出る**。「誰に読んでほしいですか」に返って
 * くるのは宛先ではなく望みで、書けているものとは限らない。だから
 * **本文のほうからも測って、ズレを出す。**
 *
 * ## 何を読ませて、何を読ませないか
 *
 * 読ませるのは**3つの軸の点数と、その根拠になった本文の一文**だけである。
 *
 * - **タイプ名を決めさせない。** 11タイプのどれかを選ばせると、名前に
 *   引きずられて点数が後付けになる。名前は点数から機械が決める
 *   （`resolveReaderType`）。P-36で「タイプは決めさせない」としたのと同じ
 * - **良し悪しを言わせない。** 「この作品は説明が多すぎる」は評価であって
 *   読者像ではない。作者は自分の作品の値踏みを頼んでいない
 * - **根拠は本文からの引用に限る。** 引用が本文に実在するかは
 *   `core/groundedEvidence.ts` と同じ考え方でコード側が照合する。
 *   実在しない引用を添えた軸は、点数ごと捨てる
 *
 * ## 点数の意味をプロンプトに書き下す
 *
 * 0〜6の数だけ渡しても、モデルによって物差しが変わる。**0点・3点・6点が
 * それぞれどういう作品かを例で示す。** 例が無いと、どのモデルも中央
 * （3点前後）へ寄せて、ズレが一度も出なくなる。
 *
 * プロンプトを変更したら version を上げること。
 */
