/**
 * 読者の区分の一覧（作者の実機報告、2026-09-21）。
 *
 * 相談で「読者型はわかりませんか？」と聞くと、年齢・性別といった一般論が
 * 返ってきた。**この拡張機能が使っている区分を、AIが1つも知らないため**
 * である（相談へ渡していたのは、診断済みの作品の「その1タイプ」だけ）。
 *
 * ## 渡すのは名前と一言だけ
 *
 * `READER_TYPE_PROMPTS`（タイプ別の書き方の方針）は渡さない。**あれを
 * 全タイプぶん送ると、AIが「短く引きの強い話」と「長く余韻のある話」を
 * 混ぜて勧めてくる**（どちらも書いてあるので、実際そう読める）。
 * ここで要るのは「そういう区分がある」と分かることだけなので、
 * **名前と一言に絞れば引きずられない。**
 *
 * ## 写しを書かない
 *
 * 名前も一言も `READER_TYPES` から組む。ここへ文章を書き写すと、
 * 区分の言い回しを直したときに片方だけが古いまま残る。
 */
export function buildReaderTypeGlossary(): string {
  const lines = (Object.keys(READER_TYPES) as ReaderTypeId[]).map(
    (id) => `- ${READER_TYPES[id].label}……${READER_TYPES[id].summary}`
  );
  return lines.join("\n");
}

