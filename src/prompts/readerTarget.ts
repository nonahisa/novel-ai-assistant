/**
 * **読者について聞かれた回にだけ**添える一段（設計書6.91.9.2）。
 *
 * 自分のタイプだけを渡していると、AIは「隣の区分と比べてどうか」に答えられ
 * ない（ほかの区分の名前を一度も見ていないため）。聞かれた回に限って一覧を
 * 添えれば、比べられるようになる。**毎回は添えない**——読者の話でない回に
 * まで送ると、助言の向きが11の区分のあいだで揺れる。
 *
 * **決めている作品にも、決めていない作品にも同じ絞り方で添える**（作者の
 * 裁定、2026-09-21）。だから文面は**どちらでも読める**ように書く——
 * この作品の区分は上の【この作品の読者】にあり、決めていなければ
 * そこに「まだ決めていません」と書いてある。
 */
export function buildReaderTypeGlossaryPrompt(): string {
  return `【読者の区分】この拡張機能で「読者」と言うときは、次の区分のことです。
この作品がどの区分かは、上の【この作品の読者】に書いてあります。
**そこに書かれていない区分を、あなたがこの作品の読者だと決めないでください。**
比べるときにだけ、この一覧を使ってください（どの区分にも上下はありません）。

${buildReaderTypeGlossary()}`;
}

/**
 * 作者の質問が、読者の話かどうか。
 *
 * **語をひとつ見るだけにする。** 「読者型」「読者層」「想定読者」「読者像」
 * と言い方は揺れるが、どれにも「読者」が入る。凝った判定にすると、
 * 当たらなかったときに理由が分からなくなる。
 */
export function questionMentionsReader(question: string): boolean {
  return question.includes("読者");
}

/**
 * 前置き。**どこから出した読者像かを断る。**
 *
 * 宣言は作者の答え、実像はAIが本文から読んだ点数で、**当たり方が違う**。
 * 実像のほうは「読み違えていることがある」と断らないと、AIが作品の性質を
 * 動かせない前提として扱ってしまう。
 *
 * 6.86 の前置きと同じで、**この文章そのものを話題にさせない**
 * （作者はこれを見ていない）。
 */
function readerNote(source: ReaderChatSource, diagnosedAt: string | undefined): string {
  const when = diagnosedAt ? `診断 ${diagnosedAt}` : "診断日は不明";
  const origin =
    source === "declared"
      ? `作者が「この読者に向けて書いている」と答えた宛先です（${when}）`
      : `本文とプロットから読み取った、この作品の向き先の推定です（${when}）。読み違えていることがあります`;
  return `以下は${origin}。
助言をどこへ向けるかの目安にだけ使い、**作品の良し悪しの話にしないでください。**
どの読者層にも上下はありません。この文章そのものを話題にしないでください
（作者はこれを見ていません）。
会話の中で作者が想定読者について語ったことがここと食い違ったら、
**いまの作者の言葉を優先**してください。`;
}

/**
 * 相談のシステムプロンプトへ足す一段を作る（設計書6.91.9）。
 *
 * **足すのは該当するタイプの文章1つだけ。** 11タイプ分を毎回送ると
 * 数千字が積み上がり、しかも他のタイプの記述に引きずられる。
 *
 * 診断していなければ `undefined`——**何も足さない**（相談は止めない）。
 * どちらの欄を使うかは `chatReaderBasis` が決める（写しを作らない）。
 */
export function buildReaderTypePrompt(
  profile: ReaderProfile | undefined
): string | undefined {
  const basis = chatReaderBasis(profile);
  if (!basis) return undefined;

  return `【この作品の読者】
${readerNote(basis.source, adviceDiagnosisDate(basis.updatedAt))}

${READER_TYPE_PROMPTS[resolveReaderType(basis.scores)]}`;
}
