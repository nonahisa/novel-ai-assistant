export function buildReaderTargetPrompt(
  input: ReaderTargetPromptInput
): string {
  const axes = READER_AXIS_ORDER.map((axis) => {
    const ruler = AXIS_RULER[axis];
    const ends = READER_AXIS_ENDS[axis];
    return [
      `■ ${axis}（${READER_AXIS_LABELS[axis]}）：0＝${ends.low} ／ 6＝${ends.high}`,
      `  0点に近い作品：${ruler.zero}`,
      `  3点の作品：${ruler.three}`,
      `  6点に近い作品：${ruler.six}`,
    ].join("\n");
  }).join("\n\n");

  const sections = [
    `【作品タイトル】\n${input.workTitle}`,
    input.plot.trim() ? `【プロット】\n${input.plot.trim()}` : "",
    input.logline.trim() ? `【ひとことの粗筋】\n${input.logline.trim()}` : "",
    `【冒頭の本文】\n${input.openingExcerpt.trim()}`,
  ].filter(Boolean);

  return `以下の作品を読んで、3つの軸それぞれに0〜6の点数を付けてください。

${axes}

【答え方】
- 3つの軸すべてに、0〜6の整数の点数を付けてください。
- それぞれの軸について、そう判断した根拠を**渡された文章から${READER_EVIDENCE_MAX_CHARS}字以内でそのまま引き写し**、どこから取ったか（「冒頭の本文」「プロット」「ひとことの粗筋」）を添えてください。引き写しでない文（あなたが書いた要約や説明）は捨てられます。
- 判断の材料が足りない軸は、点数3にして根拠を空にしてください。無理に決めないでください。
- 作品の良し悪しには触れないでください。

${sections.join("\n\n")}`;
}

