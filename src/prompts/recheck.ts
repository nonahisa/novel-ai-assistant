/**
 * P-23 指摘の再チェック（提案パネル）。
 *
 * 作者の依頼（2026-08-27）：「推敲について、なおし方を作者が決める系の
 * ものは『再チェック』ボタンを追加してください。なおして解消されたか
 * 確認したいです」「誤字脱字の提案パネルでも、違うそうじゃないという
 * 提案がきます。手書きで書き直して解消したか確認したいです」。
 *
 * ## 検知をやり直すのとは違う
 *
 * 誤字脱字（P-09）も推敲（P-10）も、作品まるごとを何十チャンクにも割って
 * 走らせる。**1件を確かめるために全部を走らせ直すのは高い**（クラウドAIでは
 * そのまま料金になる）。こちらは1件だけを見るので、渡すのは該当箇所の前後と
 * 元の指摘だけで足りる。
 *
 * ## 「まだ在るか」はコードで見る。AIに聞くのは変わったあとだけ
 *
 * 作者が直し忘れていれば、指摘が引用した文がそのまま本文に残っている。
 * それは照合で分かるので、そこではAIを呼ばない
 * （`features/recheckProposal.ts` の `isQuoteStillPresent`）。
 *
 * ## 答えは真偽値で受ける
 *
 * 「解消」「未解消」のような日本語のラベルを値にすると、**指示の言葉が
 * そのまま返ってくる**（この作品で繰り返し起きている。`CLAUDE.md`）。
 * ラベルの表記ゆれ（「解消済み」「解消。」など）を毎回コードで吸収する
 * ことになるので、真偽値だけを受け取る。
 *
 * ## 直し方は問わない
 *
 * 作者は自分の言葉で書き直す。**元の修正案どおりに直っているかを見るのでは
 * ない。** 問題が無くなっていれば解消である——ここを外すと、作者が別の言い方で
 * 直したものを毎回「まだ残っている」と言うだけの機能になる。
 *
 * プロンプトを変更したら version を上げること。
 */

// 1.0: 新設
export const RECHECK_VERSION = "1.0";

export const RECHECK_SYSTEM_PROMPT = `あなたは日本語の小説を見る校閲者です。

**すでに出した指摘が、書き直されたあとの本文にまだ当てはまるかどうかだけを判断します。**
新しい指摘を探す必要はありません。

【絶対に守る原則】
1. 判断の材料は、渡された本文の抜粋だけです。抜粋に無いことを推測で補わないこと。
2. 作者の文体・表現の好みを尊重すること。あなたの好みで書き換えを求めないこと。
3. 作品世界の設定（造語、固有名詞、独自の言い回し）を誤りとして扱わないこと。
4. **直し方が元の修正案と違っていても、問題が無くなっていれば解消です。**
   作者は自分の言葉で書き直します。元の案どおりかを見るのではありません。
5. 出力は指定されたJSON形式のみとし、前置き・後書き・説明文・
   マークダウンのコードフェンスを一切含めないこと。`;

export interface RecheckInput {
  /** どの検知から出た指摘か（「誤字脱字」「推敲」など） */
  category: string;
  /** どのファイルか。作者が場所を思い出すための手掛かり */
  fileName: string;
  /** 指摘が引用していた本文（誤字脱字なら行、推敲なら一文） */
  quote: string;
  /** 引用の中で、実際に問題とされた範囲 */
  target: string;
  /** なぜ直したいか */
  reason: string;
  /** そのときの修正案。**無いことがある**（直し方を作者が決める指摘） */
  suggestion: string;
  /** 該当箇所の前後（行番号付き） */
  contextWithLineNumbers: string;
}

export function buildRecheckPrompt(input: RecheckInput): string {
  // 修正案の無い指摘（推敲の「長すぎる文」など）では、この行ごと出さない。
  // 「（なし）」と書くと、それ自体が判断材料であるかのように読まれる
  const suggestion = input.suggestion.trim()
    ? `\n- そのときの修正案: 「${input.suggestion}」`
    : "";

  return `次の指摘が、いまの本文にまだ当てはまるかを判断してください。

【ファイル】${input.fileName}
【指摘の種類】${input.category}

【元の指摘】
- 指摘された箇所: 「${input.quote}」
- そのうち問題とされた部分: 「${input.target}」
- 理由: ${input.reason}${suggestion}

【いまの本文】（該当箇所の前後）
${input.contextWithLineNumbers}

【判断のしかた】
- 「いまの本文」を読み、元の指摘が指していた問題がまだ残っているかを見てください。
- 問題が無くなっていれば resolved を true にしてください。
  **直し方が元の修正案と違っていてもかまいません。**
- まだ残っていれば resolved を false にしてください。
- 指摘された箇所が本文に見当たらない（丸ごと書き直された、削られた）ときは、
  その指摘はもう当てはまらないので true にしてください。
- **別の新しい問題を見つけても、ここでは報告しないでください。** 聞かれているのは
  この指摘1件のことだけです。

【出力形式】JSONのみ

{
  "resolved": true または false（真偽値。文字列で書かないこと）,
  "reason": "そう判断した理由（60字以内）。まだ残っているなら、いまの本文のどこが問題かを書く"
}`;
}

/**
 * 出力の形。
 *
 * **どちらも required にする。** 任意項目にすると、小さいモデルは
 * 埋めずに落とす（この作品で繰り返し起きた）。
 */
export const RECHECK_SCHEMA = {
  type: "object",
  properties: {
    resolved: { type: "boolean" },
    reason: { type: "string" },
  },
  required: ["resolved", "reason"],
} as const;
