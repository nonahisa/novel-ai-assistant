/**
 * 「これは推定である」と断る段落。
 *
 * **タイプ別の文章の中には書かない**（作者の裁定、2026-09-07）。
 * 11タイプすべてに同じ断りを写すと、直すとき11か所になる。
 * 共通の1段落として、タイプの文章の前に置く。
 *
 * **いまの言葉を推定より優先させる。** 人は変化するので、診断は
 * 古くなる。作者が会話の中で自分について語ったことと食い違ったら、
 * そちらが正しい。
 */
function estimationNote(diagnosedAt: string | undefined): string {
  const when = diagnosedAt ? `診断 ${diagnosedAt}` : "診断日は不明";
  return `以下は作者の自己申告（${when}）からの**推定**であり、古くなっていることがあります。
助言の入り方と強さの調整にだけ使い、方針そのものを話題にしないでください
（作者はこの文章を見ていません）。
会話の中で作者が自分について語ったことが、この推定と食い違った場合は
**いまの作者の言葉を優先**してください。そのうえで、options に
「相談の助言方針を診断し直したい」を1つ添えて構いません（毎回は添えないこと）。

【profileSignals（推定を少しずつ直すための項目）】
**作者の今回の発言から変化が読み取れたときだけ**、profileSignals を入れてください。
- reader / self / taste：**-1・0・+1 の弱い傾向まで。** 読者の数字や届け方の話を
  作者が自分から出したら reader は +1、読者を意識しない発言なら -1、という程度です。
  自分の主張や作品への思い入れが前に出たら self、題材そのものへの熱が出たら taste。
- acceptance（受容度）：こちらの指摘への反応から読み取れたときだけ。
  掘り下げたがっていれば "high"、選びたい構えなら "mid"、
  指摘より感想を求めていれば "low"。
- confidence（自信度）：作品への自己評価から読み取れたときだけ。
  弱点を自分で言えていれば "high"、迷いが見えれば "mid"、
  「面白くないのでは」が出れば "low"。
- **読み取れなければ、その項目を省いてください。** 毎回入れる必要はありません。
- **作品の内容についての質問からは判断しないこと。** 「この人物の年齢は」と
  聞かれただけで作者の志向は分かりません。
- あなたはタイプを決めません。**弱い傾向を報告するだけ**で、
  点数の計算はこちら（拡張機能）が行います。`;
}

/**
 * 相談のシステムプロンプトへ足す一段を作る。
 *
 * **足すのはタイプの文章1つと、状態の文章1つだけ。**
 * 調子が未知（一度も答えていない、または14日を過ぎた）なら、
 * タイプの文章だけを返す——**相談は止めない。**
 */
export function buildAdvicePolicyPrompt(
  profile: AdviceProfile,
  now: Date
): string {
  const blocks = [ADVICE_TYPE_PROMPTS[resolveAdviceType(profile.scores)]];

  const state = freshState(profile, now);
  if (state) {
    blocks.push(ADVICE_STATE_PROMPTS[`${state.acceptance}-${state.confidence}`]);
  }

  return `【この作者への助言の方針】
${estimationNote(adviceDiagnosisDate(profile.updatedAt))}

${blocks.join("\n\n")}`;
}
