import * as vscode from "vscode";
import type { WorkEntry } from "../models/types";
import { CharacterStore } from "../core/characterStore";
import {
  createAbilityStore,
  createLocationStore,
  createOrganizationStore,
} from "../core/abilityStore";
import {
  describeProtectResult,
  protectRecords,
  type ProtectableRecord,
} from "../core/protectExternalEdits";
import { logLine } from "../core/logger";

/**
 * 拡張機能の外で直された設定資料に、「人が確定させた」印を付ける。
 *
 * **なぜ要るか**（設計書5.5、2026-08-19の作者の判断）
 *
 * 編集部は別のGitHubアカウントで、GitHub経由で編集する。つまり
 * **拡張機能の「書き換え」画面を通らない。** そのため、AIが生成したままの
 * レコード（`autoGenerated: true`）を編集部が直しても印が付かず、
 * 次の抽出で上書きされてしまう。
 *
 * 印さえ付けば、あとは既存のマージがそのまま守る（`!autoGenerated` の判定は
 * 誰が書いたかを見ていないので、編集部の記述も作者の記述と同じ扱いになる）。
 *
 * **黙って付けない。** 別のプラグインのAIが書いた場合も同じ経路を通るので、
 * 機械が勝手に決めると「AIの書いたものをAIから守る」ことになる。
 * 作者が選んだときだけ付ける。
 */
export async function protectExternalEdits(work: WorkEntry): Promise<void> {
  const characterStore = new CharacterStore(work);
  const abilityStore = createAbilityStore(work);
  const locationStore = createLocationStore(work);
  const organizationStore = createOrganizationStore(work);

  try {
    const [characters, abilities, locations, organizations] = await Promise.all([
      characterStore.loadAll(),
      abilityStore.loadAll(),
      locationStore.loadAll(),
      organizationStore.loadAll(),
    ]);

    const all: ProtectableRecord[] = [
      ...characters.characters,
      ...abilities.records,
      ...locations.records,
      ...organizations.records,
    ];
    const result = protectRecords(all);

    if (result.protectedRecords.length === 0) {
      void vscode.window.showInformationMessage(describeProtectResult(result));
      return;
    }

    // **人物は1人1ファイル。** 既存ファイルは上書きできないので
    // `saveOrUpdate()` を通す（`save()` を直接呼ぶと必ず失敗する）
    for (const character of characters.characters) {
      await characterStore.saveOrUpdate(character);
    }
    await abilityStore.saveAll(abilities.records);
    await locationStore.saveAll(locations.records);
    await organizationStore.saveAll(organizations.records);

    logLine(
      `外部で直された設定資料を守った: ${work.title} / ` +
        `${result.protectedRecords.length}件`
    );
    void vscode.window.showInformationMessage(describeProtectResult(result));
  } catch (error) {
    void vscode.window.showErrorMessage(
      `設定資料を守れませんでした: ${
        error instanceof Error ? error.message : String(error)
      }`
    );
  }
}
