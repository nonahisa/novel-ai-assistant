/**
 * 場所の略図（設計書6.93.10。作者の裁定 2026-10-09 夜）。
 *
 * 人物相関図（`relationGraphPanel.ts`）と同じ作りの WebView。置き方の計算は
 * `core/locationSketch.ts` だけが持ち、ここは台帳を読んで渡し、作者が点を
 * 動かした位置を場所の記録へ保存するだけである。AI は使わない。
 *
 * **書き換えるのは `sketchPosition` だけ。** 関係（`relations`）も、確定の印
 * （`autoGenerated`）も変えない——位置を動かしただけで記録が「確定」に
 * なると、以後その場所に抽出が関係を足さなくなる。
 *
 * 作品ごとに1枚だけ開く。
 */

const openPanels = new Map<string, LocationSketchPanel>();

/** 場所のファイルの変化が落ち着くまで待つ時間（相関図と同じ） */
const RELOAD_SETTLE_MS = 500;

export interface LocationSketchDeps {
  /**
   * 「場所の資料を開く」。実体は `extension.ts` が繋ぐ（設定資料パネルを
   * ここから直に読み込むと、互いに読み合う輪ができる）
   */
  openSettingsRecord: (work: WorkEntry, locationId: string) => Promise<void>;
  /**
   * 食い違いの線を押したとき。提案パネルの「矛盾」の同じ行と、本文の同じ所へ
   * 飛ぶ（番号は `findLocationInconsistencies` の並び）
   */
  openConflict: (work: WorkEntry, index: number) => Promise<void>;
}

export async function openLocationSketch(
  context: vscode.ExtensionContext,
  work: WorkEntry,
  deps: LocationSketchDeps,
  options: { focusId?: string } = {}
): Promise<void> {
  const existing = openPanels.get(work.id);
  if (existing) {
    await existing.revealWith(options.focusId);
    return;
  }
  const panel = new LocationSketchPanel(context, work, deps, options.focusId);
  openPanels.set(work.id, panel);
  await panel.initialize();
}

class LocationSketchPanel {
  private readonly panel: vscode.WebviewPanel;
  private records: Location[] = [];
  private loadErrors: Array<{ file: string; message: string }> = [];
  /** 作者が選び直した起点。null は「関係のいちばん多い場所」 */
  private origin: string | null = null;
  /** 開いたときに示す場所（設定資料パネルの「略図」から） */
  private focusId: string | undefined;
  private watcher: vscode.FileSystemWatcher | undefined;
  private reloadTimer: ReturnType<typeof setTimeout> | undefined;
  private disposed = false;

  constructor(
    context: vscode.ExtensionContext,
    private readonly work: WorkEntry,
    private readonly deps: LocationSketchDeps,
    focusId?: string
  ) {
    this.focusId = focusId;
    this.panel = vscode.window.createWebviewPanel(
      "novelai.locationSketch",
      `場所の略図: ${work.title}`,
      wideViewColumn(),
      { enableScripts: true, retainContextWhenHidden: true }
    );
    context.subscriptions.push(this.panel);
    this.panel.onDidDispose(() => {
      openPanels.delete(work.id);
      this.stopWatching();
    });
    this.panel.webview.html = buildLocationSketchPanelHtml(
      createNonce(),
      this.panel.webview.cspSource
    );
    this.panel.webview.onDidReceiveMessage((message: unknown) => {
      void this.handleMessage(message as PanelMessage);
    });
  }

  async initialize(): Promise<void> {
    await this.load();
    await this.watchLocations();
  }

  async revealWith(focusId?: string): Promise<void> {
    this.panel.reveal();
    if (focusId) this.focusId = focusId;
    await this.load();
  }

  /**
   * 場所のファイルが変わったら読み直す（相関図の `watchCharacters` と同じ形）。
   *
   * 資料を直す道は、設定資料パネル・承認待ちの反映・外での書き換え・
   * 抽出のし直しと複数ある。置き場そのものを見張れば道の数に依らない。
   * 自分の保存でも知らせが来るが、落ち着いてから1回だけ読み直す。
   */
  private async watchLocations(): Promise<void> {
    try {
      const config = await readWorkConfig(this.work);
      const directory = path.join(workPaths(this.work, config).settings, "locations");
      if (this.disposed) return;
      const watcher = vscode.workspace.createFileSystemWatcher(
        new vscode.RelativePattern(path.toUri(directory), "*.json")
      );
      const schedule = (): void => {
        if (this.reloadTimer) clearTimeout(this.reloadTimer);
        this.reloadTimer = setTimeout(() => {
          this.reloadTimer = undefined;
          if (!this.disposed) void this.load();
        }, RELOAD_SETTLE_MS);
      };
      watcher.onDidChange(schedule);
      watcher.onDidCreate(schedule);
      watcher.onDidDelete(schedule);
      this.watcher = watcher;
    } catch (error) {
      logStep(
        "場所の略図：場所の置き場を見張れませんでした（資料を直しても図は開き直すまで古いままです）：" +
          (error instanceof Error ? error.message : String(error))
      );
    }
  }

  private stopWatching(): void {
    this.disposed = true;
    if (this.reloadTimer) clearTimeout(this.reloadTimer);
    this.reloadTimer = undefined;
    this.watcher?.dispose();
    this.watcher = undefined;
  }

  private async load(): Promise<void> {
    const loaded = await createLocationStore(this.work).loadAll();
    this.records = loaded.records;
    this.loadErrors = loaded.errors;
    if (this.origin && !this.records.some((record) => record.id === this.origin)) {
      this.origin = null;
    }
    this.post();
  }

  private async handleMessage(message: PanelMessage): Promise<void> {
    try {
      switch (message.type) {
        case "ready":
          this.post();
          return;
        case "move":
          await this.savePosition(message.id, { x: message.x, y: message.y });
          return;
        case "resetPosition":
          await this.savePosition(message.id, undefined);
          return;
        case "origin":
          this.origin = message.id;
          this.post();
          return;
        case "openRecord":
          await this.deps.openSettingsRecord(this.work, message.id);
          return;
        case "conflict":
          await this.deps.openConflict(this.work, message.index);
          return;
      }
    } catch (error) {
      const detail = error instanceof Error ? error.message : String(error);
      useLogFile(this.work.folderPath);
      logFailure("場所の略図", { 作品: this.work.title, 内容: detail });
      void vscode.window.showErrorMessage(`場所の略図でエラーが起きました。${detail}`);
    }
  }

  /**
   * 作者が置いた位置を保存する（`position` が無ければ外す）。
   *
   * **保存は設定資料の台帳の道（`SettingsStore.saveAll`）を通す。** 保存の直前に
   * 読み直し、その記録の `sketchPosition` だけを替える——画面を開いたあとに
   * 資料が直されていても、直された中身を古い写しで巻き戻さない。読み直しと
   * 保存の間に外で書き換えられたら、台帳のハッシュ照合が止める。
   * 壊れた JSON は読み直しで落ちるので、直さずに止める（実装ルール2）。
   */
  private async savePosition(
    id: string,
    position: { x: number; y: number } | undefined
  ): Promise<void> {
    const store = createLocationStore(this.work);
    const loaded = await store.loadAll();
    const record = loaded.records.find((entry) => entry.id === id);
    if (!record) {
      const broken = loaded.errors.find((entry) => entry.file.startsWith(`${id}_`) || entry.file === `${id}.json`);
      void vscode.window.showWarningMessage(
        broken
          ? `場所の資料（${broken.file}）を読めないので、位置を保存しませんでした。${broken.message}`
          : "場所の資料が見つからないので、位置を保存しませんでした。"
      );
      await this.load();
      return;
    }
    const next = withOptionalSketchPosition(
      record,
      position
        ? // 画面の座標の細かい端数は持たない（同期の差分を読みやすくする）
          { x: Math.round(position.x * 10) / 10, y: Math.round(position.y * 10) / 10 }
        : undefined
    );
    try {
      await store.saveAll([next]);
    } catch (error) {
      if (error instanceof SettingsStoreError) {
        void vscode.window.showWarningMessage(`位置を保存しませんでした。${error.message}`);
        await this.load();
        return;
      }
      throw error;
    }
    useLogFile(this.work.folderPath);
    logStep(
      position
        ? `場所の略図：「${record.name}」を作者が置いた位置へ保存しました`
        : `場所の略図：「${record.name}」の作者の位置を外しました`
    );
    await this.load();
  }

  private post(): void {
    void this.panel.webview.postMessage({ type: "sketch", data: this.build() });
  }

  private build(): SketchView {
    const sketch = buildLocationSketch(this.records, { origin: this.origin });
    const focusId = this.focusId;
    this.focusId = undefined;
    return {
      title: `${this.work.title} の場所の略図`,
      sketch,
      origin: this.origin,
      locations: this.records.map((record) => ({ id: record.id, name: record.name })),
      focusId: focusId ?? null,
      emptyMessage:
        this.records.length === 0
          ? "まだ場所の資料がありません。資料管理 → 資料抽出 から場所を抽出するか、設定資料パネルで場所を足してください。"
          : "",
      warning:
        this.loadErrors.length > 0
          ? `読み込めなかった場所の資料が${this.loadErrors.length}件あります（${this.loadErrors
              .map((entry) => entry.file)
              .join("、")}）。その場所は図に出ていません。`
          : "",
    };
  }
}

interface SketchView {
  title: string;
  sketch: LocationSketch;
  origin: string | null;
  locations: Array<{ id: string; name: string }>;
  focusId: string | null;
  emptyMessage: string;
  warning: string;
}

type PanelMessage =
  | { type: "ready" }
  | { type: "move"; id: string; x: number; y: number }
  | { type: "resetPosition"; id: string }
  | { type: "origin"; id: string | null }
  | { type: "openRecord"; id: string }
  | { type: "conflict"; index: number };

function createNonce(): string {
  const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
  let value = "";
  for (let index = 0; index < 32; index++) {
    value += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return value;
}
