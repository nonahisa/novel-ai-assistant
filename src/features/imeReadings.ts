/**
 * IMEで打った読みを、設定資料と読み上げへ効かせる（設計書6.42.2）。
 *
 * 引き当ての決まりは `core/imeReading.ts`。ここは設定資料を読み、控えへ足し、
 * 裁定（作者、2026-10-24）どおりに設定資料の読みを埋める。
 *
 * ## 打鍵の裏で動くので、知らせを出さない
 *
 * 名前を確定するたびに走る。失敗（未保存の編集がある・外で書き換えられた・
 * 控えが壊れている）を通知にすると、名前を打つたびに知らせが出る。
 * 失敗は答えに載せて、呼ぶ側が記録（ログ）へ残す。
 */


/** 引き当てと読み上げに要るだけの項目の写し */
interface NameRecord {
  kind: SettingsKind;
  id: string;
  name: string;
  /** 別名と、姓・名に分けた呼び方（`expandNameVariants`） */
  aliases: string[];
  /**
   * ファイルにある別名だけ（分けた呼び方を含まない）。**別名の読みを埋めるのは
   * これに在る別名だけ**——分けた呼び方へ埋めると `aliases` に無い鍵ができ、
   * 保存の刈り込み（`withOptionalAliasReadings`）で消えるだけになる
   */
  ownAliases: string[];
  reading: string | null;
  aliasReadings?: AliasReadings;
  autoGenerated: boolean;
}

/**
 * 項目の写しを持っておく長さ。
 *
 * 名前の確定のたびに設定資料のJSONを全部読むと、名前の多い作品では打つたびに
 * 数百のファイルを読むことになる。短く持ち、設定資料が変わったと分かったら
 * （`invalidateImeNameCache`）捨てる。持っている間に足された名前は、最長でも
 * この長さだけ拾えないだけで、何も壊れない
 */
const NAME_CACHE_MS = 10_000;

const nameCache = new Map<string, { at: number; records: NameRecord[] }>();

/** 設定資料が変わったら呼ぶ（パネルの保存・抽出・外での書き換え・同期の取り込み） */
export function invalidateImeNameCache(workId?: string): void {
  if (workId === undefined) nameCache.clear();
  else nameCache.delete(workId);
}

/**
 * 作品ごとに1つずつ動かす。**続けて名前を確定すると、控えの「読む→足す→書く」が
 * 重なり、照合で自分の前の書き込みに弾かれる**ので、前の分が終わってから読む
 */
const queues = new Map<string, Promise<unknown>>();

function enqueue<T>(workId: string, task: () => Promise<T>): Promise<T> {
  const previous = queues.get(workId) ?? Promise.resolve();
  const next = previous.then(task, task);
  queues.set(
    workId,
    next.catch(() => undefined)
  );
  return next;
}

async function loadNameRecords(work: WorkEntry): Promise<NameRecord[]> {
  const cached = nameCache.get(work.id);
  if (cached && Date.now() - cached.at < NAME_CACHE_MS) return cached.records;

  const records: NameRecord[] = [];
  const push = (
    kind: SettingsKind,
    item: {
      id: string;
      name: string;
      aliases: string[];
      reading: string | null;
      aliasReadings?: AliasReadings;
      autoGenerated: boolean;
    }
  ): void => {
    records.push({
      kind,
      id: item.id,
      name: item.name,
      // 本文では「マルキオ・イークェス」を「マルキオ」としか書かないことが多い
      // （用語の色分けと同じ広げ方）。分けた呼び方は別名と同じ扱いにする
      aliases: expandNameVariants([item.name, ...item.aliases]).filter(
        (text) => text !== item.name.trim()
      ),
      ownAliases: item.aliases.map((alias) => alias.trim()).filter(Boolean),
      reading: item.reading,
      ...(item.aliasReadings ? { aliasReadings: item.aliasReadings } : {}),
      autoGenerated: item.autoGenerated,
    });
  };
  // **読めなかったファイルは飛ばす**（壊れた資料を直さない。読めた分だけで引き当てる）
  for (const character of (await new CharacterStore(work).loadAll()).characters) {
    push("character", character);
  }
  for (const item of (await createAbilityStore(work).loadAll()).records) push("ability", item);
  for (const item of (await createOrganizationStore(work).loadAll()).records) {
    push("organization", item);
  }
  for (const item of (await createLocationStore(work).loadAll()).records) push("location", item);
  for (const item of (await createWorldStore(work).loadAll()).records) push("world", item);

  nameCache.set(work.id, { at: Date.now(), records });
  return records;
}

/** 確定1回ぶんの結果（呼ぶ側が記録へ残す） */
export interface ImeRecordResult {
  /**
   * 拾えた読みと、その名前のいまの主な読み（名前に当たらなかったら空）。
   * 前の確定とつないだときは、いまの確定だけで当たったもの（別名「灯」）と、
   * つないで当たったもの（名前「白樺灯」）の両方が入りうる
   */
  captures: Array<ImeCapture & { primary?: string }>;
  /**
   * 読みを埋めた項目（開いている設定資料パネルへ映すのに種類と id と読みが要る）。
   * `alias` があれば、名前の読みではなくその別名の読み（`aliasReadings`）を埋めた
   */
  filled: Array<{ kind: SettingsKind; id: string; name: string; reading: string; alias?: string }>;
  /**
   * 読みの辞書への提案として**新しく出た**語（設計書6.42.2。作者の裁定、2026-10-25）。
   * 同じ（話・語・読み）を前にも打っていたもの・見送ったものは入らない（記録の行を
   * 打つたびに出さない）
   */
  words: Array<{ word: string; reading: string }>;
  /** 書けなかった理由（あれば） */
  problems: string[];
}

/** 変換1回ぶんに添える、語の提案のための手がかり */
export interface ImeWordContext {
  /** 打った話のファイル（提案は話ごとに出す。読みの辞書が話ごとなので） */
  episodePath: string;
  /** 変換を始めた所の直前の字（句を求めるとき、打った所を選ぶ） */
  before?: string;
}

/**
 * 変換1回ぶんを受け取る。名前に当たれば控えへ足し、裁定どおりに設定資料の読みを埋める。
 *
 * **埋めるのは、AIが作った項目で読みが空のものだけ**（`decideImeReading` が `fill`）。
 * 名前が当たれば名前の読み（`reading`）、別名が当たればその別名の読み
 * （`aliasReadings`）。作者が作った項目・別の読みが入っている項目は書かず、
 * 設定資料パネルで提案にする（CLAUDE.md 実装ルール2）。
 *
 * `previous` は、画面がこの確定のすぐ前に・すぐ後ろへ続けて打ったと確かめた確定
 * （姓と名を分けて確定する打ち方。設計書6.42.2）。いまの確定だけでの引き当てに
 * 加えて、つないだ組でも引き当てる（`captureJoinedImeReading`）。つないで当たった
 * のが別名なら、別名の読みの決まりにそのまま乗る。前の確定だけでの引き当ては、
 * 前の確定が届いたときに済んでいるので、ここではしない（二重に数えない）
 *
 * `wordContext` があれば、名前以外の語の読みも読みの辞書への提案として控える
 * （`recordWords`。いまの確定だけを見て、前の確定とはつながない）
 */
export function recordImeComposition(
  work: WorkEntry,
  kana: string,
  committed: string,
  previous?: CompositionPair,
  wordContext?: ImeWordContext
): Promise<ImeRecordResult> {
  return enqueue(work.id, async () => {
    const records = await loadNameRecords(work);
    const surfaces = records.flatMap((record) => [record.name, ...record.aliases]);
    const result: ImeRecordResult = { captures: [], filled: [], words: [], problems: [] };
    // 語の提案は名前とは別に拾う（名前に当たらない確定でも拾う）。失敗は理由へ積み、
    // 名前の側を止めない
    if (wordContext) await recordWords(work, kana, committed, surfaces, wordContext, result);
    const found: ImeCapture[] = [];
    const single = captureImeReading(kana, committed, surfaces);
    if (single) found.push(single);
    const joined = previous
      ? captureJoinedImeReading(previous, { kana, committed }, surfaces)
      : undefined;
    if (
      joined &&
      !found.some((item) => item.surface === joined.surface && item.reading === joined.reading)
    ) {
      found.push(joined);
    }
    if (found.length === 0) return result;

    // 控えへは1回で書く（2回に分けると、間に別の書き込みが入る余地ができる）
    const now = new Date().toISOString();
    const file = await updateImeReadings(work, (current) =>
      found.reduce((next, capture) => recordImeReadingEntry(next, capture, now), current)
    );
    const primaries = primaryImeReadings(file);
    for (const capture of found) {
      const primary = primaries.get(capture.surface);
      result.captures.push({ ...capture, primary });
      if (!primary) continue;
      await fillFor(work, records, capture.surface, primary, result);
    }
    if (result.filled.length > 0) invalidateImeNameCache(work.id);
    return result;
  });
}

/**
 * 名前以外の語の読みを、読みの辞書への提案として控えへ足す（設計書6.42.2）。
 *
 * **辞書へは書かない。** 入れるのは作者が［採る］を押したときだけ
 * （`features/readingDictionary.ts`）。ここは控え（同期しない）を書くだけ
 */
async function recordWords(
  work: WorkEntry,
  kana: string,
  committed: string,
  names: readonly string[],
  context: ImeWordContext,
  result: ImeRecordResult
): Promise<void> {
  const captures = captureImeWords(kana, committed, names);
  if (captures.length === 0) return;
  const episode = episodeRelativePath(work, context.episodePath);
  try {
    const added = await updateImeWordReadings(work, (file) => {
      const next = recordImeWordEntries(file, {
        episode,
        captures,
        committed: committed.trim(),
        // 無いまま渡す（空の字は「行頭で打った」の意味になる）
        before: context.before,
        now: new Date().toISOString(),
      });
      return { file: next.file, result: next.added };
    });
    if (added.length === 0) return;
    // 見送った語は記録にも出さない。印が読めなければ出すほうに倒す（記録の1行だけのこと）
    let dismissed: Array<{ episode: string; word: string; reading: string }> = [];
    try {
      dismissed = (await loadImeReadingDismissals(work)).file.entries;
    } catch {
      dismissed = [];
    }
    result.words.push(
      ...added.filter(
        (item) =>
          !dismissed.some(
            (mark) =>
              mark.episode === episode && mark.word === item.word && mark.reading === item.reading
          )
      )
    );
  } catch (error) {
    result.problems.push(
      `読みの提案を控えへ足せませんでした（${
        error instanceof Error ? error.message : String(error)
      }）`
    );
  }
}

/** 拾った1つぶんについて、名前の読み・別名の読みを裁定どおりに埋める */
async function fillFor(
  work: WorkEntry,
  records: readonly NameRecord[],
  surface: string,
  primary: string,
  result: ImeRecordResult
): Promise<void> {
  const targets = records.filter(
    (record) => record.name.trim() === surface && decideImeReading(record, primary) === "fill"
  );
  for (const target of targets) {
    try {
      if (await fillReading(work, target, primary)) {
        result.filled.push({
          kind: target.kind,
          id: target.id,
          name: target.name,
          reading: primary,
        });
      }
    } catch (error) {
      result.problems.push(
        `「${target.name}」の読みを埋められませんでした（${
          error instanceof Error ? error.message : String(error)
        }）`
      );
    }
  }
  // 別名が当たった項目（設計書6.42.2）。名前と同じ裁定で、その別名の読みを埋める
  const aliasTargets = records.filter(
    (record) =>
      record.name.trim() !== surface &&
      record.ownAliases.includes(surface) &&
      decideImeReading(
        { autoGenerated: record.autoGenerated, reading: aliasReadingOf(record, surface) },
        primary
      ) === "fill"
  );
  for (const target of aliasTargets) {
    try {
      if (await fillAliasReading(work, target, surface, primary)) {
        result.filled.push({
          kind: target.kind,
          id: target.id,
          name: target.name,
          reading: primary,
          alias: surface,
        });
      }
    } catch (error) {
      result.problems.push(
        `「${target.name}」の別名「${surface}」の読みを埋められませんでした（${
          error instanceof Error ? error.message : String(error)
        }）`
      );
    }
  }
}

/**
 * 項目の読みを埋める。**読み直してから、もう一度確かめて書く**（写しは10秒古い
 * ことがあり、その間に作者が読みを入れていたら書かない）。
 *
 * **作者の編集の道（`applyXxxEdits`）を通さない。** あちらは `autoGenerated` を
 * false に倒す（作者が直した印）。機械が埋めた読みに作者の印を付けると、以後の
 * 抽出の対象から外れてしまう。保存は各種の既存の口——人物は `saveOrUpdate`
 * （`save()` を直に呼ぶと既存のファイルで必ず失敗する）、ほかは `saveAll`
 * （読み込んだときのハッシュと照合する）。どちらも**同じ入れ物で `loadAll` を
 * 済ませてから**呼ぶ（照合に使う控えが読み込みで入るため）
 *
 * @returns 書いたら true
 */
async function fillReading(
  work: WorkEntry,
  target: NameRecord,
  reading: string
): Promise<boolean> {
  if (target.kind === "character") {
    const store = new CharacterStore(work);
    const loaded = await store.loadAll();
    const current = loaded.characters.find((item) => item.id === target.id);
    if (!current || current.name.trim() !== target.name.trim()) return false;
    if (decideImeReading(current, reading) !== "fill") return false;
    await store.saveOrUpdate({ ...current, reading });
    return true;
  }
  if (target.kind === "ability") return fillIn(createAbilityStore(work), target, reading);
  if (target.kind === "organization") {
    return fillIn(createOrganizationStore(work), target, reading);
  }
  if (target.kind === "location") return fillIn(createLocationStore(work), target, reading);
  return fillIn(createWorldStore(work), target, reading);
}

async function fillIn<
  T extends { id: string; updatedAt: string; name: string; reading: string | null; autoGenerated: boolean },
>(store: SettingsStore<T>, target: NameRecord, reading: string): Promise<boolean> {
  const loaded = await store.loadAll();
  const current = loaded.records.find((item) => item.id === target.id);
  if (!current || current.name.trim() !== target.name.trim()) return false;
  if (decideImeReading(current, reading) !== "fill") return false;
  await store.saveAll([{ ...current, reading }]);
  return true;
}

/**
 * 項目の別名の読みを埋める。名前の `fillReading` と同じく、**読み直してから
 * もう一度確かめて書く**（写しの間に作者が別名を消した・読みを入れたら書かない）。
 * 作者の編集の道を通さないのも同じ理由（`autoGenerated` を倒さない）
 *
 * @returns 書いたら true
 */
async function fillAliasReading(
  work: WorkEntry,
  target: NameRecord,
  alias: string,
  reading: string
): Promise<boolean> {
  if (target.kind === "character") {
    const store = new CharacterStore(work);
    const loaded = await store.loadAll();
    const current = loaded.characters.find((item) => item.id === target.id);
    if (!current || !canFillAlias(current, target, alias, reading)) return false;
    await store.saveOrUpdate(withAliasReading(current, alias, reading));
    return true;
  }
  if (target.kind === "ability") {
    return fillAliasIn(createAbilityStore(work), target, alias, reading);
  }
  if (target.kind === "organization") {
    return fillAliasIn(createOrganizationStore(work), target, alias, reading);
  }
  if (target.kind === "location") {
    return fillAliasIn(createLocationStore(work), target, alias, reading);
  }
  return fillAliasIn(createWorldStore(work), target, alias, reading);
}

interface AliasHolder {
  id: string;
  updatedAt: string;
  name: string;
  aliases: string[];
  aliasReadings?: AliasReadings;
  autoGenerated: boolean;
}

function canFillAlias(
  current: AliasHolder,
  target: NameRecord,
  alias: string,
  reading: string
): boolean {
  if (current.name.trim() !== target.name.trim()) return false;
  if (!current.aliases.some((entry) => entry.trim() === alias)) return false;
  return (
    decideImeReading(
      { autoGenerated: current.autoGenerated, reading: aliasReadingOf(current, alias) },
      reading
    ) === "fill"
  );
}

function withAliasReading<T extends AliasHolder>(current: T, alias: string, reading: string): T {
  return withOptionalAliasReadings(current, { ...(current.aliasReadings ?? {}), [alias]: reading });
}

async function fillAliasIn<T extends AliasHolder>(
  store: SettingsStore<T>,
  target: NameRecord,
  alias: string,
  reading: string
): Promise<boolean> {
  const loaded = await store.loadAll();
  const current = loaded.records.find((item) => item.id === target.id);
  if (!current || !canFillAlias(current, target, alias, reading)) return false;
  await store.saveAll([withAliasReading(current, alias, reading)]);
  return true;
}

/** 名前ごとの、IMEで打った主な読み。**控えが読めなければ空**（読み上げ・パネルを止めない） */
export async function loadImePrimaryReadings(
  work: WorkEntry
): Promise<{ primary: Map<string, string>; problem?: string }> {
  try {
    return { primary: primaryImeReadings((await loadImeReadings(work)).file) };
  } catch (error) {
    return {
      primary: new Map(),
      problem: error instanceof Error ? error.message : String(error),
    };
  }
}

/**
 * 読み上げに当てる、名前の読みの範囲（設定資料の読み、無ければIMEの控え）。
 *
 * 読みの辞書の範囲と合わせるのは呼ぶ側（辞書が先、こちらが後。`mergeReadingSpans`）
 */
export async function imeNameReadingSpans(
  work: WorkEntry,
  text: string
): Promise<{ spans: ReadingSpan[]; problem?: string }> {
  const records = await loadNameRecords(work);
  const { primary, problem } = await loadImePrimaryReadings(work);
  return { spans: nameReadingSpans(text, nameReadingsFrom(records, primary)), problem };
}
